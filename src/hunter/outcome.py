"""Исход сделки от уровня. FOUNDATION.md §8 этап 7, мини-курс стр. 9 и 14.

ЧИСТЫЙ МОДУЛЬ (§10.3): часы, сеть и глобальное состояние не трогаются.

Единица — R, и она из курса, а не привнесена: стр. 9 «Р или R - "один Риск". Это единица
измерения эффективности сделки… Позволяет вести расчет профита/убытка в сделке».
Сумма процентов результатом не является: сделка со стопом
0.3% и сделка со стопом 30% несопоставимы, а в R сопоставимы по определению.

⚠ ГЛАВНОЕ ОГРАНИЧЕНИЕ, которое здесь НЕ обходится: по бару OHLC неизвестно, что случилось
раньше — стоп или цель. Если один бар накрывает и то и другое, исход НЕ назначается, а
помечается неоднозначным. Выбрать «обычно сначала стоп» значило бы придумать правило,
которого нет ни в данных, ни в курсе (§4.3).
"""

from __future__ import annotations

from decimal import Decimal
from enum import StrEnum

from pydantic import BaseModel, ConfigDict

# ⚠ Доля первого тейка берётся ОТТУДА, ГДЕ ОНА ЖИВЁТ, а не повторяется здесь числом:
# у неё длинная докстрока о том, чего курс НЕ говорит, и вторая копия числа эту оговорку
# потеряла бы. Цикла импортов нет: `geometry` про `outcome` не знает — знают `emit` и
# `run`, то есть слои выше обоих.
from .geometry import PARTIAL_TAKE_PCT
from .levels import LevelSide
from .models import Bar


class OutcomeKind(StrEnum):
    STOP = "stop"
    """Цена дошла до стопа. R = −1 по определению."""

    TARGET = "target"
    """Цена дошла до первой основной цели (стр. 24)."""

    BREAKEVEN = "breakeven"
    """Стоп был перенесён в ТВХ, и цена туда вернулась. R = 0 по определению курса.

    Стр. 14 дословно: «Безубыток (БУ) – это когда цена вернулась к точке открытия
    сделки. Выйти в б/у = закрыть позицию в ноль когда цена пошла против вашего
    сценария плана». Это ТРЕТИЙ исход, а не разновидность стопа и не «почти цель»:
    курс называет им отдельное событие и приписывает ему ноль, а не убыток.

    Курс возвращается к нему ещё пять раз, и всякий раз как к штатному завершению
    сделки: стр. 19 «Цена показала реакцию и ушла внутрь базы – ставите стоп в б/у»;
    стр. 30 «если цена сделает ловушку - она будет тестировать его еще раз с обратной
    стороны, давая выйти в б/у»; стр. 33 «на случай пробоя уровня и закрепа у вас будет
    больше шансов выйти в бу»; стр. 44 «Приоритет – выйти в б/у на тесте уровня с
    обратной стороны»; стр. 16 «вас выбьет в безубыток и вы ничего не потеряете».

    ⚠ Без этого исхода перенос стопа в БУ считался бы СТОПОМ с R = −1, то есть журнал
    приписывал бы системе убыток там, где курс велит выходить в ноль.
    """

    AMBIGUOUS = "ambiguous"
    """Один бар накрыл и стоп, и цель. Что было раньше — из OHLC не следует."""

    OPEN = "open"
    """Ряд кончился, ни стоп, ни цель не достигнуты."""

    NOT_FILLED = "not_filled"
    """Цена так и не дошла до входа: сделки не было вовсе."""

    UNMEASURABLE = "unmeasurable"
    """Риск вырожден: стоп совпал со входом, единицы R не существует.

    ⚠⚠ ЗАВЕДЁН 2026-08-23. До этого дня такой случай возвращал `NOT_FILLED`, чьё
    определение — «цена так и не дошла до входа: сделки не было вовсе». Это отказ
    ПРИБОРА, выданный за вердикт о РЫНКЕ: цена могла прийти на вход и уйти куда угодно,
    но измерить это в R нечем — знаменатель ноль. Исход при этом попадал в знаменатель
    `emitted_outcomes` и в долю «мимо входа», то есть портил обе величины, которые
    предъявляются владельцу.

    Наружу (в леджер) он НЕ ПИШЕТСЯ: таблица состояний знает только `not_filled` и
    `open`, и добавлять туда третье значение значило бы записывать в журнал сделок то,
    что сделкой не является. Он НАЗЫВАЕТСЯ числом в приёмке — как всякий отказ (§4.3).
    """


CLOSED_KINDS = frozenset(
    {OutcomeKind.STOP, OutcomeKind.TARGET, OutcomeKind.AMBIGUOUS, OutcomeKind.BREAKEVEN}
)
"""Исходы, ЗАКРЫВАЮЩИЕ сделку, — против незакрытых состояний (`open`, `not_filled`).

⚠ ОДИН предикат на проект (ревизия 2026-08-24). Прежде набор жил СТРОКАМИ в трёх местах
`run` — `("stop", "target", "ambiguous", "breakeven")` — и когда 2026-08-23 появился
`UNMEASURABLE`, его перехватили только у одного из трёх: у двух других он падал в ветку
«записать состояние», а схема леджера состояний (`CHECK state IN ('not_filled','open')`)
отбивала запись — покруговая деградация с чужой подписью, при том что докстрока выше
прямо говорит «наружу он НЕ ПИШЕТСЯ». Новый член перечисления обязан ЛОМАТЬ ровно одно
место, а не молча уезжать в else трёх копий."""


class Outcome(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    kind: OutcomeKind
    filled_at_index: int | None
    closed_at_index: int | None
    exit_price: Decimal | None
    r: float | None

    r_partial: float | None = None
    """R по модели ЧАСТИЧНОГО выхода — и это ПОЛ, а не точечная оценка (Ф5, 2026-08-26).

    ⚠⚠ ЗАЧЕМ ВТОРОЕ ЧИСЛО. Поле `r` считает сделку по модели ПОЛНОГО выхода: цена дошла
    до первой крупной цели — позиция закрыта вся. Курс так не торгует. Стр. 15 дословно,
    и это про сделку ОТ УРОВНЯ («Актив пришел к лонг уровню, вы открыли позицию в
    лонг»): «Вы сделали тейки по достигнутым целям и передвинули стоп в бу. Далее актив
    пошел на коррекцию и просто остаток позиции закрылся в безубыток». То есть у цели
    фиксируется ЧАСТЬ, остаток идёт дальше под защитой безубытка.

    Значит `r` — ВЕРХНЯЯ оценка выигрыша, а не результат сделки курса, и всё, что на ней
    построено (экспектанси, винрейт в R), эту сделку переоценивает.

    ⚠⚠ ПОЧЕМУ ИМЕННО ПОЛ, А НЕ ТОЧКА. Доли для сделки от уровня курс НЕ НАЗЫВАЕТ ни на
    одной странице — это записано в докстроке `geometry.PARTIAL_TAKE_PCT` и проверено
    заново 2026-08-26: стр. 9 даёт 50% ПРИМЕРОМ В СЛОВАРЕ, поясняя единицу R («цена дала
    реакцию +4Р, делаем тейк 50% и забираем 2Р»), причём тейк там берётся на +4Р, а не у
    цели; стр. 11 и 16 называют СОБЫТИЕ первого тейка без числа; стр. 19 число даёт, но
    она — «ТОРГОВЛЯ ВО ФЛЕТЕ», и для сделки от уровня отозвана 2026-08-24.

    Точное R остатка поэтому неизвестно ПО ПОСТРОЕНИЮ. Но НИЖНЯЯ его граница известна и
    выдумки не требует: после первого тейка стоп стоит в безубытке (стр. 15), значит
    остаток не может дать МЕНЬШЕ нуля. Отсюда

        r_partial = s·RR₁                       — пока остаток не разрешился,
        r_partial = s·RR₁ + (1−s)·RR₂           — если остаток дошёл до второй цели,

    где s = `geometry.PARTIAL_TAKE_PCT`. Это ПОЛ: настоящий результат не ниже.

    ⚠ Определено РОВНО ТОГДА, когда определено `r`, — подвыборки не возникает. Незакрытый
    остаток пола не отменяет: он его лишь не поднимает.

    ⚠ У стопа до первой цели `r_partial` равен `r` = −1: делить там нечего, позиция ещё
    целая. Это не совпадение моделей, а один и тот же случай.
    """
    """Результат в R. `None` у неразрешённых.

    ⚠ Ноль — НЕ «нет ответа», а ответ: с 2026-08-19 он означает ровно безубыток
    (стр. 14 «закрыть позицию в ноль»). Именно поэтому неразрешённые несут `None`.
    """


def _filled(bar: Bar, price: Decimal, *, long: bool) -> bool:
    """Исполнилась ли лимитка входа на этом баре. Условие ОДНОСТОРОННЕЕ.

    ⚠ Было `bar.low <= price <= bar.high` — ДВУСТОРОННЕЕ касание диапазона, и это
    приписывало бирже поведение, которого у неё нет. Лимитка на покупку исполняется,
    как только цена опустилась ДО НЕЁ ИЛИ НИЖЕ; на продажу — как только поднялась до
    неё или выше. Цена, ПЕРЕПРЫГНУВШАЯ вход гэпом (открытие бара уже за лимиткой),
    двусторонним тестом не ловилась вовсе, и сделка получала исход «цена не дошла до
    входа» там, где ордер на бирже давно бы исполнился.

    Стоп и цель в этой же функции всегда проверялись односторонне (`bar.low <= stop`,
    `bar.high >= target`) — вход был единственным местом с другой меркой.
    """
    return (bar.low <= float(price)) if long else (bar.high >= float(price))


def resolve(
    side: LevelSide,
    entry: Decimal,
    stop: Decimal,
    target: Decimal | None,
    bars: list[Bar],
    from_index: int,
    breakeven_at: Decimal | None = None,
    target2: Decimal | None = None,
) -> Outcome:
    """Исход сделки по барам ПОСЛЕ появления уровня.

    Две фазы, и первая обязательна: сначала цена должна дойти до входа (лимитный ордер на
    ПОК, стр. 30), и только потом считается стоп или цель. Сделка, до которой цена не
    дошла, — это не убыток и не прибыль, это `NOT_FILLED`.

    `breakeven_at` — цена, по достижении которой стоп переносится в ТВХ (стр. 19: «Цена
    показала реакцию и ушла внутрь базы – ставите стоп в б/у»). Уровень этой цены здесь
    НЕ вычисляется и не угадывается: он принадлежит структуре, и его подаёт вызывающий.
    `None` — переноса нет, расчёт ровно прежний.

    ⚠ Перенос вступает в силу СО СЛЕДУЮЩЕГО бара, а не с того, на котором сработал. Это
    не осторожность, а то же ограничение OHLC, что и у `AMBIGUOUS`: внутри бара порядок
    касаний неизвестен, а бар срабатывания часто и есть бар входа — считать по нему
    возврат к ТВХ значило бы закрывать сделку тем же движением, которым её открыли.

    `target2` — ВТОРАЯ крупная цель, нужна только модели частичного выхода: она поднимает
    ПОЛ `Outcome.r_partial`, если остаток позиции до неё дошёл. `None` — пол остаётся на
    первом тейке. Разбор — в докстроке `Outcome.r_partial`.

    ⚠⚠ ЧАСТИЧНЫЙ ВЫХОД СЧИТАЕТСЯ ТЕМ ЖЕ ОБХОДОМ, а не второй функцией рядом. Правила
    входа (стр. 30), стопа и неоднозначности бара у обеих моделей ОДНИ И ТЕ ЖЕ; вторая
    их запись разошлась бы с первой не «если», а через сколько дней — этот класс проект
    ловил четырьмя копиями коробки структуры (`a971048`).
    """
    risk = abs(entry - stop)
    if risk == 0:
        # ⚠ НЕ `NOT_FILLED` (правка 2026-08-23): вырожденный стоп — это «мерить
        # нечем», а не «цена не пришла». Разбор — в докстроке `OutcomeKind.UNMEASURABLE`.
        return Outcome(kind=OutcomeKind.UNMEASURABLE, filled_at_index=None,
                       closed_at_index=None, exit_price=None, r=None)

    long = side is LevelSide.LONG
    filled: int | None = None
    be_armed = False

    def floor_r(closed_at: int) -> float:
        """ПОЛ модели частичного выхода на момент закрытия по первой цели.

        s·RR₁ плюс (1−s)·RR₂, если остаток дошёл до второй цели ПОСЛЕ первой. Ниже этого
        сделка дать не может: стоп остатка стоит в безубытке (стр. 15). Разбор и почему
        именно пол — в докстроке `Outcome.r_partial`.
        """
        assert target is not None
        share = PARTIAL_TAKE_PCT / 100.0
        gain1 = (target - entry) if long else (entry - target)
        out = share * float(gain1 / risk)
        if target2 is None:
            return out
        # Остаток ведётся СО СЛЕДУЮЩЕГО бара — то же ограничение OHLC, что у переноса
        # стопа: внутри бара первой цели порядок касаний неизвестен.
        for b in bars[closed_at + 1:]:
            reached = ((b.high >= float(target2)) if long else (b.low <= float(target2)))
            back = (b.low <= float(entry)) if long else (b.high >= float(entry))
            if reached and back:
                # Оба события в одном баре — вторая цель НЕ засчитывается: порядок
                # неизвестен, а пол обязан быть полом.
                return out
            if back:
                return out
            if reached:
                gain2 = (target2 - entry) if long else (entry - target2)
                return out + (1.0 - share) * float(gain2 / risk)
        return out

    for i in range(from_index, len(bars)):
        bar = bars[i]
        if filled is None:
            if _filled(bar, entry, long=long):
                filled = i
            else:
                continue

        if be_armed:
            hit_be = (bar.low <= float(entry)) if long else (bar.high >= float(entry))
            hit_tgt_be = (target is not None
                          and ((bar.high >= float(target)) if long
                               else (bar.low <= float(target))))
            if hit_be and hit_tgt_be:
                return Outcome(kind=OutcomeKind.AMBIGUOUS, filled_at_index=filled,
                               closed_at_index=i, exit_price=None, r=None)
            if hit_be:
                # Сюда попадают только сделки с порогом б/у (стр. 19); у сделки от уровня
                # его нет (`geometry.breakeven_watch`). Первая цель не взята, позиция
                # целая — обе модели дают ноль.
                return Outcome(kind=OutcomeKind.BREAKEVEN, filled_at_index=filled,
                               closed_at_index=i, exit_price=entry, r=0.0, r_partial=0.0)
            if hit_tgt_be:
                assert target is not None
                gain = (target - entry) if long else (entry - target)
                return Outcome(kind=OutcomeKind.TARGET, filled_at_index=filled,
                               closed_at_index=i, exit_price=target,
                               r=float(gain / risk), r_partial=floor_r(i))
            continue

        if breakeven_at is not None:
            be_armed = ((bar.high >= float(breakeven_at)) if long
                        else (bar.low <= float(breakeven_at)))

        hit_stop = (bar.low <= float(stop)) if long else (bar.high >= float(stop))
        hit_tgt = (target is not None
                   and ((bar.high >= float(target)) if long else (bar.low <= float(target))))

        if hit_stop and hit_tgt:
            return Outcome(kind=OutcomeKind.AMBIGUOUS, filled_at_index=filled,
                           closed_at_index=i, exit_price=None, r=None)
        if hit_stop:
            # ⚠ ОБЕ МОДЕЛИ ДАЮТ −1, и это не совпадение: до первой цели позиция целая,
            # делить нечего. Расходятся они только на выигрышах.
            return Outcome(kind=OutcomeKind.STOP, filled_at_index=filled,
                           closed_at_index=i, exit_price=stop, r=-1.0, r_partial=-1.0)
        if hit_tgt:
            assert target is not None
            gain = (target - entry) if long else (entry - target)
            return Outcome(kind=OutcomeKind.TARGET, filled_at_index=filled,
                           closed_at_index=i, exit_price=target, r=float(gain / risk),
                           r_partial=floor_r(i))

    if filled is None:
        return Outcome(kind=OutcomeKind.NOT_FILLED, filled_at_index=None,
                       closed_at_index=None, exit_price=None, r=None)
    return Outcome(kind=OutcomeKind.OPEN, filled_at_index=filled,
                   closed_at_index=None, exit_price=None, r=None)

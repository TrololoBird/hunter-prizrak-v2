"""Профиль объёма ИЗ СВЕЧЕЙ. Реализация `TradeWindows` поверх свечей младших ТФ:
до 2026-08-18 — всегда минутных, теперь разрешение выбирает длина окна (`TVWindows`,
лестница `PROFILE_LADDER`).

⚠ ЧИСТЫЙ МОДУЛЬ: часы, сеть и глобальное состояние не трогаются. Бары передаются извне.

## Почему профиль строится по свечам, а не по сделкам

Решение владельца 2026-08-12. До него источником были отдельные сделки `aggTrade`, и это
держалось на ОДНОЙ фразе в скобках из первого коммита проекта («профиль объёма строится
на реальных сделках (aggTrade)») — без страницы курса, без цитаты корпуса, без строки
документации.

Три свидетельства против неё, все проверяемые:

1. **Жанр так не делает.** Двадцать чужих проектов склонированы и прогреплены: сигнальные
   боты берут свечи и отдельных сделок не берут вовсе (`CryptoSignal/Crypto-Signal` —
   5.6 тыс. звёзд, два вызова ccxt: `fetch_ohlcv` и `load_markets`). `aggTrade`
   встречается только у библиотек рыночных данных — cryptofeed, nautilus_trader,
   binance-public-data;
2. **Инструмент автора курса делает так же.** Документация TradingView: «Volume profile
   indicators are calculated using data from lower timeframes for the same symbol» — для
   дневной сессии грузятся МИНУТНЫЕ бары, а не тики;
3. **Замер против разметки автора не показал преимущества тиков.** Лучшая клетка таблицы
   свечная: ETH, 5м, 14 из 16 при равном числе уровней и медиане расстояния 0.03·ATR
   против 0.13·ATR у тикового; там же тиковый источник бьёт лишь 1 сдвиговый контроль из
   4, свечной — 4 из 4.

⚠ Замер при этом НЕ доказал и превосходства свечей: на BTC знак обратный. Разбор
называет это шумом и прямо говорит, что решение по таким числам принимать нельзя —
владелец принял его, зная это. Цена вопроса измерена и она на стороне свечей: сутки BTC
через `aggTrades` стоят 3500 единиц веса, через минутные свечи — 6.

Полный разбор: `docs/audit/poc-candles-vs-ticks-2026-08-12.md`

## Как объём свечи попадает в профиль

Объём бара раскладывается РАВНОМЕРНО по всем ценовым бинам его диапазона `low…high`.
Это семейство TradingView, и приближение здесь названо честно: внутри бара цена не
проводит одинаковое время на каждом уровне, и никакая свеча этого не знает. Чем младше
разрешение, тем меньше цена приближения; с 2026-08-18 разрешение выбирает длина окна
(лестница `PROFILE_LADDER`), размен точности замерен — см. `TV_INTRABAR_MAX_BARS`.

Второй способ, «весь объём в бин цены закрытия» (так делает `volume_by_price` у
`Haehnchen/crypto-trading-bot`), ПРОВЕРЕН и ОТВЕРГНУТ: он хуже на обоих символах и всех
разрешениях замера.
"""

from __future__ import annotations

import bisect
from collections import OrderedDict
from decimal import Decimal

import numpy as np

from .bars import tf_ms
from .models import Bar, NotReady, TradeHistogram, tick_scale

PROFILE_LADDER = ("1m", "5m", "15m", "1h", "4h", "1d")
TV_INTRABAR_MAX_BARS = 5000
"""Кап числа intrabar-свечей на окно профиля. Применяется с 2026-08-18 по приказу
владельца (п. 3).

⚠ ЧЬЁ ЭТО ПРАВИЛО, названо точно (исправлено 2026-08-18 по находке аудита: прежняя
редакция склеивала в одну «цитату» настоящую фразу TV и предложение, которого у TV
нет). У TradingView дословно только это
(tradingview.com/support/solutions/43000502040-volume-profile/, перечитано 2026-08-18):
«Volume profile indicators are calculated using data from lower timeframes for the
same symbol» и — о выборе разрешения — «The particular logic used to decide which
lower timeframe should be used for the calculation varies depending on the specific
indicator». То есть TV подтверждает ПРИНЦИП (профиль из свечей младшего ТФ, выбор
разрешения зависит от длины задачи), но ни числа 5000, ни лестницы не публикует.
Число 5000 и лестница 1м…1Д (без 30м — наши аналитические ТФ) ПОДОБРАНЫ НАМИ и
держатся на собственном замере, а не на цитате.

Замер точности размена, ДО принятия (зонд 2026-08-18, сравнено 3194 окна BTC+ONDO из
3977 зон карты): ПОК по свечам своего ТФ отстоит от минутного на ~2 строки сетки —
медиана одинакова на всех ТФ; это заметно лучше случайной строки (строка-в-строку
21–23% против 2.5–3% у случайной). Цена размена: часть профилей по ТФ-свечам не
строится из-за ничьей за ПОК (444+419 отказов, систематически короткие окна) —
медианы посчитаны по благополучной подвыборке. Мотив: до правила intrabar-ТФ был
всегда 1м, и полугодовое окно суточной структуры требовало ~259 000 минуток — отсюда
минуты на сборку карты. Свод и контроль случайной строки — в разделе 20 журнала
смены 2026-08-17 и вердикте фальсификатора."""

MAX_BINS_PER_BAR = 200_000
"""Предел ширины одного бара в бинах. Свеча шире — свидетельство битых данных, а не
рынка: при шаге цены 0.1 это диапазон в 20 000 единиц котировки внутри одной минуты.
Такой бар в профиль НЕ идёт и СЧИТАЕТСЯ (`bars_too_wide`), потому что молчаливый пропуск
читался бы как «разложили всё»."""


_WindowKey = tuple[str, str, str, int, int, int, int]
_WINDOW_CACHE: OrderedDict[_WindowKey, TradeHistogram] = OrderedDict()
_WINDOW_CACHE_MAX = 40
_CACHE_MIN_BARS = 43_200
"""Кэш ДОРОГИХ окон профиля, переживающий циклы службы (2026-08-17).

Диагноз замером (evidence/profile-live-pipeline и зонд одного вызова): окно во весь
минутный ряд BTC стоит 9.2 с, 30-суточное — 0.9 с, и КАЖДЫЙ цикл службы строил их
заново — экземпляр `CandleWindows` живёт один цикл, а окна закрытых структур между
циклами НЕ МЕНЯЮТСЯ. Отсюда расчётная фаза в часы на 27 символах.

Устройство честности: ключ несёт ОТПЕЧАТОК ДАННЫХ (длина ряда и метка последнего бара
в окне) — дорос ряд, изменилось окно → ключ другой, пересчёт; никакой инвалидации по
времени. Кэшируются только окна от `_CACHE_MIN_BARS` минуток (30 суток): дешёвые
(63 мс на двух сутках) выгоднее пересчитать, чем держать. Ёмкость 40 — это композиты
VRVP всех символов вселенной плюс годовые окна старших ТФ.

⚠ Возвращается ОБЩИЙ объект: контракт потребителей — только чтение (build_level и
_with_vrvp гистограмму не мутируют). Значения при попадании в кэш БАЙТ-В-БАЙТ те же,
что при пересчёте, — это тот же объект, порядок сложений не менялся вовсе."""


def intrabar_timeframe(duration_ms: int) -> str:
    """ТФ intrabar-свечей окна по правилу TV: первый из лестницы с < 5000 баров.

    Для окон длиннее лестницы (полгода и более на 1Д не бывает при горизонте 180 суток)
    честно отдаётся старшая ступень — отказ по покрытию назовёт `CandleWindows.window`.
    """
    for tf in PROFILE_LADDER:
        if duration_ms // tf_ms(tf) < TV_INTRABAR_MAX_BARS:
            return tf
    return PROFILE_LADDER[-1]


class TVWindows:
    """Профиль по правилу TV: intrabar-ТФ выбирается ДЛИНОЙ окна, а не задан навсегда.

    Контракт `TradeWindows` (один метод `window`). Держит по `CandleWindows` на каждый
    переданный ряд и на каждое окно делегирует тому, кого выбрало правило
    `intrabar_timeframe`. Ряды приходят готовыми (минутки — из хранилища, аналитические
    ТФ — из собранных рядов прогона): модуль остаётся чистым, I/O здесь нет.

    ⚠ Отсутствие ряда выбранного ТФ — НЕ тихий даунгрейд на соседний: правило одно на
    все окна, подмена ТФ по доступности дала бы профили, несравнимые между собой.
    Отказ называется (§4.3), как и отказ покрытия внутри `CandleWindows`.
    """

    def __init__(self, symbol: str, tick: Decimal,
                 series: dict[str, list[Bar]]) -> None:
        self.symbol = symbol
        self._sources = {tf: CandleWindows(symbol, tick, bars, tf)
                         for tf, bars in series.items() if bars}
        self.windows_refused = 0
        self.refused_by_tf: dict[str, int] = {}
        """Отказы «ряда нужного ТФ не собрано» ПО ТФ — измерение, вдоль которого
        возможен перекос (правило сводки отказов); читает `run.decide_once`."""

    def series_by_tf(self) -> dict[str, list[Bar]]:
        """Ряды, которыми РЕАЛЬНО строятся профили, по ТФ. Читает `run.persist_source`:
        повтор (§10.6) обязан получить те же свечи, а не перечитать хранилище, которое
        к моменту повтора доросло, — иначе дифф объявит «расчёт изменился» на доливке."""
        return {tf: src.bars for tf, src in self._sources.items()}

    def window(self, from_ms: int, to_ms: int) -> TradeHistogram | NotReady:
        tf = intrabar_timeframe(to_ms - from_ms)
        src = self._sources.get(tf)
        if src is None:
            self.windows_refused += 1
            self.refused_by_tf[tf] = self.refused_by_tf.get(tf, 0) + 1
            return NotReady(
                reason=f"{self.symbol}: окну {from_ms}..{to_ms} по правилу TV нужны "
                       f"свечи {tf}, а ряда {tf} не собрано")
        return src.window(from_ms, to_ms)


class CandleWindows:
    """Профиль по окну из свечей. Контракт `TradeWindows`: один метод `window`.

    ⚠ ПОКРЫТИЕ ПРОВЕРЯЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ. Если в окне нет баров или в нём есть
    дыра длиннее одного шага разрешения, отдаётся `NotReady` с числом пропущенных баров.
    Без этой проверки неполное окно дало бы профиль, неотличимый от полного, — ровно тот
    класс дефекта, из-за которого §4.3 требует называть причину, а не отдавать пустое.
    """

    def __init__(self, symbol: str, tick: Decimal, bars: list[Bar],
                 timeframe: str = "1m") -> None:
        self.symbol = symbol
        self.tick = tick
        self.timeframe = timeframe
        self.step = tf_ms(timeframe)
        self.bars = sorted(bars, key=lambda b: b.open_ms)
        self._keys = [b.open_ms for b in self.bars]
        self.bars_too_wide = 0
        """Баров, отвергнутых как неправдоподобно широкие. Пара к построенным профилям."""

        self.windows_built = 0
        self.windows_refused = 0
        """Сколько окон построено и сколько отвергнуто. Ноль отказов при ненулевых
        построениях — свидетельство покрытия, а не отсутствия проверки."""

    def window(self, from_ms: int, to_ms: int) -> TradeHistogram | NotReady:
        i = bisect.bisect_left(self._keys, from_ms)
        j = bisect.bisect_left(self._keys, to_ms)
        cache_key = None
        if j - i >= _CACHE_MIN_BARS:
            cache_key = (self.symbol, self.timeframe, str(self.tick), from_ms, to_ms,
                         j - i, self._keys[j - 1] if j > i else 0)
            hit = _WINDOW_CACHE.get(cache_key)
            if hit is not None:
                _WINDOW_CACHE.move_to_end(cache_key)
                self.windows_built += 1
                return hit
        chunk = self.bars[i:j]
        if not chunk:
            self.windows_refused += 1
            return NotReady(
                reason=f"{self.symbol}: окно {from_ms}..{to_ms} не покрыто свечами "
                       f"{self.timeframe}")
        want = max(1, (to_ms - from_ms) // self.step)
        if len(chunk) < want:
            self.windows_refused += 1
            return NotReady(
                reason=f"{self.symbol}: окно {from_ms}..{to_ms} покрыто свечами "
                       f"{self.timeframe} не полностью — {len(chunk)} из {want}")

        h = TradeHistogram(symbol=self.symbol, tick_size=self.tick)
        # ⚠ РАЗНОСТНЫЙ МАССИВ, А НЕ ЦИКЛ ПО БИНАМ КАЖДОГО БАРА. Прямое добавление доли
        # объёма в каждый бин диапазона стоит O(баров × бинов): на минутных свечах BTC
        # это порядка тринадцати миллионов операций НА ОДНО ОКНО, и зонд с такой
        # реализацией не досчитывался вовсе. Здесь каждому бару правятся только концы
        # его отрезка, а один проход префиксной суммы разворачивает это в профиль —
        # O(баров + ширина диапазона).
        #
        # Равенство обоих способов ПРОВЕРЕНО, а не предположено: наибольшее расхождение
        # 9.1e-13 при масштабе 1.5e+03 на шести прогонах зонда
        # зонд probe_author_candles_2026-08-12 (удалён 19.08).
        #
        # ⚠ С 2026-08-18 те же формулы считает numpy, и равенство здесь СТРОГОЕ, а не
        # «до эпсилона». Порядок операций с плавающей точкой сохранён нарочно:
        #   * бинирование — то же выражение, что в `models.bin_index`
        #     (floor(price·scale + 0.5) // step), теми же float64;
        #   * правки концов отрезков идут ЧЕРЕДУЯСЬ по барам — пары (+доля, −доля)
        #     в порядке баров, как в прежнем цикле, — `np.add.at` без буферизации
        #     исполняет их последовательно (a −= s и a += (−s) в IEEE 754 совпадают);
        #   * префиксная сумма — последовательный `np.cumsum`, как прежний `run +=`;
        #   * `qty_seen` — ЯВНЫЙ цикл `+=` по объёмам в порядке баров. Ни `np.sum`
        #     (попарное суммирование), ни встроенный `sum` (с Python 3.12 — компенсация
        #     Ноймайера, см. CPython gh-100425) порядок прежних сложений не повторяют:
        #     диагностический зонд 2026-08-18 поймал на `sum` расхождение в 1 ulp —
        #     единственную разошедшуюся стадию из пяти.
        # Равенство бит-в-бит проверено пробником window_eq_probe 2026-08-18: дословная
        # копия прежнего скалярного цикла против этого кода, окон сравнено 8118,
        # разошлось 0 (отпечаток кэша на момент замера; первый прогон на 8114 окнах
        # поймал расхождение qty_seen — см. пункт про sum() выше). Диффом повтора это
        # НЕ держится: повтор строит профиль из архивных сделок, свечной путь ему не виден.
        lows = np.array([b.low for b in chunk], dtype=np.float64)
        highs = np.array([b.high for b in chunk], dtype=np.float64)
        vols = np.array([b.volume for b in chunk], dtype=np.float64)
        scale, step = tick_scale(self.tick)
        k0s = np.floor(lows * scale + 0.5).astype(np.int64) // step
        k1s = np.floor(highs * scale + 0.5).astype(np.int64) // step
        widths_bins = k1s - k0s + 1
        keep = widths_bins <= MAX_BINS_PER_BAR
        self.bars_too_wide += int(np.count_nonzero(~keep))
        k0s, k1s, widths_bins = k0s[keep], k1s[keep], widths_bins[keep]
        vols_kept = vols[keep]
        if k0s.size == 0:
            self.windows_refused += 1
            return NotReady(
                reason=f"{self.symbol}: окно {from_ms}..{to_ms} — все {len(chunk)} свечей "
                       f"отвергнуты как неправдоподобно широкие")
        h.trades_seen = int(k0s.size)
        qty_seen = 0.0
        for v in vols_kept.tolist():
            qty_seen += v
        h.qty_seen = qty_seen
        # ⚠⚠ РАВНОМЕРНАЯ РАСКЛАДКА — ЭТО НАШ ВЫБОР, А НЕ ПРАВИЛО ВЕНДОРА. Прежняя
        # редакция этой строки (от 2026-08-22, утро) утверждала обратное: «TradingView
        # кладёт объём бара РОВНО ПОРОВНУ… "A bar spanning 5 rows adds one fifth of its
        # volume to each" (сводка справки и разборов TV)». УТВЕРЖДЕНИЕ ОТОЗВАНО в тот же
        # день: фраза найдена только в пересказах третьих лиц, а на страницах вендора её
        # нет. Перечитаны в этот день: страница Volume Profile
        # (tradingview.com/support/solutions/43000502040-volume-profile/), страница
        # Fixed range volume profile drawing tool (…/43000707985-…) и справочник другого
        # вендора — thinkorswim VolumeProfile. НИ ОДИН не описывает, как объём ОДНОГО
        # бара ложится на строки, которые накрывает его диапазон.
        #
        # Что источником ПОДТВЕРЖДЕНО (та же страница TV, перечитана 2026-08-22) — это
        # ПРИНЦИП, и он у нас исполнен лестницей `PROFILE_LADDER`: «Volume profile
        # indicators are calculated using data from lower timeframes for the same
        # symbol»; для дневной сессии грузятся МИНУТНЫЕ бары. То есть TV не раскладывает
        # объём крупного бара — он спускается на младший ТФ. Вопрос раскладки остаётся
        # только для САМОЙ МЕЛКОЙ ступени, и вендор о нём молчит.
        #
        # Чужие реализации расходятся 2:1 ПРОТИВ нас (прочитаны по исходникам
        # 2026-08-22): `pedrobraiti/volume-profile-trading` и Sentinel-Lite кладут объём
        # ПО ДОЛЕ ПЕРЕКРЫТИЯ строки с диапазоном бара; equity-VAP у Crocodile делит
        # поровну, как мы.
        #
        # ⚠ ЦЕНА ВЫБОРА ЗАМЕРЕНА, А НЕ ОБЪЯВЛЕНА МАЛОЙ. Свежие REST-бары, боевое правило
        # выбора ступени (`intrabar_timeframe`), 2026-08-22:
        #   * ширина intrabar-бара в строках сетки: медиана 3, p90 7, максимум 49;
        #     в ОДНУ строку укладывается лишь 3.5% баров, шире трёх строк — 49.1%
        #     (4040 баров). То есть краевые строки решают, а не являются мелочью;
        #   * смена правила двигает СТРОКУ ПОК у 35.3% окон (6 из 17), медиана сдвига
        #     0.064% цены, максимум 1.62%. Объём сохраняется в обоих правилах (проверено
        #     сравнением сумм).
        # ПРАВИЛО НЕ МЕНЯЕТСЯ, и причина не в том, что разница мала — она не мала.
        # Причина в критерии: цель проекта — совпадение с РАЗМЕТКОЙ АВТОРА, а такого
        # замера по корпусу для двух правил ещё не делали. Менять расчёт по бенчмарку
        # против тиковой истины запрещено тем же доводом, которым ниже отклонена
        # треугольная раскладка. ⚠ ЭТО ОТКРЫТЫЙ ВОПРОС, а не закрытый.
        #
        # ⚠ И ЗДЕСЬ ЖЕ ОТКЛОНЕНО «УЛУЧШЕНИЕ», КОТОРОЕ БУДЕТ СОБЛАЗНЯТЬ СНОВА. Досье
        # (06-binance-data-sources.md, §4.2) провело свой бенчмарк против 17 180 335
        # aggTrades за 15 суток BTCUSDT и показало, что треугольная раскладка с пиком в
        # hlc3 точнее равномерной: на СУТОЧНОМ окне медиана |ΔПОК| $60 против $160,
        # ΔПОК/диапазон 2.1% против 5.9%. Числа правдоподобны, и всё же переходить
        # НЕЛЬЗЯ: бенчмарк меряет согласие с ТИКОВОЙ ИСТИНОЙ, а наша цель — согласие с
        # РАЗМЕТКОЙ АВТОРА, который смотрит в TradingView.
        # ⚠ Довод «прибор автора равномерен, значит треугольная увела бы нас от него»
        # СНЯТ 2026-08-22 вместе с утверждением выше: чем прибор автора раскладывает
        # объём мельчайшего бара, неизвестно. Довод против треугольной остаётся, но он
        # теперь ОДИН и он про критерий: тиковая истина нам судьёй не назначена.
        # Иерархия проекта решает это однозначно, и замер её не отменяет.
        share = vols_kept / widths_bins
        k_lo = int(k0s.min())
        k_hi = int(k1s.max())
        width = k_hi - k_lo + 2
        diff = np.zeros(width, dtype=np.float64)
        edge_idx = np.empty(2 * k0s.size, dtype=np.int64)
        edge_val = np.empty(2 * k0s.size, dtype=np.float64)
        edge_idx[0::2] = k0s - k_lo
        edge_idx[1::2] = k1s - k_lo + 1
        edge_val[0::2] = share
        edge_val[1::2] = -share
        np.add.at(diff, edge_idx, edge_val)
        run = np.cumsum(diff[: width - 1])
        positive = run > 0.0
        h.qty_by_bin = dict(zip(
            (np.nonzero(positive)[0] + k_lo).tolist(),
            run[positive].tolist(), strict=True))
        if not h.qty_by_bin:
            self.windows_refused += 1
            return NotReady(reason=f"{self.symbol}: в окне {from_ms}..{to_ms} нет объёма")
        self.windows_built += 1
        if cache_key is not None:
            _WINDOW_CACHE[cache_key] = h
            while len(_WINDOW_CACHE) > _WINDOW_CACHE_MAX:
                _WINDOW_CACHE.popitem(last=False)
        return h

class Emission(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    level: Level
    setup: Setup
    agreement: Agreement

    @property
    def direction(self) -> str:
        return "long" if self.level.side is LevelSide.LONG else "short"

    @property
    def ledger_stop(self) -> Decimal:
        """Стоп для записи в леджер — ТОТ ЖЕ, что выставляется по карточке.

        ⚠ До 2026-08-05 здесь стоял `stop_risky`, и обоснование было такое: безопасный
        стоп курс задаёт диапазоном 1-3%, выбор внутри диапазона источником не сделан, а
        рисковый — единственный, заданный одним числом.

        Довод был верен, пока выбор не делался НИГДЕ. Но следствие из него — леджер мерил
        сделку с одним стопом, а карточка предлагала оператору три, и совпадали они лишь
        случайно. Теперь стоп выбирается по стр. 18 (за стоповым объёмом либо проколом) и,
        если якоря нет, по стр. 33 запасом; леджер обязан записывать именно его, иначе он
        измеряет не то, что советует.
        """
        return self.setup.stop


def hold_reason(status: LevelStatus) -> str:
    """Почему уровень НЕ торгуется лимитками. Пустая строка — торгуется.

    Правило, а не обход: единственный обход пула живёт в `engine.decide`. Здесь только
    ответ по одному статусу, и он словами, а не булевым.

    ⚠ Формулировка называет, что МОЖНО, а не только чего нельзя. «Уровень неактивен» —
    это запрет без разрешения: оператор читает его как «уровень мёртв», а курс в обоих
    случаях оставляет вход, просто другой (стр. 31 и 43). То же различение уже сделано в
    `levels.EntryRule`, и текст берётся из его же страниц.
    """
    if status.state is LevelState.WORKED_OFF:
        return ("отработан на первое касание — стр. 25 «мы этот уровень удаляем»; "
                "вход только по слому структуры на младшем ТФ (стр. 31)")
    if status.state is LevelState.FLIPPED:
        return ("пробит и флипнут — стр. 43 «Уровень лонг/шорт менятся для нас на "
                "противоположный»; вход по ретесту в ДРУГУЮ сторону")
    if status.price_beyond:
        # Стр. 43: пробитый уровень «менятся для нас на противоположный»; стр. 7: пробой —
        # это «когда цена проходит». Цена стоит по ту сторону ВСЕЙ структуры, значит
        # лонговый уровень выше цены — уже не поддержка, а сопротивление. Вердикта
        # прокол-или-пробой может ещё не быть (`BreachKind.OPEN`), поэтому уровень не
        # снят, но лимитками не торгуется. Заведено 2026-08-18 по приказу владельца о
        # наслоении встречных зон: у 25–35% активных уровней цена стояла не с той стороны.
        return ("цена ушла ЗА структуру уровня — стр. 43 «Уровень лонг/шорт менятся для "
                "нас на противоположный»; вход только по возврату цены, лимитками "
                "уровень больше не торгуется")
    if status.price_in_zone:
        # Стр. 44, вариант 2: «Приоритет – не открывать позицию, если цена уже торгуется
        # в зоне, либо быть готовым выйти в б/у при пробое уровня – на ретесте».
        # Правка аудита 2026-08-07, находка М-09: правила не было ни в §2, ни в коде.
        #
        # Проверяется ПОСЛЕ состояний: у отработанного и пробитого уровня своя причина, и
        # она точнее. Здесь остаётся случай «уровень жив, но цена уже внутри зоны».
        return ("цена уже торгуется в зоне уровня — стр. 44 «Приоритет – не открывать "
                "позицию, если цена уже торгуется в зоне»; ждать выхода из зоны либо "
                "быть готовым выйти в б/у на ретесте")
    if not status.limit_orders_allowed:
        # Уровень ещё активен, но цена его уже касалась. Стр. 25: «уровень был отработан
        # на 1 касание… мы этот уровень удаляем и ищем новые не отработанные уровни»;
        # вход со второго-третьего касания — только по слому структуры на младшем ТФ.
        return ("цена уже касалась уровня — стр. 25 «этот уровень становиться больше не "
                "актуальным»; вход со 2-3 касания только по слому структуры на младшем ТФ")
    return ""


class TFBucket(StrEnum):
    """Три корзины, по которым стр. 48 требует баланса: «должен соблюдаться баланс
    кол-ва сделок/отложек по СТФ, локальным уровням и МТФ»."""

    SENIOR = "senior"
    LOCAL = "local"
    JUNIOR = "junior"


TF_BUCKET = {
    "1w": TFBucket.SENIOR,
    "1d": TFBucket.SENIOR,
    "4h": TFBucket.SENIOR,
    "1h": TFBucket.LOCAL,
    "15m": TFBucket.LOCAL,
    "5m": TFBucket.JUNIOR,
}
"""Состав корзин назван ТОЙ ЖЕ страницей, а не подобран: стр. 48 «Любое крупное движение
по рынку - дамп/памп и т.п. – идет чаще всего по 4ч-1Д уровням» (СТФ; 1н старше и идёт
туда же), стр. 48 «Чтобы выйти из трейда 15м-1ч ТФ» (локальные интрадей), стр. 48
«иногда хватает и 5мин тф для отработки» (МТФ). ⚠ МТФ/СТФ у автора — понятия
ОТНОСИТЕЛЬНЫЕ (стр. 4 «МТФ/СТФ - младший таймфрейм / старший таймфрейм»), поэтому
раскладка держится на конкретных ТФ, названных стр. 48, а не на самих словах."""


class TFCount(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    timeframe: str
    bucket: TFBucket | None
    """None — этот ТФ стр. 48 не называет; такие ТФ перечислены в `TFBalance.unlisted`,
    а не растворены в корзинах."""

    count: int
    share_pct: float


class BucketCount(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    bucket: TFBucket
    count: int
    share_pct: float
    timeframes: tuple[str, ...]


class TFBalance(BaseModel):
    """Сколько отложек по каждому ТФ и по каждой корзине стр. 48. Со знаменателем."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    total: int
    by_timeframe: tuple[TFCount, ...]
    by_bucket: tuple[BucketCount, ...]
    unlisted: tuple[str, ...]
    note: str
    """Готовая строка для карточки; пусто — отложек нет вовсе."""


_BUCKET_WORD = {
    TFBucket.JUNIOR: "МТФ",
    TFBucket.LOCAL: "локальные",
    TFBucket.SENIOR: "СТФ",
}

_BALANCE_RULE = (
    "Стр. 48: «должен соблюдаться баланс кол-ва сделок/отложек по СТФ, локальным уровням и МТФ». "
    "«Важно не выставлять сразу много отложек по МТФ» (стр. 48), "
    "«при дампе они все получат стоп» (стр. 48). "
    "Сколько отложек считать многими, курс не называет — счёт предъявляется оператору, "
    "отсева по нему нет"
)


def _balance_note(
    total: int,
    by_tf: tuple[TFCount, ...],
    by_bucket: tuple[BucketCount, ...],
    unlisted: tuple[str, ...],
) -> str:
    if total == 0:
        return ""
    per_tf = ", ".join(f"{c.timeframe} {c.count} ({c.share_pct:.0f}%)" for c in by_tf)
    per_bucket = ", ".join(f"{_BUCKET_WORD[b.bucket]} {b.count}" for b in by_bucket)
    tail = f"; ТФ вне разбивки стр. 48: {', '.join(unlisted)}" if unlisted else ""
    return (f"баланс отложек — всего {total}: {per_tf}; по корзинам: {per_bucket}. "
            f"{_BALANCE_RULE}{tail}")


def tf_balance(emissions: Sequence[Emission]) -> TFBalance:
    """Разбивка отложек по ТФ и по корзинам стр. 48 — ПРЕДУПРЕЖДЕНИЕ, а не отсев.

    Отсекать сигналы по этому счёту нельзя: числа баланса стр. 48 не даёт, а порог на
    выходе спрятал бы ровно те сигналы, по которым видны ошибки расчёта зон и целей.
    Поэтому здесь только счёт со знаменателем и текст правила курса.

    Область счёта задаёт вызывающий: карточка считает по символу, леджер — по прогону.
    Порядок ТФ — от младшего к старшему, чтобы разбивка была одинаковой при повторе.
    """
    counts: dict[str, int] = {}
    for em in emissions:
        counts[em.level.timeframe] = counts.get(em.level.timeframe, 0) + 1
    total = sum(counts.values())
    # ТФ, которого нет в шкале, идёт В КОНЕЦ и попадает в `unlisted`: неизвестный шаг —
    # это не «самый младший», и молча ставить его первым значило бы соврать порядком.
    order = sorted(counts, key=lambda tf: (tf not in TIMEFRAME_MS, TIMEFRAME_MS.get(tf, 0), tf))
    by_tf = tuple(
        TFCount(timeframe=tf, bucket=TF_BUCKET.get(tf), count=counts[tf],
                share_pct=counts[tf] / total * 100 if total else 0.0)
        for tf in order
    )
    by_bucket: list[BucketCount] = []
    for bucket in (TFBucket.JUNIOR, TFBucket.LOCAL, TFBucket.SENIOR):
        tfs = tuple(tf for tf in order if TF_BUCKET.get(tf) is bucket)
        n = sum(counts[tf] for tf in tfs)
        by_bucket.append(BucketCount(bucket=bucket, count=n,
                                     share_pct=n / total * 100 if total else 0.0,
                                     timeframes=tfs))
    unlisted = tuple(tf for tf in order if tf not in TF_BUCKET)
    return TFBalance(total=total, by_timeframe=by_tf, by_bucket=tuple(by_bucket),
                     unlisted=unlisted,
                     note=_balance_note(total, by_tf, tuple(by_bucket), unlisted))


def first_bar_after(bars: list[Bar], timeframe: str, since_ms: int, not_before: int) -> int:
    """Индекс первого бара, ЗАКРЫВШЕГОСЯ позже `since_ms`. `len(bars)` — таких нет.

    `not_before` — нижняя граница поиска (бар появления уровня): раньше неё сделки быть
    не может по стр. 23, даже если момент записи ещё старше.

    ⚠ ДВОИЧНЫЙ ПОИСК, А НЕ ЛИНЕЙНЫЙ (правка 2026-08-23). Здесь стоял проход циклом от
    `not_before` до конца ряда, при том что `levels`, `figures` и `profile_source` в
    этом же проекте уже везде на `bisect`. Ряд отсортирован по `open_ms` по построению
    (`barstore.append` завершается `sort`, кадры пишутся отсортированными), а условие
    `open_ms + step > since_ms` монотонно по индексу — значит место перехода ищется
    делением пополам. Зовётся функция на КАЖДЫЙ дорешиваемый сигнал леджера.

    Ответ ТОТ ЖЕ по построению: `bisect_right` по ключу `open_ms` даёт первый бар с
    `open_ms > since_ms - step`, то есть ровно первый, у которого `open_ms + step >
    since_ms` (метки целые, строгое неравенство сохраняется).
    """
    step = tf_ms(timeframe)
    lo = max(not_before, 0)
    if lo >= len(bars):
        return len(bars)
    return bisect.bisect_right(bars, since_ms - step, lo=lo,
                               key=lambda b: b.open_ms)


def outcome_of(em: Emission, bars: list[Bar], since_ms: int) -> Outcome:
    """Исход по барам, закрывшимся ПОСЛЕ `since_ms`. Цель — первая ОСНОВНАЯ (стр. 24).

    ⚠ `since_ms` — момент ЗАПИСИ сигнала в леджер, а не рождения уровня. Разница между
    ними и есть разница между журналом и бэктестом. Прежняя редакция считала от бара
    появления уровня, а он может лежать на сотни баров в прошлом: исход вычислялся по
    истории, УЖЕ ИЗВЕСТНОЙ на момент записи, и каждый прогон переигрывал её заново.
    §8 этап 7 называет леджер «единственным будущим источником ответа на вопрос,
    работает ли метод», а отвечал он на вопрос «как отработала бы история».

    Следствие честное и неприятное: у только что записанного сигнала исхода нет и быть
    не может. Он дописывается позже, по мере поступления новых баров.
    """
    # ⚠ Роль сравнивается ПЕРЕЧИСЛЕНИЕМ, а не строкой (правка 2026-08-23). Здесь стояло
    # `t.role.value == "primary"` — единственное такое место в проекте (`geometry.Setup.rr`
    # и `card.render` сравнивают члены enum). Переименование значения `TargetRole.PRIMARY`
    # молча обнулило бы ВСЕ исходы «по цели», и не поймал бы этого ни mypy, ни гейт:
    # сравнение строки со строкой законно всегда.
    #
    # ⚠⚠ СОБСТВЕННЫЙ ФИЛЬТР СНЯТ 2026-08-24: правило «какая цель считается первой» жило
    # ЗДЕСЬ, в `Setup.rr` и в `run.py` тремя копиями. Теперь оно одно —
    # `geometry.first_major`.
    first = first_major(em.setup.targets)
    # ВТОРАЯ крупная цель — только для модели частичного выхода (Ф5, 2026-08-26): к ней
    # идёт остаток после первого тейка (стр. 15). Правило «крупности» то же самое, второй
    # копии фильтра здесь нет — см. `geometry.next_major`.
    second = next_major(em.setup.targets)
    return resolve(
        side=em.level.side,
        entry=em.setup.entry,
        stop=em.ledger_stop,
        target=first.price if first is not None else None,
        bars=bars,
        from_index=first_bar_after(bars, em.level.timeframe, since_ms,
                                  em.level.created_at_index + 1),
        # ⚠⚠ БЕЗУБЫТОК ЗДЕСЬ НЕ ПЕРЕДАВАЛСЯ ВОВСЕ (правка 2026-08-24), и это давало ДВА
        # разных правила под одним именем «исход». Тот же сигнал, дорешанный позже из
        # леджера (`run._resolve_pending`), считался С безубытком — `breakeven_at`
        # хранится в таблице с v9, — а посчитанный здесь, в момент записи, БЕЗ него.
        # Что попадёт в колонку `outcome`, зависело от того, успел ли сигнал разрешиться
        # в том же прогоне; ни один инвариант этого не ловил, потому что обе ветки
        # возвращают законный `Outcome`.
        breakeven_at=breakeven_watch(em.setup.breakeven_rules),
        target2=second.price if second is not None else None,
    )

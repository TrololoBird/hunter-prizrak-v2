"""Что подлежит эмиссии и с каким исходом. FOUNDATION.md §8 этапы 6-7.

ЧИСТЫЙ МОДУЛЬ (§10.3): часы, сеть и глобальное состояние не трогаются. Запись в леджер
и отправка — дело вызывающего; здесь только ПРАВИЛО отбора, и оно обязано быть
воспроизводимо.

Отбирается по курсу, без единого собственного правила:
  стр. 23  уровня нет, пока цена не вышла из структуры → берутся только закрытые
  стр. 25  отработанный на первое касание уровень «удаляем»
  стр. 31  после отработки «уровень лимитными ордерами больше не торгуем»
  стр. 43  пробитый уровень флипается — прежним он больше не является
  стр. 18  «первая позиция всегда берётся по тренду»; стр. 47 — приоритет старшего ТФ

Согласие с приоритетом НЕ фильтрует: стр. 47 разрешает позицию против приоритета «в виде
хэджа и/или на уменьшенный объём риска». Поэтому она эмитится, но помечена — решение за
оператором, а не за кодом (§1: «Оператор торгует руками»).

⚠ Здесь была функция `select`, которая ПРОХОДИЛА по размеченным уровням и строила
эмиссии. Она удалена 2026-08-06 и заменена на `hold_reason` — предикат от одного статуса.
Причина в том, что `select` была ВТОРЫМ обходом того же пула: первый делала `card.render`,
и они расходились. Замер на кадрах прогона `a1`: карточка печатала геометрию для 94
уровней, `select` эмитировала 33. Обход теперь один и живёт в `engine.decide`, а курсовое
правило — здесь, рядом со своими цитатами.
"""

from __future__ import annotations

from decimal import Decimal

from pydantic import BaseModel, ConfigDict

from .bars import tf_ms
from .geometry import Setup
from .levels import Level, LevelSide, LevelState, LevelStatus
from .models import Bar
from .outcome import Outcome, resolve
from .priority import Agreement


class Emission(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    level: Level
    setup: Setup
    agreement: Agreement

    @property
    def direction(self) -> str:
        return "long" if self.level.side is LevelSide.LONG else "short"

    @property
    def ledger_stop(self) -> Decimal:
        """Стоп для записи в леджер — ТОТ ЖЕ, что выставляется по карточке.

        ⚠ До 2026-08-05 здесь стоял `stop_risky`, и обоснование было такое: безопасный
        стоп курс задаёт диапазоном 1-3%, выбор внутри диапазона источником не сделан, а
        рисковый — единственный, заданный одним числом.

        Довод был верен, пока выбор не делался НИГДЕ. Но следствие из него — леджер мерил
        сделку с одним стопом, а карточка предлагала оператору три, и совпадали они лишь
        случайно. Теперь стоп выбирается по стр. 18 (за стоповым объёмом либо проколом) и,
        если якоря нет, по стр. 33 запасом; леджер обязан записывать именно его, иначе он
        измеряет не то, что советует.
        """
        return self.setup.stop


def hold_reason(status: LevelStatus) -> str:
    """Почему уровень НЕ торгуется лимитками. Пустая строка — торгуется.

    Правило, а не обход: единственный обход пула живёт в `engine.decide`. Здесь только
    ответ по одному статусу, и он словами, а не булевым.

    ⚠ Формулировка называет, что МОЖНО, а не только чего нельзя. «Уровень неактивен» —
    это запрет без разрешения: оператор читает его как «уровень мёртв», а курс в обоих
    случаях оставляет вход, просто другой (стр. 31 и 43). То же различение уже сделано в
    `levels.EntryRule`, и текст берётся из его же страниц.
    """
    if status.state is LevelState.WORKED_OFF:
        return ("отработан на первое касание — стр. 25 «мы этот уровень удаляем»; "
                "вход только по слому структуры на младшем ТФ (стр. 31)")
    if status.state is LevelState.FLIPPED:
        return ("пробит и флипнут — стр. 43 «Уровень лонг/шорт менятся для нас на "
                "противоположный»; вход по ретесту в ДРУГУЮ сторону")
    if not status.limit_orders_allowed:
        # Уровень ещё активен, но цена его уже касалась. Стр. 25: «уровень был отработан
        # на 1 касание… мы этот уровень удаляем и ищем новые не отработанные уровни»;
        # вход со второго-третьего касания — только по слому структуры на младшем ТФ.
        return ("цена уже касалась уровня — стр. 25 «этот уровень становиться больше не "
                "актуальным»; вход со 2-3 касания только по слому структуры на младшем ТФ")
    return ""


def first_bar_after(bars: list[Bar], timeframe: str, since_ms: int, not_before: int) -> int:
    """Индекс первого бара, ЗАКРЫВШЕГОСЯ позже `since_ms`. `len(bars)` — таких нет.

    `not_before` — нижняя граница поиска (бар появления уровня): раньше неё сделки быть
    не может по стр. 23, даже если момент записи ещё старше.
    """
    step = tf_ms(timeframe)
    for i in range(max(not_before, 0), len(bars)):
        if bars[i].open_ms + step > since_ms:
            return i
    return len(bars)


def outcome_of(em: Emission, bars: list[Bar], since_ms: int) -> Outcome:
    """Исход по барам, закрывшимся ПОСЛЕ `since_ms`. Цель — первая ОСНОВНАЯ (стр. 24).

    ⚠ `since_ms` — момент ЗАПИСИ сигнала в леджер, а не рождения уровня. Разница между
    ними и есть разница между журналом и бэктестом. Прежняя редакция считала от бара
    появления уровня, а он может лежать на сотни баров в прошлом: исход вычислялся по
    истории, УЖЕ ИЗВЕСТНОЙ на момент записи, и каждый прогон переигрывал её заново.
    §8 этап 7 называет леджер «единственным будущим источником ответа на вопрос,
    работает ли метод», а отвечал он на вопрос «как отработала бы история».

    Следствие честное и неприятное: у только что записанного сигнала исхода нет и быть
    не может. Он дописывается позже, по мере поступления новых баров.
    """
    primary = [t for t in em.setup.targets if t.role.value == "primary"]
    return resolve(
        side=em.level.side,
        entry=em.setup.entry,
        stop=em.ledger_stop,
        target=primary[0].price if primary else None,
        bars=bars,
        from_index=first_bar_after(bars, em.level.timeframe, since_ms,
                                  em.level.created_at_index + 1),
    )

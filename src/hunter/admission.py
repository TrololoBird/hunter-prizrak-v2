# Для допуска берётся строгое из двух.
REQUIRED_BARS: dict[str, int] = {
    q: max(DEFINED_FROM_BARS.get(q, 0), CANONICAL_FROM_BARS.get(q, 0))
    for q in set(DEFINED_FROM_BARS) | set(CANONICAL_FROM_BARS)
}


# Величины, которые §2.9 называет ДОСЛОВНО: «RSI, MACD (дивергенция/конвергенция),
# полосы Боллинджера…, MA/EMA 200». Референт списка — сам КУРС, сверка 2026-08-17
# (docs/audit/indicators-course-2026-08-17.md): RSI/MACD — стр. 64-67 («индикатор
# используется только как дополнительный фактор к нашей точке входа», стр. 64);
# полосы Боллинджера — стр. 68 («Чем сильнее сузились эти линии - тем быстрее будет
# выход из структуры»); MA/EMA 200 — стр. 69 («выбираем длина 200»). ADX ни на одной
# из 69 страниц НЕ значится — он сверен с формулой (§10.2 называет его среди тех, что
# не писать самим), но системой не используется и порог допуска задавать не должен.
# ⚠ ATR УДАЛЁН ИЗ ПРОЕКТА 2026-08-21 (приказ владельца). Здесь стояло «ATR — не
# индикатор §2.9, а единица измерения порогов по §4.1»: единицей он служил двум порогам
# геометрии, и оба сняты вместе с ним. В курсе ATR не встречается ни разу на 69
# страницах; все меры автора — проценты и касания. Разбор — `range.MAX_PAIR_PCT`.
USED_BY_2_9: tuple[str, ...] = ("rsi14", "macd", "bb_upper", "ema200")


def strictest_requirement() -> int:
    """Самое длинное требование среди величин, которые §2.9 действительно называет."""
    return max(REQUIRED_BARS[q] for q in USED_BY_2_9)


def seed_floor() -> int:
    """Нижняя граница глубины ряда: строжайшее среди величин, которые система СЧИТАЕТ.

    Это §2.9 (`USED_BY_2_9`, строжайшее — ema200 с 200). ⚠ До 2026-08-21 сюда входил
    ещё `atr14` (15 баров, поглощались двумястами); ATR из проекта удалён, и слагаемое
    ушло вместе с ним, не изменив результата.

    ⚠ До 2026-08-17 нижней границей стоял `max(REQUIRED_BARS.values())` — то есть 304
    бара от `adx14`. Ложь была двойной: докстроки называли 304 «требованием §2.9», хотя
    §2.9 ADX не упоминает (см. `USED_BY_2_9` выше), а сам adx14 не считается ни одной
    строкой `src` — он лежит в таблице справочно, для оракула CI. Глубина, выведенная из
    величины без потребителя, — число без референта (§0). Поймано фальсификацией разбора
    ссылок §N: docs/audit/session-2026-08-17-auto.md."""
    return strictest_requirement()


# ⚠ `available(quantity, bars)` УДАЛЕНА 2026-08-06: потребителя не было. Тот же вопрос
# задают `check` (с причиной) и `unavailable_quantities` (списком) — булево между ними
# было третьим ответом на один вопрос.


def check(quantity: str, bars: int, symbol: str, timeframe: str) -> NotReady | None:
    """None — величину считать можно. NotReady — нельзя, с причиной (§4.3)."""
    need = REQUIRED_BARS.get(quantity)
    if need is None:
        return NotReady(reason=f"{quantity}: требование к истории не замерено")
    if bars < need:
        return NotReady(
            reason=f"{symbol} {timeframe}: {quantity} требует {need} баров, есть {bars}"
        )
    return None


def unavailable_quantities(bars: int) -> list[str]:
    return sorted(q for q, need in REQUIRED_BARS.items() if bars < need)


def admits(bars_by_timeframe: dict[str, int], required: int) -> tuple[bool, list[str]]:
    """Проходит ли символ порог `required` баров на КАЖДОМ заявленном ТФ.

    Возвращает (проходит, список ТФ, которые не дотягивают). Порог передаётся
    аргументом, а не берётся из константы: это решение владельца о политике, а не
    свойство данных.
    """
    short = sorted(tf for tf, n in bars_by_timeframe.items() if n < required)
    return (not short), short

"""Где лежат данные и конфигурация. ОДНО место на проект.

⚠⚠ ЗАВЕДЕНО 2026-08-23 ПО РАЗБОРУ АРХИТЕКТУРЫ. Пути были зашиты ОТНОСИТЕЛЬНЫМИ в шести
местах пяти модулей: `Path("data")`, `Path("data/bars")`, `Path("data/aggcache")`,
`Path("data/sent")`, `Path("config/universe.toml")`, `Path("config/bot.toml")`. Из этого
следовали две вещи, обе молчаливые:

  * поведение зависело от ТЕКУЩЕГО КАТАЛОГА процесса. Служба, запущенная из другого
    места, честно создавала пустой склад рядом с собой и начинала собирать историю с
    нуля — а выглядело это как «биржа отдаёт мало»;
  * перенести данные на другой диск было нельзя не правя код. У службы 24/7, чей склад
    баров растёт только временем, это не мелочь: место кончается раньше, чем история
    становится достаточной.

Теперь корень берётся из окружения (`HUNTER_DATA_DIR`, `HUNTER_CONFIG_DIR`), а по
умолчанию остаётся прежним — `data` и `config` от текущего каталога. Умолчание НЕ
меняет поведения ни у кого, кто не задал переменную: это условие правки, а не оговорка.

⚠ Переменная читается ОДИН РАЗ при импорте, а не на каждом обращении. Иначе один и тот
же прогон мог бы писать бары в два разных места, если кто-то поменяет окружение
посреди работы, — и разошлись бы не пути, а ДАННЫЕ.

⚠ Пустое значение переменной трактуется как незаданное: `HUNTER_DATA_DIR=` — это почти
наверняка обрыв подстановки в скрипте запуска, а `Path("")` означает текущий каталог,
то есть склад лёг бы прямо в корень проекта. Молча принять такое нельзя (§4.3).
"""

from __future__ import annotations

import os
from pathlib import Path


def _from_env(name: str, default: str) -> Path:
    value = os.environ.get(name, "").strip()
    return Path(value) if value else Path(default)


DATA_DIR = _from_env("HUNTER_DATA_DIR", "data")
"""Корень всего, что копится: склад баров, кэш сделок, кадры прогонов, леджер."""

CONFIG_DIR = _from_env("HUNTER_CONFIG_DIR", "config")
"""Корень конфигурации: вселенная и настройки бота."""

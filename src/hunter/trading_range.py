class TradingRange(BaseModel):
    """Закрытая структура: границы известны, выход подтверждён.

    Незакрытых структур этот модуль не отдаёт — стр. 23: «пока цена не вышла из
    структуры, у нас нет уровня».
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    _box: dict[tuple[int, int, int], tuple[float, float] | None] = (
        PrivateAttr(default_factory=dict))
    """Память `box()`: отпечаток ряда → коробка. НЕ поле модели."""

    _start: dict[tuple[int, int, int], int] = PrivateAttr(default_factory=dict)
    """Память `start_index()`: отпечаток ряда → первый бар структуры. НЕ поле модели."""

    def start_index(self, bars: list[Bar]) -> int:
        """Первый бар структуры на этом ряду: считается по разу.

        Память — по тому же доводу и с тем же ключом, что у `box()`: обратный проход
        короткий (медиана 5 баров), но `structure_bars` зовут в тех же горячих циклах,
        где коробку звали 12 миллионов раз.
        """
        key = _series_key(bars)
        if key not in self._start:
            self._start[key] = _structure_start(self, bars)
        return self._start[key]

    def box(self, bars: list[Bar]) -> tuple[float, float] | None:
        """Коробка ХАЙ…ЛОЙ этой структуры на этом ряду: считается по разу.

        ⚠ ЗАЧЕМ ПАМЯТЬ. Замер BTC на боевых глубинах (`cProfile`): коробка одной и той
        же структуры пересчитывалась для каждой пары (уровень, структура) и для каждого
        хозяина стопового объёма — 12 099 220 вызовов генератора `min`/`max` за один
        символ. Значение тождественно: та же функция, тот же ряд, тот же порядок.

        `_structure_box` и `_series_key` объявлены НИЖЕ по файлу (им нужен
        `structure_bars`, а тому — этот класс). Имена в теле метода разрешаются в
        момент ВЫЗОВА, а не определения, поэтому порядок «сначала объект, потом
        операции над ним» сохраняется без единого трюка.
        """
        key = _series_key(bars)
        if key not in self._box:
            self._box[key] = _structure_box(self, bars)
        return self._box[key]

    timeframe: str
    first_index: int
    last_index: int
    upper: BoundaryZone
    lower: BoundaryZone
    exit: StructureExit
    earliest_index: int = 0
    """Левее этого бара структуре расти нельзя: там ПРЕДЫДУЩАЯ структура того же ТФ.

    Ноль у первой структуры ряда. Поле нужно только `_structure_start`: продление влево
    без него залезало на соседа у 57.3% структур (замер 2026-08-21, BTC+ETH+SOL, 3433
    структуры), а это двойной счёт — один бар отдавал бы объём в ДВА профиля. Ровно то
    «наслоение», которое владелец нашёл глазами 2026-08-18.

    Стр. 40 рисует соседние базы ребром к ребру, а не внахлёст; стр. 23 говорит, что
    уровень появляется, «когда цена полноценно выходит из структуры», — значит вышла
    она из предыдущей до того, как начала новую."""

    @property
    def points(self) -> int:
        return len(self.upper.point_indices) + len(self.lower.point_indices)

    @property
    def upper_touches(self) -> int:
        """Касаний ВЕРХНЕЙ границы — стр. 57: «ждем 6 касание и берем на 6 касании»."""
        return self.upper.touches

    @property
    def lower_touches(self) -> int:
        """Касаний НИЖНЕЙ границы (стр. 57, 58)."""
        return self.lower.touches

    @property
    def touches(self) -> int:
        """Касаний обеих границ — оно же сквозной номер последней точки (схема стр. 18).

        Курс нумерует касания сквозь сторону, поэтому «6 касание» стр. 57 — это шестая
        точка структуры по времени, а не шестая на своей стороне. При чередовании сторон
        сквозной номер последней принятой точки и есть общее число касаний.
        """
        return self.points

    @property
    def is_clear(self) -> bool:
        """Дотянула ли структура до второго числа курса — стр. 23: «(4+6+ точки границ)».

        НЕ фильтр: структура с четырьмя точками остаётся структурой (стр. 22, 24). Это
        отметка «видно чётко», чтобы разница между 4 и 6 точками была предъявлена, а не
        спрятана в отсечке. См. CLEAR_STRUCTURE_POINTS.
        """
        return self.points >= CLEAR_STRUCTURE_POINTS

    @property
    def extended_hi(self) -> float:
        """Верх РАСШИРЕННОГО диапазона базы (стр. 18) — прокол, если он был."""
        return self.upper.extended_edge

    @property
    def extended_lo(self) -> float:
        """Низ РАСШИРЕННОГО диапазона базы (стр. 18) — прокол, если он был."""
        return self.lower.extended_edge

    @property
    def is_extended(self) -> bool:
        """Есть ли расширение хотя бы с одной стороны — стр. 18 про 3++ точки."""
        return self.upper.puncture is not None or self.lower.puncture is not None

    @property
    def is_long(self) -> bool:
        """Лонговое накопление — из которого цена вышла вверх (стр. 22)."""
        return self.exit.direction is Direction.ABOVE


class OpenStructure(BaseModel):
    """Структура, из которой цена ещё не вышла. Уровня по стр. 23 у неё нет.

    Существует, чтобы её было ВИДНО (§4.3). Незакрытая структура — это не «ничего не
    нашли»: она может стоять сутками, и молчать о ней значит выдавать пустоту за покой.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    first_index: int
    bars_open: int
    upper: BoundaryZone
    lower: BoundaryZone

    @property
    def points(self) -> int:
        return len(self.upper.point_indices) + len(self.lower.point_indices)

    @property
    def upper_touches(self) -> int:
        return self.upper.touches

    @property
    def lower_touches(self) -> int:
        return self.lower.touches

    @property
    def touches(self) -> int:
        """Касаний обеих границ. Здесь это нужнее, чем у закрытой структуры: вход по
        стр. 57 берётся НА шестом касании, то есть пока структура ещё не закрыта."""
        return self.points

    @property
    def is_clear(self) -> bool:
        """Стр. 23: «(4+6+ точки границ)». См. CLEAR_STRUCTURE_POINTS."""
        return self.points >= CLEAR_STRUCTURE_POINTS

    @property
    def extended_hi(self) -> float:
        return self.upper.extended_edge

    @property
    def extended_lo(self) -> float:
        return self.lower.extended_edge

    @property
    def is_extended(self) -> bool:
        return self.upper.puncture is not None or self.lower.puncture is not None


class RangeScan(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    closed: tuple[TradingRange, ...]
    open_tail: OpenStructure | None
    bars_scanned: int
    rejected: int
    """Сколько НАЧАЛ отвергнуто: попыток, которые не дали структуры.

    ⚠⚠ ВЕЛИЧИНА СМЕНИЛА СМЫСЛ 2026-08-23 ВМЕСТЕ С ПЕРЕПИСЫВАНИЕМ `detect`, И ПОЭТОМУ
    СМЕНИЛА ИМЯ. Звалась `resets` и считала распады ОДНОГО сквозного прохода. Проходов
    больше нет: водитель пробует начать структуру с каждого свинга и при неудаче делает
    шаг вправо (см. докстроку `detect`), поэтому счётчик считает ОТВЕРГНУТЫЕ НАЧАЛА и
    растёт примерно как число свингов, не ставших структурой.

    Имя сменено, а не оставлено: «распадов» печатается ВЛАДЕЛЬЦУ в карточке, и две
    разные величины под одним человеческим именем — дефект по построению.
    """

    _boxes: dict[tuple[int, int, int], tuple[tuple[float, float] | None, ...]] = (
        PrivateAttr(default_factory=dict))
    """Память `boxes()`: отпечаток ряда → коробки всех закрытых структур. НЕ поле."""

    def boxes(self, bars: list[Bar]) -> tuple[tuple[float, float] | None, ...]:
        """Коробка ХАЙ…ЛОЙ каждой закрытой структуры, в порядке `closed`.

        `None` там, где отрезок структуры пуст, — это НЕ то же самое, что коробка
        нулевой высоты, и потребитель обязан различать (`structure_bars` может вернуть
        пустой список, и прежний код на этом делал `continue`).

        ⚠⚠ ЗАВЕДЕНО 2026-08-21 ПО ЗАМЕРУ, а не «для красоты». Коробка структуры от
        уровня НЕ ЗАВИСИТ — это `min(low)`/`max(high)` по `structure_bars`, — но
        `levels.pressed_structures` считала её заново для КАЖДОЙ пары (уровень,
        структура). Профиль BTC на боевых глубинах (`cProfile`): 736 уровней × ~1400
        структур, генератор `min/max` вызван 12 099 220 раз, вся функция — 44.8 с из
        164 с расчёта, то есть 27%. Здесь тот же ответ считается по разу на структуру.

        ⚠ ОТПЕЧАТОК РЯДА В КЛЮЧЕ — не перестраховка. `RangeScan` родился из `detect(bars)`
        и по смыслу принадлежит именно тому ряду, но НИЧТО в типах этого не держит:
        потребитель волен подать другой список, и тогда молчаливая память вернула бы
        коробки чужого ряда. Отпечаток (длина, первая и последняя метки) делает такую
        подмену видимой — память просто пересчитается, а не соврёт.
        """
        key = _series_key(bars)
        if (got := self._boxes.get(key)) is None:
            got = self._boxes[key] = tuple(acc.box(bars) for acc in self.closed)
        return got


def _series_key(bars: list[Bar]) -> tuple[int, int, int]:
    """Отпечаток ряда для памяти коробок: длина и края.

    Не `id(bars)`: список после сборки мусора отдаёт свой адрес другому списку, и память
    вернула бы коробки ЧУЖОГО ряда — молча. Тот же довод уже записан в `stop_volume`,
    где ключ несёт ещё и символ: ряды разных символов выровнены одним окном бэкфилла и
    по длине с краями совпадают.
    """
    return (len(bars), bars[0].open_ms if bars else 0,
            bars[-1].open_ms if bars else 0)


def _structure_start(acc: TradingRange, bars: list[Bar]) -> int:
    """Первый бар структуры: `first_index`, продлённый ВЛЕВО, пока свеча внутри базы.

    ⚠⚠ ЗАВЕДЕНА 2026-08-21 ПО ПРИКАЗУ ВЛАДЕЛЬЦА «чини структуру, чтобы захватывала
    свечи целиком». `first_index` — это индекс ПЕРВОЙ ПРИНЯТОЙ ТОЧКИ ГРАНИЦЫ
    (`min(hi_idx + lo_idx)` в `detect`), то есть первого подтверждённого фрактала. А
    цена входит в диапазон РАНЬШЕ: до первого фрактала она успевает походить внутри
    будущих границ, и эти свечи не попадали ни в коробку, ни в профиль.

    Критерий взят из стр. 18, а не придуман: «Флэт (рэндж, база, накопление) — движение
    цены в горизонтальном ценовом диапазоне» и там же «Цена ходит от одной границы к
    другой». Значит бар, целиком лежащий между двумя рёбрами базы, — бар этой базы. Проход
    останавливается на первом баре, который из рёбер вышел: это и есть момент входа
    цены в диапазон, дальше влево идти нечем.

    Требование стр. 26 «важно захватить ВСЕ свечи структуры» относится к ПРОФИЛЮ, и
    именно профиль от этой правки и меняется.

    ЗАМЕР, ради которого правка сделана (BTC+ETH+SOL, 6 ТФ, 3433 закрытых структуры):
    у 71.3% слева от `first_index` стоят свечи, ЦЕЛИКОМ лежащие между рёбрами самой
    структуры, — медиана 5 баров, p90 39, максимум 395.

    ⚠ КОНТРОЛЬ ДВУСТОРОННИЙ, иначе число ничего не значит. Тот же счёт от СЛУЧАЙНОГО
    места ряда с теми же рёбрами даёт 3.7% и медиану 0. То есть критерий отличает
    «перед структурой» от «где попало» в девятнадцать раз, а не срабатывает всюду.

    ⚠ Рёбра берутся ПРОСТЫЕ (`edge`), а не расширенные проколом (`extended_edge`).
    Проколы стр. 18 расширили бы проход ещё левее; узкий вариант — нижняя оценка, и
    ошибается он в сторону «взяли меньше», а не «взяли чужое».

    ⚠ КОРОБКА ОТ ЭТОГО НЕ РАСТЁТ ЗА РЁБРА: добавляются только бары, целиком лежащие
    между `lower.edge` и `upper.edge`. Сдвинуть коробку они могут лишь там, где ребро
    УНАСЛЕДОВАНО у соседней структуры (лесенка стр. 40) и потому лежит дальше
    собственных баров, — и даже там коробка упирается в ребро. Замер: коробка не
    изменилась НИ У ОДНОЙ из 3433 структур, то есть границы уровня, стоп и геометрия
    правкой не тронуты вовсе — меняется только профиль.

    ⚠⚠ ЛЕВАЯ СТЕНА (`earliest_index`) — не осторожность, а исправление второго дефекта,
    найденного этим же замером. Без неё продление залезало на ПРЕДЫДУЩУЮ структуру того
    же ТФ у 57.3% случаев (крайний пример: ETH 15м, структура из 261 бара забирала 397
    чужих). Один бар отдавал бы объём в два профиля сразу — то самое наслоение.

    ЖИВАЯ ПРОВЕРКА 2026-08-21, две карточки BTC на одних свежих барах (прогоны
    `btcstruct` и `btcstruct-before` обновили ряды, карточки посчитаны обоими расчётами
    по ним). Цена 77381.8. Уровней стало 10 против 9: добавился 1ч лонг 73745.8. У всех
    девяти общих ПОК СОВПАЛ до десятой доли, а зона сдвинулась у пяти — шире всего у 4ч
    лонга 74642.9 (3.94% → 5.15% от цены) и у 1ч лонга 72152.8, чья зона уехала вниз
    (71316.2…73160.9 → 70629.8…72646.1).

    ⚠ НА СОВПАДЕНИЕ С РАЗМЕТКОЙ АВТОРА ПРАВКА НЕ ПОВЛИЯЛА: по его линиям 76750, 79099.3,
    79900.2, 80780.0, 82866.4 обе карточки дают одно и то же. Значит правка чинит ПРОФИЛЬ,
    а расхождение с автором держится на чём-то другом и остаётся неразобранным.
    """
    lo, hi = acc.lower.edge, acc.upper.edge
    i = acc.first_index
    while i > acc.earliest_index:
        b = bars[i - 1]
        if b.low < lo or b.high > hi:
            break
        i -= 1
    return i


def _structure_box(acc: TradingRange, bars: list[Bar]) -> tuple[float, float] | None:
    """Коробка ХАЙ…ЛОЙ структуры: `None`, если отрезок пуст.

    ⚠⚠ ЕДИНСТВЕННОЕ МЕСТО, ГДЕ КОРОБКА СЧИТАЕТСЯ. До 2026-08-21 та же пара `min`/`max`
    по `structure_bars` стояла в ЧЕТЫРЁХ местах: `levels.build_all` (границы уровня),
    `levels.pressed_structures` (конфигурации стр. 28), `stop_volume.classify`
    (плотность стопового объёма) и `RangeScan.boxes`. Совпадали они по счастливой
    случайности — четыре копии одной формулы, и разойтись им ничто не мешало.

    Именно так и родился дефект, который владелец нашёл глазами 2026-08-18: «границы»
    карточки и коробка профиля оказались разными величинами под одним именем. Здесь
    копий больше нет — есть одна функция и память при структуре.
    """
    seg = structure_bars(acc, bars)
    if not seg:
        return None
    return min(b.low for b in seg), max(b.high for b in seg)



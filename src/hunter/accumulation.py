class BoundaryZone(BaseModel):
    """Граница базы: ОДНА ЦЕНА `edge` плюс допуск приёма точек `lo…hi` (стр. 18).

    ⚠ Так стало 2026-08-08. Раньше границей считалась вся полоса, и наружу отдавался её
    ДАЛЬНИЙ край. Курс рисует границу базы одной тонкой линией — стр. 13, 18, 21, 23, 35,
    39; полоса в курсе есть у ПОК (стр. 30) и у уровня ПП (стр. 55), но не у ребра базы.
    На стр. 39 низ коробки выглядит двумя линиями, однако вторая — это ПОК стопового
    объёма, унаследованный как граница, а не толщина ребра.

    ⚠⚠ КАКАЯ ИМЕННО ЦЕНА — ВОПРОС НЕ ЗАКРЫТ, И ЭТА ДОКСТРОКА ДО 2026-08-11 ЛГАЛА.
    Она описывала внутренний край пары, тогда как код с 2026-08-11 берёт ВНЕШНИЙ
    (`max(hi_px)` / `min(lo_px)`). Расхождение кода с собственной докстрокой прожило
    ноль дней только потому, что его искали; полный разбор обоих прочтений и всех
    доводов — docs/DEFINITIONS.md §2.2. Здесь коротко.

    Прочтение А (внутренний край, стояло 2026-08-08 … 2026-08-11): стр. 13 определяет
    флэт так, что локальные хаи и лои ПОВТОРЯЮТСЯ; уровень, на котором обе первые точки
    стороны побывали, — их внутренний край. Схема стр. 13 не опровергает: нижняя линия
    проходит по точке 2, а точка 4 лежит НИЖЕ неё, то есть прокол.

    Прочтение Б (внешний край, стоит сейчас): стр. 18 называет границы словами «хай и
    лой», а хай пары — это её максимум. При внутреннем крае вторая точка стороны
    становится проколом АВТОМАТИЧЕСКИ, до всякого рынка. Замер: ПОК внутри базы у 92.5%
    структур против 75.3% (docs/audit/poc-inside-base-2026-08-11.md).

    ⚠ Замер прочтение НЕ доказывает: мера «ПОК внутри базы» растёт от расширения границы
    монотонно, а внешний край её и расширяет. Решающий замер — сравнение с разметкой
    автора на корпусе — НЕ ПРОВЕДЁН. Внешняя классика (границы диапазона по экстремумам
    отскока и теста у Вайкоффа) склоняет к Б, нумерация схемы стр. 18 — к А.

    Заморозка — не оптимизация, а требование стр. 13: «локальные хаи/лои повторяются и
    НЕ МЕНЯЮТСЯ». Первая редакция расширяла зону каждым новым экстремумом, и замер
    2026-08-04 показал, к чему это ведёт: на тренде BTC 15м накопилось 39 верхних точек
    против 6 нижних, «граница» расползлась на 1.82%, структура не закрывалась 316 баров
    подряд, а `detect` об этом молчал. Протокол: docs/audit/stuck-structure-2026-08-04.md
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    edge: float
    """САМА граница — одна цена. За неё считается выход и за неё меряется прокол."""

    source: BorderSource = BorderSource.OWN
    """Откуда взялась цена границы: свои точки, лесенка или чужой ТФ.

    На схеме стр. 40 верхнее ребро прежней коробки служит нижним ребром следующей, и
    обе подписаны «Структура 4ч тф» — то есть лесенка складывается внутри одного ряда.
    Курс называет и другие чужие границы: ПОК прежнего стопового объёма (стр. 39) и
    уровень старшего ТФ (стр. 46, 54). Они были внесены и ОТКАЧЕНЫ 2026-08-08 —
    причина в докстроке BorderSource.
    """

    narrowed: int = 0
    """Сколько раз граница сдвинулась ВНУТРЬ — признак накопления в сужении (стр. 34).

    Стр. 34 называет базой и такую форму: сужение, поджатие и чёткие границы стоят там
    в одном ряду. На стр. 37 у базы в сужении границы нарисованы двумя НАКЛОННЫМИ
    сходящимися линиями, по три касания каждая, и выход из клина торгуется как обычный
    выход из накопления.

    Ноль означает «граница ни разу не двигалась» — обычная горизонтальная база."""

    lo: float
    hi: float
    point_indices: tuple[int, ...] = Field(min_length=2)

    puncture: float | None = None
    """Самый дальний заход ЗА `edge` без подтверждения выхода — за него ставится стоп.

    Стр. 18: «если на 3++ точках были проколы за границы — стоп всегда ставится за этот
    прокол». `None` означает «проколов не было», а не «неизвестно»: продюсер здесь один
    и он всегда отрабатывает.

    ⚠ 2026-08-08 смысл поля РАСШИРИЛСЯ, и это следствие того, что границей стала одна
    цена. Внешняя из первых двух точек стороны лежит за внутренним краем ПО ПОСТРОЕНИЮ,
    то есть тоже прокол. Ровно это нарисовано на стр. 13: нижняя линия базы проходит по
    точке 2, а точка 4 — вторая точка той же стороны — лежит НИЖЕ неё. Нумерация курса
    идёт через сторону, поэтому вторая точка стороны и есть третья-плюс точка стр. 18.

    ⚠ И записывается прокол НЕ ВСЯКИЙ: только начиная с третьей точки по сквозной
    нумерации — `MIN_PUNCTURE_ORDINAL`. Внешней в паре бывает и первая точка стороны, и
    её курс проколом не считает. Поэтому у пары прокол появляется ровно тогда, когда
    внешняя точка пришла ВТОРОЙ.

    Цена этого видна числом. Замер на 324 рядах: пока отбора по номеру не было, прокол
    имели 11271 зона из 11288 (99.8%) — поле не различало ничего; с отбором осталось 7179
    (63.6%). Читать поле как признак выхода цены за границу нельзя по-прежнему. Читать
    следует так: самая дальняя цена стороны, за которую ставится стоп по стр. 18.
    Замеры: docs/audit/probes/probe_accumulation_after_fixes_2026-08-08.py и
    docs/audit/probes/probe_two_point_sides_2026-08-08.py
    """

    @property
    def width_pct(self) -> float:
        """Ширина ДОПУСКА приёма точек в процентах. Это не граница — граница это `edge`.

        Курс задаёт критерий «чётко видно структуру» визуально; механического порога
        он не даёт, поэтому число сообщается наружу для калибровки на корпусе (этап 3),
        а не превращается в выдуманную отсечку.
        """
        mid = (self.lo + self.hi) / 2
        return 0.0 if mid == 0 else (self.hi - self.lo) / mid * 100

    @property
    def touches(self) -> int:
        """Сколько раз цена коснулась ЭТОЙ границы — число принятых точек стороны.

        Нужно для стр. 57 и 58: «ждем 6 касание и берем на 6 касании». Само правило
        вымпела живёт не здесь, здесь только счёт.

        Прокол считается касанием: на схеме стр. 18 точка 6 ушла за нижнюю линию и
        всё равно получила номер наравне с остальными. Касание внутри коробки — НЕ
        считается: стр. 21 такие заходы не нумерует, и `detect` их не принимает.
        """
        return len(self.point_indices)

    @property
    def extended_edge(self) -> float:
        """Граница РАСШИРЕННОГО диапазона: самый дальний прокол, иначе сама граница.

        Стр. 18: «стоп всегда ставится за этот прокол, т.к. это может быть расширением
        базы и в будущем цена может ходить уже в этом расширенном диапазоне». То есть у
        базы курс называет ДВА диапазона: рабочий (`edge`, по первым двум точкам) и
        расширенный, до прокола. На схеме стр. 18 это видно прямо: зелёная коробка
        стоит по точкам 1 и 2, а выше и ниже неё нарисованы красные линии с подписью
        "лимитный барьер" — и точки 6 и 8 уходят за зелёную линию к ним.

        `edge` НЕ переопределяется: стр. 13 требует, чтобы границы базы не менялись, а
        выход из структуры проверяется против рабочей границы. Расширенный диапазон —
        отдельная величина для тех, кому нужен он: стоп (стр. 18) и разметка будущего
        хода цены.

        Прокола не было — расширения нет, и возвращается `edge`. Значение всегда лежит
        НЕ БЛИЖЕ `edge` к середине базы: прокол записывается только за границей.
        """
        return self.edge if self.puncture is None else self.puncture

    @property
    def from_first_two_points(self) -> bool:
        """Взята ли граница ровно так, как описывает стр. 18, — первыми двумя точками.

        Стр. 18: «Границы базы (хай и лой) чаще всего определяются первыми 2-мя точками».
        Слова «чаще всего» означают, что бывает и иначе, и курс называет, как именно:
        унаследованное ребро соседней структуры — лесенка стр. 40 (`source`) — и база в
        сужении стр. 34, где граница едет внутрь вслед за точками (`narrowed`).

        Признак отвечает на вопрос «это обычный случай стр. 18 или один из двух
        названных исключений» и существует, чтобы долю исключений можно было СЧИТАТЬ.
        Молча превратить «чаще всего» во «всегда» — значит спрятать оба механизма.
        """
        return self.source is BorderSource.OWN and self.narrowed == 0



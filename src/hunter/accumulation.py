class Accumulation(BaseModel):
    """Закрытая структура: границы известны, выход подтверждён.

    Незакрытых структур этот модуль не отдаёт — стр. 23: «пока цена не вышла из
    структуры, у нас нет уровня».
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    timeframe: str
    first_index: int
    last_index: int
    upper: BoundaryZone
    lower: BoundaryZone
    exit: StructureExit

    @property
    def points(self) -> int:
        return len(self.upper.point_indices) + len(self.lower.point_indices)

    @property
    def upper_touches(self) -> int:
        """Касаний ВЕРХНЕЙ границы — стр. 57: «ждем 6 касание и берем на 6 касании»."""
        return self.upper.touches

    @property
    def lower_touches(self) -> int:
        """Касаний НИЖНЕЙ границы (стр. 57, 58)."""
        return self.lower.touches

    @property
    def touches(self) -> int:
        """Касаний обеих границ — оно же сквозной номер последней точки (схема стр. 18).

        Курс нумерует касания сквозь сторону, поэтому «6 касание» стр. 57 — это шестая
        точка структуры по времени, а не шестая на своей стороне. При чередовании сторон
        сквозной номер последней принятой точки и есть общее число касаний.
        """
        return self.points

    @property
    def is_clear(self) -> bool:
        """Дотянула ли структура до второго числа курса — стр. 23: «(4+6+ точки границ)».

        НЕ фильтр: структура с четырьмя точками остаётся структурой (стр. 22, 24). Это
        отметка «видно чётко», чтобы разница между 4 и 6 точками была предъявлена, а не
        спрятана в отсечке. См. CLEAR_STRUCTURE_POINTS.
        """
        return self.points >= CLEAR_STRUCTURE_POINTS

    @property
    def extended_hi(self) -> float:
        """Верх РАСШИРЕННОГО диапазона базы (стр. 18) — прокол, если он был."""
        return self.upper.extended_edge

    @property
    def extended_lo(self) -> float:
        """Низ РАСШИРЕННОГО диапазона базы (стр. 18) — прокол, если он был."""
        return self.lower.extended_edge

    @property
    def is_extended(self) -> bool:
        """Есть ли расширение хотя бы с одной стороны — стр. 18 про 3++ точки."""
        return self.upper.puncture is not None or self.lower.puncture is not None

    @property
    def is_long(self) -> bool:
        """Лонговое накопление — из которого цена вышла вверх (стр. 22)."""
        return self.exit.direction is Direction.ABOVE


class OpenStructure(BaseModel):
    """Структура, из которой цена ещё не вышла. Уровня по стр. 23 у неё нет.

    Существует, чтобы её было ВИДНО (§4.3). Незакрытая структура — это не «ничего не
    нашли»: она может стоять сутками, и молчать о ней значит выдавать пустоту за покой.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    first_index: int
    bars_open: int
    upper: BoundaryZone
    lower: BoundaryZone

    @property
    def points(self) -> int:
        return len(self.upper.point_indices) + len(self.lower.point_indices)

    @property
    def upper_touches(self) -> int:
        return self.upper.touches

    @property
    def lower_touches(self) -> int:
        return self.lower.touches

    @property
    def touches(self) -> int:
        """Касаний обеих границ. Здесь это нужнее, чем у закрытой структуры: вход по
        стр. 57 берётся НА шестом касании, то есть пока структура ещё не закрыта."""
        return self.points

    @property
    def is_clear(self) -> bool:
        """Стр. 23: «(4+6+ точки границ)». См. CLEAR_STRUCTURE_POINTS."""
        return self.points >= CLEAR_STRUCTURE_POINTS

    @property
    def extended_hi(self) -> float:
        return self.upper.extended_edge

    @property
    def extended_lo(self) -> float:
        return self.lower.extended_edge

    @property
    def is_extended(self) -> bool:
        return self.upper.puncture is not None or self.lower.puncture is not None



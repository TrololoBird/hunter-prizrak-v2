def margin_of(price: Decimal, pct: float) -> Decimal:
    """Величина запаса — проценты ОТ ЦЕНЫ, ровно как написано в курсе.

    ⚠ ОДНО ОПРЕДЕЛЕНИЕ ЗАПАСА НА ВЕСЬ ПРОЕКТ (правка 2026-08-24). До неё формула
    `цена · pct / 100` стояла в ЧЕТЫРЁХ местах: `with_margin` и `beyond_anchor` внутри
    `build_setup`, `tgbot._level_line` запасным путём и — нигде, то есть у вымпела
    (`figures.pennant`) её не было вовсе, хотя докстрока модуля утверждала, что запас
    «накладывает `geometry`». Три копии совпадали, четвёртая молча отсутствовала —
    ровно тот исход, ради которого CLAUDE.md запрещает вторую копию формулы.

    ⚠⚠ СЧЁТ «ЧЕТЫРЁХ МЕСТ» БЫЛ НЕПОЛОН, ПОПРАВЛЕНО В ТОТ ЖЕ ДЕНЬ РЕВИЗИЕЙ ДИФФА.
    Перепись перед правкой (правило «грепом перечислить, где величина ещё считается»)
    пропустила ещё ДВЕ живые копии в этом же файле: `build_stop_volume_setup` (та же
    формула на Decimal) и `build_pp_setup` (float-вариант `край · (1 ± pct/100)`).
    Полдня докстрока объявляла «одно определение на весь проект», пока стоп стопового
    объёма и стоп ПП считались мимо него, — прибор объявлял охват больше настоящего.
    Обе копии сведены сюда; у ПП float→Decimal→float меняет значение не больше чем на
    машинный ульп — на печати карточки это не видно ни в одном знаке.
    """
    return price * Decimal(str(pct)) / Decimal(100)


def stop_beyond_edge(edge: Decimal, pct: float, *, up: bool) -> Decimal:
    """Стоп ЗА границей структуры с запасом (стр. 58: «Стоп всегда прячем за всю
    структуру с запасом 1-3%»; о том же стр. 19, 33, 36).

    что из чего следует: сторона сделки и край структуры → цена стопа. Лонг прячет
    стоп НИЖЕ нижнего края, шорт — ВЫШЕ верхнего; «за» здесь означает «дальше от
    входа», и никакого второго прочтения у этого слова в курсе нет.

    Потолка запаса нет: ни одно из четырёх мест курса его не называет (разбор — в
    `build_setup.with_margin`, там же отзыв капа «не больше высоты базы» 2026-08-18).
    """
    raw = margin_of(edge, pct)
    return edge - raw if up else edge + raw



class TakeShare(BaseModel):
    """Какую ЧАСТЬ позиции курс велит крыть на этой цели. Заведено 2026-08-19.

    До этого доля жила одним полем `Setup.partial_take_pct` на всю сделку, и его не
    читал никто. Курс же задаёт долю ПО РОЛИ цели, и в трёх местах по-разному: 50% на
    первой фиксации (стр. 9, пример автора), 30-50% на границе базы хозяина в сделке от
    стопового (стр. 39), а на промежуточных — стр. 24 — «небольшими тейками», без числа
    вовсе.

    ⚠ Ссылка «50% на границе (стр. 19)» заменена 2026-08-24 по вопросу владельца: стр. 19
    флэтовая, разбор — в докстроке `PARTIAL_TAKE_PCT`.

    `min_pct is None` — доля курсом НЕ НАЗВАНА. Это отказ с причиной в `note`, а не
    ноль и не подставленное число (§4.3).
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    min_pct: float | None
    max_pct: float | None
    note: str


def take_share(role: TargetRole, *, first: bool = True) -> TakeShare:
    """Доля фиксации по роли цели И ПО ПОРЯДКУ. Все ответы — из курса, своих чисел нет.

    ⚠ `first` заведён 2026-08-19 по чтению карточки ГЛАЗАМИ: без него доля 50%
    печаталась на КАЖДОЙ основной цели, а их у 5м-уровня шесть — в сумме 300%
    позиции. Курс называет 50% для ПЕРВОЙ фиксации и только для неё: стр. 9, пример
    автора — «делаем тейк 50% и забираем 2Р». Долей ОСТАЛЬНЫХ целей курс не называет
    нигде, и подставлять её нельзя — остаток позиции ведётся по стр. 15 (тейки по
    достигнутым целям и стоп в б/у), а не по выдуманному проценту.

    ⚠ Референт «первой» правился 2026-08-24: стоял стр. 19 («По верхней границе – делаете
    тейк 50%»), а это правило ФЛЭТОВОЙ сделки — вход у границы, ход внутри коробки.
    Довод про 300% позиции от замены референта не зависит и остаётся в силе.
    """
    if role is TargetRole.INTERMEDIATE:
        return TakeShare(min_pct=None, max_pct=None,
                         note="стр. 24: «промежуточные цели с небольшими тейками» — "
                              "доли курс не называет")
    if role is TargetRole.BOUNDARY:
        # ⚠ Роль порождает ОДНА сделка от стопового объёма, и граница там — край базы
        # ХОЗЯИНА, то есть ДРУГОЙ структуры. Правило ей даёт стр. 39; ссылка на стр. 19
        # стояла здесь один день 2026-08-24 и снята вместе с отзывом (см. `build_targets`).
        return TakeShare(min_pct=BOUNDARY_TAKE_MIN_PCT, max_pct=BOUNDARY_TAKE_MAX_PCT,
                         note="стр. 39: «цель - верхняя граница, где кроем часть 30-50%»")
    if not first:
        return TakeShare(min_pct=None, max_pct=None,
                         note="доли курс не называет: 50% на стр. 9 сказано про ПЕРВУЮ "
                              "фиксацию; остаток ведётся по стр. 15")
    # ⚠ Референт заменён 2026-08-24: было «стр. 19: „делаете тейк 50% - но не 100%“» —
    # флэтовая страница в сделке от уровня. Разбор — докстрока `PARTIAL_TAKE_PCT`.
    return TakeShare(min_pct=PARTIAL_TAKE_PCT, max_pct=PARTIAL_TAKE_PCT,
                     note="стр. 9, пример автора: «делаем тейк 50% и забираем 2Р»; "
                          "доли ИМЕННО для сделки от уровня курс не называет — стр. 11 "
                          "и 16 говорят о первом тейке без числа")


MAJOR_TAKE_ROLES: frozenset[TargetRole] = frozenset(
    {TargetRole.PRIMARY, TargetRole.BOUNDARY})
"""Роли, на которых курс велит крыть БОЛЬШУЮ часть позиции, а не «небольшой тейк».

Разделение не наше: у первой цели стр. 9 даёт «делаем тейк 50% и забираем 2Р», у границы
базы хозяина стр. 39 — «цель - верхняя граница, где кроем часть 30-50%», а про
промежуточные стр. 24 говорит «могут быть взяты как промежуточные цели с НЕБОЛЬШИМИ
тейками» и доли не называет вовсе.

⚠ Ссылка на стр. 19 отсюда снята 2026-08-24 вместе с остальными: страница флэтовая,
разбор — в докстроке `PARTIAL_TAKE_PCT`.

⚠ Заведено 2026-08-24, и заведено как ОДНО определение на трёх потребителей: `Setup.rr`,
`emit.outcome_of` и запись цели в леджер (`run.py`) до этого дня каждый сам фильтровал
`role is TargetRole.PRIMARY`. Три копии одного правила — дефект по построению (правило
«величина считается в ОДНОМ месте»), и разошлись бы они молча: каждая ветка вернула бы
законную цель, просто разную. Появление роли `BOUNDARY` у обычной сделки как раз и есть
то изменение, на котором три копии разъехались бы."""


class Target(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    role: TargetRole
    price: Decimal
    timeframe: str
    distance_pct: float
    take: TakeShare
    """Доля фиксации ИМЕННО НА ЭТОЙ цели — `take_share(role)`."""


def first_major(targets: tuple[Target, ...]) -> Target | None:
    """Первая по ходу сделки цель с КРУПНЫМ тейком. None — таких нет.

    Цели приходят отсортированными по расстоянию (`build_targets`), поэтому «первая» —
    это просто первая подходящая. Промежуточные (стр. 24) пропускаются: позиция на них
    не закрывается, и мерить по ним РР значило бы называть РР сделки числом, до которого
    она доходит малой частью объёма."""
    return next((t for t in targets if t.role in MAJOR_TAKE_ROLES), None)



# ⚠⚠ ПОЛ «НЕ БЛИЖЕ 1R» БЫЛ ВВЕДЁН И ОТОЗВАН В ОДНУ СМЕНУ, 2026-08-24. Запись оставлена
# нарочно, чтобы правку не завели повторно.
#
# Повод был настоящий: на свежих данных того дня (Crypto.com, 23 символа, ТФ 15м/1ч/4ч
# по 300 баров, 132 размеченных уровня) порог взведения безубытка лежал на МЕДИАНЕ
# 0.131R, минимум 0.0031R, максимум 1.617R — разброс в пятьсот раз. Классический ТА по
# этому вопросу единогласен (Trading Heroes; бэктесты Quantified Strategies через
# atas.net; Olivito/liverium.com — перевод стопа на 10% пути до цели поднимает долю
# «выигрышей» вчетверо при падающем матожидании), и я поставил пол в 1R.
#
# Отозвано по ДВУМ причинам, каждой достаточно:
#   1. пол противоречит самому курсу. Стр. 19 задаёт ПОРЯДОК: «набираете позицию в Лонг
#      у нижней границы. Цена показала реакцию и ушла внутрь базы – ставите стоп в б/у.
#      По верхней границе – делаете тейк 50%». Безубыток стоит РАНЬШЕ тейка по границе,
#      а пол 1R ставит его ПОЗЖЕ: цель дальше 1R лишь у 8% сделок;
#   2. правило становится мёртвым. Пол оказался дальше цели у 121 сделки из 132 (92%) —
#      то есть взвестись не мог почти никогда. Мёртвое правило хуже неверного: оно не
#      видно.
#
# ⚠ Довод классики при этом НЕ опровергнут — он адресован другому объекту. Он верен для
# выхода ЦЕЛИКОМ, а курс на стр. 19 закрывает у границы 50% «- но не 100%». Безубыток
# там защищает ОСТАТОК позиции, а не всю. Наш `outcome.resolve` частичных выходов не
# знает вовсе и закрывает сделку первой целью — и вот в этой модели ранний безубыток
# действительно «улучшает» результат, подменяя стопы нулями: замер того же дня дал
# сумму R −1.79 против −16.22 без безубытка. Число красивое и НЕВЕРНОЕ, и лечится оно
# моделью частичного выхода, а не порогом. Открытый вопрос №6.


def build_breakeven_rules(
    *, inside_base: Decimal, level_price: Decimal, first_take: Decimal | None,
) -> tuple[BreakevenRule, ...]:
    """Условия перевода стопа в безубыток. Стр. 15, 19, 43, 44.

    `inside_base` — цена, по которой видно, что «цена показала реакцию и ушла внутрь
    базы» (стр. 19). Курс эту фразу не оцифровывает; РЕШЕНИЕ (2026-08-19): берётся
    ДАЛЬНИЙ по ходу сделки край объёмной зоны входа — за ним позиция уже набрана вся,
    и цена вышла из области набора внутрь базы. Решение меняется одним аргументом.

    ⚠ Известная слабость этой оцифровки НАЗВАНА, а не забыта: край зоны откалиброван по
    ширине ОБЪЁМНОЙ ЗОНЫ, а «база» стр. 19 — это структура от границы до границы. Из-за
    этого порог гуляет от 0.0031R до 1.617R (замер 2026-08-24). Открытый вопрос №6:
    числа там, менять расчёт без источника нельзя.

    `first_take` — цена ближайшей цели; None (целей нет) убирает правило стр. 15, но
    не остальные: б/у по стр. 19 и 44 от целей не зависит.

    ⚠ Цены правил встречаются и НА ПОДХОДЕ к уровню: `inside_base` — это тот же край
    зоны, через который цена входит, а `level_price` — сама ТВХ. Правила смотрят на
    них только ПОСЛЕ набора позиции: это сопровождение открытой сделки, а не вход.
    """
    out = [
        BreakevenRule(
            trigger=BreakevenTrigger.REACTION_INSIDE_BASE, watch_price=inside_base,
            note="стр. 19: «Цена показала реакцию и ушла внутрь базы – ставите стоп в б/у»"),
    ]
    if first_take is not None:
        out.append(BreakevenRule(
            trigger=BreakevenTrigger.PARTIAL_TAKE_DONE, watch_price=first_take,
            note="стр. 15: «Вы сделали тейки по достигнутым целям и передвинули стоп в бу»"))
    out.append(BreakevenRule(
        trigger=BreakevenTrigger.LEVEL_BREACH_RETEST, watch_price=level_price,
        note="стр. 44: «быть готовым выйти в б/у при пробое уровня – на ретесте»"))
    return tuple(out)


def breakeven_watch(rules: tuple[BreakevenRule, ...]) -> Decimal | None:
    """Цена, по достижении которой стоп реально переносится в ТВХ. None — правил нет.

    Из трёх правил стр. 15/19/44 расчёту исхода годится ровно ОДНО, и это не вопрос
    вкуса:
      * `LEVEL_BREACH_RETEST` смотрит на саму ТВХ (стр. 44 — пробой уровня и ретест).
        Как порог взведения это тавтология: сделка ОТКРЫВАЕТСЯ на этой цене, то есть
        условие выполнено в момент входа всегда;
      * `PARTIAL_TAKE_DONE` стоит на первой цели (стр. 15). Взведение и закрытие по цели
        приходятся на один бар, и порядок касаний внутри бара неизвестен — исход
        «в безубытке» становится недостижим;
      * `REACTION_INSIDE_BASE` (стр. 19) наступает раньше цели и потому вообще способен
        сработать.

    ⚠⚠ ВЫБИРАЕТСЯ ПО ТРИГГЕРУ, А НЕ ПО НОМЕРУ (2026-08-24). В `run.py` стояло
    `breakeven_rules[0].watch_price`, то есть правило выбиралось ПОЗИЦИЕЙ В СПИСКЕ.
    Довод «первое по ходу сделки» был записан в комментарии рядом и держался
    исключительно на порядке `append` внутри `build_breakeven_rules`: перестановка строк
    там молча сменила бы смысл величины, которая уходит в леджер, и ни mypy, ни гейт
    этого не увидели бы — индекс 0 законен при любом порядке."""
    for r in rules:
        if r.trigger is BreakevenTrigger.REACTION_INSIDE_BASE:
            return r.watch_price
    return None


def build_add_ons(
    *, entry: Decimal, first_take: Decimal | None, repeat_share_pct: float | None,
) -> tuple[AddOn, ...]:
    """Доливка и добор. Стр. 16, 19, 24.

    Оба вида идут ПОСЛЕ взятия цели — так их и описывает курс, — поэтому без цели
    список пуст: добирать не после чего, и молчаливой доливки «когда-нибудь» не бывает.

    `repeat_share_pct` — доля повторного добора на своём же уровне. 50% там, где курс
    называет число (стр. 19); None там, где не называет (стр. 39: «с низу каждый раз
    повторно откупаем», доли нет).
    """
    if first_take is None:
        return ()
    share_note = ("стр. 19: «добираете снова те же 50% позиции»"
                  if repeat_share_pct is not None
                  else "стр. 39: «с низу каждый раз повторно откупаем» — доли курс не даёт")
    return (
        AddOn(kind=AddOnKind.RETURN_TO_ENTRY, price=entry, trigger_price=first_take,
              share_pct=repeat_share_pct,
              note=share_note + "; условие стр. 19: нет доп факторов за разворот"),
        AddOn(kind=AddOnKind.NEW_LEVEL_AFTER_TAKE, price=None, trigger_price=first_take,
              share_pct=None,
              note="стр. 24: на новом уровне после коррекции можно «долить к текущей "
                   "позиции» — цена уровня в момент постройки сделки не существует"),
    )


def build_setup(
    level: Level,
    pool: tuple[MappedLevel, ...] = (),
    *,
    structural_anchor: Decimal | None = None,
    margin_min_pct: float = STOP_MARGIN_MIN_PCT,
    margin_max_pct: float = STOP_MARGIN_MAX_PCT,
) -> Setup:
    """Сделка от уровня. Ничего не выбирает за оператора: оба стопа и оба края запаса.

    Курс даёт два стопа (безопасный и рисковый) и диапазон запаса — здесь всё это
    сообщается как есть. Свернуть в одно число значило бы принять решение, которого
    источник не принимает.

    ⚠ ЗДЕСЬ СТОЯЛО ЛОЖНОЕ УТВЕРЖДЕНИЕ, СНЯТО 2026-08-22. Дословно было: «Лестница
    закупа (стр. 32) собирается по тому же правилу, что и цели». Никакой лестницы эта
    функция не собирает и не собирала с 2026-08-19, когда её удалил приказ владельца
    («не надо писать где именно ордера ставить»); у `Setup` нет и поля под неё. Правило
    «только уровни, живые на момент появления родителя» живо и верно — но относится к
    ЦЕЛЯМ (`build_targets`) и к якорю стопового объёма, а не к лестнице.
    """
    up = level.side is LevelSide.LONG
    # Стоп — за ГРАНИЦУ базы, а границы с 2026-08-18 — коробка ХАЙ…ЛОЙ всех баров
    # структуры (докстрока `Level.boundary_hi`). Основание — рисунки, а не замер:
    # стр. 30 подписывает коробку ХАЙ и ЛОЙ, стр. 58 велит прятать стоп «за ВСЮ
    # структуру», прокол стр. 18 («стоп всегда ставится за этот прокол») — крайняя
    # цена, то есть край той же коробки. Приказ владельца 2026-08-18: стоп ставится
    # ЗА СТРУКТУРУ, ПОК и зона — внутри неё.
    #
    # ⚠ История виляний, чтобы не повторить: 2026-08-11 стоп был переведён на коробку
    # с опорой на замер «ПОК внутри: 100%» — замер был тавтологией (профиль строится
    # ровно по этому диапазону), и правку я отозвал обратно на линии детекции. Отзыв
    # выплеснул ребёнка: негодным было ОБОСНОВАНИЕ, а не конвенция. Ответ всё это
    # время лежал в рисунках стр. 26/30 — у автора одна сущность, коробка по свечам.
    edge = level.boundary_lo if up else level.boundary_hi
    sign = Decimal(-1) if up else Decimal(1)

    height = level.boundary_hi - level.boundary_lo
    """Высота базы — от нижней границы до верхней. Она же ограничивает запас."""

    def with_margin(pct: float) -> Decimal:
        """Стоп за границу с запасом (стр. 33: «с запасом 1-3%», стр. 19: «1-5%»).

        Запас — проценты ОТ ЦЕНЫ, ровно как написано, без ограничений сверху: стр. 58
        говорит «ВСЕГДА прячем за всю структуру с запасом 1-3%», и ни одно из четырёх
        мест курса (стр. 19, 33, 36, 58) потолка не называет.

        ⚠ ОТЗЫВ капа «запас не больше высоты базы» (стоял здесь 2026-08-11 —
        2026-08-18). Кап был выведен ИЗ ЗАМЕРА (на 5м запас 3% — девять высот базы,
        РР 0.26) — то есть ровно запрещённой формой «курс говорит A, замер показал,
        что A дорого, поэтому B». Докстрока честно называла его решением, которое
        владелец может снять одной строкой; владелец снял 2026-08-18 («стоп 3-5% за
        структуру ставится!»). Цена исполнения курса как написано остаётся ценой, а
        не основанием: на младших ТФ стоп в разы больше цели — это факт о том, что
        младшие ТФ при таком запасе редко дают РР 1к3 (стр. 9), а не право резать
        запас.
        """
        raw = edge * Decimal(str(pct)) / Decimal(100)
        return edge + sign * raw

    # Якорь считается в `levels.build_all` — там есть ряды баров младшего ТФ. Сюда он
    # приходит на уровне; параметр оставлен для зондов, подающих якорь вручную.
    anchor = structural_anchor if structural_anchor is not None else level.stop_anchor

    def beyond_anchor(price: Decimal) -> Decimal:
        """Стоп ЗА якорем с запасом, а не НА его цене.

        До 2026-08-18 стоп ставился РОВНО на цену якоря. Источника у этого не было:
        ни курс, ни корпус так не говорят — это перевод слова за в знак равенства,
        сделанный кодом, то есть выдумка. Владелец спросил, почему стопы не ставятся
        за структуру с запасом, — проверка курсом показала: дословно «СТОП прятать с
        запасом за структуру» (стр. 19), и то же требование о запасе повторяют
        стр. 33, 36, 58 (на 58 — «Стоп всегда прячем за всю структуру с запасом
        1-3%»). ⚠ Во всех четырёх местах запас назван ЗА СТРУКТУРУ/ГРАНИЦЫ; переноса
        запаса на якорь курс не пишет — это РЕШЕНИЕ-композиция, и держится оно на
        двух ногах: прокол стр. 18 сам объяснён как возможное расширение базы (его
        цена — граница расширенного диапазона, за границу — базовое правило), а стоп
        вплотную курс называет «Рисковый СТОП» (стр. 33) и не рекомендует.

        РАЗМЕР запаса за якорем ни курс, ни корпус не называют (в корпусе
        единственное найденное живое место — стоп ювелирно за хай, и оно про перенос
        в безубыток). Взят БЛИЖНИЙ край курсового диапазона 1-3%
        (`STOP_MARGIN_MIN_PCT`), а не дальний, как у голой границы: у якоря защитой
        служит он сам, добавка лишь снимает стоп с точной цены, которую рынок уже
        показывал. Первая редакция правки брала дальний край — аудит 2026-08-18
        показал цену: 30 стопов из 82 дальше 2 высот базы от входа (то, что
        утренняя правка полосы убирала) и 37 из 82 за полосой 5% от границы;
        отвергнуто. С ближним краем и капами: 12 и 0 соответственно.

        Две рамки поверх добавки:
          * добавка не больше высоты базы — то же решение по смыслу, что у
            `with_margin` (замер 2026-08-11), с той разницей, что здесь оно
            ограничивает ДОБАВКУ, а не полное расстояние;
          * якорь ИЗ ПОЛОСЫ (стоповый объём, свинг): полный отступ стопа от границы
            не дальше внешнего края самой полосы — «в диапазоне 2-5% от границы»
            (стр. 18) — единственной количественной рамки, которую курс этой
            конструкции даёт. Кап режет ДОБАВКУ — вплоть до нуля, если якорь стоит
            на самом краю полосы, — но не якорь: ближе цены якоря стоп не бывает.
            Прокол полосе НЕ подчинён: «стоп всегда ставится за этот прокол»
            (стр. 18) — безусловный императив, прокол бывает и глубже полосы.
        """
        raw = price * Decimal(str(STOP_MARGIN_MIN_PCT)) / Decimal(100)
        stop = price + sign * (min(raw, height) if height > 0 else raw)
        # Источник известен только у якоря самого уровня; якорь, поданный вручную
        # (`structural_anchor` зондов), источника не несёт и читается консервативно —
        # как полосный, то есть кап применяется.
        source = (
            level.stop_anchor_source
            if structural_anchor is None or structural_anchor == level.stop_anchor
            else None
        )
        if source is not StopAnchorSource.PUNCTURE:
            band = Decimal(str(STOP_ANCHOR_BAND_MAX_PCT)) / Decimal(100)
            outer = edge * (Decimal(1) + sign * band)
            stop = max(stop, outer) if up else min(stop, outer)
            stop = min(stop, price) if up else max(stop, price)
        return stop

    # Пол под ЛЮБЫМ стопом — курсовый запас за всей структурой: «Стоп ВСЕГДА прячем
    # за всю структуру с запасом 1-3%» (стр. 58; то же стр. 33, 36; для лимитных
    # ордеров стр. 19 даёт 1-5%). Якорь этому полу не хозяин: стоп за якорем законен
    # (стр. 18 «идеально стоп прятать за них»), но «всегда … с запасом» безусловно —
    # если якорь ближе запаса, держит запас, а якорь остаётся внутри. Величина пола —
    # DEFAULT_MARGIN_PCT = 3%: единственное число в пересечении курсовых диапазонов
    # (1-3% и 1-5%) со словами владельца 2026-08-18 «стоп 3-5% за структуру
    # ставится!» (выбор точки в диапазоне — решение о риске, оно его).
    floor = with_margin(DEFAULT_MARGIN_PCT)
    if anchor is not None:
        anchored = beyond_anchor(anchor)
        if (floor < anchored) if up else (floor > anchored):
            stop, basis = floor, StopBasis.MARGIN
        else:
            stop, basis = anchored, StopBasis.ANCHOR
    else:
        stop, basis = floor, StopBasis.MARGIN
    targets = build_targets(level, pool)
    first_take = targets[0].price if targets else None
    return Setup(
        level=level,
        entry=level.price,
        entry_zone_lo=level.zone_lo,
        entry_zone_hi=level.zone_hi,
        stop_safe_near=with_margin(margin_min_pct),
        stop_safe_far=with_margin(margin_max_pct),
        stop_risky=edge,
        stop=stop,
        stop_basis=basis,
        structural_anchor=anchor,
        targets=targets,
        breakeven_rules=build_breakeven_rules(
            # «Внутрь базы» (стр. 19) — дальний по ходу сделки край зоны входа.
            inside_base=level.zone_hi if up else level.zone_lo,
            level_price=level.price, first_take=first_take),
        add_ons=build_add_ons(entry=level.price, first_take=first_take,
                              repeat_share_pct=ADD_ON_SHARE_PCT),
    )




class StopVolumeSetup(BaseModel):
    """ОТДЕЛЬНАЯ сделка от уровня стопового объёма. Стр. 35, 37, 39.

    ⚠ Заведено 2026-08-19. До этого стоповый объём участвовал в расчёте ровно одним
    способом — как якорь стопа сделки от основного уровня, — тогда как курс говорит о
    нём как о самостоятельной точке входа: стр. 35 «После выхода из стопового вверх, у
    нас также появляется уровень в лонг, на тесте данного уровня мы и открываем
    позицию». Там же курс прямо разводит две сделки: «Также снизу у нас есть уровень
    лонговый всего накопления, он также актуален и от него берем позицию в лонг», а
    стр. 37 называет нижнее накопление «отдельный трейд». Поэтому это отдельная модель,
    а `Setup` от основного уровня не меняется ни на йоту.

    Состав по курсу:
      * ТВХ — ПОК стопового: стр. 39 «ТВХ позиции от уровня Стопового»;
      * стоп — за границу стопового: стр. 37 «со стопом за границу стопового», запас
        3% по общему правилу стр. 58 (`DEFAULT_MARGIN_PCT`);
      * цель — граница базы по ходу сделки: стр. 39 «цель - верхняя граница»,
        доля фиксации 30-50% (`TargetRole.BOUNDARY`);
      * повторный откуп — стр. 39 «с низу каждый раз повторно откупаем», доли нет.

    В эмиссию сигналов это НЕ идёт: новый тип сигнала меняет состав леджера — тот же
    выбор, что у `PPSetup`, и он принимается отдельно.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    base: Level
    """Основное накопление, от границы которого искался стоповый объём."""

    level: Level
    """Уровень САМОГО стопового объёма: его ПОК и есть ТВХ (стр. 39)."""

    side: LevelSide
    entry: Decimal
    stop: Decimal
    stop_basis: StopBasis
    target: Target
    breakeven_rules: tuple[BreakevenRule, ...]
    add_ons: tuple[AddOn, ...]

    @property
    def breakeven_price(self) -> Decimal:
        """Стр. 14: б/у — точка открытия, здесь это ПОК стопового."""
        return self.entry

    @property
    def rr(self) -> float | None:
        """РР до границы базы (стр. 9). None — риск нулевой, а не «ноль»."""
        risk = abs(self.entry - self.stop)
        if risk == 0:
            return None
        return float(abs(self.target.price - self.entry) / risk)


def stop_volume_level(base: Level, pool: tuple[MappedLevel, ...]) -> Level | NotReady:
    """Уровень стопового объёма, за который спрятан стоп сделки от `base`.

    Стоповый объём — накопление младшего ТФ (стр. 18, 34), поэтому его ПОК живёт в пуле
    обычным уровнем. Связь с якорем восстанавливается по цене: якорь взят у ГРАНИЦЫ
    стопового (`levels.stop_anchor`), значит искомый уровень — тот, чья коробка эту цену
    содержит. Из подходящих берётся ближайший границей к якорю.

    Отбор такой же, как у целей: уровень обязан быть живым НА МОМЕНТ появления базы,
    иначе сделка строилась бы от уровня, которого тогда ещё не было. (Упоминание
    «лестницы» здесь снято 2026-08-22 — её нет с 2026-08-19.)

    Сторона совпадает со стороной базы: стр. 35 говорит про выход из стопового ВВЕРХ,
    после которого «появляется уровень в лонг», то есть в ту же сторону, что и сделка
    от нижней границы накопления.
    """
    if base.stop_anchor_source is not StopAnchorSource.STOP_VOLUME or base.stop_anchor is None:
        return NotReady(reason=f"{base.symbol} {base.timeframe}: стоп держится не на стоповом "
                               f"объёме — сделки стр. 35/37/39 нет")
    anchor = base.stop_anchor
    up = base.side is LevelSide.LONG
    best: Level | None = None
    for mapped in pool:
        lvl = mapped.level
        step = _tf_step(base.timeframe, lvl.timeframe)
        if lvl.symbol != base.symbol or lvl.side is not base.side:
            continue
        if step is None or step < 1 or not mapped.alive_at(base.created_at_ms):
            continue
        if not (lvl.boundary_lo <= anchor <= lvl.boundary_hi):
            continue
        if best is None or abs(_sv_edge(lvl, up) - anchor) < abs(_sv_edge(best, up) - anchor):
            best = lvl
    if best is None:
        return NotReady(reason=f"{base.symbol} {base.timeframe}: ПОК стопового объёма у цены "
                               f"{anchor} не построен — сделку от него не от чего строить")
    return best


def _sv_edge(lvl: Level, up: bool) -> Decimal:
    """Граница стопового по ходу сделки: для лонга нижняя, для шорта верхняя (стр. 37)."""
    return lvl.boundary_lo if up else lvl.boundary_hi


def build_stop_volume_setup(
    base: Level, pool: tuple[MappedLevel, ...] = (),
) -> StopVolumeSetup | NotReady:
    """Сделка от стопового объёма (стр. 35, 37, 39) или НАЗВАННАЯ причина её отсутствия.

    Сделку от основного уровня не трогает: `build_setup` вызывается отдельно и о
    существовании этой не знает.
    """
    found = stop_volume_level(base, pool)
    if isinstance(found, NotReady):
        return found
    up = base.side is LevelSide.LONG
    entry = found.price
    edge = _sv_edge(found, up)
    sign = Decimal(-1) if up else Decimal(1)
    stop = edge + sign * edge * Decimal(str(DEFAULT_MARGIN_PCT)) / Decimal(100)
    goal = base.boundary_hi if up else base.boundary_lo
    if (goal <= entry) if up else (goal >= entry):
        return NotReady(reason=f"{base.symbol} {base.timeframe}: граница базы {goal} не впереди "
                               f"ТВХ стопового {entry} — цели стр. 39 нет")
    target = Target(role=TargetRole.BOUNDARY, price=goal, timeframe=base.timeframe,
                    distance_pct=float(abs(goal - entry) / entry * 100),
                    take=take_share(TargetRole.BOUNDARY))
    return StopVolumeSetup(
        base=base,
        level=found,
        side=base.side,
        entry=entry,
        stop=stop,
        stop_basis=StopBasis.MARGIN,
        target=target,
        breakeven_rules=build_breakeven_rules(
            inside_base=found.zone_hi if up else found.zone_lo,
            level_price=entry, first_take=goal),
        # Стр. 39 велит откупать повторно, но доли для этого случая не называет —
        # в отличие от стр. 19, где названы 50%.
        add_ons=build_add_ons(entry=entry, first_take=goal, repeat_share_pct=None),
    )


class PPSetup(BaseModel):
    """Геометрия сделки ОТ ПЕРЕПРИОРА — стр. 50: «Торговля ПП – точкой входа является
    тест ПП, со стопом за хай/лой или базу в месте слома».

    ⚠ Заведено 2026-08-10 (реестр долга, строка 3 — М-11). До этого `tested_at_index`
    вычислялся, а геометрии сделки от ПП не существовало: сетап строился только от
    уровня ПОК. Здесь сделка СТРОИТСЯ И ПЕЧАТАЕТСЯ картой; в эмиссию она не идёт —
    новый ТИП сигнала меняет состав леджера, и это отдельный заход (тот же выбор, что
    у слома на младшем ТФ и конфигураций стр. 28).

    Конвенции, названные вслух:
      * вход — БЛИЖНИЙ край зоны тени, и «ближний» здесь определено, а не подразумевается:
        это край, которого цена касается ПЕРВЫМ, возвращаясь на тест. У лонга (слом хая,
        тест сверху) это `zone_hi`, у шорта (слом лоя, тест снизу) — `zone_lo`. Слово
        «ближний» без этой оговорки читается двояко — от чего ближний, от цены или от
        ПОК, — и в реестре долга оно так и числилось неоднозначным.

        ⚠ ССЫЛКА НА РЕШЕНИЕ ВЛАДЕЛЬЦА ЗДЕСЬ НЕ ПОДТВЕРЖДЕНА. Прежняя редакция строки
        гласила «решение владельца по обзору слома структуры»; дословной цитаты его слов
        ни в обзоре, ни в переписке нет, а с 2026-08-19 такая подпись законна только
        рядом с цитатой. Основание у выбора при этом ЕСТЬ и оно не в подписи: тест по
        стр. 50 приходит с одной стороны, и вход в него на дальнем крае означал бы ждать
        прохода всей зоны насквозь — то есть события, которое курс тестом уже не считает
        (обзор: docs/audit/bos-projects-2026-08-07.md, ретест по закрытию);
      * стоп — за ДАЛЬНИЙ край зоны (это и есть хай/лой слома, стр. 50), И С ЗАПАСОМ
        `DEFAULT_MARGIN_PCT`.

        ⚠ ЗДЕСЬ СТОЯЛО ОБРАТНОЕ, СНЯТО 2026-08-24. Дословно было: «запаса курс для ПП
        не даёт, поэтому стоп РОВНО за краем, без процента». Код так не делает с
        2026-08-19: приказ владельца «СТОП ВСЕГДА СТАВИТСЯ ЗА СТРУКТУРУ И НИКАК ИНАЧЕ»
        добавил запас (`stop = pp.zone_hi * (1 + margin)`), и разбор стоит прямо в теле
        `build_pp_setup`. Докстрока пережила правку и полгода обещала читателю другую
        цену стопа — ровно тот класс, из-за которого утверждения кода о себе объявлены
        гипотезой, а не свидетельством;
      * цель — ближний край ПРОТИВОПОЛОЖНОГО ПП: стр. 49 задаёт горизонт от переприора
        до переприора в обратном направлении (пересказ схемы). Нет противоположного —
        цели нет, и это названо, а не подменено числом (§4.3).
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    side: str
    entry: float
    stop: float
    target: float | None
    rr: float | None


def build_pp_setup(pp: Pereprior, opposite: Pereprior | None) -> PPSetup:
    """Сделка от ПП. `opposite` — последний ПП противоположной стороны того же ТФ."""
    # Цель законна только ПО НАПРАВЛЕНИЮ сделки: противоположный ПП, стоящий позади
    # входа, целью не является — маршрут «от ПП до ПП» идёт вперёд, а не назад. Первая
    # редакция это не проверяла и печатала отрицательный РР — поймано первым же диффом.
    # ⚠ СТОП ЗА ХАЙ/ЛОЙ, А НЕ НА НЁМ (2026-08-19, приказ владельца: «СТОП ВСЕГДА
    # СТАВИТСЯ ЗА СТРУКТУРУ И НИКАК ИНАЧЕ»). Здесь стояло `stop = pp.zone_hi` — РОВНО
    # край тени свечи слома, то есть «за» было превращено в «=», а запаса не было
    # вовсе. Тот же дефект уже чинился у уровней 2026-08-18 и вернулся здесь.
    #
    # Стр. 50 дословно: «Торговля ПП – точкой входа является тест ПП, со стопом за
    # хай/лой или базу в месте слома, если она есть». Запас — общий для всех стопов
    # курса: стр. 58 «Стоп ВСЕГДА прячем за всю структуру с запасом 1-3%», и слово
    # «всегда» там безусловное. Берётся `DEFAULT_MARGIN_PCT`, тот же, что у уровней:
    # два разных запаса под одним правилом разошлись бы при первой правке.
    #
    # ⚠ Вторая ветвь стр. 50 — «или базу в месте слома, если она есть» — НЕ
    # реализована: накопление в месте слома здесь неизвестно (`build_pp_setup` получает
    # только сам ПП и встречный). Это названо, а не умолчано; ветвь ставит стоп ДАЛЬШЕ,
    # значит нынешний стоп её не нарушает, а недобирает.
    margin = DEFAULT_MARGIN_PCT / 100
    if pp.side is PPSide.SHORT:
        entry = pp.zone_lo
        stop = pp.zone_hi * (1 + margin)
        cand = opposite.zone_hi if opposite is not None else None
        target = cand if cand is not None and cand < entry else None
        risk = stop - entry
        rr = (entry - target) / risk if target is not None and risk > 0 else None
    else:
        entry = pp.zone_hi
        stop = pp.zone_lo * (1 - margin)
        cand = opposite.zone_lo if opposite is not None else None
        target = cand if cand is not None and cand > entry else None
        risk = entry - stop
        rr = (target - entry) / risk if target is not None and risk > 0 else None
    return PPSetup(side=pp.side.value, entry=entry, stop=stop, target=target, rr=rr)

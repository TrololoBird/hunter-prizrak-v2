"""Геометрия сделки §2.7. Источник — мини-курс, стр. 9, 19, 24, 30, 33, 18.

ЧИСТЫЙ МОДУЛЬ (§10.3): часы, сеть и глобальное состояние не трогаются.

  стр. 30  вход: «надёжнее всего брать от уровня ПОК (немного выше/ниже, т.к. идеально
           может не доходить)… чтобы точно забрало ваш ордер — используем 2-3 ордера,
           на зону, и на уровень ПОК». Крупное накопление (1Д-1Н-1М) — делить на зону и
           уровень; мелкое (5м-1ч) — «эффективнее входить 1 ордером от уровня»
  стр. 33  стоп: «Безопасный СТОП за дно структуры с ЗАПАСОМ 1-3%… Рисковый СТОП: прямо
           за лой структуры или же за объёмную зону»
  стр. 18  «Если в диапазоне 2-5% от границы есть стоповый объём — база мелкого ТФ — или
           Лой того же ТФ или ТФ-1 — ИДЕАЛЬНО стоп прятать за них»
  стр. 24  цель: «другой сопоставимый уровень 4ч ТФ, либо уровень 1Д тф, если он
           ближайший… могут быть взяты как промежуточные цели с небольшими тейками…
           Уровни ТФ-2 (15м и ниже) обычно не берутся в расчет»
  стр. 19  «По верхней границе делаете тейк 50% — но не 100%»
  стр. 9   «Золотым стандартом считаются сделки с РР 1к3 и выше»

Проценты здесь допустимы вопреки §4.1: он сам делает исключение для величин, которые курс
задаёт в процентах прямо, и называет ровно этот случай — стоп 1-3% за структуру.
"""

from __future__ import annotations

from decimal import Decimal
from enum import StrEnum

from pydantic import BaseModel, ConfigDict

from .levels import Level, LevelSide, MappedLevel
from .levels import nested as nested_levels
from .pereprior import Pereprior, PPSide

TF_ORDER = ("5m", "15m", "1h", "4h", "1d", "1w")
"""Стр. 17: «Мы используем основные ТФ (5м/15м/час/4ч/1Д/1Н)». Порядок задаёт ТФ-1 и ТФ-2."""

STOP_MARGIN_MIN_PCT = 1.0
STOP_MARGIN_MAX_PCT = 3.0
"""Стр. 33: «с запасом 1-3%». Курс даёт ДИАПАЗОН и внутри него не выбирает.

Поэтому здесь не выбирается тоже: считаются оба края, и RR приводится для обоих.
Выбрать один — значит назначить число, которого в источнике нет.
Стр. 19 в одном месте называет 1-5%, но 1-3% встречается трижды (стр. 33, 36, 58).
"""

PARTIAL_TAKE_PCT = 50.0
"""Стр. 19: «делаете тейк 50% — но не 100%». Число названо курсом прямо."""

GOLDEN_RR = 3.0
"""Стр. 9: «Золотым стандартом считаются сделки с РР 1к3 и выше». Не гейт, а отметка."""

BIG_STRUCTURE_TFS = frozenset({"1d", "1w"})
"""Стр. 30: крупное накопление — закуп делить на зону И уровень. Мелкое — одним ордером."""


class StopBasis(StrEnum):
    """Чем обоснован выставляемый стоп. Оба варианта — из курса, третьего нет."""

    ANCHOR = "anchor"
    """За стоповым объёмом или за проколом границы (стр. 18).

    Стр. 18 называет это предпочтительным: «идеально стоп прятать за них». Прокол при
    3+ точках границы — вообще обязателен: «стоп ВСЕГДА ставится за этот прокол».
    """

    MARGIN = "margin"
    """Запас за структуру, когда прятать не за что (стр. 33: «с запасом 1-3%»)."""


DEFAULT_MARGIN_PCT = STOP_MARGIN_MAX_PCT
"""Какой край диапазона 1-3% берётся, когда якоря нет.

⚠ Это ВЫБОР ВНУТРИ ДИАПАЗОНА, названного курсом, а не замер. Курс даёт «1-3%» и внутри
не выбирает; выставить же можно одно число. Взят ДАЛЬНИЙ край, потому что назначение
запаса курс формулирует как защиту: «обезопасит от сквизов на рынке, и на случай пробоя
уровня и закрепа у вас будет больше шансов выйти в бу» (стр. 33). Ближний край той же
цели служит хуже, а РР при отсутствии якоря и так худший из возможных.
"""


class TargetRole(StrEnum):
    PRIMARY = "primary"
    """Сопоставимый уровень своего ТФ либо ближайший старший (стр. 24)."""

    INTERMEDIATE = "intermediate"
    """ТФ-1: «промежуточные цели с небольшими тейками» (стр. 24)."""


class Target(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    role: TargetRole
    price: Decimal
    timeframe: str
    distance_pct: float


class Setup(BaseModel):
    """Сделка от уровня: вход, два стопа, цели. Ничего не сворачивается в одно число."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    level: Level
    entry: Decimal
    """ПОК уровня (стр. 30)."""

    entry_zone_lo: Decimal
    entry_zone_hi: Decimal
    split_orders: bool
    """Стр. 30: крупная база — делить закуп на зону и уровень; мелкая — один ордер."""

    ladder: tuple[Decimal, ...]
    """Все уровни внутри большой структуры, снизу вверх (стр. 32).

    Первым элементом всегда идёт `entry` — основной ПОК; дальше ПОК вложенных структур
    младшего ТФ. Пустой лестницы не бывает: одиночный уровень — это лестница из одного.
    Стр. 32: «лучше закуп делать на все уровни».
    """

    @property
    def average_entry_equal_shares(self) -> Decimal:
        """Средняя ТВХ при РАВНЫХ долях на каждый уровень лестницы.

        Стр. 32 называет цель — «что бы ваша средняя твх была максимально безопасная», —
        но долей НЕ задаёт. Поэтому равные доли названы прямо в имени: это допущение
        читателя, а не правило курса, и молча зашивать его в поле `entry` нельзя.
        """
        return sum(self.ladder, Decimal(0)) / Decimal(len(self.ladder))

    stop_safe_near: Decimal
    stop_safe_far: Decimal
    """Безопасный стоп за структуру с запасом. Два края диапазона 1-3% (стр. 33)."""

    stop_risky: Decimal
    """Прямо за границу структуры, без запаса (стр. 33)."""

    stop: Decimal
    """ОДИН стоп, который выставляется. Всё выше — как он получен, а не выбор оператору.

    ⚠ До 2026-08-05 этого поля не было, и карточка печатала три цены: безопасный ближний,
    безопасный дальний и рисковый. Выставить можно только ОДИН стоп, значит карточка
    выдавала не сигнал, а меню, и РР был не определён — все замеры РР и R считались по
    невыбранному стопу. Выбор делается здесь, по стр. 18 и 33, и называется в `stop_basis`.
    """

    stop_basis: StopBasis
    """Чем стоп обоснован. Печатается рядом с ценой: оператор обязан видеть НЕ ТОЛЬКО
    число, но и правило, по которому оно получено."""

    structural_anchor: Decimal | None
    """Стоповый объём или прокол в 2-5% от границы — «идеально стоп прятать за них» (стр. 18).

    None — якоря нет: ни прокола на 3+ точках, ни стопового объёма в полосе. Тогда стоп
    ставится запасом за структуру (стр. 33).
    """

    targets: tuple[Target, ...]
    partial_take_pct: float = PARTIAL_TAKE_PCT

    def rr(self, stop: Decimal | None = None) -> float | None:
        """РР до ПЕРВОЙ цели (стр. 9). None — целей нет, а не «ноль».

        Без аргумента считается по ВЫСТАВЛЯЕМОМУ стопу — единственное значение, имеющее
        смысл. Аргумент оставлен для замеров, сравнивающих варианты между собой.
        """
        stop = self.stop if stop is None else stop
        primary = [t for t in self.targets if t.role is TargetRole.PRIMARY]
        if not primary:
            return None
        risk = abs(self.entry - stop)
        if risk == 0:
            return None
        return float(abs(primary[0].price - self.entry) / risk)


def _tf_step(a: str, b: str) -> int | None:
    """На сколько ступеней ТФ `b` младше `a`. None — один из ТФ не из основных."""
    if a not in TF_ORDER or b not in TF_ORDER:
        return None
    return TF_ORDER.index(a) - TF_ORDER.index(b)


def build_targets(level: Level, pool: tuple[MappedLevel, ...]) -> tuple[Target, ...]:
    """Цели по стр. 24: свой ТФ и старшие — основные, ТФ-1 — промежуточные, ТФ-2 — нет.

    Целью служит уровень ПРОТИВОПОЛОЖНОЙ стороны по ходу сделки: от лонгового уровня
    идём вверх к шортовому (стр. 24, пример «цена забирает 4ч Лонг уровень; ваша цель —
    шорт уровень 4ч тф»).

    ⚠ Пул подаётся РАЗМЕЧЕННЫМ (`MappedLevel`), и это не удобство типов. Прежняя редакция
    брала `tuple[Level, ...]` и не проверяла ни момент появления цели, ни её состояние.
    Замер на 374 уровнях (docs/audit/critical-review-verified-2026-08-04.md):

      * 196 основных целей из 366 (54%) появились ПОЗЖЕ уровня, от которого строилась
        сделка, — тейк-профит выбирался задним числом, и `outcome.resolve` затем искал
        достижение именно этой цены;
      * 283 цели из 366 (83%) были в состоянии `worked_off` или `flipped`, то есть по
        стр. 25 «мы этот уровень удаляем», а по стр. 43 он уже противоположный.

    Оба отсева делает `MappedLevel.alive_at` НА МОМЕНТ ПОЯВЛЕНИЯ уровня, а не на конец
    ряда: фильтровать по нынешнему состоянию значило бы заменить одно заглядывание вперёд
    другим — цель, снятая через месяц после сигнала, в момент сигнала была законной.
    """
    entry = level.price
    up = level.side is LevelSide.LONG
    want = LevelSide.SHORT if up else LevelSide.LONG
    as_of = level.created_at_ms

    out: list[Target] = []
    for mapped in pool:
        other = mapped.level
        if other.symbol != level.symbol or other.side is not want:
            continue
        if not mapped.alive_at(as_of):
            continue
        if (other.price > entry) is not up or other.price == entry:
            continue
        step = _tf_step(level.timeframe, other.timeframe)
        if step is None or step >= 2:
            # Стр. 24: «Уровни ТФ-2 (15м и ниже) обычно не берутся в расчёт».
            continue
        role = TargetRole.INTERMEDIATE if step == 1 else TargetRole.PRIMARY
        out.append(Target(role=role, price=other.price, timeframe=other.timeframe,
                          distance_pct=float(abs(other.price - entry) / entry * 100)))
    return tuple(sorted(out, key=lambda t: t.distance_pct))


def build_setup(
    level: Level,
    pool: tuple[MappedLevel, ...] = (),
    *,
    structural_anchor: Decimal | None = None,
    margin_min_pct: float = STOP_MARGIN_MIN_PCT,
    margin_max_pct: float = STOP_MARGIN_MAX_PCT,
) -> Setup:
    """Сделка от уровня. Ничего не выбирает за оператора: оба стопа и оба края запаса.

    Курс даёт два стопа (безопасный и рисковый) и диапазон запаса — здесь всё это
    сообщается как есть. Свернуть в одно число значило бы принять решение, которого
    источник не принимает.

    Лестница закупа (стр. 32) собирается по тому же правилу, что и цели: в неё идут
    только уровни, живые НА МОМЕНТ появления родителя. Ордер на отработанный уровень
    запрещает стр. 31 («уровень лимитными ордерами больше не торгуем») ровно так же,
    как стр. 25 запрещает целиться в него.
    """
    up = level.side is LevelSide.LONG
    # Стоп — за ГРАНИЦУ базы (стр. 33: «за дно структуры»). Граница с 2026-08-11 —
    # внешний край первых двух точек стороны, то есть хай/лой базы по стр. 18.
    #
    # ⚠ ОТЗЫВ собственной правки того же дня. Сначала я перевёл стоп на `range_lo/hi`
    # (крайние цены ВСЕХ баров структуры), опираясь на замер «ПОК внутри базы: 100%».
    # Замер был тавтологией: профиль строится ровно по этому диапазону, поэтому иного
    # ответа он выдать НЕ МОГ. Мера «доля ПОК внутри границы» вообще монотонна по
    # ширине — «граница = весь график» дала бы те же 100%, — и потому выбирать по ней
    # конвенцию нельзя. Причина оказалась не в том, от чего считать стоп, а в том, что
    # граница была занижена внутренним краем пары; это исправлено в детекторе.
    edge = level.boundary_lo if up else level.boundary_hi
    sign = Decimal(-1) if up else Decimal(1)

    height = level.boundary_hi - level.boundary_lo
    """Высота базы — от нижней границы до верхней. Она же ограничивает запас."""

    def with_margin(pct: float) -> Decimal:
        """Стоп за границу с запасом (стр. 33: «с запасом 1-3%», стр. 19: «1-5%»).

        ⚠ ЗАПАС ОГРАНИЧЕН ВЫСОТОЙ БАЗЫ, и это РЕШЕНИЕ ПО СМЫСЛУ, а не правило курса.
        Названо так прямо, потому что числа этого ограничения в курсе нет.

        Повод — замер 2026-08-11. Курс задаёт запас в процентах ОТ ЦЕНЫ, и на масштабе
        автора (4ч, 1Д — стр. 48 называет старшие ТФ сильнее) это соразмерно: медианная
        высота базы 2.88% на 4ч и 7.29% на 1Д, то есть запас 3% — от одной высоты базы
        до трети её. На младших ТФ то же число даёт абсурд:

            ТФ    медианная высота базы    запас 3% это
            5м            0.32%            9.5 высоты базы
            15м           0.51%            5.9 высоты
            1ч            1.26%            2.4 высоты
            4ч            2.88%            1.0 высоты
            1Д            7.29%            0.4 высоты

        Стоп, отнесённый на девять высот базы, — это не «запас за структуру», это
        другая сделка: риск 3.70% при цели 0.97% даёт РР 0.26 (замер по 24 сигналам с
        целью: 8 из них имели РР < 1, медиана 2.76 при том, что стр. 9 называет золотым
        стандартом РР 1к3 и выше). Такая сделка проиграна геометрией до открытия, и
        именно она давала средний выигрыш +0.13R при среднем убытке −1.00R.

        Само слово «запас» означает ДОБАВКУ к границе, а не основную величину риска.
        Отсюда потолок: добавка не больше самой базы. Курс потолка не называет —
        поэтому это моё решение, и владелец может его снять одной строкой.
        """
        raw = edge * Decimal(str(pct)) / Decimal(100)
        return edge + sign * min(raw, height) if height > 0 else edge + sign * raw

    alive = tuple(m.level for m in pool if m.alive_at(level.created_at_ms))
    inner = nested_levels(level, alive)
    # Якорь считается в `levels.build_all` — там есть ряды баров младшего ТФ. Сюда он
    # приходит на уровне; параметр оставлен для зондов, подающих якорь вручную.
    anchor = structural_anchor if structural_anchor is not None else level.stop_anchor
    if anchor is not None:
        stop, basis = anchor, StopBasis.ANCHOR
    else:
        stop, basis = with_margin(DEFAULT_MARGIN_PCT), StopBasis.MARGIN
    return Setup(
        level=level,
        entry=level.price,
        entry_zone_lo=level.zone_lo,
        entry_zone_hi=level.zone_hi,
        split_orders=level.timeframe in BIG_STRUCTURE_TFS,
        ladder=tuple(sorted({level.price, *(x.price for x in inner)})),
        stop_safe_near=with_margin(margin_min_pct),
        stop_safe_far=with_margin(margin_max_pct),
        stop_risky=edge,
        stop=stop,
        stop_basis=basis,
        structural_anchor=anchor,
        targets=build_targets(level, pool),
    )




class PPSetup(BaseModel):
    """Геометрия сделки ОТ ПЕРЕПРИОРА — стр. 50: «Торговля ПП – точкой входа является
    тест ПП, со стопом за хай/лой или базу в месте слома».

    ⚠ Заведено 2026-08-10 (реестр долга, строка 3 — М-11). До этого `tested_at_index`
    вычислялся, а геометрии сделки от ПП не существовало: сетап строился только от
    уровня ПОК. Здесь сделка СТРОИТСЯ И ПЕЧАТАЕТСЯ картой; в эмиссию она не идёт —
    новый ТИП сигнала меняет состав леджера, и это отдельный заход (тот же выбор, что
    у слома на младшем ТФ и конфигураций стр. 28).

    Конвенции, названные вслух:
      * вход — БЛИЖНИЙ край зоны тени: решение владельца по обзору слома структуры
        (docs/audit/bos-projects-2026-08-07.md, принят ближний край и ретест по
        закрытию);
      * стоп — за ДАЛЬНИЙ край зоны (это и есть хай/лой слома, стр. 50); запаса курс
        для ПП не даёт, поэтому стоп РОВНО за краем, без процента;
      * цель — ближний край ПРОТИВОПОЛОЖНОГО ПП: стр. 49 задаёт горизонт от переприора
        до переприора в обратном направлении (пересказ схемы). Нет противоположного —
        цели нет, и это названо, а не подменено числом (§4.3).
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    side: str
    entry: float
    stop: float
    target: float | None
    rr: float | None


def build_pp_setup(pp: Pereprior, opposite: Pereprior | None) -> PPSetup:
    """Сделка от ПП. `opposite` — последний ПП противоположной стороны того же ТФ."""
    # Цель законна только ПО НАПРАВЛЕНИЮ сделки: противоположный ПП, стоящий позади
    # входа, целью не является — маршрут «от ПП до ПП» идёт вперёд, а не назад. Первая
    # редакция это не проверяла и печатала отрицательный РР — поймано первым же диффом.
    if pp.side is PPSide.SHORT:
        entry, stop = pp.zone_lo, pp.zone_hi
        cand = opposite.zone_hi if opposite is not None else None
        target = cand if cand is not None and cand < entry else None
        risk = stop - entry
        rr = (entry - target) / risk if target is not None and risk > 0 else None
    else:
        entry, stop = pp.zone_hi, pp.zone_lo
        cand = opposite.zone_lo if opposite is not None else None
        target = cand if cand is not None and cand > entry else None
        risk = entry - stop
        rr = (target - entry) / risk if target is not None and risk > 0 else None
    return PPSetup(side=pp.side.value, entry=entry, stop=stop, target=target, rr=rr)

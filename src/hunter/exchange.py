    def check_capabilities(self) -> tuple[str, ...]:
        """Что из необходимого биржа не умеет. Пустой кортеж — умеет всё.

        Печатает ЧИСЛО проверенного: «нарушений 0» без знаменателя неотличимо от
        непроведённой проверки. Возвращает список, а не булево, чтобы вызывающий назвал
        отсутствующее поимённо.
        """
        missing, emulated = [], []
        for name, why in REQUIRED_CAPABILITIES.items():
            value = self._ex.has.get(name)
            if value == "emulated":
                emulated.append(name)
            elif not value:
                missing.append(f"{name} ({why})")
        log.info("возможности ccxt проверены", проверено=len(REQUIRED_CAPABILITIES),
                 отсутствует=len(missing), эмулируется=len(emulated))
        if emulated:
            log.degraded("возможность ЭМУЛИРУЕТСЯ ccxt, а не даётся биржей напрямую",
                         методы=", ".join(sorted(emulated)))
        return tuple(missing)

    async def open(self) -> ClockSync:
        log.info("площадка", класс=self.venue.ccxt_class, что=self.venue.human)
        # ⚠ ДО СЕТИ. Идентификаторы рынков у площадок Binance совпадают (`BTC/USDT` и
        # `BTC/USDT:USDT` оба дают `BTCUSDT`), поэтому кэш сделок, собранный одной
        # площадкой, дозаписанный другой, стал бы смесью двух разных рынков без единого
        # признака. Отказ здесь дешевле испорченных данных.
        from .archive import check_venue
        if why := check_venue(self.venue.ccxt_class):
            raise CapabilityMissing(why)
        await self._ex.load_markets()
        # Проверка ПОСЛЕ load_markets: у ccxt часть `has` уточняется по ответу биржи.
        # И ДО всего остального: отказ обязан случиться в начале прогона, а не из
        # середины стека спустя минуты сбора.
        if missing := self.check_capabilities():
            raise CapabilityMissing(
                f"{self._ex.id}: нет необходимых возможностей ccxt — " + "; ".join(missing)
            )
        await self._read_weight_limit()
        # Темп настраивается СРАЗУ после чтения лимита и до всякого сбора: очередь
        # троттлера здесь пуста, пересборка никого не бросит.
        self._tune_rate_limiter()
        # Два вопроса, два прибора: доступен ли НАШ шлюз и не на обслуживании ли Binance.
        # Ни один не отвечает за другого — см. докстроки обоих.
        await self.read_status()
        await self.read_maintenance()
        sync = await clock.measure(self.fetch_server_ms)
        log.info("часы сведены", сдвиг_мс=sync.offset_ms, rtt_мс=sync.rtt_ms,
                 замеров=sync.samples)
        return sync

    async def _read_weight_limit(self) -> None:
        """Спросить у биржи её собственный лимит веса (задание Ж-11).

        После перехода на REST 2026-08-05 лимит запросов стал ГЛАВНЫМ отказом системы:
        по документации Binance превышение даёт `HTTP 429`, а продолжение после него —
        бан по IP (`418`) на срок от 2 минут до 3 суток. Прибора на это в проекте не было
        вовсе: заголовки веса не читались нигде.

        Отказ здесь НЕ роняет прогон: без лимита система работает, просто перестаёт
        сравнивать с ним потребление, и это сказано числом (`weight_limit is None`).
        """
        try:
            # ⚠ Имя метода — `fapiPublicGetExchangeInfo`, а НЕ snake_case: ccxt порождает
            # оба варианта, но `fapi_public_get_exchangeinfo` среди них нет, и первая
            # редакция падала на нём `AttributeError` уже в `open()`.
            #
            # ⚠ И оно РАЗНОЕ У ПЛОЩАДОК (правка 2026-08-11): на споте этого метода нет
            # вовсе, там `publicGetExchangeInfo`. Путь берётся из таблицы `VENUES`, а не
            # зашит, иначе подключение спота падало бы `AttributeError` в `open()` —
            # ровно тем отказом, который эта же функция однажды уже дала.
            call = getattr(self._ex, self.venue.exchange_info, None)
            if call is None:
                log.degraded("у площадки нет метода лимитов",
                             площадка=self.venue.ccxt_class,
                             метод=self.venue.exchange_info)
                return
            info = await call()
        except ccxt.BaseError as e:
            log.degraded("лимит веса у биржи не прочитан",
                         причина=f"{type(e).__name__} {e}")
            return
        self._note_weight()
        for row in info.get("rateLimits", []):
            if (row.get("rateLimitType") == "REQUEST_WEIGHT"
                    and row.get("interval") == "MINUTE"
                    and int(row.get("intervalNum", 0)) == 1):
                self.weight_limit = int(row["limit"])
                log.info("лимит веса прочитан у биржи", вес_в_минуту=self.weight_limit)
                return
        log.degraded("в exchangeInfo нет строки REQUEST_WEIGHT/MINUTE/1",
                     строк=len(info.get("rateLimits", [])))

    def _tune_rate_limiter(self) -> None:
        """Настроить темп по лимиту, ПРОЧИТАННОМУ У БИРЖИ, и включить окно вместо ведра.

        До 2026-08-11 обе величины были чужими умолчаниями, которых мы не выбирали.

        ЧИСЛО. Руководство ccxt (Manual.md, «What the rateLimit number means») даёт формулу
        прямо: пауза перед запросом = `rateLimit` × стоимость запроса, а само `rateLimit`
        берётся делением опубликованного лимита биржи. Там же умолчание 50 мс названо
        дословно «a safe default which is sub-optimal», а настройка отнесена к пользователю.
        Мы лимит уже читаем (`_read_weight_limit`) — значит число можно ВЫЧИСЛИТЬ, а не
        подобрать. Доля названа в `RATE_UTILISATION`.

        АЛГОРИТМ. Умолчание ccxt — «дырявое ведро» ёмкостью 1 (ccxt/base/exchange.py,
        `init_rest_rate_limiter`): всплесков нет вовсе, каждый запрос ждёт свою задержку
        целиком. Binance же считает вес В ОКНЕ ОДНОЙ МИНУТЫ. Оконный режим ccxt эту модель
        воспроизводит точно: в его троттлере `maxWeight = rollingWindowSize / rateLimit`,
        то есть при окне 60 000 мс величина `60000 / rateLimit` и есть допустимый вес за
        минуту. Подставив наше `rateLimit`, получаем ровно `weight_limit × RATE_UTILISATION`
        веса в минуту — с всплесками внутри бюджета и блокировкой по его исчерпании.

        ⚠ Оконный ограничитель БЕЗОПАСНЕЕ ведра, а не рискованнее: он не позволяет
        превысить бюджет ни в одном скользящем окне минуты, а значит и ни в одном
        фиксированном. Ведро же держит средний темп, но о минутном окне биржи не знает.

        ⚠ `tokenBucket` сбрасывается в `None` ПЕРЕД пересборкой. Иначе бесполезно:
        `init_rest_rate_limiter` накладывает умолчания под уже существующее ведро
        (`extend(defaultBucket, existingBucket)`), и старая скорость пополнения победила бы
        новую. Зовётся сразу после чтения лимита, когда очередь троттлера пуста.

        Лимит не прочитан — не трогаем ничего: угадывать бюджет опаснее, чем идти медленно.
        """
        if self.weight_limit is None:
            log.degraded("темп оставлен на умолчании ccxt — лимит биржи не прочитан",
                         rate_limit_мс=self._ex.rateLimit)
            return
        was = self._ex.rateLimit
        budget = self.weight_limit * RATE_UTILISATION
        self._ex.rateLimit = 60_000 / budget
        self._ex.rateLimiterAlgorithm = "rollingWindow"
        self._ex.rollingWindowSize = 60_000.0
        self._ex.tokenBucket = None
        self._ex.init_rest_rate_limiter()
        log.info("темп настроен по лимиту биржи", лимит_веса_в_минуту=self.weight_limit,
                 доля=RATE_UTILISATION, бюджет_веса_в_минуту=round(budget),
                 rate_limit_мс=round(self._ex.rateLimit, 2), было_мс=was,
                 алгоритм="rollingWindow")

    async def read_status(self) -> bool | None:
        """Отвечает ли ШЛЮЗ НАШЕЙ ПЛОЩАДКИ. `None` — спросить не удалось.

        ⚠ ЗДЕСЬ БЫЛ `fetch_status`, И ЭТО БЫЛА ОШИБКА — ИСПРАВЛЕНО 2026-08-11 построчным
        чтением исходника. Единый `fetchStatus` у Binance зовёт `sapiGetSystemStatus`, то
        есть эндпоинт СПОТОВОГО КОШЕЛЬКА (ccxt/binance.py, `fetch_status`). На USDⓈ-M он
        отвечает про спот. Мой же зонд напечатал «ok» на трёх площадках и это было прочтено
        как три ответа — а был один спотовый эндпоинт, вызванный трижды. Прибор не мог
        ответить иначе.

        Теперь спрашивается `ping` САМОЙ площадки (вес 1) — путь, который руководство ccxt
        прямо называет допустимым для статуса («using the exchange ping or fetchTime
        endpoint to see if its alive»).

        ⚠ Что это МЕРЯЕТ и чего НЕ меряет. `ping` отвечает «шлюз принимает запросы». Он не
        отвечает «данные свежие» и не отвечает «техобслуживания нет»: у USDⓈ-M отдельного
        поля статуса ccxt не даёт вовсе. Поэтому возврат булев, а не строка статуса — иначе
        величина обещала бы больше, чем содержит.

        Отказ НЕ роняет прогон: неизвестная живость хуже известной, но лучше остановки.
        """
        call = getattr(self._ex, self.venue.ping, None)
        if call is None:
            log.degraded("у площадки нет метода ping — живость шлюза не проверена",
                         площадка=self.venue.ccxt_class, метод=self.venue.ping)
            return None
        got = await self._rest("проверка шлюза", self.venue.ccxt_class, call)
        if isinstance(got, NotReady):
            log.degraded("шлюз площадки НЕ ОТВЕТИЛ", площадка=self.venue.ccxt_class,
                         причина=got.reason)
            return False
        log.info("шлюз площадки отвечает", площадка=self.venue.ccxt_class,
                 метод=self.venue.ping)
        return True

    async def read_maintenance(self) -> str | None:
        """Состояние СПОТОВОЙ системы Binance: `ok`, `maintenance`, `shutdown`, `error`.

        ⚠ ВЕЛИЧИНА НЕ ПРО НАШУ ПЛОЩАДКУ, И ЭТО НАЗВАНО В ИМЕНИ ВОЗВРАТА. `fetchStatus` у
        Binance зовёт `sapiGetSystemStatus` — эндпоинт спотового кошелька (ccxt/binance.py),
        и на USDⓈ-M отвечает про спот.

        ⚠ ПОЧЕМУ ОНА ВСЁ-ТАКИ ВЕРНУЛАСЬ. 2026-08-11 я заменил `fetchStatus` на `ping`
        площадки и назвал замену улучшением. Это было неверно наполовину: `ping` отвечает
        «шлюз принимает запросы» и НИЧЕГО не говорит про техобслуживание, а `fetchStatus` —
        единственный признак обслуживания, который ccxt для Binance вообще отдаёт (со
        значениями и полем `eta`). Убрав его, я не улучшил прибор, а снял единственный
        источник одного из двух сигналов. Теперь их два, и каждый отвечает на свой вопрос:
        `read_status` — «доступен ли наш шлюз», `read_maintenance` — «не на обслуживании
        ли Binance в целом».

        Отказ не роняет прогон и не считается нарушением: величина справочная.
        """
        if not self._ex.has.get("fetchStatus"):
            return None
        got = await self._rest("состояние Binance", self.venue.ccxt_class,
                               lambda: self._ex.fetch_status())
        if isinstance(got, NotReady):
            log.degraded("состояние Binance не прочитано", причина=got.reason)
            return None
        status = None if got.get("status") is None else str(got["status"])
        if status == "ok":
            log.info("Binance (спотовая система) в рабочем состоянии", статус=status)
        else:
            log.degraded("BINANCE СООБЩАЕТ О НЕРАБОЧЕМ СОСТОЯНИИ — величина СПОТОВАЯ, "
                         "но других признаков обслуживания ccxt не даёт",
                         статус=str(status), до=str(got.get("eta")))
        return status

    def _rate_limit_pause_s(self) -> float:
        """Длина паузы после 429/418: `Retry-After` биржи, если он есть, но не короче минуты.

        ⚠ ССЫЛКА ЗДЕСЬ БЫЛА НЕВЕРНОЙ, ИСПРАВЛЕНО 2026-08-11. Докстрока утверждала, что
        Binance присылает `Retry-After` при обоих кодах, и ссылалась на General Info
        ФЬЮЧЕРСОВ. Проверка двумя запросами к документации показала обратное:

          * фраза «A `Retry-After` header is sent with a 418 or 429 responses and will
            give the number of seconds required to wait» стоит в СПОТОВОЙ документации
            (Spot API, REST, Limits);
          * страница USDⓈ-M (General Info) слова `Retry-After` НЕ СОДЕРЖИТ вовсе. Про
            429 она говорит только «it's your obligation as an API to back off and not
            spam the API», про 418 — что баны «scale in duration for repeat offenders,
            from 2 minutes to 3 days».

        То есть для НАШЕЙ площадки заголовок документацией не обещан. Поведение кода от
        этого не меняется и не должно: заголовок читается как НЕОБЯЗАТЕЛЬНЫЙ, его
        отсутствие даёт минуту, а наличие — максимум из него и минуты. Неверным было
        утверждение, а не расчёт.

        ⚠ Эмпирически не проверено и проверено не будет: единственный способ увидеть
        заголовок — получить 429, то есть намеренно нарушить лимит публичного бота.

        Минута снизу — из окна веса: лимит считается за одну минуту
        (`REQUEST_WEIGHT/MINUTE/1` в `exchangeInfo`, читается при открытии). Регистр
        ключа ищется явно — та же ловушка асинхронного клиента, что у `_note_weight`.
        """
        headers = self._ex.last_response_headers or {}
        raw = next((v for k, v in headers.items() if k.lower() == "retry-after"), None)
        if raw is None:
            return RATE_LIMIT_BACKOFF_S
        try:
            return max(RATE_LIMIT_BACKOFF_S, float(raw))
        except ValueError:
            log.degraded("Retry-After нечитаем — пауза по умолчанию", значение=str(raw))
            return RATE_LIMIT_BACKOFF_S

    def _declare_quiet(self, pause_s: float) -> None:
        """Объявить глобальную тишину REST на `pause_s` от СЕЙЧАС. Только удлиняет:
        две паузы подряд не укорачивают друг друга."""
        until = clock.monotonic_ns() + int(pause_s * 1e9)
        self._rest_quiet_until_ns = max(self._rest_quiet_until_ns, until)

    async def _quiet_gate(self) -> None:
        """Подождать объявленную тишину ПЕРЕД REST-запросом.

        Зовётся в начале каждого REST-метода класса. Пока тишина не объявлена (обычный
        режим), стоит ноль: одна вычитание и сравнение. После 429/418 здесь ждут ВСЕ
        задачи, а не только поймавшая отказ, — окно веса у биржи одно на IP, и запрос
        любой задачи внутри окна одинаково приближает бан.
        """
        wait_s = (self._rest_quiet_until_ns - clock.monotonic_ns()) / 1e9
        if wait_s <= 0:
            return
        self.rest_gate_held += 1
        log.degraded("REST придержан глобальной паузой лимита", секунд=round(wait_s, 1))
        await asyncio.sleep(wait_s)

    def _note_weight(self) -> None:
        """Запомнить потребление веса из заголовка последнего ответа.

        Зовётся после КАЖДОГО REST-вызова этого класса. Заголовок приходит не всегда
        (например, у ответов из кэша ccxt), поэтому число прочтений считается отдельно.

        ⚠ Регистр ключа ищется ЯВНО. У синхронного клиента ccxt заголовки приходят в
        `CaseInsensitiveDict`, и `get("X-MBX-USED-WEIGHT-1M")` работает; у асинхронного —
        в ОБЫЧНОМ `dict` со строчными ключами, и тот же вызов молча даёт `None`. Механизм
        был проверен на синхронном клиенте, а применён к асинхронному: прогон напечатал
        «пик 0 — 0.0% лимита» при живом заголовке `x-mbx-used-weight-1m = 2`.
        Поймал это `weight_reads`: ноль замеров отличим от нуля потребления.
        """
        headers = self._ex.last_response_headers or {}
        raw = next((v for k, v in headers.items()
                    if k.lower() == "x-mbx-used-weight-1m"), None)
        if raw is None:
            return
        self.weight_reads += 1
        self.weight_peak = max(self.weight_peak, int(raw))

    def _note_watch(self, kind: str, *args: str) -> bool:
        """Запомнить подписку по её АРГУМЕНТАМ. `True` — она новая.

        Аргументы, а не символ: снятие обязано повторить их в точности, иначе адресуется
        другому каналу. У свечей это (символ, таймфрейм), у остальных — (символ,).
        """
        live = self._watching.setdefault(kind, set())
        if args in live:
            return False
        live.add(args)
        return True

    async def unwatch_all(self) -> None:
        """Снять ВСЕ живые подписки явно. Отказ снятия не роняет остановку.

        ⚠ Снималась только одна из шести подписок, пока потоков было шесть. Брошенная
        подписка — не пустяк для службы, которая переоткрывает соединение: биржа ещё
        какое-то время считает её живой и продолжает слать в неё данные.
        """
        for kind, subs in sorted(self._watching.items()):
            method, params = UNWATCH.get(kind, ("", {}))
            call = getattr(self._ex, method, None) if method else None
            if call is None:
                self.ws_unwatch_failed += len(subs)
                log.degraded("для потока нет метода снятия — закроется обрывом",
                             род=kind, подписок=len(subs))
                continue
            for args in sorted(subs):
                try:
                    # Аргументы повторяются В ТОЧНОСТИ: у свечей это ещё и таймфрейм,
                    # и без него снялась бы подписка на умолчание `1m`.
                    await asyncio.wait_for(
                        call(*args, params=params) if params else call(*args),
                        timeout=WS_UNSUBSCRIBE_TIMEOUT_S)
                    self.ws_unwatched += 1
                except (TimeoutError, TypeError, ccxt.BaseError) as e:
                    # `TypeError` тоже ловится: расхождение в числе аргументов — это
                    # наша ошибка таблицы, и она не должна ронять остановку прогона.
                    self.ws_unwatch_failed += 1
                    log.degraded("подписка не снята явно — закроем обрывом",
                                 род=kind, аргументы=",".join(args),
                                 причина=f"{type(e).__name__} {e}")
        self._watching.clear()

    async def close(self) -> None:
        """Снять подписки ЯВНО и закрыть соединение вместе с сессией HTTP.

        ⚠ ДВЕ ПРАВКИ 2026-08-11 по обратной сверке, и обе про разницу «закрыли» и
        «отпустили»:

        * `un_watch_trades` не звался НИ РАЗУ. Подписки снимались обрывом сокета, то есть
          биржа узнавала о нашем уходе по молчанию, а не по слову. Для одного процесса,
          который завершается, разница невелика; для службы, которая переоткрывает
          соединение, брошенная подписка — это поток, который биржа ещё какое-то время
          считает живым;
        * `close()` без аргумента оставляет сессию HTTP жить до сборки мусора. Аргумент
          `True` закрывает и её.

        Ни то, ни другое не имеет права уронить остановку: закрытие — последнее, что
        делает прогон, и исключение здесь потеряло бы отчёт, который уже собран. Поэтому
        отказы считаются и печатаются, но не поднимаются.
        """
        await self.unwatch_all()
        try:
            # `True` — закрыть и сессию HTTP, а не только сокеты (ccxt: `close(True)`).
            await self._ex.close(True)
        except TypeError:
            # Версия ccxt без этого аргумента: закрываем как умеем, но не молча.
            log.degraded("ccxt не принимает close(True) — сессия HTTP закроется сборщиком")
            await self._ex.close()

    async def _rest(
        self, what: str, key: str, call: Callable[[], Any]
    ) -> Any | NotReady:
        """ЕДИНСТВЕННОЕ место, где исключение ccxt превращается в названный отказ.

        ⚠ ПОЯВИЛОСЬ 2026-08-11 ПО ОБРАТНОЙ СВЕРКЕ, и повод — не стиль, а дефект.
        Прежде каждый REST-вызов писал свою цепочку `except`, и они разошлись:

            метод                        ловил
            fetch_agg_trades_window      RateLimit, DDoS, NetworkError, ExchangeError,
                                         OperationFailed
            _fetch_ohlcv_guarded         RateLimit, DDoS, NetworkError, ExchangeError
            fetch_agg_trades_from        RateLimit, DDoS, NetworkError, ExchangeError
            count_history                НИЧЕГО

        Третья ветвь стояла ровно в том методе, где её нашёл зонд, — то есть починено
        было МЕСТО ПАДЕНИЯ, а не КЛАСС дефекта. Дерево ccxt 4.5.71 (замер по `__mro__`):
        под `BaseError` три ветви — `ExchangeError`, `OperationFailed`, `UnsubscribeError`,
        и `NetworkError` лежит под `OperationFailed`, а не рядом. Значит пара
        `except NetworkError` + `except ExchangeError` пропускает `OperationFailed`,
        `BadResponse`, `NullResponse`, `CancelPending`, `UnsubscribeError`.

        Достижимость проверена по карте ошибок САМОЙ ccxt для binanceusdm
        (`describe()['exceptions']`): в непойманную ветвь отображено 57 кодов Binance,
        из них на публичных эндпоинтах достижимы как минимум `-1000` (UNKNOWN),
        `-1001` (DISCONNECTED), `-1006` (UNEXPECTED_RESP), `-1010` (ERROR_MSG_RECEIVED) и
        `linear/-1008` («Server is currently overloaded»). Код `-1000` уже наблюдался
        живым зондом 2026-08-11 — он и уронил тогда добор окна.

        Замыкающая ветвь ловит `BaseError`, а НЕ `OperationFailed` поимённо: поимённая
        оставила бы мимо `UnsubscribeError` и любой класс, который ccxt заведёт впредь.

        ⚠ Замыкающая ветвь тишину НЕ объявляет, и это выбор, а не недосмотр. Пауза на
        минуту оправдана превышением лимита, где она названа документацией; распространять
        её на всякий неизвестный отказ значило бы замораживать весь REST на минуту из-за,
        например, ошибки разбора ответа. Цена обратного выбора для `-1008` не замерена и
        замерена быть не может без намеренной перегрузки биржи — это названо в отчёте
        обратной сверки, а не решено молча.
        """
        await self._quiet_gate()
        try:
            got = await call()
        except RATE_LIMIT_ERRORS as e:
            self.rest_errors[type(e).__name__] += 1
            self.rest_rate_limited += 1
            pause = self._rate_limit_pause_s()
            log.error(f"{what}: ЛИМИТ БИРЖИ ПРЕВЫШЕН — глобальная пауза, повтора нет",
                      ключ=key, пауза_с=pause, причина=f"{type(e).__name__} {e}")
            # Пауза объявляется НА КЛИЕНТА: окно веса у биржи одно на IP, и запрос
            # любой другой задачи внутри окна одинаково приближает бан по 418.
            self._declare_quiet(pause)
            return NotReady(reason=f"{key}: {what} — лимит биржи ({type(e).__name__})")
        except ccxt.NetworkError as e:
            self.rest_errors[type(e).__name__] += 1
            log.degraded(f"{what}: сетевой сбой", ключ=key,
                         причина=f"{type(e).__name__} {e}")
            return NotReady(reason=f"{key}: {what} — сеть ({type(e).__name__})")
        except ccxt.ExchangeError as e:
            self.rest_errors[type(e).__name__] += 1
            log.error(f"{what}: биржа отвергла запрос", ключ=key,
                      причина=f"{type(e).__name__} {e}")
            return NotReady(reason=f"{key}: {what} — отказ биржи ({type(e).__name__})")
        except ccxt.BaseError as e:
            self.rest_errors[type(e).__name__] += 1
            log.error(f"{what}: прочий отказ ccxt (третья ветвь дерева исключений)",
                      ключ=key, причина=f"{type(e).__name__} {e}")
            return NotReady(reason=f"{key}: {what} — отказ ({type(e).__name__})")
        self._note_weight()
        return got

    async def fetch_server_ms(self) -> int:
        """Время биржи. БРОСАЕТ, а не отдаёт `NotReady`: оба вызывающих ловят `BaseError`
        сами и оставляют прежнее сведение часов (`run._resync_clock_impl`, `observe`).

        ⚠ Ветвь лимита здесь всё же нужна, и это находка обратной сверки: без неё
        единственный REST-вызов проекта, не объявляющий глобальную тишину, — как раз тот,
        что ходит на биржу по таймеру круглые сутки. `429` на нём считался бы обычным
        отказом пересведения, и остальные задачи продолжали бы слать запросы в то же
        минутное окно веса. Исключение после объявления тишины пробрасывается дальше —
        вызывающий по-прежнему сам решает, что делать с часами.
        """
        await self._quiet_gate()
        try:
            got = int(await self._ex.fetch_time())
        except RATE_LIMIT_ERRORS as e:
            self.rest_errors[type(e).__name__] += 1
            self.rest_rate_limited += 1
            self._declare_quiet(self._rate_limit_pause_s())
            raise
        self._note_weight()
        return got


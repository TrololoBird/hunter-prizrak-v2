    async def fetch_closed_ohlcv(
        self,
        symbol: str,
        timeframe: str,
        limit: int = CCXT_EFFECTIVE_LIMIT,
        since_ms: int | None = None,
    ) -> OhlcvFetch | NotReady:
        """REST-засев. Незакрытая свеча отбрасывается здесь же (§6).

        Битый бар (экстремумы не накрывают open/close) не роняет прогон и не
        проходит молча: он отклоняется, причина с числами уходит наверх и в лог.
        Замер 2026-08-03: 1 такой бар на 73 828 — BCH/USDT:USDT 1w 2020-01-13,
        подтверждён сырым ответом биржи, см. docs/audit/broken-bar-bch-2026-08-03.md

        `since_ms` отматывает окно назад. Нужен для приёмки этапа 3: разборы корпуса
        датированы июлем, а без него доступны только последние `limit` баров — для 15м
        это 10.4 суток, то есть до дат разборов окно не достаёт.
        """
        raw = await self._fetch_ohlcv_paged(symbol, timeframe, since_ms, limit)
        if isinstance(raw, NotReady):
            return raw
        if not raw:
            return NotReady(reason=f"{symbol} {timeframe}: биржа вернула пустой список")
        bars: list[Bar] = []
        rejected: list[str] = []
        rejected_at: list[int] = []
        for r in raw:
            try:
                bars.append(Bar(open_ms=int(r[0]), open=float(r[1]), high=float(r[2]),
                                low=float(r[3]), close=float(r[4]), volume=float(r[5])))
            except ValidationError as e:
                why = (f"{symbol} {timeframe} бар {int(r[0])}: o={r[1]} h={r[2]} "
                       f"l={r[3]} c={r[4]} — {e.errors()[0]['msg']}")
                rejected.append(why)
                rejected_at.append(int(r[0]))
                log.error("бар отклонён как битый", причина=why)
        if not bars:
            return NotReady(
                reason=f"{symbol} {timeframe}: все {len(raw)} баров отклонены как битые"
            )
        off_grid = [b.open_ms for b in bars if not on_grid(b.open_ms, timeframe)]
        if off_grid:
            return NotReady(
                reason=f"{symbol} {timeframe}: {len(off_grid)} баров вне сетки, "
                       f"первый {off_grid[0]}"
            )
        closed = closed_only(bars, timeframe, clock.now_ms())
        if not closed:
            return NotReady(
                reason=f"{symbol} {timeframe}: все {len(bars)} баров ещё не закрыты"
            )
        return OhlcvFetch(bars=closed, rejected=rejected,
                          rejected_at_ms=rejected_at)

    async def _fetch_ohlcv_paged(
        self, symbol: str, timeframe: str, since_ms: int | None, limit: int
    ) -> list[list[Any]] | NotReady:
        """Свечи ГЛУБЖЕ предела ccxt в 1000 — курсором по времени.

        ⚠ ЗАЧЕМ. `bars_per_timeframe = 1000` в конфигурации выглядело выбором глубины, а
        было чужим потолком: ccxt режет выдачу свечей на 1000 жёстко (ccxt/binance.py,
        `maxLimit = 1000`), тогда как сама Binance для фьючерсов принимает 1500. Отсюда
        карта младших ТФ обрывалась не там, где кончается горизонт, а там, где кончается
        предел библиотеки:

            ТФ    1000 баров это     горизонт 180 суток
            5м    3.5 суток          не достигался
            15м   10.4 суток         не достигался
            1ч    41.7 суток         не достигался
            4ч    166.7 суток        почти не достигался
            1Д    2.7 года           достигался

        То есть повышение горизонта с 90 до 180 суток на четырёх младших ТФ не меняло
        ничего, и это было НЕ ВИДНО: отказа не возникало, ряд просто был короче.

        КАК. Ниже предела — ровно один запрос, как раньше: путь короткой истории не
        трогается, и повтор карточки обязан совпасть побайтово. Выше предела — курсор по
        `since` страницами по 1000, с дедупликацией по метке открытия (соседние страницы
        накладываются на границе).

        ⚠ Обрыв посреди пагинации НЕ МОЛЧИТ. Пустой результат — `NotReady` с причиной;
        частичный — счётчик `bars_pages_short` и строка с числами, потому что «ряд вышел
        короче запрошенного» неотличимо от «на бирже столько и есть», а разница между
        ними — разница между отказом сети и возрастом инструмента.
        """
        if limit <= CCXT_EFFECTIVE_LIMIT:
            return await self._fetch_ohlcv_guarded(symbol, timeframe, since_ms, limit)

        step = tf_ms(timeframe)
        # Без явного `since` глубина отсчитывается назад от СЕЙЧАС: запрос «дай N баров»
        # означает последние N, а не первые N от сотворения рынка.
        start = since_ms if since_ms is not None else clock.now_ms() - limit * step
        by_open: dict[int, list[Any]] = {}
        cursor = start
        pages = 0
        # Страниц заведомо хватает на `limit` баров плюс запас на пустые участки истории;
        # предел — предохранитель от неподвижного курсора, а не бюджет.
        max_pages = limit // CCXT_EFFECTIVE_LIMIT + 4
        while pages < max_pages and len(by_open) < limit:
            page = await self._fetch_ohlcv_guarded(
                symbol, timeframe, cursor, CCXT_EFFECTIVE_LIMIT)
            if isinstance(page, NotReady):
                if not by_open:
                    return page
                self.bars_pages_short += 1
                log.degraded("ряд добран НЕ ЦЕЛИКОМ — пагинация оборвана", символ=symbol,
                             тф=timeframe, набрано=len(by_open), просили=limit,
                             страниц=pages, причина=page.reason)
                break
            pages += 1
            if not page:
                break
            before = len(by_open)
            for row in page:
                by_open[int(row[0])] = row
            last = int(page[-1][0])
            if len(by_open) == before and last <= cursor:
                # Курсор стоит и новых баров нет: дальше история не идёт. Это НЕ отказ —
                # это конец ряда, и он молчит законно.
                break
            cursor = last + step
        ordered = [by_open[k] for k in sorted(by_open)]
        if not ordered:
            return NotReady(
                reason=f"{symbol} {timeframe}: пагинация не принесла ни одного бара")
        return ordered[-limit:]

    async def _fetch_ohlcv_guarded(
        self, symbol: str, timeframe: str, since_ms: int | None, limit: int
    ) -> list[list[Any]] | NotReady:
        """REST-запрос свечей с РАЗБОРОМ КЛАССА ОТКАЗА. Отдаёт `NotReady`, а не бросает.

        ⚠ До 2026-08-05 обёртки не было вовсе, и это пережиток WS-схемы: тогда REST
        работал только в засеве. После перехода на опрос REST стал ОСНОВНЫМ источником
        баров, а необработанное исключение здесь означало:
          * в `seed` — падение ВСЕГО прогона (засев не обёрнут в задачу);
          * в `_poll_bars_impl` — смерть задачи ряда навсегда: `_guarded` пробрасывает,
            и символ переставал опрашиваться до конца прогона.
        Один сетевой сбой на 162 ряда стоил ряда целиком.

        Классы разделены по указанию самой ccxt («Seven mistakes…», ошибка 4: не
        обрабатывать все ошибки одинаково) и по практике выборки:

        * `RateLimitExceeded` и `DDoSProtection` — превышение лимита. **Оба наследуют
          `NetworkError`**, то есть общий `except NetworkError` принял бы их за обрыв и
          пошёл бы повторять — а продолжение после `HTTP 429` даёт бан по IP (`418`) до
          трёх суток. Поэтому отдельная ветка и ЯВНАЯ пауза, а не повтор;
        * прочий `NetworkError` — обрыв, штатно повторяемый следующим опросом;
        * `ExchangeError` — запрос неверен, и повтор того же запроса не поможет
          (OctoBot: «there is a real issue … Don't loop»).

        Все три считаются по классам: без счётчика отказ неотличим от пустого ответа.

        ⚠ Разбор ветвей переехал в `_rest` 2026-08-11: цепочка здесь пропускала ТРЕТЬЮ
        ветвь дерева ccxt (`OperationFailed` и потомки). Разбор — в докстроке `_rest`.
        """
        raw = await self._rest(
            "опрос свечей", f"{symbol} {timeframe}",
            lambda: self._ex.fetch_ohlcv(symbol, timeframe, since=since_ms, limit=limit),
        )
        if isinstance(raw, NotReady):
            return raw
        # ccxt не типизирован: `fetch_ohlcv` объявлен как Any. Приведение здесь, а не
        # у вызывающего, — граница типизированной части проекта проходит по этому классу.
        return list(raw)


# ⚠ `atr(period)` УДАЛЕНА 2026-08-06, и это НЕ мелкая уборка — читать вместе с §8.
#
# Потребителя у неё не было ни одного: стоп строится по стоповому объёму либо проколу
# (стр. 18) и запасом за структуру (стр. 33), то есть в ПРОЦЕНТАХ, названных курсом.
# §2.9 ATR не называет — `admission.py` прямо это фиксирует: «ATR — не индикатор §2.9,
# а единица измерения порогов по §4.1». Но и по §4.1 он не понадобился: «кратные ATR»
# там одна из ТРЁХ допустимых форм относительного порога, а пороги метода источник даёт
# процентами, и проект принял их как есть.
#
# ⚠ ЭТО РАСХОДИТСЯ С §8, и владелец должен знать. Этап 2 называет ATR (Уайлдер) первым
# примитивом и требует сверки с внешней реализацией. Сверять было нечего: три

"""Канонические величины §2.9 как выражения polars. FOUNDATION.md §10.2, §0.2.

§10.2: «Индикаторы: не писать свои» — считает `polars_talib`.

ИСКЛЮЧЕНИЕ — MACD. Он определён как разность EMA12 и EMA26 тремя источниками
(Wikipedia, StockCharts, TradingView), а `polars_talib.macd` этому определению НЕ
удовлетворяет: замер 2026-08-03 показал, что он не равен разности собственных
`ema(12)` и `ema(26)` библиотеки — расхождение 5.874e-02 на баре 33, ноль с бара 300.
Библиотека, противоречащая своим же EMA, неправа по определению, поэтому MACD здесь
СОБИРАЕТСЯ из библиотечных EMA, а не берётся готовым.
Протокол: docs/audit/macd-talib-inconsistency-2026-08-03.md

Собственных реализаций сглаживания тут нет: EMA по-прежнему считает библиотека.
"""

from __future__ import annotations

import polars as pl
import polars_talib as plta


# У polars_talib нет типовых стабов, его выражения приходят как Any. Приведение
# собрано в одном месте, а не рассыпано по функциям: так видно, где кончается
# типизированная часть проекта.
def _expr(x: object) -> pl.Expr:
    assert isinstance(x, pl.Expr)
    return x


MACD_FAST = 12
MACD_SLOW = 26
MACD_SIGNAL = 9


# ⚠ `atr(period)` УДАЛЕНА 2026-08-06, и это НЕ мелкая уборка — читать вместе с §8.
#
# Потребителя у неё не было ни одного: стоп строится по стоповому объёму либо проколу
# (стр. 18) и запасом за структуру (стр. 33), то есть в ПРОЦЕНТАХ, названных курсом.
# §2.9 ATR не называет — `admission.py` прямо это фиксирует: «ATR — не индикатор §2.9,
# а единица измерения порогов по §4.1». Но и по §4.1 он не понадобился: «кратные ATR»
# там одна из ТРЁХ допустимых форм относительного порога, а пороги метода источник даёт
# процентами, и проект принял их как есть.
#
# ⚠ ЭТО РАСХОДИТСЯ С §8, и владелец должен знать. Этап 2 называет ATR (Уайлдер) первым
# примитивом и требует сверки с внешней реализацией. Сверять было нечего: три
# индикаторных гейта звали `plta.atr` НАПРЯМУЮ, минуя эту обёртку, — то есть проверяли
# библиотеку, а не проект (находка Н-5 разбора). Пробник: период 14→20 в этом файле, все
# три гейта зелёные.
#
# Вернуть — три строки поверх `plta.atr`. Пока нет порога, выраженного в ATR, возвращать
# нечего: §0 запрещает величину без референта, а «§8 её называет» — референт плана, не
# метода. Решение о §8 за владельцем; разбор: docs/audit/dead-code-2026-08-06.md


def rsi(period: int = 14) -> pl.Expr:
    return _expr(plta.rsi(pl.col("close"), timeperiod=period))


def ema(period: int) -> pl.Expr:
    return _expr(plta.ema(pl.col("close"), timeperiod=period))


def macd_line(fast: int = MACD_FAST, slow: int = MACD_SLOW) -> pl.Expr:
    """MACD = EMA(fast) − EMA(slow). Определение, а не вызов macd() библиотеки."""
    return ema(fast) - ema(slow)


# ⚠ `macd_signal(...)` УДАЛЕНА 2026-08-06: потребителя не было, и по §2.9 не могло быть.
# Там названа «MACD (дивергенция/конвергенция)» — а дивергенция строится по ЛИНИИ MACD,
# которую считает `macd_line`. Сигнальная линия нужна пересечениям, и пересечений §2.9
# не называет: завести их значило бы придумать правило (§3).
#
# Её собственная докстрока это и признавала: «Пока эта величина §2.9 не используется…
# и до её применения поведение надо замерить» — то есть код был написан ДО того, как
# понадобился, и замер, который он требовал, никто не делал полтора года. `MACD_SIGNAL`
# оставлен: он и есть тот период, который понадобится, если пересечения будут введены.


def bbands_upper(period: int = 20, dev: float = 2.0) -> pl.Expr:
    return _expr(plta.bbands(pl.col("close"), timeperiod=period, nbdevup=dev,
                             nbdevdn=dev)).struct.field("upperband")


def bbands_lower(period: int = 20, dev: float = 2.0) -> pl.Expr:
    return _expr(plta.bbands(pl.col("close"), timeperiod=period, nbdevup=dev,
                             nbdevdn=dev)).struct.field("lowerband")

def rsi(period: int = 14) -> pl.Expr:
    return _expr(plta.rsi(pl.col("close"), timeperiod=period))


def ema(period: int) -> pl.Expr:
    """Экспоненциальная скользящая В КОНВЕНЦИИ TRADINGVIEW: затравка первым close.

    ⚠ Переведена с TA-Lib-затравки (SMA первых N) 2026-08-09. Формула одна —
    s_t = a·x_t + (1−a)·s_{t−1}, a = 2/(N+1), — конвенции затравки две, и обе законны
    (Wikipedia EMA описывает обе; TA-Lib/StockCharts сеют SMA, TradingView `ta.ema` —
    первым значением). Инструмент курса — TradingView (скриншоты стр. 69), и по решению
    владельца о переносе инструментов TV (docs/audit/tv-transfer-2026-08-09.md) референт
    фактора — то, что видит автор на экране.

    Цена вопроса ЗАМЕРЕНА (docs/audit/probes/probe_ema_seed_2026-08-09.py, 318 серий):
    медиана расхождения двух конвенций 0.035% от цены, но на коротких рядах — до 6.7%
    (ряд 345 баров): свежий листинг у нас и в TV давал бы РАЗНЫЕ «EMA200 в X% от цены».

    `ewm_mean(adjust=False, min_samples=1)` polars — ровно рекурсия TV с бара 0.
    Каноничность по-прежнему признаётся с бара N (admission.CANONICAL_FROM_BARS):
    ранние значения зависят от точки старта ряда, и фактор до N баров не печатается.
    MACD (разность ema) переезжает на ту же конвенцию согласованно — как и в TV.
    """
    return _expr(pl.col("close").ewm_mean(alpha=2.0 / (period + 1),
                                          adjust=False, min_samples=1))


def sma(period: int) -> pl.Expr:
    """Простая скользящая. Стр. 69 называет ОБЕ: «Скользящее среднее» и «(эксп.)».

    ⚠ Заведена 2026-08-07, находка М-13. Курс дословно: «если местоположение этих
    скользящих ИЛИ ОДНОЙ ИЗ НИХ совпадает с нашей точкой входа/выхода, то для нас это
    дополнительный фактор». Считалась только экспоненциальная, то есть половина
    названного фактора отсутствовала. Скриншот настроек на стр. 69 показывает оба
    инструмента с длиной 200.
    """
    return _expr(plta.sma(pl.col("close"), timeperiod=period))


def macd_line(fast: int = MACD_FAST, slow: int = MACD_SLOW) -> pl.Expr:
    """MACD = EMA(fast) − EMA(slow). Определение, а не вызов macd() библиотеки."""
    return ema(fast) - ema(slow)


# ⚠ `macd_signal(...)` УДАЛЕНА 2026-08-06: потребителя не было, и по §2.9 не могло быть.
# Там названа «MACD (дивергенция/конвергенция)» — а дивергенция строится по ЛИНИИ MACD,
# которую считает `macd_line`. Сигнальная линия нужна пересечениям, и пересечений §2.9
# не называет: завести их значило бы придумать правило (§3).
#
# Её собственная докстрока это и признавала: «Пока эта величина §2.9 не используется…
# и до её применения поведение надо замерить» — то есть код был написан ДО того, как
# понадобился, и замер, который он требовал, никто не делал полтора года. `MACD_SIGNAL`
# оставлен: он и есть тот период, который понадобится, если пересечения будут введены.


def bbands_upper(period: int = 20, dev: float = 2.0) -> pl.Expr:
    return _expr(plta.bbands(pl.col("close"), timeperiod=period, nbdevup=dev,
                             nbdevdn=dev)).struct.field("upperband")


def bbands_middle(period: int = 20, dev: float = 2.0) -> pl.Expr:
    """Средняя линия полос — ПРОСТАЯ скользящая, не экспоненциальная.

    Заведена 2026-08-09: сверка с источниками нашла, что знаменатель ширины полос в
    карточке считался по `ema(20)`, тогда как средняя линия Боллинджера — SMA той же
    длины, что и σ (Bollinger «Bollinger on Bollinger Bands»; StockCharts; TradingView
    `ta.bb`; TA-Lib `BBANDS` отдаёт `middleband` = SMA). Поле берётся из ТОГО ЖЕ вызова
    `bbands`, что верх и низ, — три линии не могут разъехаться по параметрам.
    """
    return _expr(plta.bbands(pl.col("close"), timeperiod=period, nbdevup=dev,
                             nbdevdn=dev)).struct.field("middleband")


def bbands_lower(period: int = 20, dev: float = 2.0) -> pl.Expr:
    return _expr(plta.bbands(pl.col("close"), timeperiod=period, nbdevup=dev,
                             nbdevdn=dev)).struct.field("lowerband")

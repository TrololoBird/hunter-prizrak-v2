def resample(src: list[Bar], source: str, timeframe: str) -> list[Bar]:
    """Собрать бары ТФ из младших — jesse-модель, принятая владельцем 2026-08-17.

    ⚠ БЫЛА `resample_from_1m` С ЖЁСТКОЙ МИНУТОЙ; источник стал параметром 2026-08-23,
    когда у функции появился ПЕРВЫЙ боевой потребитель — пересборка битого старшего бара
    (`run._rebuild_from_lower`). Прежняя докстрока называла отсутствие такого потребителя
    прямо: «символ, чей ряд старшего ТФ биржа не отдала, сейчас теряется целиком, хотя
    минутки для него есть». Случай нашёлся не гипотетический: BCH/USDT:USDT, неделя
    2020-01-13 — биржа отдаёт агрегат с максимумом НИЖЕ открытия (o=339.65 h=215.69
    l=182.65 c=339.62) и объёмом, заниженным впятеро против суммы суток.
    ⚠ Сверка на 2 127 895 корзинах делалась ИМЕННО ДЛЯ МИНУТ; для источника крупнее
    она не повторялась, и это названо, а не замолчано. Правило же («корзина с недобором
    источника пропускается») от гранулярности не зависит: оно про полноту, а не про минуту.

    ⚠⚠ БОЕВЫМ КОДОМ НЕ ВЫЗЫВАЕТСЯ, и это сказано здесь, чтобы читатель не принял её за
    работающую часть конвейера (проверено грепом 2026-08-21: единственный вызывающий —
    её собственный гейт `gates/resample_agrees.py`). Ряды всех ТФ приходят от биржи
    нативными; решение «хранить одну каноническую гранулярность» принято, но НЕ
    ВКЛЮЧЕНО.

    Удалить её вместе с гейтом предлагал план Т-1 того же дня — предложение ОТОЗВАНО:
    здесь записано ПРАВИЛО (фантомная минута с volume == 0 вне OHLC, пустая корзина
    пропускается, неделя якорится понедельником), выведенное сверкой с барами самой
    биржи. Удаление дало бы минус пятьдесят строк и минус одно знание; включение —
    отдельная работа, и до неё функция стоит помеченной, а не тихо мёртвой.

    Правило, без которого совпадения с биржей НЕТ: минуты с volume == 0 не участвуют
    в OHLC. Пустая минута несёт фантомную цену — перенесённый close предыдущей, за
    которым не стоит ни одной сделки; нативный бар биржи строится по сделкам и фантома
    не видит (механизм найден на ASTR 2026-02-18 09:40). С правилом совпадение ТОЧНОЕ:
    0 расхождений OHLC на 2 127 895 полных корзинах шести ТФ по 30 рынкам
    (зонд probe_resample_2026-08-17 (удалён 19.08),
    evidence/probe-resample2-2026-08-17.txt); объём — сумма всех минут, сходится с
    нативным в пределах 1e-9 относительных (порядок сложения float).

    Корзина, где НИ ОДНА минута не торговала, ПРОПУСКАЕТСЯ, и это названное
    ограничение, а не забывчивость: нативная свеча такого периода — сплошной фантом
    (o=h=l=c=перенесённый close), сверка зонда такие корзины не покрывала, а
    сочинять цену без сделок запрещает §4.3. Дыра в ряду честнее выдуманного бара;
    вызывающий видит её `gaps()`-ом.

    Неполные КРАЙНИЕ корзины (начало ряда, форминг-хвост) возвращаются как есть —
    отрезать их обязан вызывающий по своим часам (`is_closed`), как и для нативных
    рядов; функция времени не знает (§10.3).

    ⚠⚠ КОРЗИНА С ДЫРОЙ ВНУТРИ РЯДА ТЕПЕРЬ ПРОПУСКАЕТСЯ (2026-08-20). До этого дня она
    возвращалась как обычный бар, и отличить её от полной было НЕЧЕМ — молчаливая
    деградация, запрещённая §4.3.

    Найдено сверкой с барами САМОЙ БИРЖИ (6 символов, четыре ТФ, 50 895 корзин):

        корзина     результат      штук
        полная      сходится      50857
        НЕПОЛНАЯ    расходится       38

    Полных корзин с расхождением — НОЛЬ, то есть формула точна, а все 38 расхождений
    объясняются потерянными минутами. Худшее: ANKR 5м, объём меньше биржевого на 84%;
    1000RATS 4ч — на 98%. Такой бар портит и профиль объёма, и границы структуры.

    Правило совпадает с уже принятым здесь для полностью неторговавшей корзины: «Дыра в
    ряду честнее выдуманного бара». Различить потерянную минуту и фантомную можно счётом:
    хранилище держит и минуты с нулевым объёмом (иначе полных корзин не было бы 50 857 из
    50 895), значит недобор минут означает именно потерю данных.

    ⚠ ЭТА ФУНКЦИЯ В БОЮ НЕ ВЫЗЫВАЕТСЯ. Единственный её потребитель — гейт
    `gates/resample_agrees.py`. То есть гейт зелёный, функция сверена, а к продукту это
    отношения не имеет — тот же класс, что и находка Н-5 про `plta.atr` («гейты звали
    библиотеку напрямую, минуя обёртку, то есть проверяли библиотеку, а не проект»).
    Место, где она нужна, названо: символ, чей ряд старшего ТФ биржа не отдала (за цикл
    2026-08-20 таких рядов 57), сейчас теряется целиком, хотя минутки для него есть."""
    if not src:
        return []
    step = tf_ms(timeframe)
    src_step = tf_ms(source)
    if src_step >= step:
        raise ValueError(f"источник {source} не мельче цели {timeframe}")
    anchor = grid_anchor_ms(timeframe)
    out: list[Bar] = []
    cur_bucket: int | None = None
    traded = False
    o = h = lo_ = c = 0.0
    vol = 0.0
    need = step // src_step
    minutes = 0
    # ⚠ Края берутся у ОТСОРТИРОВАННОГО ряда, а не `src[0]`: функция прямо допускает
    # неотсортированный вход, и при перемешанном порядке `first_bucket` указывал на
    # чужую корзину — настоящая первая теряла поблажку `edge` и отбрасывалась недобором
    # минут. Сортировка и так нужна циклу, края читаются с её концов, а не двумя
    # дополнительными проходами min/max (ревизия 2026-08-24).
    srt = sorted(src, key=lambda x: x.open_ms)
    first_bucket = (srt[0].open_ms - anchor) // step * step + anchor
    last_bucket = (srt[-1].open_ms - anchor) // step * step + anchor
    for b in srt:
        bucket = (b.open_ms - anchor) // step * step + anchor
        if bucket != cur_bucket:
            edge = cur_bucket in (first_bucket, last_bucket)
            if cur_bucket is not None and traded and (edge or minutes >= need):
                out.append(Bar(open_ms=cur_bucket, open=o, high=h, low=lo_,
                               close=c, volume=vol))
            cur_bucket = bucket
            traded = False
            vol = 0.0
            minutes = 0
        vol += b.volume
        minutes += 1
        if b.volume > 0:
            if not traded:
                o, h, lo_, c = b.open, b.high, b.low, b.close
                traded = True
            else:
                h = max(h, b.high)
                lo_ = min(lo_, b.low)
                c = b.close
    if cur_bucket is not None and traded and (
            cur_bucket in (first_bucket, last_bucket) or minutes >= need):
        out.append(Bar(open_ms=cur_bucket, open=o, high=h, low=lo_,
                       close=c, volume=vol))
    return out

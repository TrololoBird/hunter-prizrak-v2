VENUE_MS: dict[str, int] = {
    "1s": 1_000, "1m": 60_000, "3m": 180_000, "5m": 300_000, "15m": 900_000,
    "30m": 1_800_000, "1h": 3_600_000, "2h": 7_200_000, "4h": 14_400_000,
    "6h": 21_600_000, "8h": 28_800_000, "12h": 43_200_000, "1d": 86_400_000,
    "3d": 259_200_000, "1w": 604_800_000,
}
"""ДЛИТЕЛЬНОСТИ ВСЕХ ТАЙМФРЕЙМОВ, КОТОРЫЕ ОТДАЁТ ПЛОЩАДКА. Только арифметика.

⚠ ЧТО ЭТА ТАБЛИЦА ЗНАЧИТ И ЧЕГО НЕ ЗНАЧИТ. Она НЕ расширяет методологию. Порядок ключей
`TIMEFRAME_MS` — список старшинства со стр. 17 курса, и `levels.rank` берёт приоритет
только оттуда; сетап и приоритет на `2h` или `3d` посчитать нечем, потому что курс их не
называет, а придумать старшинство «по смыслу» значило бы завести правило без источника.

Здесь лежит ровно длительность — чтобы разбор по запросу владельца мог построить свинги,
накопления и профиль на любом периоде, который биржа отдаёт, и назвать найденные уровни.

Список сверен с площадкой вызовом: `binanceusdm().timeframes` даёт шестнадцать значений,
включая `1M` (календарный месяц). `1M` СЮДА НЕ ВНЕСЁН намеренно: месяц не постоянной
длины, и любое число миллисекунд для него было бы выдумкой. Пятнадцать из шестнадцати.
"""


def tf_ms(timeframe: str) -> int:
    """Длительность таймфрейма. Знает ТФ анализа (§2.8), профиля и площадки."""
    if timeframe in TIMEFRAME_MS:
        return TIMEFRAME_MS[timeframe]
    if timeframe in PROFILE_MS:
        return PROFILE_MS[timeframe]
    if timeframe in VENUE_MS:
        return VENUE_MS[timeframe]
    raise ValueError(
        f"неизвестный таймфрейм {timeframe!r}; §2.8 задаёт {sorted(TIMEFRAME_MS)}, "
        f"профиль строится из {sorted(PROFILE_MS)}, площадка отдаёт {sorted(VENUE_MS)}"
    )


def grid_anchor_ms(timeframe: str) -> int:
    return GRID_ANCHOR_MS.get(timeframe, 0)


def grid_floor_ms(ts_ms: int, timeframe: str) -> int:
    """Округлить метку ВНИЗ до сетки таймфрейма. Нужно, чтобы закрепить левый край ряда.

    Сетка берётся та же, по которой площадка нарезает свои бары (`GRID_ANCHOR_MS`), —
    то есть это НЕ выдуманная точка отсчёта, а календарь биржи. Для `1w` якорь 4 суток
    от эпохи, что даёт понедельник 00:00 UTC.
    """
    step = tf_ms(timeframe)
    anchor = grid_anchor_ms(timeframe)
    return ts_ms - (ts_ms - anchor) % step


def bars_needed(timeframe: str, horizon_days: int, warmup: int) -> int:
    """Прогрев ПЛЮС охват. Сколько баров нужно, чтобы горизонт считался целиком.

    ⚠⚠ ДО 2026-08-23 ЗДЕСЬ СТОЯЛО `max(floor, need)`, И ЭТО БЫЛ ДЕФЕКТ РАСЧЁТА, А НЕ
    выбор величины. Прогрев и охват отвечают на РАЗНЫЕ вопросы: охват — сколько рынка
    мы разбираем, прогрев — сколько истории нужно ПЕРЕД левым краем этого разбора,
    чтобы величины на нём считались. Строжайшее из двух не годится ни для одного:
    при `max` перед левым краем горизонта прогрева не остаётся ВОВСЕ.

    Перекос шёл вдоль ТФ и бил ровно по старшим, которые курс называет сильнее
    (стр. 48: «Чем старше ТФ - тем выше винрейт»). Прогрев в 700 баров относился к
    горизонту в 180 суток так:

        5м 1.4% · 15м 4.1% · 1ч 16.2% · 4ч 64.8% · 1Д 389% · 1Н 2800%

    То есть на 1Д и 1Н горизонт целиком лежал внутри собственного прогрева: ряд из 201
    бара при `ema200` давал индикатор ровно на ОДНОМ баре из 180.

    ЗАМЕР ЦЕНЫ (2026-08-23, 40 символов доски по обороту вниз, эталон — тот же ряд с
    запасом 2000 баров слева, ключ структуры — бар ВЫХОДА): доля структур внутри
    горизонта, чья разметка совпадает с эталонной, на 4ч **68.3%** при нынешней глубине.
    На 1ч — 91.1%, и градиент повторяет таблицу выше.

    ⚠ ЗАЧЕМ ЭТО ПОЯВИЛОСЬ ВООБЩЕ. Глубина была ОДНА НА ВСЕ ТФ, и это делало карту несопоставимой
    саму с собой. При 500 барах (умолчание `--seed-limit`) ряды накрывали:

        5м  1.7 суток · 15м 5.2 · 1ч 20.8 · 4ч 83.3 · 1Д 1.4 года · 1Н 9.6 года

    То есть один и тот же `horizon_days` применялся к рядам, различающимся по глубине в
    две тысячи раз. Уровень на 1Д искался за годы, уровень на 5м — за неполные двое суток,
    и обе карты клались рядом как равные. Отказа при этом не возникало: ряд просто был
    короче, и `needed_days` честно отсекал то, чего в нём нет.

    ⚠ Здесь же исправлено ЛОЖНОЕ УТВЕРЖДЕНИЕ, прожившее в проекте до 2026-08-11. Ключ
    `bars_per_timeframe = 1000` в `config/universe.toml` не читался НИЧЕМ — ни `config.py`,
    ни любым другим местом, — но на него ссылались две докстроки как на действующую
    глубину. Настоящая глубина всё это время была 500 из умолчания командной строки.

    ПРОГРЕВ обязателен и берётся не из вкуса. Он складывается из двух требований, и
    каждое стоит рядом со своим референтом: величины §2.9 требуют истории сами по себе
    (`admission.seed_floor()`, строжайшее — ema200 с 200 барами, замер
    `gates/formula_reference.py`), а детектор структур требует, чтобы структура,
    накрывающая левый край, помещалась целиком (`trading_range.MAX_STRUCTURE_BARS`).
    Складывает их ВЫЗЫВАЮЩИЙ (`run.seed_depth`) — здесь принимается уже готовое число.

    ⚠ Правка 2026-08-11 заменила здесь верное «ema200 — самое длинное» на «adx14 — 304»,
    и это была ложь: 304 — строка справочной таблицы по величине, которую не считает ни
    один модуль, а §2.9 ADX не называет. Отозвано 2026-08-17
    (docs/audit/session-2026-08-17-auto.md).
    """
    if horizon_days <= 0:
        return warmup
    need = horizon_days * 86_400_000 // tf_ms(timeframe)
    return warmup + int(need)


def on_grid(open_ms: int, timeframe: str) -> bool:
    """Лежит ли ЛЕВЫЙ край бара на сетке своего ТФ.

    ⚠ Здесь названа предпосылка, на которую опирается весь расчёт и которая до 2026-08-08
    нигде записана не была: `open_ms` считается И левым краем интервала, И меткой бара.
    Поле этот вопрос ставит явно и вынесенным в параметр — pandas даёт `closed` (какая
    сторона интервала включена) и `label` (какой границей бар подписан), backtrader —
    `rightedge`, barter-rs ключует свечу по времени ЗАКРЫТИЯ. Мы отвечаем на оба молча.

    Предпосылка ПРОВЕРЕНА на живых данных, а не предположена: 324 ряда, 160 126 баров,
    баров вне сетки 0 и шагов, не кратных ТФ, 0. Контроль двусторонний — подсаженный сдвиг
    на полшага пойман, повтор на чистом корпусе дал то же число.
    Замер: зонд probe_bars_questions_2026-08-08 (удалён 19.08)

    В боевой путь эта проверка сознательно НЕ внесена: слишком строгая, она начала бы молча
    отвергать законные бары биржи и худить ряд. Решение о её вводе — за владельцем.
    """
    return (open_ms - grid_anchor_ms(timeframe)) % tf_ms(timeframe) == 0


def is_closed(open_ms: int, timeframe: str, now_ms: int) -> bool:
    """Бар закрыт, когда биржевое сейчас дошло до его правой границы.

    Проверка по времени, а не «отбросить последний элемент кэша»: последний элемент
    бывает и закрытым — тогда отбрасывание подало бы позапрошлый бар.
    """
    return now_ms >= open_ms + tf_ms(timeframe)


def closed_only(bars: list[Bar], timeframe: str, now_ms: int) -> list[Bar]:
    return [b for b in bars if is_closed(b.open_ms, timeframe, now_ms)]


def expected_last_closed_open_ms(timeframe: str, now_ms: int) -> int:
    """Левая граница новейшего бара, который к этому моменту обязан быть закрыт.

    Считается из сетки и времени, а не из длины полученного списка. Курс на этот счёт
    молчит; из чужих реализаций отвечают пятеро, и все пятеро делают так же — ccxt
    (`round_timeframe`), freqtrade (`timeframe_to_prev_date`), jesse
    (`next_candle_timestamp`), nautilus (таймер на границу) и candles. Расхождения с полем
    здесь нет, и причина записана 2026-08-08 только затем, чтобы умолчание перестало быть
    умолчанием. Обзор: docs/audit/bars-projects-2026-08-08.md
    """
    step = tf_ms(timeframe)
    anchor = grid_anchor_ms(timeframe)
    return ((now_ms - anchor) // step) * step + anchor - step


def continuous_tail(bars: list[Bar], timeframe: str) -> list[Bar]:
    """Самый длинный НЕПРЕРЫВНЫЙ хвост ряда — то, на чём можно считать рекурсию.

    ⚠ Зачем. ATR, RSI, EMA и MACD рекурсивны: значение бара зависит от предыдущего.
    Ряд с дырой они считают так, будто бары смежные, и экспоненциальное сглаживание
    протаскивает искажение на десятки последующих баров. `find_gaps` в проекте есть с
    самого начала, но до 2026-08-04 её результат шёл ТОЛЬКО в отчёт: ни `card`, ни
    `indicators` её не звали (проверено грепом). То есть дыра доходила до стопа через ATR.

    Дыра берётся из сетки ТФ, а не из числа баров: биржа может не отдать бар вовсе, и
    тогда соседние по списку элементы не соседние по времени.

    Возвращается ХВОСТ, а не отказ: свежие бары важнее длины, а сколько отброшено —
    считает вызывающий и обязан сказать (§4.3).

    ⚠ И хвост НЕ «правильнее» автоматически: выбор здесь размен, а не исправление —
    испорченная рекурсия меняется на недопрогретую. Ценность правки в том, что разрыв
    ПЕРЕСТАЁТ быть невидимым; какой из вариантов брать — решение, а не вывод.

    ⚠⚠ ЧИСЛА, КОТОРЫМИ ЭТО ОБОСНОВЫВАЛОСЬ, ОТОЗВАНЫ 2026-08-08. Здесь стояло: «замер
    2026-08-04, BTC 5м, 599 баров, дыра в 20 баров с 300-го: EMA200 по целому ряду
    63625.08, по ряду с дырой 63628.18, по хвосту из 279 баров 63657.07». Обзор нашёл, что
    у этих чисел нет ни зонда, ни протокола, ни команды воспроизведения: они существуют
    только в этой докстроке и в теле коммита c41a2d0. §7.3 такое число не фиксирует.

    Чем они заменены. Замер 2026-08-08 на всём корпусе (324 ряда, 160 126 баров):
      * рядов, где эта функция вообще что-то делает, — ОДИН. Разрыв в корпусе один, на
        BCH 1Н; на пяти остальных ТФ разрывов нет;
      * на нём |EMA200(достроенный ряд) − EMA200(хвост)| = 0.0189 ATR14, а
        |EMA200(достроенный) − EMA200(ряда как есть)| = 0.0027 ATR14;
      * контроль: на рядах БЕЗ дыр все три способа дают тождественно одно число.
    ⚠ Вердикта по порогу нет и быть не может: одно наблюдение порогом не проверяется.
    Заодно стало видно, почему прежний замер брал ИСКУССТВЕННУЮ дыру — настоящих в корпусе
    практически нет.
    Допуск: docs/audit/tolerance-bars.md · зонд:
    зонд probe_bars_questions_2026-08-08 (удалён 19.08) · обзор:
    docs/audit/bars-projects-2026-08-08.md
    """
    if len(bars) < 2:
        return list(bars)
    step = tf_ms(timeframe)
    cut = 0
    for i in range(len(bars) - 1, 0, -1):
        if bars[i].open_ms - bars[i - 1].open_ms != step:
            cut = i
            break
    return list(bars[cut:])


def steps_between(earlier: Bar, later: Bar, timeframe: str) -> int:
    """Сколько ШАГОВ ТФ между открытиями баров. На непрерывном ряду — разность индексов.

    ⚠ Функция существует ровно потому, что эти два числа расходятся, а весь расчёт
    считал их одним. Курс говорит о свечах: «возвращается той же или следующей свечей»
    (стр. 55), «2-3 полных тел свечей ЭТОГО ТФ» (стр. 55), — то есть о ВРЕМЕНИ. Код
    считал позиции в списке, и при дыре в ряду (а дыры есть — `find_gaps`, отказы биржи)
    соседние по списку бары оказывались соседними «по курсу», отстоя на часы. Прокол
    превращался в пробой и наоборот, а от этого зависит и состояние уровня, и попадание
    в леджер. Разбор: Р-2 в docs/audit/critical-review-2026-08-04.md
    """
    return (later.open_ms - earlier.open_ms) // tf_ms(timeframe)


def find_gaps(bars: list[Bar], timeframe: str) -> list[tuple[int, int]]:
    """Пары (открытие предыдущего, открытие следующего) там, где шаг не равен шагу ТФ.

    ⚠ Предпосылка, до 2026-08-08 нигде не записанная: ЛЮБОЙ шаг мимо сетки считается
    дефектом сбора. Она верна потому, что крипта торгуется круглосуточно и законного
    разрыва у неё нет — но невысказанная предпосылка и отсутствующая выглядят одинаково.
    На рынках с сессиями это неверно: MarketProfile на MQL5 держит ТРИ политики для
    выходных, потому что там разрыв законен. Обзор: docs/audit/bars-projects-2026-08-08.md

    ⚠ ПРЕЖНЯЯ ОЦЕНКА ЧАСТОТЫ ОТОЗВАНА 2026-08-21. Здесь стояло: «на 324 рядах и 160 126
    барах корпуса разрыв ОДИН — BCH 1Н; ветка срабатывает один раз из трёхсот двадцати
    четырёх». Замер того же вида по нынешнему `data/bars` (2832 ряда, 7 609 053 бара)
    даёт 204 разрыва в 183 рядах и 655 602 пропущенных бара. Число выросло не потому, что
    рынок изменился, а потому, что выросло само хранилище: старая оценка снята с корпуса
    из 324 рядов и на сегодняшний диск не переносится.

    Где эти разрывы лежат — важнее их числа: в рабочих рядах вселенной (25 символов × 6
    ТФ) и на доске их НОЛЬ; все они на 1м вселенной (профильная лестница, добирается по
    требованию) и на рядах символов, выбывших из вселенной, которых расчёт не читает.
    """
    step = tf_ms(timeframe)
    out: list[tuple[int, int]] = []
    for prev, cur in pairwise(bars):
        if cur.open_ms - prev.open_ms != step:
            out.append((prev.open_ms, cur.open_ms))
    return out



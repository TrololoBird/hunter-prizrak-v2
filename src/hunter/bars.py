def right_edge_ms(series: dict[str, list[Bar]]) -> int:
    """Правый край ЗАКРЫТЫХ баров всех рядов — «сейчас» решения и горизонта.

    ⚠ ОДНА формула на проект (2026-08-24). До этого выражение
    `max((s[-1].open_ms for s in series.values() if s), default=0)` стояло дословно в
    четырёх местах: `levels.build_all` (срез горизонта), `engine.decide` (момент отбора
    целей) и дважды в `run`. Пока копии совпадали, «момент решения» и «сейчас горизонта»
    были одной величиной по счастливой случайности; правка любой копии молча развела бы
    их — тот же класс, что у коробки структуры, считавшейся в четырёх местах.
    """
    return max((s[-1].open_ms for s in series.values() if s), default=0)

# Сдвиг сетки от эпохи UTC. Замер 2026-08-03 на BTC/USDT:USDT: у недельных баров
# open_ms % 604800000 == 345600000 (=4 суток) — бар открывается в понедельник 00:00 UTC,
# а эпоха приходится на четверг. У остальных ТФ сдвига нет.
# Протокол: docs/audit/exchange-facts-2026-08-03.md
#
# ⚠⚠ НЕ ЗАМЕНЯТЬ БИБЛИОТЕЧНЫМ `exchange.round_timeframe` — ОН ЗДЕСЬ НЕВЕРЕН. У ccxt есть
# такая функция, и пример из её же документации («fetch-ohlcv-on-new-candle») строит на
# ней цикл опроса, поэтому соблазн «убрать своё, взять готовое» очевиден. Оракул на живых
# барах BTC/USDT:USDT (2026-08-12) сравнил обе на всех шести ТФ проекта:
#
#     ТФ    наш on_grid   ccxt round_timeframe(ROUND_DOWN)
#     5м    сходится      сходится
#     15м   сходится      сходится
#     1ч    сходится      сходится
#     4ч    сходится      сходится
#     1Д    сходится      сходится
#     1Н    сходится      РАСХОДИТСЯ на 345 600 000 мс = ровно 4 суток
#
# То есть библиотечная функция привязана к ЭПОХЕ, а эпоха — четверг. Для недельного бара
# она отдала бы четверг вместо понедельника, и вся недельная разметка уехала бы на четыре
# дня. Длительности ТФ при этом совпали у обеих 6 из 6 (`parse_timeframe`), так что
# расхождение именно в якоре, а не в арифметике.
#
# Контроль прибора пройден: подсаженный сдвиг на минуту даёт `on_grid=False`.

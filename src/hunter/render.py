_PP_FILL, _PP_EDGE = "#4a3b6b", "#9575cd"
_STRUCT_FILL, _STRUCT_EDGE = "none", "#4dd0e1"
"""Бокс СТРУКТУРЫ — голубой, как на разметке автора курса (скриншот владельца
2026-08-17). Цвет один на обе стороны: структура это факт истории, а не намерение."""


@dataclass(frozen=True)
class ZoneSpec:
    """Одна полоса на графике. `kind`: level | pp."""

    side: str
    timeframe: str
    price: float
    zone_lo: float
    zone_hi: float
    kind: str = "level"
    entry_rule: str = ""
    """Чем уровень торгуется: limit | confirmation | retest_flipped. Пусто — не записано
    (строка карты до схемы 6). Нужен, чтобы уровень, которого цена УЖЕ касалась, не
    выглядел как свежий: курс снимает лимитки на первое касание (стр. 25)."""

    state: str = "active"
    """Судьба уровня: active | worked_off | flipped. Нужна значкам разметки — красной
    стрелке отработки (стр. 25) и крестику отмены (стр. 43)."""

    retired_at_ms: int = 0
    """Когда уровень снят с карты. Ноль — не снят либо не передано. Задаёт, НА КАКОМ
    баре ставить значок: без него стрелка встала бы в конец графика, то есть соврала бы
    о моменте события."""

    from_ms: int = 0
    to_ms: int = 0
    """Окно СТРУКТУРЫ во времени. Ноль — не передано, бокс не рисуется.

    ⚠ Заведено 2026-08-17 по образцу разметки автора курса, который владелец показал
    скриншотом. У автора структура — КОМПАКТНЫЙ БОКС на тех барах, где она произошла, а
    не полоса через весь экран; от неё вправо идёт линия уровня, а зона входа стоит
    отдельным прямоугольником в БУДУЩЕМ. Прежний рендер растягивал всё на всю ширину, и
    отличить «где накопление было» от «где ждём цену» было нельзя."""

    boundary_lo: float = 0.0
    boundary_hi: float = 0.0
    """Границы СТРУКТУРЫ, породившей уровень (стр. 23-26) — того самого боковика, внутри
    которого считался профиль. Ноль в обоих полях — границы не переданы, контур не рисуется.

    ⚠ Заведено 2026-08-17 по запросу владельца, и запрос был содержательным: на графике
    зона и структура сливались в одну полосу, хотя это РАЗНЫЕ величины. Зона — Value Area
    70% объёма, структура — контейнер, из которого она посчитана. Замер на BTW показал,
    что у 4 уровней из 14 зона оказалась ШИРЕ границ структуры (до 3×): профиль считается
    по временному окну структуры, а цена внутри окна выходит за границы боковика проколами.
    Пока обе величины рисовались одинаково, увидеть это было нельзя."""

    vrvp_density: float | None = None
    """Плотность объёма в зоне: во сколько раз объём на ценовую строку профиля выше
    среднего по композиту. Вторая половина критерия силы: стр. 22 — «Сила уровня
    определяется ТФ и объемом».

    ⚠⚠ `None` — НЕ СЧИТАЛОСЬ, и это не то же самое, что измеренный ноль (§4.3). До
    2026-08-23 поле было `float = 0.0`, и «композит не построен» превращалось в ноль
    ещё на входе: `Level.vrvp_density` отдаёт `None`, схема леджера в этом месте
    специально оговаривает «NULL — композит не построен либо строка до схемы 8», а
    показ приравнивал непосчитанное к посчитанному нулю И ОТБИРАЛ ПО НЕМУ уровни,
    которые владелец увидит. Теперь неизмеренная плотность в отборе не участвует
    вовсе: при равном ТФ измеренная сильнее неизмеренной, а неизмеренные между собой
    разрешаются шириной зоны, как было до введения объёма в отбор.

    ⚠ Заведено 2026-08-19 по приказу владельца «примени силу по объёму в отборе уровней».
    До этого объём в ОТБОР не входил вовсе: при совпадении ТФ бот оставлял просто более
    широкую зону. ⚠ И первая редакция этого поля несла ДОЛЮ объёма — она оказалась
    переодетой шириной зоны (корреляция +0.716), разбор в `levels.Level.vrvp_zone_bins`."""


def _zone_style(z: ZoneSpec) -> tuple[str, str]:
    """Цвет — по СТОРОНЕ сделки на любом ТФ (решение владельца 2026-08-17: «как у
    призрака»; на его кадрах BUY всегда зелёный, SHORT всегда красный, и жёлтый
    младших ТФ читателю ничего не говорил)."""
    if z.kind == "pp":
        return _PP_FILL, _PP_EDGE
    return (_LONG_FILL, _LONG_EDGE) if z.side == "long" else (_SHORT_FILL, _SHORT_EDGE)


def chart_png(
    symbol: str,
    timeframe: str,
    bars: list[Bar],
    zones: list[ZoneSpec],
    out_path: Path,
    caption: str = "",
    price: float = 0.0,
) -> Path:
    """Нарисовать свечи с полосами зон и ценовыми плашками. Возвращает путь PNG.

    Шкала цены — по свечам (±5%): зоны за пределами видимого НЕ растягивают график
    (урок разбора собственной визуализации 2026-08-10 — растяжка в 4.5× сплющивала
    свечи), полосы клипуются, невидимые зоны просто не рисуются — их называет ТЕКСТ
    сообщения бота.

    `price` — ЕДИНАЯ цена ответа (закрытие младшего графика), та же, по которой
    считают `compose_text` и `tradable_counts`. Ноль — не передана, берётся закрытие
    последней свечи ЭТОГО графика. Заведена 2026-08-18 по находке аудита: торгуемость
    стороны решалась закрытием 4ч-свечи, и уровень между 4ч-закрытием и текущей ценой
    получал бокс на одном графике, не получал на другом, а текст звал его третьим
    именем — тот же класс дефекта «две цены в одном ответе», что уже чинился в tgbot.
    """
    # ⚠ ПУСТОЙ РЯД — НАЗВАННЫЙ ОТКАЗ, А НЕ `ValueError` ИЗ НЕДР `min()` (2026-08-23).
    # Строкой ниже пустой список обрабатывался явно (`bars[-1].close if bars else 0.0`),
    # а следом `min(b.low for b in bars)` падал с «min() arg is an empty sequence» —
    # сообщением, по которому нельзя понять ни символа, ни ТФ (§4.3).
    if not bars:
        raise ValueError(
            f"{symbol} {timeframe}: график не рисуется — ряд баров пуст")
    ref_price = price if price > 0 else bars[-1].close
    lo = min(b.low for b in bars)
    hi = max(b.high for b in bars)
    pad = (hi - lo) * 0.05
    lo, hi = lo - pad, hi + pad

    # ПОЛЕ БУДУЩЕГО справа — там стоят зоны входа, как у автора курса: слева история,
    # справа то, чего ещё не было. Без него зона входа неотличима от следа накопления.
    future = max(12, len(bars) // 6)
    right = len(bars) + future

    fig, ax = plt.subplots(figsize=(12.8, 7.2), dpi=100)
    fig.patch.set_facecolor(_BG)
    ax.set_facecolor(_BG)
    ax.axvspan(len(bars) - 0.5, right, facecolor=_BG_FUTURE, zorder=0)

    tags: list[tuple[float, str, str]] = []
    """Отложенные ценовые плашки (y, текст, цвет): рисуются после цикла зон с
    раздвижкой по вертикали — до 2026-08-17 плашки близких уровней наезжали друг
    на друга и читались как одна (session-2026-08-17 §5)."""

    entry_boxes: list[tuple[str, float, float]] = []
    """Кандидаты боксов входа (side, lo, hi): рисуются после цикла зон СО СКЛЕЙКОЙ
    пересекающихся одной стороны в один бокс — как «диапазон интереса» у автора."""

    conf_boxes: list[tuple[float, float]] = []
    """Зоны режима «по факту/наблюдение» — жёлтые, как у автора (id 7654: «работать
    с ней лучше всего по факту»); лимиткой не торгуются, но на карте автора видны."""

    inside_boxes: list[tuple[float, float]] = []
    """Зоны, ВНУТРИ которых цена уже стоит. Стр. 44: «Приоритет – не открывать позицию,
    если цена уже торгуется в зоне». Отдельная корзина, потому что подпись действия здесь
    была бы приглашением туда, куда курс входить не велит.

    ⚠ Заведена 2026-08-20 по разбору владельцем ответа по XLM: график рисовал жёлтый бокс
    режима наблюдения на уровне 5м 0.182725, а текст того же ответа про него же писал, что
    вход отсюда не приоритет по стр. 44. Два правила для одной величины: картинка брала
    только `entry_rule` из леджера и о стр. 44 не знала вовсе."""

    def bar_index(ms: int) -> int | None:
        """Номер бара по метке времени. None — метка вне окна графика."""
        if ms <= 0 or not bars:
            return None
        step = bars[1].open_ms - bars[0].open_ms if len(bars) > 1 else 0
        if step <= 0:
            return None
        idx = (ms - bars[0].open_ms) // step
        return int(idx) if 0 <= idx < len(bars) else None

    for z in sorted(zones, key=lambda z: z.zone_hi - z.zone_lo, reverse=True):
        if z.zone_lo > hi or z.zone_hi < lo:
            continue
        fill, edge = _zone_style(z)
        z_lo, z_hi = max(z.zone_lo, lo), min(z.zone_hi, hi)

        # 1. БОКС СТРУКТУРЫ на СВОИХ барах — там, где накопление реально было.
        # ⚠ ТОЛЬКО СВОЙ ТФ. Замечание владельца 2026-08-17 («структуры вне свечей»)
        # проверено числами: расчёт верен, границы всех 14 уровней лежат внутри свечей
        # своего окна. Неверна была ОТРИСОВКА — бокс структуры ЧУЖОГО таймфрейма
        # растягивался по этому графику: часовая структура занимала 89 баров
        # пятнадцатиминутки, свечи внутри неё ходили 0.275…0.35, и полоса выглядела
        # «мимо свечей». У автора на графике ТФ размечены структуры этого же ТФ.
        # Уровни старших ТФ остаются линией и зоной входа — без бокса.
        i0 = bar_index(z.from_ms) if z.timeframe == timeframe else None
        i1 = bar_index(z.to_ms) if z.timeframe == timeframe else None
        drawn_box = False
        if i0 is not None and z.boundary_lo > 0 and z.boundary_hi > z.boundary_lo:
            i1 = i1 if i1 is not None else len(bars) - 1
            b_lo, b_hi = max(z.boundary_lo, lo), min(z.boundary_hi, hi)
            if b_lo < hi and b_hi > lo and i1 >= i0:
                # РАМКА БЕЗ ЗАЛИВКИ — так у автора курса. Проверено по PDF (стр. 13,
                # 18, 20, 30, 34): структура обводится тонкой бирюзовой рамкой, сквозь
                # которую видны свечи, а проколы за границы ДОПУСКАЮТСЯ и торчат наружу
                # (стр. 18: «если на 3++ точках были проколы за границы - стоп всегда
                # ставится за этот прокол»). Заливка прятала бы и свечи, и проколы.
                ax.add_patch(patches.Rectangle(
                    (i0 - 0.5, b_lo), max(i1 - i0 + 1, 1),
                    max(b_hi - b_lo, (hi - lo) * 0.004),
                    facecolor="none", edgecolor=_STRUCT_EDGE, linewidth=1.4,
                    zorder=6,
                ))
                drawn_box = True

        # 2. ЛИНИЯ УРОВНЯ — от структуры вправо, а не через весь экран.
        # ⚠ Для уровня ЧУЖОГО ТФ бокс структуры не рисуется (см. выше), но линия всё
        # равно обязана начинаться там, где накопление было: до 2026-08-19 такие линии
        # шли от левого края кадра через весь экран, и двенадцать уровней давали сетку
        # поперёк графика. У автора линия выходит ИЗ структуры вправо (стр. 22, 27, 30).
        own_start = bar_index(z.from_ms)
        start = i0 if (drawn_box and i0 is not None) else (own_start or 0)
        # ⚠ ЛИНИЯ ОБРЫВАЕТСЯ В ТОЧКЕ ОТРАБОТКИ. Стр. 25 дословно: «этот уровень
        # становиться больше не актуальным, т.е. мы этот уровень удаляем». На рисунках
        # стр. 22 и 27 линия физически кончается там, где цена его забрала, — тянуть её
        # дальше значит показывать живым то, чего уже нет.
        i_ev = bar_index(z.retired_at_ms) if z.state != "active" else None
        line_end = i_ev if i_ev is not None else right
        if lo <= z.price <= hi:
            # Линия уровня — тонкий пунктир, как у автора на кадрах терминала:
            # иерархию задают цветные плашки и зоны, а не толщина линии
            # (разбор session-2026-08-17 §5 — «лес» одинаковых линий).
            ax.plot([start, line_end], [z.price, z.price], color=_TICK,
                    linewidth=0.8, linestyle=(0, (5, 3)), zorder=3)
            if i_ev is None:
                # Плашка кладётся ОТЛОЖЕННО: сначала собираются все, потом раздвигаются
                # по вертикали, чтобы не наезжать друг на друга (см. ниже).
                tags.append((z.price, f"{z.price:g}", edge))

        # 3. ЗОНА ВХОДА — бокс кандидатом в `entry_boxes`, рисование ПОСЛЕ цикла со
        # склейкой пересекающихся (см. ниже). Прежняя редакция рисовала бокс каждому
        # уровню прямо здесь, и все вставали в одну колонку будущего: живой ответ по
        # ONDO 18.08.2026 (14 зон на 1ч) дал стену перекрывающихся прямоугольников с
        # наползающими подписями «SELL SELL» — владелец увидел это раньше меня.
        # Бокс — только ЖИВОМУ входу: уровень активен И стоит по торгуемую сторону
        # (лимитка на покупку — ниже цены, на продажу — выше; стр. 30 «вход от
        # уровня»). Отработанным и пройденным остаются линия и значки судьбы: бокс
        # BUY над ценой — приглашение войти там, где входа нет.
        tradable_side = (z.price < ref_price if z.side == "long"
                         else z.price >= ref_price)
        if z.kind == "level" and z.state == "active" and tradable_side:
            # НАСТОЯЩИЕ границы, не обрезанные кадром: обрезка — при рисовании.
            # Иначе ценник границы печатал бы край кадра вместо цены зоны.
            if z.zone_lo <= ref_price <= z.zone_hi:
                # Стр. 44 — то же правило и той же проверкой, что в тексте карточки.
                inside_boxes.append((z.zone_lo, z.zone_hi))
            elif z.entry_rule in ("limit", "retest_flipped"):
                entry_boxes.append((z.side, z.zone_lo, z.zone_hi))
            else:
                # «По факту»-зона: не готовый вход (стр. 25 — лимитки сняты), но у
                # автора она на карте ЖЁЛТАЯ, а не отсутствует (корпус, раздел 4).
                conf_boxes.append((z.zone_lo, z.zone_hi))
        # 3б. ЗНАЧКИ СУДЬБЫ — как на разметке автора: красная стрелка там, где уровень
        # отработан (стр. 25 «мы этот уровень удаляем»), синий крестик там, где пробит
        # и сменил сторону (стр. 43). Ставятся НА БАРЕ СОБЫТИЯ, а не в конце графика:
        # значок в неверном месте хуже отсутствующего — он утверждает время, которого
        # не было.
        if z.kind == "level" and z.state in ("worked_off", "flipped"):
            if i_ev is not None and lo <= z.price <= hi:
                if z.state == "worked_off":
                    # ЦВЕТ И НАПРАВЛЕНИЕ — по словарю значков автора, снятому с 16
                    # страниц PDF: ЗЕЛЁНАЯ стрелка ВВЕРХ под лонговым уровнем, КРАСНАЯ
                    # ВНИЗ над шортовым (стр. 19, 21-32, 39, 41, 43, 44, 46, 47).
                    # Прежняя редакция красила обе красным — это была моя выдумка.
                    up = z.side == "long"
                    dy = (hi - lo) * 0.055
                    ax.annotate(
                        "", xy=(i_ev, z.price + (dy if up else -dy)),
                        xytext=(i_ev, z.price + (-dy if up else dy) * 0.35),
                        arrowprops={"arrowstyle": "-|>",
                                    "color": "#2f9e4f" if up else "#d0342c",
                                    "linewidth": 2.4, "mutation_scale": 16},
                        zorder=8, annotation_clip=False,
                    )
                else:
                    # ⚠ КРЕСТИКА В КУРСЕ НЕТ. Проверено по всем 69 страницам: значков X
                    # нет ни на одной, слова «крестик» нет в тексте. Курс велит уровень
                    # СТИРАТЬ (стр. 25), и на рисунках линия просто обрывается.
                    # Крестик взят с РАЗМЕТКИ КАНАЛА автора (скриншот владельца
                    # 2026-08-17) — источник второго ряда, и здесь это названо, а не
                    # выдано за курс.
                    ax.plot([i_ev], [z.price], marker="x", color="#2f6fd0",
                            markersize=11, markeredgewidth=2.4, zorder=8)

        if z.kind == "pp":
            # Зона переприора — узкая полоса у правого края: это зона тени свечи слома,
            # а не область входа лимитками.
            ax.add_patch(patches.Rectangle(
                (len(bars) - future * 0.35, z_lo), future * 0.45,
                max(z_hi - z_lo, (hi - lo) * 0.003),
                facecolor=fill, edgecolor=edge, linewidth=1.0, alpha=0.8, zorder=4,
            ))

    # БОКСЫ ВХОДА — после цикла, СКЛЕЕННЫЕ: пересекающиеся боксы одной стороны
    # рисуются ОДНИМ прямоугольником с одной подписью — тот же приём, что строка
    # «Диапазон интереса» в сводке (пост автора 17.08.2026: две структуры — один
    # диапазон 64890–65200). Введено по живому ответу ONDO 18.08.2026: без склейки
    # 6 лимиток одной стороны вставали стеной с кашей подписей «SELL SELL».
    # Склейка транзитивная по перекрытию, критерий геометрический.
    def merge_spans(spans: list[tuple[float, float]]) -> list[list[float]]:
        out: list[list[float]] = []
        for b_lo, b_hi in sorted(spans):
            if out and b_lo <= out[-1][1]:
                out[-1][1] = max(out[-1][1], b_hi)
            else:
                out.append([b_lo, b_hi])
        return out

    # ПОДПИСЬ ПО-РУССКИ И ДЕЙСТВИЕМ. Читатель канала мини-курса не открывал: «BUY» и
    # «SELL» он опознает, но «ПО ФАКТУ» рядом с ними — уже жаргон, и по-русски вся
    # тройка читается одинаково быстро. Автор подписывает коробки действием (его
    # разметка BTC 19.08.2026: SHORT, BUY 1, BUY 2), а не именем стороны.
    groups = [
        ("ПОКУПКА", _LONG_FILL, _LONG_EDGE,
         [(b_lo, b_hi) for s, b_lo, b_hi in entry_boxes if s == "long"]),
        ("ПРОДАЖА", _SHORT_FILL, _SHORT_EDGE,
         [(b_lo, b_hi) for s, b_lo, b_hi in entry_boxes if s == "short"]),
        # Жёлтая зона наблюдения — подпись словами автора («по факту», id 7654).
        ("ПО ФАКТУ", _CONF_FILL, _CONF_EDGE, conf_boxes),
        ("ЦЕНА ВНУТРИ", _INSIDE_FILL, _INSIDE_EDGE, inside_boxes),
    ]
    ruler_edges: list[float] = []
    """Ближние края боксов вне цены — кандидаты линейки замера хода (ниже)."""
    # ⚠ ПОЛОСЫ И НУМЕРАЦИЯ (2026-08-19). Все три группы рисовались на ОДНОМ месте по
    # x, и коробка «по факту» ложилась поверх «BUY»: живой рендер BTC дал подпись
    # «ПО BUYКТУ» — две надписи в одной точке. Теперь торгуемые (BUY/SELL) занимают
    # свою полосу, наблюдение — соседнюю, и налезать им негде.
    #
    # Нумерация взята С РАЗМЕТКИ АВТОРА (скрин BTC 19.08.2026: «BUY 1» выше, «BUY 2»
    # ниже): счёт идёт ОТ ЦЕНЫ наружу, то есть первым нумеруется ближайший вход — он
    # же исполнится первым. Одиночная коробка номера не получает: «ПОКУПКА 1» без
    # «ПОКУПКА 2» обещает продолжение, которого нет.
    LANES = {"ПО ФАКТУ": (0.54, 0.30)}
    for label, fill, edge, spans in groups:
        x0f, wf = LANES.get(label, (0.06, 0.44))
        merged = merge_spans(spans)
        numbered = len(merged) > 1
        order_by_price = sorted(
            range(len(merged)),
            key=lambda i: abs((merged[i][0] + merged[i][1]) / 2 - ref_price))
        seq = {idx: n + 1 for n, idx in enumerate(order_by_price)}
        for n, (b_lo, b_hi) in enumerate(merged):
            d_lo, d_hi = max(b_lo, lo), min(b_hi, hi)
            ax.add_patch(patches.Rectangle(
                (len(bars) + future * x0f, d_lo), future * wf,
                max(d_hi - d_lo, (hi - lo) * 0.004),
                facecolor=fill, edgecolor=edge, linewidth=1.2, alpha=0.55, zorder=4,
            ))
            text = f"{label} {seq[n]}" if numbered and label != "ПО ФАКТУ" else label
            ax.annotate(
                text,
                xy=(len(bars) + future * (x0f + wf / 2), (d_lo + d_hi) / 2),
                va="center", ha="center", fontsize=8, fontweight="bold",
                color="white", zorder=6,
            )
            # ОБЕ ГРАНИЦЫ ЗОНЫ — ценниками на шкалу. Так у автора на скриншотах
            # разметки (корпус docs/audit/tg-prizrak-2026-08.md раздел 8: зона EIGEN
            # подписана парой 0,1593/0,1621, уровни ARB/DOT идут парами линий с
            # обеими ценами на шкале). Ценник получает только граница, попавшая в
            # кадр, и это НАСТОЯЩАЯ цена зоны, а не край обрезки: первый же пробный
            # рендер напечатал границе-за-кадром цену кадра, что было бы ложью
            # прибора. Плашки идут в общую раздвижку с дедупликацией.
            for y in (b_lo, b_hi):
                if lo <= y <= hi:
                    tags.append((y, f"{y:g}", edge))
            if ref_price > 0 and (ref_price < b_lo or ref_price > b_hi):
                ruler_edges.append(b_lo if ref_price < b_lo else b_hi)

    # Линейка замера хода — серая вертикаль с процентом, как у автора (корпус
    # tg-prizrak, раздел 8: «−13,00%» у KAS). По ОДНОЙ на направление — до
    # ближайшей зоны сверху и снизу; ход короче 1.5% высоты кадра не размечается.
    above = [y for y in ruler_edges if y > ref_price]
    below = [y for y in ruler_edges if y < ref_price]
    for edge_y in ([min(above)] if above else []) + ([max(below)] if below else []):
        if abs(edge_y - ref_price) < (hi - lo) * 0.015:
            continue
        x_r = len(bars) + future * 0.78
        y0c, y1c = max(min(ref_price, edge_y), lo), min(max(ref_price, edge_y), hi)
        if y1c <= y0c:
            continue
        move = (edge_y - ref_price) / ref_price * 100
        ax.plot([x_r, x_r], [y0c, y1c], color=_TICK, linewidth=1.0, zorder=6)
        ax.plot([x_r], [y1c if edge_y > ref_price else y0c],
                marker="^" if edge_y > ref_price else "v",
                color=_TICK, markersize=4, zorder=6)
        ax.annotate(f"{move:+.2f}%", xy=(x_r, (y0c + y1c) / 2),
                    xytext=(3, 0), textcoords="offset points",
                    va="center", ha="left", fontsize=7.5, color=_TEXT, zorder=6)

    w = 0.62
    for i, b in enumerate(bars):
        c = _UP if b.close >= b.open else _DN
        ax.plot([i, i], [b.low, b.high], color=c, linewidth=0.9, zorder=5)
        body_lo, body_hi = min(b.open, b.close), max(b.open, b.close)
        ax.add_patch(patches.Rectangle(
            (i - w / 2, body_lo), w, max(body_hi - body_lo, (hi - lo) * 0.0012),
            facecolor=c, edgecolor=c, zorder=5,
        ))

    # ПРОФИЛЬ ОБЪЁМА у правого края — как на разметке автора курса. Считается по
    # ВИДИМЫМ барам: объём каждого раскладывается равномерно по его диапазону
    # (то же приближение, что у `profile_source.CandleWindows`), и это честное
    # приближение, а не тот профиль, из которого посчитаны уровни: тот строится по
    # минутным свечам окна структуры, а здесь — по барам этого графика.
    rows_n = 48
    step_px = (hi - lo) / rows_n
    if step_px > 0:
        buckets = [0.0] * rows_n
        for b in bars:
            k0 = max(0, min(rows_n - 1, int((b.low - lo) / step_px)))
            k1 = max(0, min(rows_n - 1, int((b.high - lo) / step_px)))
            share = b.volume / (k1 - k0 + 1)
            for k in range(k0, k1 + 1):
                buckets[k] += share
        vmax = max(buckets) or 1.0
        poc_k = buckets.index(max(buckets))
        # Узкая полоса у самого края (треть поля будущего): прежняя ширина 0.9
        # съедала кадр и зоны входа ложились ПОВЕРХ профиля — разбор ответа
        # 2026-08-17, замечание владельца о «ужасных графиках».
        width_px = future * 0.32
        for k, v in enumerate(buckets):
            if v <= 0:
                continue
            colr = "#c8b93a" if k == poc_k else "#2a3a55"
            ax.add_patch(patches.Rectangle(
                (right - v / vmax * width_px, lo + k * step_px),
                v / vmax * width_px, step_px * 0.92,
                facecolor=colr, edgecolor="none", alpha=0.8, zorder=1,
            ))

    # ТЕКУЩАЯ ЦЕНА — пунктир через весь график и контрастная плашка справа.
    # Без неё читатель не видел, ГДЕ рынок относительно зон (session-2026-08-17 §5).
    last_close = bars[-1].close
    if lo <= last_close <= hi:
        ax.plot([-1, right], [last_close, last_close], color=_TEXT,
                linewidth=0.9, linestyle=(0, (4, 3)), zorder=7)
        # Плашка текущей цены — цветом последней свечи, как в терминале автора.
        tags.append((last_close, f"{last_close:g}",
                     _UP if bars[-1].close >= bars[-1].open else _DN))

    # ПЛАШКИ ЦЕН — с раздвижкой: близкие сдвигаются по вертикали, чтобы каждая
    # читалась; линия остаётся на своей цене, сдвигается только подпись.
    # ⚠ Раздвижка ОГРАНИЧЕНА КАДРОМ (2026-08-17, второй заход). Первая редакция двигала
    # каждую следующую плашку вверх без предела и рисовала с annotation_clip=False:
    # живой ответ по BTC (79 зон на графике) выстроил столбец плашек до 66817 при шкале
    # до 64100 — подписи ушли за верх кадра и сломали компоновку. Теперь плашка, которой
    # не хватило места до верха шкалы, НЕ рисуется: линия уровня остаётся, цену называет
    # текст сводки. Повторы одной цены (уровень на двух ТФ) схлопываются в одну плашку.
    min_gap = (hi - lo) * 0.024
    prev: float | None = None
    seen_txt: set[str] = set()
    for y, txt, colr in sorted(tags, key=lambda t: t[0]):
        if txt in seen_txt:
            continue
        seen_txt.add(txt)
        y_lab = y if prev is None else max(y, prev + min_gap)
        if y_lab > hi:
            continue
        prev = y_lab
        ax.annotate(
            txt, xy=(right, y_lab), xytext=(6, 0),
            textcoords="offset points",
            va="center", ha="left", fontsize=8.5, fontweight="bold", color="white",
            bbox={"boxstyle": "square,pad=0.22", "facecolor": colr, "edgecolor": "none"},
            zorder=9, annotation_clip=False,
        )

    # ОСЬ ВРЕМЕНИ — даты по нижнему краю (6 меток), формат от длительности бара:
    # внутридневные ТФ несут время, дневные и старше — только дату.
    step_ms = bars[1].open_ms - bars[0].open_ms if len(bars) > 1 else 0
    fmt = "%d.%m %H:%M" if 0 < step_ms < 86_400_000 else "%d.%m.%y"
    n_ticks = 6
    idxs = [round(k * (len(bars) - 1) / (n_ticks - 1)) for k in range(n_ticks)]
    ax.set_xticks(idxs)
    ax.set_xticklabels(
        [datetime.fromtimestamp(bars[i].open_ms / 1000, UTC).strftime(fmt)
         for i in idxs], fontsize=7.5, color=_TICK)
    ax.tick_params(axis="x", length=2, color=_TICK)

    # ШКАЛА ЦЕНЫ — редкие деления справа, как на платформе автора.
    ax.yaxis.tick_right()
    span = hi - lo
    raw = span / 6
    mag = 10 ** int(f"{raw:e}".split("e")[1])
    step_y = max(raw // mag, 1) * mag
    y0 = (int(lo / step_y) + 1) * step_y
    yticks = []
    yv = y0
    while yv < hi:
        yticks.append(yv)
        yv += step_y
    ax.set_yticks(yticks)
    ax.set_yticklabels([f"{v:g}" for v in yticks], fontsize=7.5, color=_TICK)
    ax.tick_params(axis="y", length=2, color=_TICK)

    # ЛЕГЕНДА-ПЛАШКА УБРАНА С КАРТИНКИ (решение владельца 2026-08-17 «как у призрака»:
    # на его кадрах служебного текста нет). Зоны подписаны BUY/SELL прямо внутри,
    # остальные значки объясняет хвост текстовой сводки бота.

    ax.set_xlim(-1, right)
    ax.set_ylim(lo, hi)
    for side in ("top", "right", "left", "bottom"):
        ax.spines[side].set_visible(False)
    # Шапка минимальная, как строка тикера в терминале: символ · ТФ · подпись.
    title = f"{symbol} · {timeframe}"
    if caption:
        title += f" · {caption}"
    ax.set_title(title, loc="left", fontsize=10.5, color=_TEXT)
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path)
    plt.close(fig)
    return out_path

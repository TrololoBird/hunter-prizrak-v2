class SwingKind(StrEnum):
    HIGH = "high"
    LOW = "low"


class Swing(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    kind: SwingKind
    index: int = Field(ge=0)
    """Позиция среднего бара в поданном ряду."""

    open_ms: int
    price: float
    confirmed_at_index: int
    """Индекс бара, после закрытия которого фрактал стал известен: `index + depth`.

    ⚠ ЗДЕСЬ СТОЯЛО «index + 2» (исправлено 2026-08-23) — число от ПЯТИБАРНОГО фрактала
    Вильямса, у которого крыло равно двум. `ZIGZAG_DEPTH` равен 5 с 2026-08-20, то есть
    подтверждение отстоит на ПЯТЬ баров, а не на два. Поле — то самое, по которому
    потребитель решает, что свинг можно брать БЕЗ ЗАГЛЯДЫВАНИЯ ВПЕРЁД (I-5): докстрока,
    занижающая задержку подтверждения втрое, разрешала бы читать будущее.

    ⚠ Здесь именно `depth`, а не литерал: значение приходит из `local_extremes`, и
    зависимость проверяется отдельно (`SwingSet._ordered`), а не выводится из `index`."""


class SwingSet(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    swings: tuple[Swing, ...]
    bars_scanned: int
    confirmed_until_index: int
    """Дальше этого индекса фракталы ещё не могут быть подтверждены.

    ⚠⚠ ПОЛЕ НИКТО НЕ ЧИТАЕТ, А ПИШУТ ЕГО ТРОЕ И ПО-РАЗНОМУ. Установлено грепом
    2026-08-22: вхождений в `src` ровно четыре — это объявление и три присваивания,
    ни одного чтения. Смыслы у трёх писателей разные:

      * `detect` (этот модуль) — `len(bars) - 1 - depth`, то есть настоящий ГОРИЗОНТ
        подтверждения для полного ряда: правее него фрактал подтвердиться не успел;
      * `engine._trend_as_of` — `cut[-1].confirmed_at_index`, то есть подтверждение
        ПОСЛЕДНЕГО ВЗЯТОГО свинга. Оно не больше горизонта, но это другая величина;
      * `figures.pennant` — `structure.first_index`, то есть ГРАНИЦА ОТБОРА, по которой
        подмножество и построено.

    Каждое значение по-своему защитимо, и расчёт ни одно из них не портит — потому что
    расчёт их не спрашивает. Опасно другое: поле НАЗЫВАЕТСЯ гарантией причинности и
    потому выглядит проверкой, которой нет. Это тот же класс, что удалённый в 2026-08-05
    счётчик `ws_unclosed_violations`, — величина, которая не может оказаться неверной,
    потому что её никто не сверяет.

    Поле оставлено, а не удалено: снятие тронуло бы три модуля ради нуля выигрыша в
    расчёте. Но опираться на него ЗАПРЕЩЕНО — сначала свести три смысла к одному и
    завести читателя. Причинность держат `Swing.confirmed_at_index` и явные резы у
    потребителей (`levels` — префикс по `born_ms`, `engine._trend_as_of` — рез по
    `upto_ms`), а не это поле."""

    _by_kind: dict[SwingKind, tuple[Swing, ...]] = PrivateAttr(default_factory=dict)
    """Память `of()`. НЕ поле модели: в сравнение, хэш и сериализацию не входит."""

    _confirmed_of: dict[SwingKind, tuple[int, ...]] = PrivateAttr(default_factory=dict)
    """Память `confirmed_of()` — та же причина."""

    _prefixes: ZigzagPrefixes | None = PrivateAttr(default=None)
    """Память `prefixes_of()` — индекс зигзага со всеми префиксами этого набора.

    ⚠ Перенесена сюда 2026-08-23 из МОДУЛЬНОГО словаря `_PREFIX_CACHE`: чистый модуль
    не имеет права держать глобальное состояние (§10.3), а память чистой функции,
    привязанная к своему объекту, состоянием модуля не является. Разбор — в докстроке
    `prefixes_of`."""

    @model_validator(mode="after")
    def _ordered(self) -> SwingSet:
        """Экстремумы обязаны идти слева направо — это условие, а не совпадение.

        ⚠ Проверка ЗАВЕДЕНА 2026-08-21 вместе с памятью `of()` и двоичным поиском в
        `figures.head_and_shoulders`. Оба опираются на порядок: поиск по отсортированному
        ряду на неотсортированном молча вернёт НЕ ТО, без исключения и без следа. Порядок
        обеспечивает `local_extremes` (проход по возрастанию `i`), но обеспечивает его
        КОД, а код меняется. Значит условие держит проверка при рождении объекта, а не
        докстрока у потребителя.

        Стоит она один проход на ряд — шесть раз на символ, — тогда как опора на неё
        экономит миллионы сравнений (замер в `of()`).

        `confirmed_at_index` проверяется ОТДЕЛЬНО от `index`, а не выводится из него:
        сейчас это `index + depth` при постоянном `depth`, но зависимость эта —
        свойство сегодняшнего `local_extremes`, а опирается поиск именно на
        `confirmed_at_index`. Проверяется то, чем пользуются.
        """
        prev_i = prev_c = -1
        for sw in self.swings:
            if sw.index < prev_i:
                raise ValueError(
                    f"экстремумы не по возрастанию индекса: {sw.index} после {prev_i}")
            if sw.confirmed_at_index < prev_c:
                raise ValueError(
                    f"экстремумы не по возрастанию подтверждения: "
                    f"{sw.confirmed_at_index} после {prev_c}")
            prev_i, prev_c = sw.index, sw.confirmed_at_index
        return self

    def confirmed_of(self, kind: SwingKind) -> tuple[int, ...]:
        """Метки подтверждения экстремумов одной стороны — ряд для двоичного поиска.

        Неубывающий по построению (проверено `_ordered`), поэтому `bisect_right` по нему
        даёт ЧИСЛО экстремумов, подтверждённых не позже заданного бара. Ровно это и
        нужно правилу «заглядывать вперёд нельзя» (I-5).
        """
        if (got := self._confirmed_of.get(kind)) is None:
            got = self._confirmed_of[kind] = tuple(
                sw.confirmed_at_index for sw in self.of(kind))
        return got

    def of(self, kind: SwingKind) -> tuple[Swing, ...]:
        """Экстремумы одной стороны, в порядке появления.

        ⚠ ЗАПОМИНАЕТСЯ С 2026-08-21, и это не преждевременная оптимизация, а замер.
        Профиль расчёта BTC на боевых глубинах рядов (51840 баров 5м, `cProfile`,
        178 с на символ): этот метод вызывался 3208 раз, и его генератор — 8 181 291
        раз, 7.8 с. Зовёт его `figures.head_and_shoulders` на КАЖДОМ переприоре, а
        набор экстремумов от переприора не зависит вовсе — пересчитывался один и тот
        же ответ.

        Ответ ТОТ ЖЕ: `self.swings` заморожен (`tuple` в замороженной модели), значит
        второй вызов не может увидеть другой набор. Это условие правильности памяти, и
        держит его не докстрока, а `frozen=True` на модели.
        """
        if (got := self._by_kind.get(kind)) is None:
            got = self._by_kind[kind] = tuple(s for s in self.swings if s.kind is kind)
        return got


class TrendDirection(StrEnum):
    UP = "up"
    DOWN = "down"
    NONE = "none"
    """Ни того, ни другого. Курс такого случая не называет — и здесь он не выдумывается."""


class Trend(BaseModel):
    """Тренд по стр. 12 — определение курса, а не индикатор.

    Дословно: «Восходящий тренд — движение цены на выбранном ТФ, при котором **каждый
    следующий ЛОЙ выше предыдущего**. Нисходящий — при котором **каждый следующий ХАЙ
    ниже предыдущего**.»
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    direction: TrendDirection
    holds_for: int = Field(ge=0)
    """На скольких подряд идущих экстремумах свойство выполняется, считая от последнего.

    Окна здесь нет умышленно: курс говорит «каждый следующий», но не говорит, сколько
    их брать. Вместо выдуманного окна сообщается ЗАМЕРЕННАЯ глубина, на которой свойство
    держится, — читающий видит, тренд это из двух точек или из десяти (§I-7).
    """


def trend(swings: SwingSet) -> Trend:
    """Направление по стр. 12 и глубина, на которой оно держится.

    Минимальная проверка — два последних экстремума нужной стороны: «следующий выше
    предыдущего» меньше чем на двух не определено. Если выполняются оба условия сразу
    (лои растут И хаи падают) — это не тренд, а сходящаяся структура, и направление
    не назначается.
    """
    # ⚠ Тренд читается по ЦЕПОЧКЕ, а не по сырым экстремумам, и это не украшение.
    # Стр. 12 говорит «каждый следующий ЛОЙ выше предыдущего» — про колена зигзага. На
    # сыром ряду два лоя подряд без хая между ними образуют пару, которой в определении
    # курса нет, и «тренд» считался бы по половинке колена. Будущее здесь уже известно
    # (ряд подан целиком), поэтому схлопывание законно — в отличие от `detect`, где оно
    # изымало бы экстремум из прошлого.
    return trend_of_chain(zigzag(list(swings.swings)))


def trend_of_chain(chain: list[Swing]) -> Trend:
    """То же, что `trend`, но по УЖЕ построенной цепочке.

    Выделено 2026-08-23 ради снятия квадратичности: цепочку для ПРЕФИКСА теперь отдаёт
    `prefixes_of`, и строить её заново каждому вызывающему больше не нужно.
    """
    lows = [s.price for s in chain if s.kind is SwingKind.LOW]
    highs = [s.price for s in chain if s.kind is SwingKind.HIGH]

    def depth(seq: list[float], rising: bool) -> int:
        n = 0
        for i in range(len(seq) - 1, 0, -1):
            if (seq[i] > seq[i - 1]) if rising else (seq[i] < seq[i - 1]):
                n += 1
            else:
                break
        return n + 1 if n else 0

    up = depth(lows, rising=True)
    down = depth(highs, rising=False)
    if up and down:
        return Trend(direction=TrendDirection.NONE, holds_for=0)
    if up:
        return Trend(direction=TrendDirection.UP, holds_for=up)
    if down:
        return Trend(direction=TrendDirection.DOWN, holds_for=down)
    return Trend(direction=TrendDirection.NONE, holds_for=0)


def local_extremes(bars: list[Bar], depth: int) -> list[Swing]:
    """СЫРЫЕ экстремумы окна `depth` с каждой стороны, в порядке подтверждения.

    ⚠⚠ СРАВНЕНИЕ СПРАВА СТАЛО НЕСТРОГИМ 2026-08-21, И ЭТО ПРАВКА МЕТОДА, А НЕ СТИЛЯ.
    Прежняя редакция сравнивала строго с обеих сторон и объясняла это так: «определение
    говорит "lower HIGHs" и "higher LOWs", то есть равенство экстремума не образует».
    Довод ОТОЗВАН: он взят из определения ТРЕНДА (стр. 12, «каждый следующий ЛОЙ выше
    предыдущего») и приложен к определению ЭКСТРЕМУМА, где курс говорит обратное.

    Стр. 13 определяет флэт через ПОВТОР: «Флэт - это боковой тренд, при котором в
    течении периода времени локальные хаи/лои повторяются и не меняются.» Повторяющийся
    хай — это два бара с ОДИНАКОВЫМ хаем. При строгом сравнении с обеих сторон такое
    плато не даёт экстремума НИ ОДНОГО: у первого бара плато равный сосед справа, у
    второго — равный сосед слева. То есть чем точнее флэт отвечает определению курса,
    тем вернее его границу прибор не видел.

    ЧТО СТАЛО: строго СЛЕВА, нестрого СПРАВА. Плато даёт РОВНО ОДИН экстремум — свой
    первый бар, и это же отвечает стр. 18 («Границы базы (хай и лой) чаще всего
    определяются первыми 2-мя точками»): границу задаёт первое касание уровня, а не
    последнее. Полностью нестрогое сравнение отвергнуто — оно объявило бы экстремумом
    КАЖДЫЙ бар плато. Асимметрия не наша выдумка: так устроен `ta.pivothigh` в Pine
    (строго слева, нестрого справа), и так же её воспроизводят чужие реализации.

    ЗАМЕР, ПОКАЗАВШИЙ ЦЕНУ ПРЕЖНЕГО ПРАВИЛА (2026-08-21, свежие REST-бары, 8 символов ×
    5 ТФ, 38 386 закрытых баров): пар соседних баров с РАВНЫМ хаем или лоем — 2748, то
    есть 7.16% баров. Экстремумов строго 4503, нестрого справа 4815: строгое правило
    молча теряло 312 экстремумов (6.9%). Потеря распределена не случайно, а ровно там,
    где шаг цены крупен относительно цены: ANKR 5м 83 → 118 (+42%), ARPA 5м 109 → 138,
    XAG 15м 90 → 117, ONDO 5м 87 → 113; на BTC 1Д, 4ч и 1ч прибавки НЕТ ВОВСЕ (0).

    КОНТРОЛЬ В ОБЕ СТОРОНЫ (тот же день, тем же кодом):
      * структуры, которые автор обвёл в разборах, обязаны выжить и не размножиться —
        и не меняются НИ ОДНОЙ: ETH флэт 01-05.08 1 и 1, BTC база 08-10.08 2 и 2,
        BTC BUY 1 14-17.08 3 и 3;
      * там, где плато есть, структуры обязаны появиться — появляются: SOL 4ч 7 → 13,
        ONDO 5м 5 → 11, ANKR 5м 6 → 13, XAG 15м 6 → 13. Всего по выборке 256 → 308.

    Отдельная функция, а не тело `detect`, потому что цепочку зигзага надо уметь
    строить из тех же экстремумов при другой ширине окна — иначе замер чувствительности
    к `ZIGZAG_DEPTH` пришлось бы писать копией этого цикла, и копия разошлась бы с
    оригиналом на первой же правке.

    ⚠ Имя `pivots` снято 2026-08-21 вместе с этой правкой. Слово `pivot` в литературе
    несёт ТРИ несовместимых значения — свинговый экстремум (`ta.pivothigh` у вендоров),
    точка покупки при выходе из базы (O'Neil, из «pivotal point» Ливермора) и формула
    `(H+L+C)/3` с уровнями R1/S1 (фольклор торговых ям). Ни одно не является
    первоисточным термином, и в проекте оно не употребляется.
    """
    found: list[Swing] = []
    for i in range(depth, len(bars) - depth):
        mid = bars[i]
        left = bars[i - depth:i]
        right = bars[i + 1:i + 1 + depth]

        if all(b.high < mid.high for b in left) and all(b.high <= mid.high for b in right):
            found.append(Swing(kind=SwingKind.HIGH, index=i, open_ms=mid.open_ms,
                               price=mid.high, confirmed_at_index=i + depth))
        if all(b.low > mid.low for b in left) and all(b.low >= mid.low for b in right):
            found.append(Swing(kind=SwingKind.LOW, index=i, open_ms=mid.open_ms,
                               price=mid.low, confirmed_at_index=i + depth))
    return found


def zigzag(raw: list[Swing]) -> list[Swing]:
    """ЦЕПОЧКА зигзага: строго чередующиеся звенья, только окончательные.

    Правило одно и оно из определения зигзага, а не наше: пока не подтверждён экстремум
    ПРОТИВОПОЛОЖНОЙ стороны, последний экстремум своей стороны предварителен, и более
    крайний (высший хай, низший лой) его ЗАМЕЩАЕТ. Приход противоположного делает
    предыдущее звено окончательным.

    То же самое явным циклом выписано в smart-money-concepts (`swing_highs_lows`):
    из двух хаёв подряд остаётся высший, из двух лоёв — низший.

    ⚠ ЧТО ЗДЕСЬ ЛЕЧИТСЯ. До 2026-08-20 цепочки не было вовсе, и потребитель
    (`range.detect`) при двух одноимённых подряд ОТБРАСЫВАЛ второй. Замер на BTC,
    3000 баров каждого ТФ: одноимённых подряд 175/176/150/192/20 на 5м/15м/1ч/4ч/1Д, и из
    них 57%/60%/60%/64%/55% были ЭКСТРЕМАЛЬНЕЕ уже принятой точки; медиана потерянной
    высоты 0.060%/0.105%/0.338%/1.028%/2.957%, максимум 22.90% на 4ч. То есть границей
    базы становилась не её вершина, а та вершина, что пришла первой, — при том что стр. 18
    называет границей «хай и лой» базы.

    ⚠ Внешний бар даёт оба экстремума на одном индексе (около 3% случаев, на 1Н 5.52% —
    замер 2026-08-17). В цепочку идёт тот, что ЧЕРЕДУЕТСЯ с предыдущим звеном; если
    предыдущего нет, берётся первый по порядку. Голосование источников (13 против 17)
    этот случай не решало, а цепочка решает его по построению.

    ⚠ `confirmed_at_index` у звена ПЕРЕПИСЫВАЕТСЯ на момент, когда оно стало
    окончательным. Это не косметика: потребитель проигрывает свинги по этому индексу, и
    отдать звено раньше значило бы отдать предварительное — см. докстроку модуля.

    ⚠⚠ ТЕЛО ЦИКЛА ЗДЕСЬ БОЛЬШЕ НЕ ЖИВЁТ. Оно было ВТОРОЙ КОПИЕЙ свёртки из
    `ZigzagPrefixes.__init__`, и копии успели разойтись по существу: правило внешнего
    бара, объявленное абзацем выше, не исполнялось НИ ОДНОЙ из них — оба экстремума
    одного бара проходили как разные звенья и давали колено НУЛЕВОЙ длины, по которому
    `trend()` читает «каждый следующий лой выше предыдущего» (стр. 12). Правило заведено
    в свёртке, свёртка осталась одна, а `zigzag` — её полный префикс.
    """
    return ZigzagPrefixes(raw).upto(len(raw))


class ZigzagPrefixes:
    """Цепочка зигзага СО ВСЕМИ ЕЁ ПРЕФИКСАМИ, посчитанная одним проходом.

    ⚠⚠ ЗАЧЕМ. Профиль прогона 2026-08-23 (2 символа, `decide` 200 с под cProfile) показал:
    из 3971 вызова `trend` **3959 — это запрос по ПРЕФИКСУ одного и того же набора
    свингов**, и стоили они 99.8 с из 287 с. Оба вызывающих делают одно и то же:

        figures.pennant     prior = свинги с `confirmed_at_index <= structure.first_index`
        engine._trend_as_of cut   = свинги, подтверждённые не позже `upto_ms`

    и каждый строит зигзаг ЗАНОВО. Для каждой структуры — проход по всему префиксу, то
    есть O(структур x свингов): на 2 символах это 1873 структуры на ~5000 свингов.

    ⚠ ПОЧЕМУ ЭТО ЗАКОННО, а не «кэш, который однажды соврёт». Три свойства, и каждое
    проверяемо:

      1. ключ сортировки в `zigzag` начинается с `confirmed_at_index`, поэтому набор
         «все свинги с `confirmed_at_index <= K`» есть ПРЕФИКС отсортированного порядка,
         каким бы ни был порядок на входе;
      2. тело цикла `zigzag` — свёртка слева направо: состояние после m-го элемента не
         зависит от того, есть ли элементы правее. Значит `zigzag(префикс длины m)` равен
         значению `chain[:-1]` после m шагов полного прохода;
      3. `chain[:-1]` — это ровно те звенья, что уже ОКОНЧАТЕЛЬНЫ: звено на позиции i
         замораживается в момент, когда появляется звено i+1, и больше не трогается
         (меняется только `chain[-1]`).

    Отсюда: достаточно один раз пройти весь ряд и запомнить, НА КАКОМ ШАГЕ каждое звено
    стало окончательным. Ответ на префикс длины m — звенья с шагом не больше m, то есть
    двоичный поиск по неубывающему списку шагов.

    ⚠ ССЫЛКА НА `gates/zigzag_prefixes.py` УБРАНА 2026-08-23: такого файла в `gates/`
    НЕТ и не было (`ls gates/` → 23 файла, этого имени среди них нет). Строка обещала
    исчерпывающую сверку `upto(m)` с `zigzag(префикс)` — сверки не существует. Свойство
    держится теперь ПО ПОСТРОЕНИЮ, а не сверкой: `zigzag` есть `upto(len(raw))` того же
    объекта, то есть второй реализации, с которой можно разойтись, больше нет.

    ⚠⚠ ЗДЕСЬ ЖЕ ЖИВЁТ ПРАВИЛО ВНЕШНЕГО БАРА. Бар, чей хай выше предыдущего, а лой ниже,
    даёт ОБА экстремума на одном индексе. Оба звена в цепочку не идут: колено между ними
    имеет нулевую длину по времени, а `trend` читает такое колено как настоящее.
    Берётся тот, что ЧЕРЕДУЕТСЯ с предыдущим звеном; при пустой цепочке — первый по
    порядку сортировки. Правило было записано в докстроке `zigzag` с 2026-08-17 и до
    2026-08-23 не исполнялось ни одной строкой кода.
    """

    __slots__ = ("_finals", "_steps", "_total")

    def __init__(self, raw: list[Swing]) -> None:
        finals: list[Swing] = []
        steps: list[int] = []
        chain: list[Swing] = []
        # ⚠ `x.kind`, А НЕ `x.kind.value` — правка скорости 2026-08-23, порядок ТОТ ЖЕ.
        # `SwingKind` это `StrEnum`, то есть член сам является строкой и сравнивается с
        # такой же строкой как она; `.value` же идёт через дескриптор
        # `DynamicClassAttribute` и стоит вызова на КАЖДОЕ сравнение внутри сортировки.
        # Цена замерена профилем прогона 2 символов: `enum.__get__` 1 970 076 вызовов, 4.6 с.
        order = sorted(raw, key=lambda x: (x.confirmed_at_index, x.index, x.kind))
        n = len(order)
        i = 0
        while i < n:
            s = order[i]
            # ⚠ ШАГ — ПОЗИЦИЯ ВЗЯТОГО свинга, а не конца пары. От этого зависит
            # свойство префикса: `upto(m)` обязан совпадать с `zigzag(order[:m])` при
            # ЛЮБОМ m, а не только на границах пар.
            m = i + 1
            i += 1
            if i < n and order[i].index == s.index and order[i].kind is not s.kind:
                # внешний бар: два экстремума на одном индексе — берём чередующийся
                other, other_m = order[i], i + 1
                i += 1
                if chain and s.kind is chain[-1].kind:
                    s, m = other, other_m
            if not chain:
                chain.append(s)
                continue
            if chain[-1].kind is s.kind:
                outer = (s.price > chain[-1].price if s.kind is SwingKind.HIGH
                         else s.price < chain[-1].price)
                if outer:
                    chain[-1] = s
                continue
            fin = chain[-1].model_copy(
                update={"confirmed_at_index": s.confirmed_at_index})
            finals.append(fin)
            steps.append(m)
            chain[-1] = fin
            chain.append(s)
        self._finals: tuple[Swing, ...] = tuple(finals)
        self._steps: tuple[int, ...] = tuple(steps)
        self._total = n

    def upto(self, m: int) -> list[Swing]:
        """Цепочка для префикса длины `m` — то же, что `zigzag(префикс)`."""
        return list(self._finals[:bisect.bisect_right(self._steps, m)])

    @property
    def total(self) -> int:
        """Сколько сырых свингов легло в индекс."""
        return self._total


def prefixes_of(swings: SwingSet) -> ZigzagPrefixes:
    """Индекс префиксов набора — считается один раз на набор.

    ⚠ Это ЗАПОМИНАНИЕ ЧИСТОЙ ФУНКЦИИ, а не состояние расчёта: тот же кортеж свингов
    всегда даёт тот же индекс. Промах стоит одного лишнего прохода, а не неверного
    ответа.

    ⚠⚠ ПАМЯТЬ ЖИВЁТ НА САМОМ НАБОРЕ (правка 2026-08-23). Здесь стоял МОДУЛЬНЫЙ
    `_PREFIX_CACHE` — `OrderedDict` на 16 записей с ключом `id(кортежа)` и проверкой
    `is` при попадании. Модуль объявлен ЧИСТЫМ (§10.3 запрещает глобальное состояние
    внутри расчёта), а `gates/purity.py` разбирал одни импорты и модульного состояния
    не видел — та же дыра, что у `_VOL_MEMO` и `_WINDOW_CACHE`.

    Теперь индекс лежит в `SwingSet._prefixes` — рядом с двумя такими же памятками
    (`_by_kind`, `_confirmed_of`), которые в этом классе живут с самого начала. Ключ по
    `id` при этом исчез как понятие: владелец кортежа и есть его набор, вытеснять
    нечего, а вопрос «не переиспользован ли `id` после сборки мусора» не возникает.
    """
    made = swings._prefixes
    if made is None:
        made = ZigzagPrefixes(list(swings.swings))
        swings._prefixes = made
    return made


def trend_upto(swings: SwingSet, prefix_len: int) -> Trend:
    """Тренд по ПРЕФИКСУ набора длины `prefix_len` — без пересборки зигзага.

    Вызывающий обязан подать длину набора, который он БЫ отфильтровал по
    `confirmed_at_index`; что такой набор есть префикс сортированного порядка —
    свойство ключа сортировки, разобранное в `ZigzagPrefixes`.
    """
    return trend_of_chain(prefixes_of(swings).upto(prefix_len))


def detect(bars: list[Bar], depth: int = ZIGZAG_DEPTH) -> SwingSet | NotReady:
    """Экстремумы зигзага на закрытых барах — окно `depth` с каждой стороны.

    ⚠⚠ ЧЕРЕДОВАНИЕ ЗДЕСЬ НЕ ПРИМЕНЯЕТСЯ, И ЭТО НЕ НЕДОДЕЛКА. Схлопывание подряд идущих
    одноимённых в экстремум требует знать СЛЕДУЮЩИЙ экстремум — то есть будущее
    относительно того, который схлопывается. Производитель, сделавший это у себя, изымал
    бы экстремум задним числом: наружу он бы не вышел вовсе, хотя в момент подтверждения
    был известен и законен. Это ровно I-5, заглядывание вперёд.

    Поэтому цепочку строит ПОТРЕБИТЕЛЬ, по мере прохода слева направо: `range.detect`
    при одноимённом экстремуме уточняет ещё не замороженную точку границы либо записывает
    прокол (стр. 18). Тот же зигзаг, но каждое звено принимается в момент, когда оно стало
    известно, и ни одно не исчезает из прошлого.

    Замер 2026-08-20 на закреплённом окне (BTC+ETH+SOL, 5 ТФ, отсечка 19.08) подтвердил,
    что причинный вариант ещё и ЛУЧШЕ по существу:

        схлопывание у производителя (предварительное звено отброшено):
            уровней 47, ширина p90 3.65%, максимум 6.6%
        схлопывание у потребителя (стоит):
            уровней 64, ширина p90 2.74%, максимум 4.5%

    Первый вариант терял последнюю точку всякой структуры, чей выход шёл сразу за ней:
    звено оставалось предварительным до следующего противоположного экстремума, а тот
    приходил уже после выхода. Четырёхточечная структура превращалась в трёхточечную и
    отбраковывалась порогом стр. 22.

    `zigzag()` остаётся и применяется там, где цепочка нужна целиком и будущее уже
    известно, — например в `trend()`.
    """
    need = 2 * depth + 1
    if len(bars) < need:
        return NotReady(
            reason=f"зигзаг с окном {depth} требует {need} баров, подано {len(bars)}"
        )

    return SwingSet(
        swings=tuple(local_extremes(bars, depth)),
        bars_scanned=len(bars),
        confirmed_until_index=len(bars) - 1 - depth,
    )

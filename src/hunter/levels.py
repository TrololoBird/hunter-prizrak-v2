class EntryRule(StrEnum):
    """ЧЕМ уровень торгуется в этом состоянии. У каждого значения своя страница.

    Введено 2026-08-04 после разметки автора: у него в легенде 🟢 «лимитки стоят» и
    🟡 «можем проколоть без реакции, работать по факту» — ДВА РАЗНЫХ разрешения, а не
    «активен/неактивен». Мой `limit_orders_allowed` их различал наполовину: он говорил,
    чего делать НЕЛЬЗЯ, и молчал о том, что можно. Молчание о доступном действии — та же
    потеря, что молчание о деградации (§4.3).

    ⚠ Красного 🔴 «шорт-зона в перезакуп» здесь НЕТ и не будет. «Шорт-зона» — это
    `side`, он уже есть; «перезакуп» — рыночная оценка автора, которой курс не даёт ни
    определения, ни порога. Завести под неё состояние значило бы придумать метрику (§3).
    """

    LIMIT = "limit"
    """Лимитки на ПОК и зону — стр. 30: «надежнее всего брать от уровня ПОК»."""

    CONFIRMATION = "confirmation"
    """Только по слому структуры на младшем ТФ — стр. 31.

    Дословно: «уровень лимитными ордерами больше не торгуем… Позицию от уровня смотрим
    только по факту слома структуры на более мелких ТФ». Стр. 25 говорит то же про
    повторные касания: «можно рассматривать вход от 2 или 3 касания только по факту
    слома структуры на младшем ТФ».
    """

    RETEST_FLIPPED = "retest_flipped"
    """По ретесту с обратной стороны, в ПРОТИВОПОЛОЖНУЮ сторону — стр. 43.

    Дословно: «По возврату цены на ретест уровня -  открываем позицию и ставим СТОП за
    накопление». Сам уровень при этом уже другой стороны — `Level.flipped()`.
    """


class LevelStatus(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    state: LevelState
    event: Breach | None
    """Событие, приведшее к состоянию. None — уровень активен, событий не было."""

    limit_orders_allowed: bool
    """Стр. 25 и 31: после отработки лимитками уровень больше не торгуется."""

    entry_rule: EntryRule
    """Чем уровень торгуется СЕЙЧАС. Не выводится из `state` вызывающим — выводится здесь.

    Вывод отработан-значит-ничего-нельзя напрашивается и НЕВЕРЕН: стр. 25 и 31 прямо
    оставляют вход по слому младшего ТФ, а стр. 43 — вход по ретесту после пробоя.
    """

    price_in_zone: bool = False
    """Торгуется ли цена ПРЯМО СЕЙЧАС внутри объёмной зоны уровня.

    ⚠ Заведено 2026-08-07, находка М-09. Стр. 44, вариант 2, дословно: «Приоритет – не
    открывать позицию, если цена уже торгуется в зоне, либо быть готовым выйти в б/у при
    пробое уровня – на ретесте». Правила не было ни в §2, ни в коде: `EntryRule.LIMIT`
    выдавался независимо от того, где цена находится в момент печати карточки.

    Считается по ПОСЛЕДНЕМУ бару ряда — это «сейчас» с точностью до таймфрейма уровня.
    Заглядывания вперёд здесь нет: последний бар ряда уже закрыт (§6).
    """

    price_beyond: bool = False
    """Цена ПРЯМО СЕЙЧАС по ту сторону ВСЕЙ структуры уровня.

    ⚠ Заведено 2026-08-18 по приказу владельца: «допускаешь НАСЛОЕНИЕ противоположных
    зон!». Разбор карты (5 символов, 4413 уровней в состоянии `active`) показал, что у
    **25–35%** активных уровней цена стоит НЕ С ТОЙ СТОРОНЫ: лонговый уровень выше цены,
    шортовый ниже. Такой уровень своей стороной не работает — лонговый уровень выше цены
    есть сопротивление, а не поддержка, и покупать «от него» некуда: цена уже под ним.
    Оттуда и наслоение встречных зон на карте — 385–418 пар у одного символа.

    Курс: стр. 43 «Уровень лонг/шорт менятся для нас на противоположный»; стр. 7 пробой —
    «когда цена проходит». Вердикта прокол-или-пробой при этом может ещё не быть
    (`BreachKind.OPEN`: «заход не закончился к последнему бару»), поэтому состояние
    уровня здесь НЕ меняется — меняется РАЗРЕШЕНИЕ, ровно как у касания (стр. 25) и у
    «цена в зоне» (стр. 44): лимитки снимаются, вход остаётся по слому младшего ТФ.

    Считается по последнему ЗАКРЫТОМУ бару и по ГРАНИЦАМ базы, а не по ПОК: заход внутрь
    коробки — ещё не проход сквозь неё, и путать это значило бы снимать уровень при
    первом же касании зоны.
    """

    take: ZoneTake | None = None
    """Глубина забора уровня по стр. 30 и была ли реакция. `None` — не считалась.

    ⚠ Заведено 2026-08-19. До этого отработкой считалось любое пересечение бара с зоной,
    и три варианта стр. 30 наружу не выходили ничем — ни в карточку, ни в отбор.
    """

    playout: Playout = Playout.NONE
    """Какая из семи картин стр. 28 сложилась у этого уровня. Одно поле на всю страницу."""

    resolved_at_ms: int | None
    """ЗАКРЫТИЕ бара, на котором событие разрешилось. None — не разрешилось (или его нет).

    Без этого поля состояние отвечает только на вопрос «что с уровнем СЕЙЧАС», а нужен
    ещё и вопрос «что с ним было на момент сигнала»: отбор целей по нынешнему состоянию
    — такое же заглядывание вперёд, как и отбор целей из будущего (Н-1).
    """

    def state_at(self, as_of_ms: int) -> LevelState:
        """Состояние НА МОМЕНТ `as_of_ms`, а не на конец ряда.

        Эквивалентно пересчёту `status` по ряду, обрезанному этим моментом, и это не
        совпадение: вердикт ищет `first_verdict` слева направо, и НОМЕР бара, на котором
        он найден, не зависит от того, насколько ряд продолжается вправо. Пока вердикта
        нет, `status` и так отдаёт `active` (ветки OPEN и UNRESOLVED).

        ⚠ Прежняя редакция обосновывала это иначе — «у уровня по стр. 25/43 ОДНА судьба»,
        — и обоснование ОПРОВЕРГНУТО курсом 2026-08-19 (разбор — докстрока
        `breach.first_breach`). Вывод уцелел, потому что держится не на единственности
        судьбы, а на монотонности обхода; посылку заменяю, чтобы верный вывод не стоял на
        неверном основании.

        Считать обрезкой ряда было бы честно, но дорого: 374 уровня × пул целей — это
        десятки тысяч повторных проходов `first_breach` вместо одного сравнения.
        """
        if self.resolved_at_ms is None or self.resolved_at_ms > as_of_ms:
            return LevelState.ACTIVE
        return self.state


class MappedLevel(BaseModel):
    """Уровень ВМЕСТЕ с его судьбой. Пара, а не два независимых значения.

    Заведено 2026-08-04: `geometry.build_targets` брал целью любой уровень пула, а замер
    показал, что 83% целей — уровни в состоянии `worked_off` или `flipped`, то есть ровно
    те, про которые стр. 25 говорит «мы этот уровень удаляем», а стр. 43 — что он стал
    противоположным. Состояние было доступно вызывающему и просто не подавалось; пара
    закрывает эту возможность на уровне типа, а не дисциплины.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    level: Level
    status: LevelStatus

    def alive_at(self, as_of_ms: int) -> bool:
        """Существовал ли уровень на момент `as_of_ms` и был ли ещё в силе.

        Два условия, и оба из курса: уровня нет до подтверждения выхода (стр. 23) и нет
        после отработки или пробоя (стр. 25, 43).
        """
        return (self.level.created_at_ms <= as_of_ms
                and self.status.state_at(as_of_ms) is LevelState.ACTIVE)


def map_levels(
    built: tuple[Level, ...],
    series: dict[str, list[Bar]],
    scans: dict[str, RangeScan] | None = None,
) -> tuple[MappedLevel, ...]:
    """Уровни со свежепосчитанной судьбой. Одно место, где `status` зовётся по всему пулу.

    Уровень, чьего ряда в кадрах нет, в карту НЕ попадает: состояние у него неизвестно, а
    подставить `active` значило бы объявить живым то, что не проверялось (§4.3).

    `scans` — разбор структур по ТФ; без него картины 2, 5, 6 и 7 стр. 28 не считаются
    (`LevelStatus.playout` тогда знает только 1, 3, 4 и закреп без ретеста). Умолчание
    `None` оставлено для зондов и старых вызовов, и оно ВИДНО в вердикте, а не молчит.
    """
    by_tf = scans or {}
    return tuple(
        MappedLevel(level=lvl, status=status(lvl, bars, scan=by_tf.get(lvl.timeframe)))
        for lvl in built
        if (bars := series.get(lvl.timeframe))
    )


def resolve_carried(side: str, zone_lo: float, zone_hi: float,
                    boundary_lo: float, boundary_hi: float,
                    bars: list[Bar], *,
                    confirm_bodies: int = CONFIRM_BODIES) -> str | None:
    """Разрешён ли ПЕРЕНЕСЁННЫЙ уровень свежими барами. `None` — ещё нет.

    ⚠⚠ ЗАВЕДЕНО 2026-08-20. До этого дня уровень, чья структура вышла из рамки
    построения, не оценивался НИКОГДА: `store.carried_levels` возвращала его как есть, и
    он оставался активным вечно. Замер на живом леджере: 2317 активных уровней из 3476
    (67%) имели структуру старше 30 суток, из них 1142 пятиминутных, и это давало 4205
    пар ВСТРЕЧНЫХ уровней с пересечением зон — то самое наслоение, которое владелец нашёл
    глазами.

    Оценка идёт по ТЕМ ЖЕ двум правилам курса, что и у обычного уровня, и других здесь
    нет:

      * ПРОБОЙ (стр. 43): `confirm_bodies` подряд идущих ПОЛНЫХ ТЕЛ за коробкой структуры
        в сторону против уровня. Стр. 43: «Уровень лонг/шорт менятся для нас на
        противоположный». Возвращается `flipped`;
      * ОТРАБОТКА (стр. 25): цена ЗАШЛА в зону и потом ЕЁ ПОКИНУЛА. Стр. 25 дословно:
        «уровень был отработан на 1 касание (как на графике - увидели хорошую реакцию)»,
        и скобка — это условие: одного касания без ухода мало. Возвращается `worked_off`.

    ⚠ Порядок проверок не произволен: пробой сильнее отработки. Цена, прошедшая коробку
    насквозь, по дороге неизбежно задевает зону, и без этого порядка всякий флип
    записывался бы отработкой.

    ⚠ Своей мерки «реакции» здесь НЕ вводится. У обычного уровня её считает `take_depth`
    по глубине захода; у перенесённого нет ни индексов, ни ПОК-профиля свежего прогона,
    поэтому берётся наблюдаемый факт — вход в зону и выход из неё. Это СЛАБЕЕ, чем у
    обычного уровня, и названо слабее, а не выдано за то же самое.
    """
    if not bars:
        return None
    long = side == "long"
    beyond = 0
    for b in bars:
        body_lo, body_hi = min(b.open, b.close), max(b.open, b.close)
        out = (body_hi < boundary_lo) if long else (body_lo > boundary_hi)
        beyond = beyond + 1 if out else 0
        if beyond >= confirm_bodies:
            return "flipped"
    inside = False
    for b in bars:
        if b.low <= zone_hi and b.high >= zone_lo:
            inside = True
        elif inside:
            return "worked_off"
    return None


def status(
    level: Level,
    bars: list[Bar],
    *,
    scan: RangeScan | None = None,
    confirm_bodies: int = CONFIRM_BODIES,
    return_bars: int = RETURN_BARS,
) -> LevelStatus:
    """Состояние уровня §2.10 — выводится из первого события, ПО КОТОРОМУ КУРС ДАЁТ ВЕРДИКТ.

    Своей логики у §2.10 нет: прокол уже объявлен отработкой (стр. 6), пробой — флипом
    (стр. 43), первое касание — снятием лимиток (стр. 25). Здесь только связывание одного
    с другим, без новых правил.

    ⚠ КАСАНИЕ подключено 2026-08-06, и до этого правило стр. 25 не исполнялось вовсе.
    Состояние выводилось только из `first_breach`, то есть из того, ЗАШЛА ли цена ЗА
    уровень. Но стр. 25 говорит о другом событии — о приходе цены НА уровень:

        «Как только уровень был отработан на 1 касание (как на графике - увидели хорошую
        реакцию) этот уровень становиться больше не актуальным, т.е. мы этот уровень
        удаляем и ищем новые не отработанные уровни для входа в новую позицию.
        … можно рассматривать вход от 2 или 3 касания только по факту слома структуры на
        младшем ТФ»

    Замер на кадрах прогона `a1` (3 символа, 94 уровня): из 33 уровней, по которым система
    выставляла лимитки, **18 цена уже касалась** — больше половины. У всех восемнадцати
    событие было `unresolved`, то есть цена за уровень заходила, но курс вердикта
    прокол-или-пробой не давал, и `status` оставлял лимитки разрешёнными.

    Отработка зоны меняет РАЗРЕШЕНИЕ, а не состояние, и это существенно. Иначе флипов не
    было бы вовсе: любой пробой начинается с касания, и «первое событие — касание»
    объявляло бы отработанным даже то, что стр. 43 велит считать противоположным уровнем.
    Поэтому `state` выводится из ВЕРДИКТА (прокол или пробой), а отработка зоны снимает
    лимитки и переводит вход на слом младшего ТФ.

    ⚠⚠ 2026-08-19 УСЛОВИЕ СНЯТИЯ ЛИМИТОК ИСПРАВЛЕНО. Снимало его ЛЮБОЕ пересечение бара
    с зоной (`first_test_index`), тогда как стр. 25 и 31 требуют ДВУХ вещей сразу:
    «уровень был отработан на 1 касание (как на графике - увидели хорошую реакцию)» и
    «если цена ранее забирала зону И уже получила от нее хорошую лонг реакцию». Скобка на
    стр. 25 — не пояснение, а второе условие. Теперь снятие связано с вердиктом глубины
    (`take_depth`, три варианта стр. 30) и с реакцией; уровень, которого цена коснулась и
    в котором она сидит без реакции, лимитки не теряет — его держит стр. 44 через
    `price_in_zone`, и держит по своей причине, а не по чужой.

    ⚠ До 2026-08-19 здесь стояло «`state` по-прежнему выводит `first_breach`». С правкой
    того дня это неверно: `state` выводит `first_verdict`, а посылка «первое событие
    решает» отозвана (разбор — в докстроке `breach.first_breach`). Строка прожила правку
    и найдена аудитом; это ровно тот дефект, который сам пакет ловил в другом месте —
    два текста в одном модуле говорят разное, и прав не тот, что описывает замысел.
    """
    # ⚠ `first_verdict`, а НЕ `first_breach` (2026-08-19). Прежняя редакция брала первое
    # событие и при `UNRESOLVED` («источник вердикта не даёт») объявляла уровень живым
    # НАВСЕГДА — «вердикта нет» кодировалось тем же состоянием, что и «ничего не было».
    # Отсюда наслоение встречных зон: уровень, вокруг которого рынок с тех пор построил
    # целое встречное накопление, продолжал числиться активным своей прежней стороной.
    # Курс правила «первый заход решает» не даёт вовсе и повторные заходы к одному
    # уровню разбирает прямо (стр. 25, 28, 31, 43, 45) — разбор в докстроке
    # `breach.first_breach`. Замер цены — в докстроке `breach.first_verdict`.
    ev = first_verdict(bars, float(level.price), level.breach_direction, level.timeframe,
                       from_index=level.created_at_index + 1,
                       confirm_bodies=confirm_bodies, return_bars=return_bars)
    # Стр. 44: «не открывать позицию, если цена уже торгуется в зоне». Считается по
    # последнему ЗАКРЫТОМУ бару — это «сейчас» с точностью до ТФ уровня (М-09).
    last = bars[-1] if bars else None
    in_zone = bool(last is not None
                   and last.low <= float(level.zone_hi)
                   and last.high >= float(level.zone_lo))
    # Цена по ту сторону ВСЕЙ структуры — уровень своей стороной не работает (стр. 43,
    # стр. 7; см. `LevelStatus.price_beyond`). Считается по границам базы: коробка
    # ХАЙ…ЛОЙ и есть структура, сквозь которую цена либо прошла, либо нет.
    beyond = bool(last is not None and (
        last.close < float(level.boundary_lo) if level.side is LevelSide.LONG
        else last.close > float(level.boundary_hi)))
    # Глубина забора (стр. 30) и «хорошая реакция» (стр. 25, 31) — ими решается снятие
    # лимиток. Стр. 31 называет ОБА условия в одном предложении: «если цена ранее
    # забирала зону И уже получила от нее хорошую лонг реакцию, уровень лимитными
    # ордерами больше не торгуем». Прежде проверялось только первое — любое пересечение
    # бара с зоной (`first_test_index`), — то есть уровень терял лимитки от касания без
    # всякой реакции. Стр. 25 говорит то же самое ещё яснее: «уровень был отработан на
    # 1 касание (как на графике - увидели хорошую реакцию)» — скобка и есть условие.
    take = take_depth(level, bars, confirm_bodies=confirm_bodies)
    took = take.reacted and take.depth in (
        TakeDepth.ZONE, TakeDepth.POC, TakeDepth.PUNCTURE)
    pressed = pressed_structures(level, scan, bars) if scan is not None else ()
    play = playout(level, bars, event=ev, take=take, pressed=pressed)
    if ev is None or ev.kind in (BreachKind.OPEN, BreachKind.UNRESOLVED):
        if beyond or took:
            return LevelStatus(state=LevelState.ACTIVE, event=ev,
                               limit_orders_allowed=False, price_in_zone=in_zone,
                               price_beyond=beyond, take=take, playout=play,
                               entry_rule=EntryRule.CONFIRMATION, resolved_at_ms=None)
        return LevelStatus(state=LevelState.ACTIVE, event=ev, limit_orders_allowed=True,
                           price_in_zone=in_zone, price_beyond=beyond, take=take,
                           playout=play,
                           entry_rule=EntryRule.LIMIT, resolved_at_ms=None)
    assert ev.resolved_index is not None  # у разрешившегося события бар есть по построению
    at = bars[ev.resolved_index].open_ms + tf_ms(level.timeframe)
    if ev.kind is BreachKind.BREAKOUT:
        return LevelStatus(state=LevelState.FLIPPED, event=ev, limit_orders_allowed=False,
                           price_in_zone=in_zone, price_beyond=beyond, take=take,
                           playout=play,
                           entry_rule=EntryRule.RETEST_FLIPPED, resolved_at_ms=at)
    return LevelStatus(state=LevelState.WORKED_OFF, event=ev, limit_orders_allowed=False,
                       price_in_zone=in_zone, price_beyond=beyond, take=take,
                       playout=play,
                       entry_rule=EntryRule.CONFIRMATION, resolved_at_ms=at)


class PressedKind(StrEnum):
    """Конфигурации отработки стр. 28, выраженные новым накоплением у уровня."""

    BELOW = "below"
    """Конфигурация 2: накопление ПОД уровнем — «цена не дошла до уровня, остановилась
    в зоне» (стр. 44, вариант 2). Вход курс рисует свечами от ПОК нового накопления
    (стр. 28, находка М-29)."""

    ABOVE = "above"
    """Конфигурация 5: новая структура НАД уровнем (стр. 28)."""

    ASTRIDE = "astride"
    """Конфигурация 7: «пила» — накопление НА уровне; курс: выйти в бу и дождаться
    выхода из пилы (стр. 28)."""


class PressedStructure(BaseModel):
    """Закрытое накопление, прижатое к зоне уровня, — конфигурации 2/5/7 стр. 28.

    ⚠ Заведено 2026-08-10 (реестр долга, строка 1). До этого система различала четыре
    исхода события на уровне, а конфигурации «новое накопление у уровня» не выражала
    ничем — при том, что у 2 и 7 курс даёт СВОИ правила действий. Здесь конфигурация
    ОБНАРУЖИВАЕТСЯ И НАЗЫВАЕТСЯ; эмиссию она не порождает — тот же выбор, что у слома
    на младшем ТФ (А-02): новый путь сигнала меняет состав эмиссии.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    kind: PressedKind
    first_index: int
    last_index: int
    box_lo: float
    box_hi: float
    exit_long: bool = False
    """Из новой базы вышли ВВЕРХ (стр. 22). Этим и различаются картины 2 и 6 стр. 28:
    геометрия у них одна — база с ближней стороны уровня, — а выход противоположный."""


def pressed_structures(level: Level, scan: RangeScan,
                       bars: list[Bar]) -> tuple[PressedStructure, ...]:
    """Закрытые накопления ТОГО ЖЕ ТФ, закрывшиеся после появления уровня и прижатые
    к его зоне (пересечение коробки с [zone_lo, zone_hi]).

    Сторона относительно ЦЕНЫ уровня (ПОК) делит их на 2/5/7: коробка целиком ниже —
    ПОД уровнем; целиком выше — НАД; ПОК внутри коробки — «пила». Открытая структура
    у уровня сюда не входит: она видна в `open_tail`, а стр. 28 рисует исходы по
    ЗАКРЫТЫМ (стр. 23: пока цена не вышла, структуры-события нет).

    ⚠⚠ КОРОБКА — ЭКСТРЕМУМЫ СВЕЧЕЙ, А НЕ ЛИНИИ ДЕТЕКТОРА. Правка 2026-08-20, и это тот
    же класс дефекта, что владелец нашёл глазами 2026-08-18: две разные величины под
    одним человеческим именем «коробка». До этой правки сюда шли `acc.lower.edge` и
    `acc.upper.edge` — линии по первым двум точкам границ, — а `Level.boundary_lo/hi`,
    которые карточка печатает словом «границы» у САМОГО уровня, с 2026-08-18 берутся по
    экстремумам баров структуры. Карточка печатала обе как «коробку», и совпадать они
    не обязаны: замер 2026-08-20 на BTC+ETH+SOL, 417 структур — свечи выходят за линии
    детектора у 85.4% из них, медиана превышения 0.703%, максимум 22.42%.

    Стр. 26 требует ровно того, что теперь и делается: «Натягивая» профиль на структуру
    – важно захватить все свечи структуры!

    ⚠ `bars` подаются аргументом, а не читаются: модуль чистый (§10.3), и ряд ему
    неоткуда взять. Отрезок структуры считает `structure_bars` — одна функция на всех
    потребителей, чтобы вторая копия не разошлась с первой.
    """
    lo_z, hi_z = float(level.zone_lo), float(level.zone_hi)
    price = float(level.price)
    out: list[PressedStructure] = []
    for acc in scan.closed:
        if acc.last_index <= level.created_at_index:
            continue
        seg = structure_bars(acc, bars)
        if not seg:
            continue
        lo, hi = min(b.low for b in seg), max(b.high for b in seg)
        if hi < lo_z or lo > hi_z:
            continue
        kind = (PressedKind.ASTRIDE if lo <= price <= hi
                else PressedKind.BELOW if hi < price else PressedKind.ABOVE)
        out.append(PressedStructure(kind=kind, first_index=acc.first_index,
                                    last_index=acc.last_index, box_lo=lo, box_hi=hi,
                                    exit_long=acc.is_long))
    return tuple(out)


def _stop_taken(level: Level, bars: list[Bar], event: Breach, retest_index: int) -> bool:
    """Дошла ли цена до стопа между закрепом и ретестом — тем и различаются 3 и 4 стр. 28.

    Порогом берётся якорь стопа (стр. 18), а если якоря нет — дальняя граница базы:
    стр. 43 ставит стоп «за накопление», стр. 58 — «за всю структуру».
    """
    long_side = level.side is LevelSide.LONG
    edge = level.stop_anchor if level.stop_anchor is not None else (
        level.boundary_lo if long_side else level.boundary_hi)
    lo = max(event.start_index, 0)
    hi = min(retest_index, len(bars) - 1)
    if hi < lo:
        return False
    seg = bars[lo:hi + 1]
    return (min(b.low for b in seg) < float(edge) if long_side
            else max(b.high for b in seg) > float(edge))


def playout(
    level: Level,
    bars: list[Bar],
    *,
    event: Breach | None,
    take: ZoneTake,
    pressed: tuple[PressedStructure, ...] = (),
) -> Playout:
    """Какая из семи картин стр. 28 сложилась. Новых правил здесь нет — только сведение.

    Порядок разбора идёт от самой определённой картины к самой общей: «пила» (7) видна
    сразу по накоплению НА уровне, закреп за уровнем разводит 5/3/4, база с ближней
    стороны — 2 и 6, и лишь потом остаётся простой забор (1).

    `pressed` пустой означает «структуры у уровня не подавались», а не «их нет»: без
    разбора того же ТФ картины 2, 5, 6 и 7 не выражаются вовсе.
    """
    if any(p.kind is PressedKind.ASTRIDE for p in pressed):
        return Playout.SAW
    long_side = level.side is LevelSide.LONG
    beyond_kind = PressedKind.BELOW if long_side else PressedKind.ABOVE
    near_kind = PressedKind.ABOVE if long_side else PressedKind.BELOW
    if event is not None and event.kind is BreachKind.BREAKOUT:
        if any(p.kind is beyond_kind for p in pressed):
            return Playout.BASE_BEYOND
        assert event.resolved_index is not None  # у пробоя бар закрепа есть по построению
        rt = retest_after(bars, float(level.price), event.resolved_index + 1)
        if rt is None:
            return Playout.BROKEN
        return (Playout.STOP_RUN_FLIP if _stop_taken(level, bars, event, rt)
                else Playout.QUIET_FLIP)
    near = [p for p in pressed if p.kind is near_kind]
    if near:
        return (Playout.BASE_NEAR if any(p.exit_long == long_side for p in near)
                else Playout.TRADED_OUT)
    if take.reacted and take.depth in (TakeDepth.ZONE, TakeDepth.POC, TakeDepth.PUNCTURE):
        return Playout.TAKEN
    if take.depth is TakeDepth.NONE and event is None:
        return Playout.NONE
    return Playout.IN_PROGRESS


def first_test_index(level: Level, bars: list[Bar]) -> int | None:
    """Первое касание уровня после его появления — момент, от которого ищется слом на
    младшем ТФ (стр. 25, 31).

    ⚠ С 2026-08-19 ЭТО НЕ УСЛОВИЕ СНЯТИЯ ЛИМИТОК. Снятие требует ещё и «хорошей
    реакции» (стр. 25, 31) и потому считается `take_depth`; здесь остался ровно вопрос
    «когда цена пришла к уровню впервые», и на нём стоит `engine._mtf_break`.

    ⚠ КАСАНИЕМ СЧИТАЕТСЯ ЗАХОД В ЗОНУ, А НЕ ДОСТИЖЕНИЕ ПОК. Правка аудита 2026-08-07,
    находка М-08.

    Прежняя редакция требовала, чтобы цена достала САМ ПОК (`low <= ПОК <= high`), и
    обосновывала это стр. 30, которая действительно РАЗДЕЛЯЕТ события «цена забирает
    объемную зону» и «цена забирает идеально уровень ПОК». Но снятие лимиток курс
    привязывает именно к ЗОНЕ — стр. 31:

        «ВАЖНО: если цена ранее забирала зону и уже получила от нее хорошую лонг реакцию,
         уровень лимитными ордерами больше не торгуем - т.к. уровень стал слабее, и в
         след раз может не отработать.»

    Та же стр. 30 называет заход в зону самостоятельным вариантом отработки: «1 - цена
    забирает объемную зону… и идет в нужном направлении». А схема стр. 24 несёт выноску,
    которой нет в текстовом слое: "тест объемов / сам уровень не забрали" — вход берётся
    по достижении зоны, когда линия ПОК не достигнута.

    Замер расхождения до правки (docs/audit/evidence/E-040-zone-vs-poc): из 17 уровней
    разрешение менялось у 13; у трёх цена не касалась ПОК ВООБЩЕ, то есть уровень
    оставался бы «свежим» бесконечно. Медианная задержка ПОК против зоны — 3 бара,
    максимум 79.

    `None` означает «тестов ещё не было», а не «нет данных»: диапазон поиска задан
    явно и пуст только если уровень моложе конца ряда.
    """
    lo, hi = float(level.zone_lo), float(level.zone_hi)
    for i in range(level.created_at_index + 1, len(bars)):
        if bars[i].low <= hi and bars[i].high >= lo:
            return i
    return None

class LevelSide(StrEnum):
    LONG = "long"
    SHORT = "short"


class Level(BaseModel):
    """Уровень ПОК накопления. Живёт после структуры и ждёт теста (стр. 23, 25)."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    symbol: str = Field(min_length=1)
    timeframe: str = Field(min_length=1)
    side: LevelSide

    price: Decimal
    """ПОК — сам уровень. Стр. 30: «надёжнее всего брать от уровня ПОК»."""

    zone_lo: Decimal
    zone_hi: Decimal
    """Объёмная зона (стр. 30: «цена забирает объёмную зону»).

    ⚠ Отождествление «объёмная зона» = область стоимости 70% — НЕ из курса. Курс рисует
    зону на графике и доли не называет. Проверяется на корпусе (этап 3.3); до проверки
    зона сообщается рядом с ПОК, а не вместо него.
    """

    created_at_index: int
    """Бар подтверждения выхода. Раньше него уровня не существует (стр. 23)."""

    created_at_ms: int
    """ЗАКРЫТИЕ бара подтверждения — момент, с которого уровень известен, в биржевом времени.

    Индекс выше живёт в своём ряду и между ТФ несравним; сравнивать моменты появления
    уровней РАЗНЫХ ТФ без общей шкалы нельзя, а сравнивать их приходится: цель по стр. 24
    берётся с другого ТФ, и она обязана существовать НА МОМЕНТ сигнала.

    ⚠ Поле заведено 2026-08-04 по внешнему разбору. До него `geometry.build_targets`
    момент появления не проверял вовсе, и замер на 374 уровнях дал 196 основных целей из
    366 (54%), созданных ПОЗЖЕ уровня, от которого строилась сделка: тейк-профит
    выбирался задним числом. Разбор: docs/audit/critical-review-verified-2026-08-04.md

    Именно закрытие, а не открытие: система работает по закрытым барам (§6), значит бар
    подтверждения становится известен в момент своей правой границы, а не левой.
    """

    structure_first_index: int
    structure_last_index: int

    structure_from_ms: int
    structure_to_ms: int
    """Окно структуры в биржевом времени — ТО ЖЕ, по которому натянут профиль (стр. 26).

    Индексы выше живут в СВОЁМ ряду баров и между ТФ несравнимы: индекс 40 на 15м и
    индекс 40 на 4ч — разные моменты. Вложенность уровней (стр. 32) без общей шкалы
    времени не выражается вовсе, поэтому окно хранится, а не пересчитывается.
    """

    stop_anchor: Decimal | None = None
    """Цена, ЗА которую курс велит прятать стоп. `None` — якоря нет, ставится запас 1-3%.

    Стр. 18 даёт ДВА повода сдвинуть стоп дальше границы, и оба вычисляются здесь, а не
    оставляются оператору:

      * «если на 3++ точках были **проколы** за границы — стоп ВСЕГДА ставится за этот
        прокол, т.к. это может быть расширением базы»;
      * «если в диапазоне **2-5% от границы** есть **стоповый объем** — база мелкого ТФ —
        или Лой того же ТФ или ТФ-1 — **идеально стоп прятать за них**».

    Берётся ДАЛЬНИЙ из применимых якорей: оба правила говорят «стоп за X», и стоп за
    самым дальним удовлетворяет обоим сразу.

    ⚠ 2026-08-09 к двум видам якоря добавился третий — лой того же ТФ или ТФ−1, вторая
    половина той же фразы стр. 18, не реализованная до обзора стопового объёма. Чем
    оказался якорь, теперь видно в `stop_anchor_source`.

    ⚠ Заведено 2026-08-05. До него `geometry.build_setup` печатал ТРИ стопа —
    безопасный ближний, безопасный дальний и рисковый, — и выбор оставался оператору.
    Выставить можно только один; значит РР был не определён, а все замеры РР и R
    считались по невыбранному стопу. При этом `stop_volume.py` (§2.3, стр. 34-40) был
    реализован целиком и НЕ ВЫЗЫВАЛСЯ ниоткуда, а `BoundaryZone.puncture` вычислялся и
    не читался: оба входа правила стр. 18 существовали и не были соединены с ним.
    """

    stop_anchor_source: StopAnchorSource | None = None
    """Чем оказался якорь: прокол, стоповый объём или свинг. `None` — якоря нет.

    ⚠ Заведено 2026-08-09. До этого наружу уходила одна цена, и оператор не мог сказать,
    откуда взялся стоп; §4.3 требует, чтобы найденное было ВИДНО. Обзор стопового объёма
    нашёл, что о стоповом объёме до карточки не доходило вообще ничего — даже сам факт,
    что якорь взят у него."""

    stop_anchor_narrowed: bool = False
    """Якорь взят у стопового объёма, который был В СУЖЕНИИ (стр. 34, 57).

    Стр. 57 приравнивает: треугольник это структура накопления, то есть стоповый, просто в
    сужении. Признак вычислялся с 2026-08-08 (правка Н10 обзора накопления) и до карточки
    не доходил."""

    structure_volume: float = Field(gt=0)
    """Объём структуры. Стр. 22: сила = ТФ И объём, РАЗДЕЛЬНО.

    Свёртки ТФ и объёма в одно число здесь нет и не будет: стр. 22 приводит прямой
    контрпример — «в маленькой часовой наторговке может быть объём больше, чем в 4ч-1д
    накоплении». §3 запрещает составные метрики, курс это подтверждает.
    """

    vrvp_zone_qty: float | None = None
    """Объём ЗОНЫ уровня по композиту всех структур символа — замена VRVP (стр. 22, 63).

    ⚠ Заведено 2026-08-10 (реестр долга, строка 7 — М-12). Автор смотрит «объём» силы
    уровня по VRVP — профилю видимой области экрана; у системы экрана нет, и «типичного
    N видимых баров» не существует (vrvp-visible-range-2026-08-09: это жест пользователя).
    Безэкранная замена — якорь ОТ СТРУКТУРЫ, как у официального Auto Anchored VP самого
    TV и композитов Далтона: окно = объединение окон всех структур символа, объём зоны —
    сумма тиковых бинов композита внутри [zone_lo, zone_hi]. `None` — композит не покрыт
    сделками; причина в `vrvp_note`."""

    vrvp_total_qty: float | None = None
    """Полный объём того же композита — знаменатель для чтения `vrvp_zone_qty`."""

    vrvp_note: str = ""
    """При посчитанном композите — какое окно им было (структура какого ТФ); при
    отсутствии — названная причина (§4.3)."""

    boundary_lo: Decimal
    boundary_hi: Decimal

    range_lo: Decimal
    range_hi: Decimal
    """ХАЙ и ЛОЙ структуры — крайние цены её баров. ЭТО И ЕСТЬ ГРАНИЦЫ БАЗЫ по курсу.

    ⚠ Заведено 2026-08-11, и это исправление понятия, а не добавка поля. Разбор:
    docs/audit/poc-inside-base-2026-08-11.md

    На стр. 30 коробка структуры подписана автором «ХАЙ» сверху и «ЛОЙ» снизу; профиль
    натянут ровно на неё (стр. 26: «"Натягивая" профиль на структуру – важно захватить
    все свечи структуры!»), объёмная зона нарисована ДВУМЯ линиями ВНУТРИ коробки, а ПОК
    — между ними. То есть у автора одна система координат: коробка по свечам, и всё
    остальное внутри неё.

    У нас же `boundary_lo/hi` — ЛИНИИ по точкам свингов, и они уже коробки (медиана
    отношения 3.156 по замеру У3). Из-за этого ПОК оказывался вне «границ» у 21.6%
    уровней, а зона была шире «базы» у 46.3% — при том что на рисунке курса и то и
    другое строго внутри.

    Разведение ролей, а не подмена:
      * ЛИНИИ (`boundary_lo/hi`) — механизм ДЕТЕКЦИИ: по ним считаются точки касания
        (стр. 22: «понятные 4 и более точек»), выход из структуры и прокол. Цена
        отбивается от линии, тени её протыкают — это и есть прокол;
      * КОРОБКА (`range_lo/hi`) — ГРАНИЦЫ БАЗЫ наружу: от неё считается стоп («за дно
        структуры», стр. 33 — дно это лой), от неё ищется якорь (стр. 18: «в диапазоне
        2-5% от границы»), внутри неё обязаны лежать ПОК и зона.
    """

    boundary_narrowed: int
    """Сколько раз границы базы съехали ВНУТРЬ — база «в сужении» (стр. 34, 37).

    Ноль значит горизонтальную коробку. Поле здесь, а не только в структуре, потому
    что §4.3 требует, чтобы форма базы дошла до оператора: сужение и ровные границы
    дают РАЗНЫЙ уровень, а в карточке выглядели одинаково."""

    boundary_ladder: bool
    """Хоть одна граница взята у ПРЕДЫДУЩЕЙ структуры этого ряда — лесенка (стр. 40).

    Оператору это меняет доверие к уровню: граница держится на точках ТОЙ структуры,
    а не этой.

    ⚠ Признака «граница с другого ТФ» здесь БОЛЬШЕ НЕТ: механизм внесён и откачен
    2026-08-08, причина — в докстроке `accumulation.BorderSource`."""

    @property
    def breach_direction(self) -> Direction:
        """С какой стороны цена уходит ЗА уровень.

        Лонговый уровень — поддержка: цена подходит сверху, значит уйти за него значит
        уйти ВНИЗ. Шортовый — сопротивление, зеркально (стр. 22, 28).
        """
        return Direction.BELOW if self.side is LevelSide.LONG else Direction.ABOVE

    def flipped(self) -> Level:
        """Уровень после ПРОБОЯ. Стр. 43: «Уровень лонг/шорт менятся для нас на противоположный».

        Меняется только сторона: цена, геометрия и происхождение остаются те же — это
        тот же уровень, прочитанный наоборот, а не новый.
        """
        other = LevelSide.SHORT if self.side is LevelSide.LONG else LevelSide.LONG
        return self.model_copy(update={"side": other})


def structure_window_ms(
    acc: Accumulation, bars: list[Bar], timeframe_ms: int
) -> tuple[int, int]:
    """Окно `[от, до)` для профиля: все бары структуры и только они (стр. 26).

    Свечи ВЫХОДА в окно не входят: по стр. 23 структура кончается там, где цена из неё
    вышла, — тела выхода это уже не накопление. Граница проводится по первому телу
    выхода, а не по бару подтверждения.
    """
    last_inside = acc.exit.first_body_index - 1
    return bars[acc.first_index].open_ms, bars[last_inside].open_ms + timeframe_ms


def created_at_ms(acc: Accumulation, bars: list[Bar], timeframe_ms: int) -> int:
    """Момент, с которого уровень существует: ЗАКРЫТИЕ бара подтверждения (стр. 23).

    Выделено в функцию, потому что число нужно двоим — `build_all` и любому зонду, — а
    вторая копия «плюс один таймфрейм» разошлась бы с первой на первой же правке.
    """
    return bars[acc.exit.confirmed_at_index].open_ms + timeframe_ms


def build_level(
    acc: Accumulation,
    hist: TradeHistogram,
    symbol: str,
    window_ms: tuple[int, int],
    born_ms: int,
    price_range: tuple[Decimal, Decimal],
) -> Level | NotReady:
    """Уровень из закрытого накопления.

    Гистограмма обязана покрывать ВСЕ бары структуры (стр. 26). Проверить это здесь
    нельзя — у гистограммы нет разбивки по барам, — поэтому ответственность на
    вызывающем, и он обязан строить её ровно по окну структуры.

    `window_ms` — то же окно, что подано гистограмме (`structure_window_ms`). Передаётся
    аргументом, а не берётся из `hist.first_ms`: у гистограммы это МОМЕНТЫ КРАЙНИХ
    СДЕЛОК, а нужны границы окна. Разница мала и потому опасна — она молча сместила бы
    проверку вложенности (стр. 32) там, где структура кончается тихим участком.

    `born_ms` — `created_at_ms(acc, bars, tf_ms)`. Тоже аргументом, и по той же причине,
    что и окно: ряда баров здесь нет, а выводить момент из `structure_to_ms` арифметикой
    («плюс два тела») неверно на ряду с разрывом.

    `price_range` — крайние цены баров структуры, `(min low, max high)`. Аргументом по той
    же причине: ряда баров здесь нет.
    """
    # ⚠ С 2026-08-09 профиль строится ПРИБОРОМ АВТОРА — сеткой TV (`build_tv`), а не
    # тиковыми бинами: решение владельца о переносе инструментов TV
    # (docs/audit/tv-transfer-2026-08-09.md). Число строк — `TV_ROWS`, его источники — в
    # докстроке константы. Прежний тиковый профиль (`build`) остаётся в модуле для замеров.
    #
    # ⚠ ДИАПАЗОН СЕТКИ — КРАЙНИЕ ЦЕНЫ БАРОВ, а не границы структуры. Правка У3 обзора
    # уровней (docs/audit/levels-projects-2026-08-09.md, фаза 6). До 2026-08-10 сюда шли
    # `acc.lower.edge` и `acc.upper.edge`, и сделки за границами прижимались к крайним
    # строкам.
    #
    # Источник — рисунок: на стр. 26 и 30 строки профиля продолжаются НИЖЕ коробки
    # структуры, а на стр. 30 низ коробки отдельно подписан. Это фиксированный профиль,
    # натянутый на ценовой размах выбранных свечей. То же самое говорит докстрока
    # `TVProfile.clamped_volume` — «его диапазон — экстремумы баров», — то есть модуль
    # знал правило, а вызывающий подавал другое. Шесть профильных реализаций из шести в
    # обзоре берут `min(low)`…`max(high)`.
    #
    # Цена правки замерена ДО внесения на 3326 структурах (54 кадра, 716 файлов суток):
    # ПОК уезжает дальше половины строки у 99.8%, а ВНЕ прежней зоны оказывается у 46.4%
    # — у почти половины уровней меняется сама ТВХ. Прижималось при этом 44.39% объёма по
    # медиане, потому что размах баров шире границ в 3.156 раза.
    profile: TVProfile | NotReady = build_tv(
        hist,
        bottom=price_range[0],
        top=price_range[1],
        rows=TV_ROWS,
    )
    if isinstance(profile, NotReady):
        return NotReady(reason=f"{symbol} {acc.timeframe}: ПОК не построен — {profile.reason}")

    # ⚠ ИНВАРИАНТ: ПОК и зона обязаны лежать внутри базы (ХАЙ…ЛОЙ структуры).
    #
    # Повод — вопрос владельца 2026-08-11: как ПОК может оказаться вне базы, если базу
    # мы определяем первой. Ответ: так быть не должно, а происходило потому, что границей
    # считался внутренний край пары первых точек. На стр. 30 коробка подписана ХАЙ и ЛОЙ,
    # профиль натянут на неё, зона и ПОК внутри неё.
    # Разбор целиком: docs/audit/poc-inside-base-2026-08-11.md
    #
    # После разведения ролей (линии — детекция, коробка — границы наружу) инвариант
    # держится ПО ПОСТРОЕНИЮ: профиль строится по `price_range`, значит все его цены
    # внутри него. Проверка ниже поэтому не рыночный отказ, а сторож вызова: сработает,
    # если вызывающий подаст профилю не тот диапазон, что кладёт в уровень. Молча такое
    # расхождение прошло бы — ровно как проходило до сегодня.
    lo, hi = price_range
    if not lo <= profile.poc_price <= hi:
        return NotReady(
            reason=f"{symbol} {acc.timeframe}: ПОК {profile.poc_price} вне базы "
                   f"[{lo}, {hi}] — профиль построен не по тому диапазону, что подан "
                   f"в уровень"
        )

    return Level(
        symbol=symbol,
        timeframe=acc.timeframe,
        side=LevelSide.LONG if acc.is_long else LevelSide.SHORT,
        price=profile.poc_price,
        zone_lo=profile.val_price,
        zone_hi=profile.vah_price,
        created_at_index=acc.exit.confirmed_at_index,
        created_at_ms=born_ms,
        structure_first_index=acc.first_index,
        structure_last_index=acc.last_index,
        structure_from_ms=window_ms[0],
        structure_to_ms=window_ms[1],
        structure_volume=profile.total_volume,
        boundary_lo=Decimal(str(acc.lower.edge)),
        boundary_hi=Decimal(str(acc.upper.edge)),
        range_lo=price_range[0],
        range_hi=price_range[1],
        boundary_narrowed=acc.upper.narrowed + acc.lower.narrowed,
        boundary_ladder=BorderSource.LADDER in (acc.upper.source, acc.lower.source),
    )


class Unbuilt(BaseModel):
    """Почему уровень не построен. §4.3: пропуск обязан дойти до оператора с причиной."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    timeframe: str
    index: int | None
    """Индекс первого бара структуры. None — не дошли даже до структур."""

    reason: str = Field(min_length=1)


LevelBuild = tuple[tuple["Level", ...], tuple["Unbuilt", ...]]
"""Что отдаёт `build_all`: построенные уровни и НАЗВАННЫЕ причины, где не построен.

Имя заведено, чтобы этот результат можно было передать из рук в руки, не разворачивая:
`card.render` принимает его целиком (находка А-2, дублирование расчёта).
"""


def build_all(
    symbol: str,
    series: dict[str, list[Bar]],
    trades: TradeWindows | None,
    timeframes: tuple[str, ...],
    scans: dict[str, AccumulationScan],
    swings: dict[str, SwingSet] | None = None,
) -> LevelBuild:
    """Все уровни по всем ТФ плюс НАЗВАННЫЕ причины, где уровень не построен.

    Живёт здесь, а не в карточке: уровни нужны и печати, и эмиссии, и доставке, а
    вторая копия этого цикла разошлась бы с первой на первой же правке.

    Причины возвращаются РАЗОБРАННЫМИ (ТФ отдельно от текста), а не готовой строкой:
    подпись ТФ — дело печати, и склеивать её здесь значит навязывать формат всем
    вызывающим.

    ⚠ `scans` подаётся ГОТОВЫМ и обязателен с 2026-08-06. До этого функция звала
    `swings.detect` и `accumulation.detect` сама — и звала их ВТОРОЙ раз: первый делала
    карточка по тем же барам. Разбор ряда теперь один на весь конвейер и живёт в
    `engine.read_series`; ТФ, не давшие разбора, туда просто не попадают, и причина
    называется там же (§4.3).
    """
    built: list[Level] = []
    unbuilt: list[Unbuilt] = []
    # ⚠ Свинги приходят готовыми из `engine.SeriesRead`, а не считаются здесь заново: до
    # 2026-08-06 этот разбор жил в трёх местах сразу. Умолчание `None` оставлено для
    # зондов и старых вызовов — тогда третий вид якоря (свинг, стр. 18) просто не ищется,
    # и это ВИДНО по `stop_anchor_source`, а не молчит.
    sw_by_tf: dict[str, SwingSet] = swings or {}
    for tf in timeframes:
        bars = series.get(tf)
        scan = scans.get(tf)
        if not bars or scan is None:
            continue
        accs = scan.closed
        younger = _younger_tfs(tf, timeframes)
        for acc in accs:
            if trades is None:
                unbuilt.append(Unbuilt(timeframe=tf, index=acc.first_index,
                                       reason="сделок не собрано"))
                continue
            lo, hi = structure_window_ms(acc, bars, TIMEFRAME_MS[tf])
            hist = trades.window(lo, hi)
            if isinstance(hist, NotReady):
                unbuilt.append(Unbuilt(timeframe=tf, index=acc.first_index,
                                       reason=hist.reason))
                continue
            seg = bars[acc.first_index:acc.last_index + 1]
            lvl = build_level(acc, hist, symbol, (lo, hi),
                              created_at_ms(acc, bars, TIMEFRAME_MS[tf]),
                              (Decimal(str(min(b.low for b in seg))),
                               Decimal(str(max(b.high for b in seg)))))
            if isinstance(lvl, NotReady):
                unbuilt.append(Unbuilt(timeframe=tf, index=acc.first_index,
                                       reason=lvl.reason))
                continue
            # Стоповый объём — накопления ВСЕХ младших ТФ, отнесённые к этой структуре
            # (стр. 34; пример стр. 40 — база 4ч и стоповый на 15м, то есть ТФ−2).
            # Якорь стопа считается ЗДЕСЬ, где есть оба ряда баров: у `build_setup` их нет.
            #
            # ⚠ Ранг плотности (`StopVolumeSet.densities`) при склейке нескольких ТФ
            # теряет общую базу: каждый вызов `classify` ранжирует внутри своего ряда.
            # Это осознанно и безвредно ровно потому, что ранг не читает НИКТО — обзор
            # 2026-08-09 это и нашёл. Когда ранг понадобится, склейку придётся заменить
            # одним вызовом на объединённый набор.
            collected: list[StopVolume] = []
            for y in younger:
                y_scan = scans.get(y)
                y_bars = series.get(y)
                if y_scan is not None and y_bars:
                    collected.extend(classify_stop_volume(
                        y_scan.closed, y_bars, acc, bars, tf).items)
            svs: tuple[StopVolume, ...] = tuple(collected)
            down = lvl.side is LevelSide.LONG
            # Лои своего ТФ и ТФ−1 для лонга, хаи для шорта — вторая половина фразы
            # стр. 18, внесённая 2026-08-09.
            kind = SwingKind.LOW if down else SwingKind.HIGH
            sw_prices: list[float] = []
            for stf in (tf, *younger[:1]):
                sw = sw_by_tf.get(stf)
                if sw is not None:
                    sw_prices.extend(s.price for s in sw.swings if s.kind is kind)
            anchor = stop_anchor(lvl.side, float(lvl.boundary_lo if down else lvl.boundary_hi),
                                 acc.lower if down else acc.upper, svs, tuple(sw_prices))
            built.append(lvl.model_copy(update={
                "stop_anchor": None if anchor is None else anchor.price,
                "stop_anchor_source": None if anchor is None else anchor.source,
                "stop_anchor_narrowed": bool(anchor is not None and anchor.narrowed),
            }))
    built = _with_vrvp(built, trades)
    return tuple(built), tuple(unbuilt)


def _with_vrvp(built: list[Level], trades: TradeWindows | None) -> list[Level]:
    """Объём зоны каждого уровня по КОМПОЗИТУ — замена VRVP (стр. 22, 63).

    Композит — самое ШИРОКОЕ покрытое окно среди структур символа (окно самой длинной
    структуры): якорь от структуры, как у Auto Anchored VP и композитов Далтона
    (обоснование — докстрока `Level.vrvp_zone_qty`).

    ⚠ Первая редакция брала ОБЪЕДИНЕНИЕ окон всех структур — и на первых же кадрах
    честно отказала по всем уровням сразу: объединение требует непрерывного покрытия
    сделками от самой старой структуры до самой свежей, а бэкфилл держит не все сутки.
    Окно самой длинной структуры покрыто ПО ПОСТРОЕНИЮ — её уровень уже построен из
    этих сделок. Урок backfill-window-2026-08-04 («сто честных отказов подряд читаются
    как рынок») здесь сработал заранее: отказ по всем уровням одной причиной — дефект
    выбора окна, а не данные.
    """
    if not built or trades is None:
        return built
    widest = max(built, key=lambda lv: lv.structure_to_ms - lv.structure_from_ms)
    comp = trades.window(widest.structure_from_ms, widest.structure_to_ms)
    if isinstance(comp, NotReady):
        # Покрыто при построении уровня, но повторное чтение могло упереться в
        # вытесненный кэш — причина называется, а не глотается.
        note = f"композит (окно структуры {widest.timeframe}) не прочитан: {comp.reason}"
        return [lv.model_copy(update={"vrvp_note": note}) for lv in built]
    out: list[Level] = []
    for lv in built:
        lo, hi = float(lv.zone_lo), float(lv.zone_hi)
        zone = sum(q for b, q in comp.qty_by_bin.items()
                   if lo <= float(comp.bin_price(b)) <= hi)
        out.append(lv.model_copy(update={
            "vrvp_zone_qty": zone, "vrvp_total_qty": comp.qty_seen,
            "vrvp_note": f"окно композита — структура {widest.timeframe}"}))
    return out


NESTED_MAX_STEPS = 1
"""На сколько ступеней ТФ вниз ищутся вложенные уровни. Число из курса, не подобранное.

Стр. 32 говорит «если мы перейдем на МТФ» — на МЛАДШИЙ ТФ, в единственном числе, то есть
одна ступень. Стр. 24 то же самое запрещает распространять дальше прямо: «Уровни ТФ-2
(15м и ниже) обычно не берутся в расчет, т.к. на старшем ТФ их вообще "нет"».

⚠ Замер 2026-08-04 показал, ЧТО именно это ограничивает. Без него (все младшие ТФ сразу)
лестницы доходили до 15, 17 и 22 ступеней: суточная структура вмещает десятки пятиминутных.
«лучше закуп делать на все уровни» из стр. 32 при двадцати двух ордерах перестаёт быть
исполнимым планом, и это признак того, что читается стр. 32 неверно, а не что рынок такой.
"""


def nested(
    parent: Level, pool: tuple[Level, ...], *, max_steps: int = NESTED_MAX_STEPS
) -> tuple[Level, ...]:
    """Дополнительные уровни ВНУТРИ большой структуры. Источник — стр. 32.

    Дословно: «если у нас есть большая структура на СТФ - и у нее есть основной уровень
    ПОК. Но если мы перейдем на МТФ, то в одной большой структуре могут быть
    дополнительные уровни и цена может забрать как и основной уровень, так и пройтись по
    всем локальным уровням которые находятся в одной большой структуре».

    ⚠ Это НЕ вторые пики того же профиля объёма. Читать стр. 32 так — распространённая
    ошибка (я сам так её понял, пока не прочёл дословно); курс говорит про ПЕРЕХОД НА
    МЛАДШИЙ ТФ, где внутри одной большой структуры видны свои накопления со своими ПОК.
    Механизм уже есть целиком — структуры считаются на всех ТФ; недоставало только
    отношения вложенности, и оно здесь.

    Вложенным считается уровень, у которого:
      * ТФ младше родительского (иначе это не «переход на МТФ»);
      * окно структуры целиком внутри окна родителя — по биржевому времени;
      * сам ПОК внутри границ родительской структуры;
      * он УЖЕ СУЩЕСТВОВАЛ, когда появился родитель (стр. 23).

    Последнее условие добавлено 2026-08-04: окно младшей структуры может лежать внутри
    родительского, а бар подтверждения её выхода — уже за ним. Лестница закупа (стр. 32)
    в этом случае содержала бы ордер на уровень, которого в момент сигнала ещё нет.

    Проверяется положение ПОК, а не всей младшей структуры: курс говорит про «локальные
    уровни, которые находятся в одной большой структуре», то есть про уровни. Младшая
    структура может выходить за границу проколом (стр. 18), уровень при этом внутри.

    Сторона НЕ фильтруется: стр. 32 велит «закуп делать на все уровни», не различая их
    происхождение. Отбор по стороне — работа вызывающего, здесь его нет.
    """
    rank = _tf_rank(parent.timeframe)
    out = [
        lvl for lvl in pool
        if lvl.symbol == parent.symbol
        and lvl is not parent
        and 1 <= rank - _tf_rank(lvl.timeframe) <= max_steps
        and lvl.structure_from_ms >= parent.structure_from_ms
        and lvl.structure_to_ms <= parent.structure_to_ms
        and lvl.created_at_ms <= parent.created_at_ms
        and parent.boundary_lo <= lvl.price <= parent.boundary_hi
    ]
    return tuple(sorted(out, key=lambda x: x.price))


STOP_ANCHOR_BAND_MIN_PCT = 2.0
STOP_ANCHOR_BAND_MAX_PCT = 5.0
"""Полоса поиска стопового объёма у границы. Стр. 18 называет её прямо: «в диапазоне
2-5% от границы». Числа взяты у курса, не подобраны, и §4.1 их допускает как исключение
(«величины, которые курс задаёт в процентах прямо»)."""

"""⚠ Здесь был `MIN_PUNCTURE_POINTS = 3`, и он СНЯТ 2026-08-08 по решению владельца.

Он проверял `len(zone.point_indices) >= 3` — число точек ОДНОЙ стороны, тогда как стр. 18
нумерует точки сквозь обе (на схеме 1, 3, 5, 7, 9 сверху и 2, 4, 6, 8, 10 снизу). Вторая
точка любой стороны имеет сквозной номер 3 или 4 и под «3++ точках» уже подпадает, а порог
её отбрасывал: замер на 324 рядах дал 7570 сторон из 11288, где прокол существовал, но в
стоп не шёл. Сквозного номера зона одной стороны не содержит, поэтому отбор перенесён
туда, где номер известен, — `accumulation.MIN_PUNCTURE_ORDINAL`. Сюда `puncture` приходит
уже отобранным, и второй проверки быть не должно."""


class StopAnchorSource(StrEnum):
    """Чем оказался якорь стопа. Стр. 18 называет ТРИ вида, и все три здесь."""

    PUNCTURE = "puncture"
    """Прокол за границу базы: «стоп всегда ставится за этот прокол» (стр. 18)."""

    STOP_VOLUME = "stop_volume"
    """Стоповый объём — база мелкого ТФ (стр. 18, 34)."""

    SWING = "swing"
    """Лой (для лонга) или хай (для шорта) того же ТФ либо ТФ−1 — стр. 18.

    ⚠ Заведено 2026-08-09 обзором стопового объёма. Фраза стр. 18 называет ДВА якоря в
    одном предложении — «стоповый объем – база мелкого ТФ - или Лой того же ТФ или ТФ-1», —
    а реализована была только первая половина. Замер до правки: свинг в полосе 2-5%
    находится у 8163 сторон из 11288, то есть у 72.3%.
    Разбор: docs/audit/stopvol-projects-2026-08-09.md
    """


class StopAnchor(BaseModel):
    """Якорь стопа: цена И ЧЕМ он оказался.

    ⚠ Прежде отдавалась одна цена, и карточка не могла сказать, откуда взялся стоп. §4.3
    требует, чтобы найденное было видно; обзор 2026-08-09 нашёл, что до оператора не
    доходило вообще ничего о стоповом объёме — даже сам факт, что якорь взят у него.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    price: Decimal
    source: StopAnchorSource
    narrowed: bool = False
    """Стоповый объём был В СУЖЕНИИ (стр. 34: «может быть в сужении, в поджатии»).

    Осмысленно только при `source = STOP_VOLUME`. Замер 2026-08-09: в сужении 16.3%
    стоповых объёмов, 14918 из 91795.
    """


def stop_anchor(
    side: LevelSide,
    boundary: float,
    zone: BoundaryZone,
    stop_volumes: tuple[StopVolume, ...],
    swing_prices: tuple[float, ...] = (),
) -> StopAnchor | None:
    """Якорь стопа по стр. 18. `None` — якоря нет.

    Возвращается ДАЛЬНИЙ якорь: прокол, стоповый объём и свинг — все три вида «стоп за X»,
    и стоп за самым дальним из них удовлетворяет всем требованиям сразу.

    `swing_prices` — лои своего ТФ и ТФ−1 для лонга, хаи для шорта. Пустой кортеж означает
    «свинги не поданы», а не «свингов нет»: умолчание оставлено, чтобы зонды могли звать
    функцию, не собирая ряды.
    """
    down = side is LevelSide.LONG          # лонг: якоря НИЖЕ границы, шорт — выше
    lo_pct, hi_pct = STOP_ANCHOR_BAND_MIN_PCT, STOP_ANCHOR_BAND_MAX_PCT
    if down:
        band_lo, band_hi = boundary * (1 - hi_pct / 100), boundary * (1 - lo_pct / 100)
    else:
        band_lo, band_hi = boundary * (1 + lo_pct / 100), boundary * (1 + hi_pct / 100)

    found: list[tuple[float, StopAnchorSource, bool]] = []
    if zone.puncture is not None:
        found.append((zone.puncture, StopAnchorSource.PUNCTURE, False))
    for sv in stop_volumes:
        acc = sv.accumulation
        edge = acc.lower.edge if down else acc.upper.edge
        if band_lo <= edge <= band_hi:
            narrow = bool(acc.upper.narrowed or acc.lower.narrowed)
            found.append((edge, StopAnchorSource.STOP_VOLUME, narrow))
    for p in swing_prices:
        if band_lo <= p <= band_hi:
            found.append((p, StopAnchorSource.SWING, False))
    if not found:
        return None
    best = min(found, key=lambda x: x[0]) if down else max(found, key=lambda x: x[0])
    return StopAnchor(price=Decimal(str(best[0])), source=best[1], narrowed=best[2])


def _younger_tfs(tf: str, available: tuple[str, ...]) -> tuple[str, ...]:
    """ВСЕ младшие ТФ из имеющихся, от ближайшего к самому мелкому (стр. 34).

    ⚠ Здесь была `_younger_tf`, возвращавшая РОВНО ОДИН ближайший младший ТФ. Обзор
    2026-08-09 нашёл, что это расходится с курсом: стр. 34 говорит «на более мелком ТФ»,
    без указания на один шаг, а стр. 40 приводит собственный ПРИМЕР — база 4ч и стоповый
    объём на 15м. В лестнице стр. 17 (5м/15м/час/4ч/1Д/1Н) 15м отстоит от 4ч на два шага,
    то есть пример самого курса прежний код увидеть не мог.

    Цена правки замерена ДО внесения: стоповых объёмов 91795 при одном ТФ−1 против 262517
    при всех младших, прибавка 186%; частный случай стр. 40 появился — 19154 зоны.
    ⚠ И там же названа беда, которую правка усиливает: 46 зон на структуру в среднем при
    полном отсутствии отсева. Разбор: docs/audit/stopvol-projects-2026-08-09.md

    Пустой кортеж — младше нечего взять. Это НЕ значит «стопового объёма нет»: значит, что
    ряд, на котором он виден, не собран.
    """
    rank = _tf_rank(tf)
    younger = [t for t in available if _tf_rank(t) < rank]
    return tuple(sorted(younger, key=_tf_rank, reverse=True))


def _tf_rank(tf: str) -> int:
    """Старшинство ТФ по порядку `TIMEFRAME_MS` — он и есть список курса со стр. 17.

    Своей копии порядка здесь нет умышленно: вторая копия разошлась бы с первой на первой
    же правке. Неизвестный ТФ падает через `tf_ms`, а не становится молча самым младшим.
    """
    tf_ms(tf)
    return list(TIMEFRAME_MS).index(tf)


class LevelState(StrEnum):
    ACTIVE = "active"
    """Уровень жив: цена за него ещё не заходила."""

    WORKED_OFF = "worked_off"
    """Отработан на первое касание — стр. 25: «мы этот уровень удаляем».

    Стр. 31 уточняет, чем именно нельзя торговать: «уровень лимитными ордерами больше не
    торгуем… Позицию от уровня смотрим только по факту слома структуры на более мелких
    ТФ». То есть уровень не исчезает совсем, но лимитки по нему сняты.
    """

    FLIPPED = "flipped"
    """Пробит — стр. 43: «Уровень лонг/шорт менятся для нас на противоположный»."""


class EntryRule(StrEnum):
    """ЧЕМ уровень торгуется в этом состоянии. У каждого значения своя страница.

    Введено 2026-08-04 после разметки автора: у него в легенде 🟢 «лимитки стоят» и
    🟡 «можем проколоть без реакции, работать по факту» — ДВА РАЗНЫХ разрешения, а не
    «активен/неактивен». Мой `limit_orders_allowed` их различал наполовину: он говорил,
    чего делать НЕЛЬЗЯ, и молчал о том, что можно. Молчание о доступном действии — та же
    потеря, что молчание о деградации (§4.3).

    ⚠ Красного 🔴 «шорт-зона в перезакуп» здесь НЕТ и не будет. «Шорт-зона» — это
    `side`, он уже есть; «перезакуп» — рыночная оценка автора, которой курс не даёт ни
    определения, ни порога. Завести под неё состояние значило бы придумать метрику (§3).
    """

    LIMIT = "limit"
    """Лимитки на ПОК и зону — стр. 30: «надежнее всего брать от уровня ПОК»."""

    CONFIRMATION = "confirmation"
    """Только по слому структуры на младшем ТФ — стр. 31.

    Дословно: «уровень лимитными ордерами больше не торгуем… Позицию от уровня смотрим
    только по факту слома структуры на более мелких ТФ». Стр. 25 говорит то же про
    повторные касания: «можно рассматривать вход от 2 или 3 касания только по факту
    слома структуры на младшем ТФ».
    """

    RETEST_FLIPPED = "retest_flipped"
    """По ретесту с обратной стороны, в ПРОТИВОПОЛОЖНУЮ сторону — стр. 43.

    Дословно: «По возврату цены на ретест уровня -  открываем позицию и ставим СТОП за
    накопление». Сам уровень при этом уже другой стороны — `Level.flipped()`.
    """


class LevelStatus(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    state: LevelState
    event: Breach | None
    """Событие, приведшее к состоянию. None — уровень активен, событий не было."""

    limit_orders_allowed: bool
    """Стр. 25 и 31: после отработки лимитками уровень больше не торгуется."""

    entry_rule: EntryRule
    """Чем уровень торгуется СЕЙЧАС. Не выводится из `state` вызывающим — выводится здесь.

    Вывод отработан-значит-ничего-нельзя напрашивается и НЕВЕРЕН: стр. 25 и 31 прямо
    оставляют вход по слому младшего ТФ, а стр. 43 — вход по ретесту после пробоя.
    """

    price_in_zone: bool = False
    """Торгуется ли цена ПРЯМО СЕЙЧАС внутри объёмной зоны уровня.

    ⚠ Заведено 2026-08-07, находка М-09. Стр. 44, вариант 2, дословно: «Приоритет – не
    открывать позицию, если цена уже торгуется в зоне, либо быть готовым выйти в б/у при
    пробое уровня – на ретесте». Правила не было ни в §2, ни в коде: `EntryRule.LIMIT`
    выдавался независимо от того, где цена находится в момент печати карточки.

    Считается по ПОСЛЕДНЕМУ бару ряда — это «сейчас» с точностью до таймфрейма уровня.
    Заглядывания вперёд здесь нет: последний бар ряда уже закрыт (§6).
    """

    resolved_at_ms: int | None
    """ЗАКРЫТИЕ бара, на котором событие разрешилось. None — не разрешилось (или его нет).

    Без этого поля состояние отвечает только на вопрос «что с уровнем СЕЙЧАС», а нужен
    ещё и вопрос «что с ним было на момент сигнала»: отбор целей по нынешнему состоянию
    — такое же заглядывание вперёд, как и отбор целей из будущего (Н-1).
    """

    def state_at(self, as_of_ms: int) -> LevelState:
        """Состояние НА МОМЕНТ `as_of_ms`, а не на конец ряда.

        Эквивалентно пересчёту `status` по ряду, обрезанному этим моментом, и это не
        совпадение: у уровня по стр. 25/43 ОДНА судьба, её ищет `first_breach`, и первое
        событие ряда не зависит от того, насколько ряд продолжается вправо. Пока событие
        не разрешилось, `status` и так отдаёт `active` (ветки OPEN и UNRESOLVED).

        Считать обрезкой ряда было бы честно, но дорого: 374 уровня × пул целей — это
        десятки тысяч повторных проходов `first_breach` вместо одного сравнения.
        """
        if self.resolved_at_ms is None or self.resolved_at_ms > as_of_ms:
            return LevelState.ACTIVE
        return self.state


class MappedLevel(BaseModel):
    """Уровень ВМЕСТЕ с его судьбой. Пара, а не два независимых значения.

    Заведено 2026-08-04: `geometry.build_targets` брал целью любой уровень пула, а замер
    показал, что 83% целей — уровни в состоянии `worked_off` или `flipped`, то есть ровно
    те, про которые стр. 25 говорит «мы этот уровень удаляем», а стр. 43 — что он стал
    противоположным. Состояние было доступно вызывающему и просто не подавалось; пара
    закрывает эту возможность на уровне типа, а не дисциплины.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    level: Level
    status: LevelStatus

    def alive_at(self, as_of_ms: int) -> bool:
        """Существовал ли уровень на момент `as_of_ms` и был ли ещё в силе.

        Два условия, и оба из курса: уровня нет до подтверждения выхода (стр. 23) и нет
        после отработки или пробоя (стр. 25, 43).
        """
        return (self.level.created_at_ms <= as_of_ms
                and self.status.state_at(as_of_ms) is LevelState.ACTIVE)


def map_levels(
    built: tuple[Level, ...], series: dict[str, list[Bar]]
) -> tuple[MappedLevel, ...]:
    """Уровни со свежепосчитанной судьбой. Одно место, где `status` зовётся по всему пулу.

    Уровень, чьего ряда в кадрах нет, в карту НЕ попадает: состояние у него неизвестно, а
    подставить `active` значило бы объявить живым то, что не проверялось (§4.3).
    """
    return tuple(
        MappedLevel(level=lvl, status=status(lvl, bars))
        for lvl in built
        if (bars := series.get(lvl.timeframe))
    )


def status(
    level: Level,
    bars: list[Bar],
    *,
    confirm_bodies: int = CONFIRM_BODIES,
    return_bars: int = RETURN_BARS,
) -> LevelStatus:
    """Состояние уровня §2.10 — выводится из первого события на нём.

    Своей логики у §2.10 нет: прокол уже объявлен отработкой (стр. 6), пробой — флипом
    (стр. 43), первое касание — снятием лимиток (стр. 25). Здесь только связывание одного
    с другим, без новых правил.

    ⚠ КАСАНИЕ подключено 2026-08-06, и до этого правило стр. 25 не исполнялось вовсе.
    Состояние выводилось только из `first_breach`, то есть из того, ЗАШЛА ли цена ЗА
    уровень. Но стр. 25 говорит о другом событии — о приходе цены НА уровень:

        «Как только уровень был отработан на 1 касание (как на графике - увидели хорошую
        реакцию) этот уровень становиться больше не актуальным, т.е. мы этот уровень
        удаляем и ищем новые не отработанные уровни для входа в новую позицию.
        … можно рассматривать вход от 2 или 3 касания только по факту слома структуры на
        младшем ТФ»

    Замер на кадрах прогона `a1` (3 символа, 94 уровня): из 33 уровней, по которым система
    выставляла лимитки, **18 цена уже касалась** — больше половины. У всех восемнадцати
    событие было `unresolved`, то есть цена за уровень заходила, но курс вердикта
    прокол-или-пробой не давал, и `status` оставлял лимитки разрешёнными.

    Касание меняет РАЗРЕШЕНИЕ, а не состояние, и это существенно. Иначе флипов не было бы
    вовсе: любой пробой начинается с касания, и «первое событие — касание» объявляло бы
    отработанным даже то, что стр. 43 велит считать противоположным уровнем. Поэтому
    `state` по-прежнему выводит `first_breach`, а касание снимает лимитки и переводит вход
    на слом младшего ТФ.
    """
    ev = first_breach(bars, float(level.price), level.breach_direction, level.timeframe,
                      from_index=level.created_at_index + 1,
                      confirm_bodies=confirm_bodies, return_bars=return_bars)
    # Стр. 44: «не открывать позицию, если цена уже торгуется в зоне». Считается по
    # последнему ЗАКРЫТОМУ бару — это «сейчас» с точностью до ТФ уровня (М-09).
    last = bars[-1] if bars else None
    in_zone = bool(last is not None
                   and last.low <= float(level.zone_hi)
                   and last.high >= float(level.zone_lo))
    if ev is None or ev.kind in (BreachKind.OPEN, BreachKind.UNRESOLVED):
        if first_test_index(level, bars) is not None:
            return LevelStatus(state=LevelState.ACTIVE, event=ev,
                               limit_orders_allowed=False, price_in_zone=in_zone,
                               entry_rule=EntryRule.CONFIRMATION, resolved_at_ms=None)
        return LevelStatus(state=LevelState.ACTIVE, event=ev, limit_orders_allowed=True,
                           price_in_zone=in_zone,
                           entry_rule=EntryRule.LIMIT, resolved_at_ms=None)
    assert ev.resolved_index is not None  # у разрешившегося события бар есть по построению
    at = bars[ev.resolved_index].open_ms + tf_ms(level.timeframe)
    if ev.kind is BreachKind.BREAKOUT:
        return LevelStatus(state=LevelState.FLIPPED, event=ev, limit_orders_allowed=False,
                           price_in_zone=in_zone,
                           entry_rule=EntryRule.RETEST_FLIPPED, resolved_at_ms=at)
    return LevelStatus(state=LevelState.WORKED_OFF, event=ev, limit_orders_allowed=False,
                       price_in_zone=in_zone,
                       entry_rule=EntryRule.CONFIRMATION, resolved_at_ms=at)


class PressedKind(StrEnum):
    """Конфигурации отработки стр. 28, выраженные новым накоплением у уровня."""

    BELOW = "below"
    """Конфигурация 2: накопление ПОД уровнем — «цена не дошла до уровня, остановилась
    в зоне» (стр. 44, вариант 2). Вход курс рисует свечами от ПОК нового накопления
    (стр. 28, находка М-29)."""

    ABOVE = "above"
    """Конфигурация 5: новая структура НАД уровнем (стр. 28)."""

    ASTRIDE = "astride"
    """Конфигурация 7: «пила» — накопление НА уровне; курс: выйти в бу и дождаться
    выхода из пилы (стр. 28)."""


class PressedStructure(BaseModel):
    """Закрытое накопление, прижатое к зоне уровня, — конфигурации 2/5/7 стр. 28.

    ⚠ Заведено 2026-08-10 (реестр долга, строка 1). До этого система различала четыре
    исхода события на уровне, а конфигурации «новое накопление у уровня» не выражала
    ничем — при том, что у 2 и 7 курс даёт СВОИ правила действий. Здесь конфигурация
    ОБНАРУЖИВАЕТСЯ И НАЗЫВАЕТСЯ; эмиссию она не порождает — тот же выбор, что у слома
    на младшем ТФ (А-02): новый путь сигнала меняет состав эмиссии.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    kind: PressedKind
    first_index: int
    last_index: int
    box_lo: float
    box_hi: float


def pressed_structures(level: Level, scan: AccumulationScan) -> tuple[PressedStructure, ...]:
    """Закрытые накопления ТОГО ЖЕ ТФ, закрывшиеся после появления уровня и прижатые
    к его зоне (пересечение коробки с [zone_lo, zone_hi]).

    Сторона относительно ЦЕНЫ уровня (ПОК) делит их на 2/5/7: коробка целиком ниже —
    ПОД уровнем; целиком выше — НАД; ПОК внутри коробки — «пила». Открытая структура
    у уровня сюда не входит: она видна в `open_tail`, а стр. 28 рисует исходы по
    ЗАКРЫТЫМ (стр. 23: пока цена не вышла, структуры-события нет).
    """
    lo_z, hi_z = float(level.zone_lo), float(level.zone_hi)
    price = float(level.price)
    out: list[PressedStructure] = []
    for acc in scan.closed:
        if acc.last_index <= level.created_at_index:
            continue
        lo, hi = acc.lower.edge, acc.upper.edge
        if hi < lo_z or lo > hi_z:
            continue
        kind = (PressedKind.ASTRIDE if lo <= price <= hi
                else PressedKind.BELOW if hi < price else PressedKind.ABOVE)
        out.append(PressedStructure(kind=kind, first_index=acc.first_index,
                                    last_index=acc.last_index, box_lo=lo, box_hi=hi))
    return tuple(out)


def first_test_index(level: Level, bars: list[Bar]) -> int | None:
    """Первое касание уровня после его появления. Стр. 25: дальше уровень удаляется.

    ⚠ КАСАНИЕМ СЧИТАЕТСЯ ЗАХОД В ЗОНУ, А НЕ ДОСТИЖЕНИЕ ПОК. Правка аудита 2026-08-07,
    находка М-08.

    Прежняя редакция требовала, чтобы цена достала САМ ПОК (`low <= ПОК <= high`), и
    обосновывала это стр. 30, которая действительно РАЗДЕЛЯЕТ события «цена забирает
    объемную зону» и «цена забирает идеально уровень ПОК». Но снятие лимиток курс
    привязывает именно к ЗОНЕ — стр. 31:

        «ВАЖНО: если цена ранее забирала зону и уже получила от нее хорошую лонг реакцию,
         уровень лимитными ордерами больше не торгуем - т.к. уровень стал слабее, и в
         след раз может не отработать.»

    Та же стр. 30 называет заход в зону самостоятельным вариантом отработки: «1 - цена
    забирает объемную зону… и идет в нужном направлении». А схема стр. 24 несёт выноску,
    которой нет в текстовом слое: "тест объемов / сам уровень не забрали" — вход берётся
    по достижении зоны, когда линия ПОК не достигнута.

    Замер расхождения до правки (docs/audit/evidence/E-040-zone-vs-poc): из 17 уровней
    разрешение менялось у 13; у трёх цена не касалась ПОК ВООБЩЕ, то есть уровень
    оставался бы «свежим» бесконечно. Медианная задержка ПОК против зоны — 3 бара,
    максимум 79.

    `None` означает «тестов ещё не было», а не «нет данных»: диапазон поиска задан
    явно и пуст только если уровень моложе конца ряда.
    """
    lo, hi = float(level.zone_lo), float(level.zone_hi)
    for i in range(level.created_at_index + 1, len(bars)):
        if bars[i].low <= hi and bars[i].high >= lo:
            return i
    return None

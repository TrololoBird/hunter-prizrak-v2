class LevelSide(StrEnum):
    LONG = "long"
    SHORT = "short"


def other_side(side: LevelSide) -> LevelSide:
    """Противоположная сторона. ЕДИНСТВЕННОЕ место, где `long` меняется на `short`.

    что из чего следует: сторона → противоположная ей. Правило стр. 43 («Уровень
    лонг/шорт менятся для нас на противоположный») здесь НЕ решается — оно решает, НАДО
    ли менять, а эта функция только меняет.

    ⚠ Заведена 2026-08-26 ревизией слитых PR #4/#5. Смена стороны была выписана ДВАЖДЫ:
    здесь, на перечислении (`Level.flipped`), и строковым тернарником в `tgbot.read_map`
    («short» если в столбце «long»). Копия в потребителе (`live_unique`) в тех же PR уже
    дала двойной переворот — тот дефект чинился переносом правила к производителям, а
    сама формула так и осталась в двух записях, только в разных типах. Правило проекта
    «величина считается в ОДНОМ месте, а не сверяется копиями» разницы типов не знает:
    у обеих записей один референт — стр. 43, и разойтись им ничто не мешало.
    """
    return LevelSide.SHORT if side is LevelSide.LONG else LevelSide.LONG



"""Стоповый объём §2.3. Источник — мини-курс, стр. 34-40.

ЧИСТЫЙ МОДУЛЬ (§10.3): часы, сеть и глобальное состояние не трогаются.

Разбор источника с цитатами: docs/audit/course-reading-2026-08-03.md

Механика, взятая дословно:
  стр. 34  «небольшое накопление, которое останавливает цену… это такое же накопление
           (база), но на более мелком ТФ, чем основное движение актива, и обычно более
           плотное (часто большой объём в мелком диапазоне)»
  стр. 34  «часто формируется над/под большим будущим накоплением — и в последствии
           удерживает цену внутри него как поддержка/сопротивление»
  стр. 35  «после выхода из стопового вверх у нас также появляется уровень в лонг…
           стоповый объём — это такое же накопление, и торговать его можно по тренду
           как обычное накопление»
  стр. 36  стоповый ВНУТРИ структуры — «когда в структуре несколько уровней»
  стр. 37  стоповый ЗА пределами границ базы
  стр. 39  стоповый ПЕРЕД накоплением: «на его зоне/ПОКе формирует новое большое накопление»

Отдельного детектора здесь НЕТ и быть не должно: стр. 34 и 35 дважды говорят, что это
«такое же накопление». Модуль только КЛАССИФИЦИРУЕТ уже найденные накопления младшего ТФ
по отношению к структуре старшего и меряет плотность.

⚠ Порога плотности здесь нет. Курс говорит «обычно», «часто» — это не порог, а наблюдение;
§4.1 запрещает абсолютные пороги. Плотность сообщается числом и рангом среди структур
самого символа, а решение принимает читающий.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field

from .models import Bar
from .trading_range import TradingRange


class Placement(StrEnum):
    """Где стоповый стоит относительно структуры старшего ТФ. Стр. 34, 36, 37, 39."""

    INSIDE = "inside"
    """Внутри границ (стр. 36) — это и есть «в структуре несколько уровней»."""

    ABOVE = "above"
    """Над верхней границей (стр. 34, 37)."""

    BELOW = "below"
    """Под нижней границей (стр. 34, 37)."""

    BEFORE = "before"
    """Раньше по времени, чем началась структура (стр. 39)."""


class StopVolume(BaseModel):
    """Накопление младшего ТФ, отнесённое к структуре старшего."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    trading_range: TradingRange
    host_timeframe: str = Field(min_length=1)
    placement: Placement

    price_range: float = Field(gt=0)
    """Высота структуры ПО СВЕЧАМ: `box_hi - box_lo`.

    ⚠ До 2026-08-20 бралась разность линий детектора (`upper.edge - lower.edge`), тогда
    как коробка рядом считалась по свечам, — две геометрии одной структуры в одной
    функции. С 2026-08-18 границей базы в проекте считается именно коробка, и плотность
    обязана мериться ею же: иначе «объём на единицу цены» делит объём одной структуры на
    высоту другой."""

    box_lo: float
    box_hi: float
    """Коробка стопового объёма ПО СВЕЧАМ его структуры, а не по линиям детектора.

    ⚠ Заведены 2026-08-20. Стр. 18 говорит про стоповый объём «идеально стоп прятать за
    них», и «за них» — это за КРАЙ их свечей: стоп, поставленный на линию детекции,
    оказывается ВНУТРИ малой базы, потому что свечи за эту линию выходят. Замер того же
    дня на BTC+ETH+SOL (417 структур): свечи выходят за линии детектора у 85.4%, медиана
    превышения 0.703%, максимум 22.42%.

    Это тот же класс дефекта, что владелец нашёл глазами 2026-08-18, — две величины под
    одним именем «граница», и наружу шла непроверенная. Отрезок считает
    `range.structure_bars`, одна функция на всех потребителей.
    """

    bar_volume: float = Field(ge=0)
    """Сумма объёма БАРОВ СТРУКТУРЫ — тех же, что дают коробку (`structure_bars`).

    ⚠ До 2026-08-20 суммировался отрезок `first_index..last_index + 1`, где `last_index` —
    бар ПОДТВЕРЖДЕНИЯ выхода: в объём входили оба тела выхода, а в коробку — нет. Замер
    (10 символов, четыре ТФ, 753 структуры): отношение прежнего объёма к нынешнему —
    медиана 1.046, p90 1.139, p99 1.991, максимум 10.74, совпадающих точно НОЛЬ. То есть
    завышены были ВСЕ структуры без исключения, а больше чем в полтора раза — 17 (2.3%).
    Тела выхода — самые объёмные бары ряда, и именно они попадали в «плотность базы».

    ⚠ Это НЕ объём профиля: профиль по §5 строится на сделках (aggTrade), а здесь берётся
    объём свечей. Величины близкие, но не тождественные, и путать их нельзя — сюда объём
    сделок не тянется умышленно, чтобы классификация не требовала скачивания архива.
    """

    @property
    def density(self) -> float:
        """Объём на единицу цены. Стр. 34: «большой объём в мелком диапазоне»."""
        return self.bar_volume / self.price_range


class StopVolumeSet(BaseModel):
    """Результат классификации с рангами плотности внутри самого набора."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    items: tuple[StopVolume, ...]
    densities: tuple[float, ...]
    """Плотности всех поданных накоплений младшего ТФ — база для ранга."""

    def density_percentile(self, sv: StopVolume) -> float:
        """Доля структур того же прогона, чья плотность НЕ выше данной, в процентах.

        §4.1: порог — «перцентиль собственной истории символа», а не абсолютное число.
        Ранг считается по поданному набору; на одном элементе он равен 100 и смысла
        не несёт — это видно по длине `densities`, она не прячется.

        ⚠⚠ ЭТОТ РАНГ НИЧЕГО НЕ ОТБИРАЕТ, И ЭТО РЕШЕНИЕ ПО КУРСУ, А НЕ УПУЩЕНИЕ.
        Проверено 2026-08-20: `density_percentile` не вызывается ни из одного модуля.
        Первым побуждением было счесть это дефектом — стр. 34 ведь называет плотность
        приметой стопового объёма — и ввести по ней отбор. Чтение страницы это ОТМЕНИЛО.

        Стр. 34 дословно: «Стоповый объем может быть в сужении, в поджатии, с четкими
        границами – это такое же накопление (база), но на более мелком ТФ, чем основное
        движение актива, и обычно более «плотное» (часто большой объем в мелком
        диапазоне)».

        Слова «ОБЫЧНО» и «ЧАСТО» — это описание типичного, а не условие. Определение же
        дано первой фразой страницы и говорит о РОЛИ: «небольшое накопление, которое
        останавливает цену». Отбор по плотности сделал бы правило СТРОЖЕ курса — тот же
        класс ошибки, что требовать третье касание там, где курс просит два.

        Поэтому отбор идёт по роли и положению (накопление младшего ТФ у границы), а
        плотность остаётся ИЗМЕРИМЫМ СВОЙСТВОМ. Наружу она пока не предъявляется, и это
        честный остаток: чтобы напечатать её в карточке, ранг нужно донести до `Level`
        (новое поле плюс ступень схемы леджера), а цена такой правки выше пользы от
        строки про свойство, которое курс сам называет необязательным.
        """
        d = sv.density
        return sum(1 for x in self.densities if x <= d) / len(self.densities) * 100


# ⚠⚠ `_VOL_MEMO` УДАЛЁН 2026-08-23. Модульный изменяемый словарь на 100 000 записей жил
# между вызовами в модуле, чья первая строка объявляет: «ЧИСТЫЙ МОДУЛЬ (§10.3): часы,
# сеть и глобальное состояние не трогаются». Гейт чистоты этого не ловил, потому что
# разбирал одни импорты; в тот же день он расширен на модульное состояние.
# Память переехала к владельцу величины — `TradingRange.bar_volume`, туда же, где уже
# живут `box()` и `start_index()`. Ключ с символом стал не нужен: структура принадлежит
# ряду своего символа по построению.


def _placement(small_box: tuple[float, float], host_box: tuple[float, float],
               small_last_ms: int, host_first_ms: int) -> Placement:
    """Где стоповый стоит относительно хозяина. Обе геометрии — КОРОБКИ ПО СВЕЧАМ.

    ⚠⚠ ЗДЕСЬ ЖИЛА ТРЕТЬЯ ГЕОМЕТРИЯ ТОЙ ЖЕ СТРУКТУРЫ (исправлено 2026-08-23). Функция
    брала ЛИНИИ детектора — `small.upper.edge`, `small.lower.edge`, `host.upper.edge`,
    `host.lower.edge`, — тогда как `price_range`, `box_lo`, `box_hi` и `bar_volume` в
    том же `classify` с 2026-08-20 считаются по КОРОБКЕ свечей, и сам модуль объявил
    этот класс закрытым («ОДИН ОТРЕЗОК И ОДНА ГЕОМЕТРИЯ НА СТРУКТУРУ»).

    Расхождение не косметическое: замер 2026-08-20, записанный в поле `box_lo/box_hi`,
    даёт «свечи выходят за линии детектора у 85.4%, медиана превышения 0.703%, максимум
    22.42%». `placement` — это то, чем стоповый объём относится к базе (стр. 34/36/37/39),
    то есть ИМЕННО РАЗЛИЧЕНИЕ "внутри структуры" и "за её границей"; на разнице в 0.7%
    у границы вердикт переворачивается.
    """
    if small_last_ms < host_first_ms:
        return Placement.BEFORE
    mid = (small_box[0] + small_box[1]) / 2
    if mid > host_box[1]:
        return Placement.ABOVE
    if mid < host_box[0]:
        return Placement.BELOW
    return Placement.INSIDE


def classify(
    small: tuple[TradingRange, ...],
    small_bars: list[Bar],
    host: TradingRange,
    host_bars: list[Bar],
    host_timeframe: str,
) -> StopVolumeSet:
    """Отнести накопления младшего ТФ к структуре старшего.

    Ничего не отсеивается: курс не даёт признака, по которому накопление младшего ТФ
    НЕ является стоповым. Отсев по выдуманному порогу плотности здесь был бы ровно тем
    «магическим числом», от которого правило §0 и защищает.

    ⚠ АРГУМЕНТ `symbol` УДАЛЁН 2026-08-23 вместе с модульной памятью `_VOL_MEMO`: он был
    нужен ТОЛЬКО её ключу (ряды разных символов выровнены одним окном бэкфилла и по
    длине с краями совпадают, поэтому без символа память отдавала бы чужой объём).
    Память теперь живёт на самой структуре, и вопрос принадлежности решён владением, а
    не ключом. Оставить аргумент значило бы держать ручку, не соединённую ни с чем.
    """
    items: list[StopVolume] = []
    # Коробка ХОЗЯИНА считается по разу на вызов, а не на каждое младшее накопление:
    # `TradingRange.box` держит собственную память, но обращение к ней стоит ключа ряда.
    host_box = host.box(host_bars)
    if host_box is None:
        # Отрезок структуры-хозяина пуст — относить к ней нечего. То же решение, что
        # строкой ниже для младшего накопления: `None` от `box` означает «отрезка нет»,
        # а не «коробка нулевой высоты», и подставлять вместо него линии детектора
        # значило бы вернуть ту самую вторую геометрию.
        return StopVolumeSet(items=(), densities=())
    host_first_ms = host_bars[host.first_index].open_ms
    for a in small:
        # ⚠ Коробка — из памяти самой структуры (2026-08-21). Прежде здесь стояла
        # четвёртая копия формулы `min(low)/max(high)` по `structure_bars`, и считалась
        # она заново для КАЖДОГО хозяина: 306 вызовов `classify` на символ × сотни
        # структур младшего ТФ. Значение то же — `TradingRange.box` зовёт ту же
        # `structure_bars` и те же `min`/`max`; изменилось только число вызовов.
        box = a.box(small_bars)
        if box is None:
            continue
        box_lo, box_hi = box
        # ⚠⚠ ОДИН ОТРЕЗОК И ОДНА ГЕОМЕТРИЯ НА СТРУКТУРУ. Правка 2026-08-20.
        #
        # До неё в этой функции жили ДВЕ разные структуры под одним именем — ровно то, что
        # запрещает раздел «прибор обязан смотреть на ТУ ЖЕ величину»:
        #   * коробка бралась `structure_bars`, то есть БЕЗ свечей выхода (стр. 26
        #     «важно захватить ВСЕ свечи структуры» — выход в структуру не входит);
        #   * объём суммировался по `first_index..last_index + 1`, где `last_index` — бар
        #     ПОДТВЕРЖДЕНИЯ выхода, то есть ВМЕСТЕ с обоими телами выхода;
        #   * диапазон брался по линиям детектора (`upper.edge - lower.edge`), а не по
        #     коробке, хотя с 2026-08-18 границей базы считается именно коробка.
        #
        # Плотность (`bar_volume / price_range`) стоит на обеих величинах сразу, а по
        # стр. 22 «Сила уровня определяется ТФ и объемом» — то есть это не диагностика, а
        # то, чем уровни сравниваются между собой.
        #
        # Замер раздутия объёма (10 символов, четыре ТФ, 753 структуры): отношение
        # «объём с выходом / объём структуры» — медиана 1.046, p90 1.139, p99 1.991,
        # МАКСИМУМ 10.74; совпадающих точно НОЛЬ, то есть завышены были ВСЕ без
        # исключения, а больше чем в полтора раза — 17 структур (2.3%).
        rng = box_hi - box_lo
        if rng <= 0:
            continue
        # Объём — из памяти самой структуры, как и коробка (2026-08-23). Разбор — в
        # докстроке `TradingRange.bar_volume` и в комментарии на месте `_VOL_MEMO` выше.
        vol = a.bar_volume(small_bars)
        items.append(
            StopVolume(
                trading_range=a,
                host_timeframe=host_timeframe,
                placement=_placement(
                    (box_lo, box_hi), host_box,
                    small_bars[a.last_index].open_ms, host_first_ms),
                price_range=rng,
                bar_volume=vol,
                box_lo=box_lo,
                box_hi=box_hi,
            )
        )
    return StopVolumeSet(
        items=tuple(items),
        densities=tuple(i.density for i in items),
    )

def _beyond_price(z: ZoneSpec, last_price: float) -> bool:
    """Цена прошла СКВОЗЬ структуру зоны: лонговая целиком выше цены, шортовая ниже.

    Границы, а не зона: коробка ХАЙ…ЛОЙ и есть структура (стр. 30), а заход внутрь неё
    проходом сквозь не является. То же правило и тем же способом считает
    `levels.status` (`LevelStatus.price_beyond`) — один смысл обязан считаться одинаково
    в тексте и на картинке, иначе они снова разойдутся.
    """
    return z.boundary_lo > last_price if z.side == "long" else z.boundary_hi < last_price


def zones_for_chart(
    zones: tuple[ZoneSpec, ...], timeframe: str, last_price: float,
    near_local: int = 4, near_senior: int = 6, first_ms: int = 0,
    now_ms: int = 0, price_lo: float = 0.0, price_hi: float = 0.0,
) -> list[ZoneSpec]:
    """Отбор зон для графика ТФ X: как в обзорах автора — не вся карта разом.

    ⚠⚠ ПРАВИЛО СМЕНЕНО 2026-08-19 ПО ВОЗРАЖЕНИЮ ВЛАДЕЛЬЦА. Здесь стояло
    `order[z.timeframe] >= rank` — «свой ТФ и старше», то есть на 4ч-графике не
    рисовался НИ ОДИН уровень 5м, 15м и 1ч. Владелец дословно: «почему только своего
    и старше? на том таймфрейме есть 5 или 15 минутный уровень!» — и он прав дважды.
    Уровень это ЦЕНА: горизонтальная линия видна на любом графике независимо от того,
    на каком ТФ нашлась её структура. И стр. 22 прямо называет случай, когда младший
    сильнее старшего: «иногда в маленькой часовой наторговке может быть объем больше,
    чем в 4ч-1д накоплении - от таких структур стараемся брать».

    Замер цены прежнего правила (BTC, свежий расчёт, кадр 4ч 62229…66924): живых
    уровней в кадре 15 — из них 7 пятиминутных, 3 пятнадцатиминутных, 3 часовых и
    только 2 четырёхчасовых. Прежний фильтр выбрасывал 13 из 15, и среди выброшенных
    были те, что совпадают с разметкой автора: его BUY 1 62 883–63 035 — это наши
    5м и 15м уровни с ПОК 62 876.3.

    ПРАВИЛО ТЕПЕРЬ ТАКОЕ: уровень идёт на график, если он ЖИВОЙ (стр. 25 снимает
    отработанные) и его ПОК попадает в ЦЕНОВОЙ КАДР графика. Ни ТФ, ни близость к
    цене отбором не служат — кадр и живость отсекают достаточно.

    ⚠ С 2026-08-17 кап есть И НА СТАРШИЕ (`near_senior` на сторону). Прежняя редакция
    пропускала старшие ВСЕ, и живой ответ по BTC показал цену этого: карта выросла до
    2177 строк, на график 4ч шло 79 зон, плашки цен выезжали за верх кадра, компоновка
    ломалась (снимок разбора: пол-экрана пустых, столбец плашек до 66817 при шкале до
    64100). Сами числа 4 и 6 ПОДОБРАНЫ ПО ЧИТАЕМОСТИ КАРТИНКИ, а не замерены: замер
    дал только «кап нужен» (79 зон ломали кадр), а сколько именно — решено глазами;
    старших больше, чем локальных, потому что курс стр. 48 считает старший ТФ
    сильнее, но «сильнее» не значит «все разом».

    `first_ms` — левый край окна графика. Снятый уровень, чьё событие (`retired_at_ms`)
    старше кадра, не рисуется вовсе: значок поставить негде (`bar_index` вернёт None),
    и уровень лёг бы полной линией — как живой, которым не является.

    `now_ms` — момент ответа для отбора СНЯТЫХ по `retired_at_ms`.
    ⚠ ФИЛЬТР ВОЗРАСТА СНЯТ 2026-08-21 (основание — комментарий в `live_unique`).
    Прежняя редакция: рамка фильтра «уровень у структуры» — живой уровень,
    скрытый из СВОДКИ, не имеет права остаться на графике — картинка и текст обязаны
    говорить об одном наборе уровней (тот же класс расхождения, что «57 на графике
    против 56 в тексте»). Снятых фильтр не касается: их судьбу решает `retired_at_ms`.
    """
    fit = list(zones)
    if price_hi > price_lo > 0:
        # ЦЕНОВОЙ КАДР вместо фильтра по ТФ: уровень вне видимой шкалы нарисовать
        # некуда — его линия легла бы на край и соврала о цене.
        fit = [z for z in fit if price_lo <= z.price <= price_hi]
    if first_ms > 0:
        fit = [z for z in fit if z.state == "active" or z.retired_at_ms >= first_ms]
    # Возрастной фильтр «у структуры» снят 2026-08-21 — основание в `live_unique`.
    # `now_ms` остаётся в сигнатуре: им пользуется отбор снятых по `retired_at_ms`.
    # 2026-08-18, приказ владельца «допускаешь НАСЛОЕНИЕ противоположных зон!»: активная
    # зона, СКВОЗЬ которую цена уже прошла, на график не идёт. Лонговая зона выше цены —
    # сопротивление, а не поддержка (стр. 43 «Уровень лонг/шорт менятся для нас на
    # противоположный»), и именно такие зоны накладывались на встречные: замер по карте
    # 5 символов дал 385–418 пар наслоения у одного символа при 25–35% активных уровней
    # не с той стороны от цены. Снятых фильтр не касается — у них своя разметка (стрелка
    # отработки, крестик отмены), она и рассказывает историю цены.
    fit = [z for z in fit if z.state != "active" or not _beyond_price(z, last_price)]

    # СКЛЕЙКА — ТА ЖЕ, ЧТО У ТЕКСТА. До 2026-08-19 график получал СЫРУЮ карту, а текст
    # склеенную, и картинка показывала как разные уровни то, что сводка считала одним:
    # живой BTC дал плашки 64 335.9 / 64 331.2 / 64 326 / 64 317.2 / 64 312.7 в полосе
    # 0.1% — пять подписей на один уровень. Одна функция на оба пути, иначе они
    # разъедутся при первой правке (тот же довод, что у `_dedupe` в `live_unique`).
    fit = _dedupe(fit, last_price)

    # ОТБОР ПО СИЛЕ, А НЕ ПО БЛИЗОСТИ. Стр. 22: «Сила уровня определяется ТФ и
    # объемом». Прежний кап брал БЛИЖАЙШИЕ к цене — и на плотной карте все места
    # доставались уровням в пределах полупроцента, а картинка теряла разнос: у автора
    # линии распределены по всему кадру (его BTC 19.08: от 62 024 до 65 203, размах 5%).
    # Сортировка по силе даёт тот же разнос без выдуманного «шага между линиями».
    order = {tf: i for i, tf in enumerate(TIMEFRAME_MS)}
    cap = near_senior + near_local

    def strongest(cands: list[ZoneSpec]) -> list[ZoneSpec]:
        return sorted(cands, key=lambda z: tuple(-v for v in _strength(z, order)))[:cap]

    above = strongest([z for z in fit if z.price >= last_price])
    below = strongest([z for z in fit if z.price < last_price])
    # Рисуются в порядке цены — так их читает глаз, снизу вверх.
    return sorted(above + below, key=lambda z: z.price)



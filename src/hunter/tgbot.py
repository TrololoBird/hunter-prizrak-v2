SENT_DIR = Path("data/sent")
"""Куда складывается ТЕКСТ каждого отправленного сообщения, по суткам.

⚠ ЗАВЕДЕНО 2026-08-19 по вопросу владельца: "почему у тебя нигде не сохраняется
сообщения которые были отправлены в телеграм?". Ответ был — никто этого не написал.
Лог писал СОБЫТИЕ отправки (символ, пользователь, длительность, исход) и не писал
текст, поэтому проверить, что именно прочитал читатель, было НЕЧЕМ. Для проекта, где
всё предъявляемое обязано быть проверяемо, это дыра в самом конце конвейера: карточку
и сигнал проверить можно, а то, что реально ушло в канал, — нет.

`data/` не идёт в git (`.gitignore`), поэтому архив не попадёт в репозиторий.
Формат — JSONL по суткам: одна строка на сообщение, дописывается, ничего не
переписывается."""


def archive_sent(chat: int | str, kind: str, text: str) -> None:
    """Записать отправленное. Отказ архива НЕ роняет доставку — сообщение важнее записи."""
    if not text:
        return
    try:
        SENT_DIR.mkdir(parents=True, exist_ok=True)
        at = clock.now_ms()
        day = datetime.fromtimestamp(at / 1000, tz=UTC).strftime("%Y-%m-%d")
        row = {"at_ms": at, "chat": str(chat), "kind": kind, "text": text}
        with open(SENT_DIR / f"{day}.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
    except OSError as e:
        log.degraded("архив отправленного не записан", причина=f"{type(e).__name__} {e}")


def last_sent(limit: int = 50) -> list[dict[str, str | int]]:
    """Последние отправленные сообщения, свежие первыми. Пусто — архива ещё нет."""
    if not SENT_DIR.exists():
        return []
    out: list[dict[str, str | int]] = []
    for f in sorted(SENT_DIR.glob("*.jsonl"), reverse=True):
        rows: list[dict[str, str | int]] = []
        for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            try:
                rows.append(json.loads(line))
            except ValueError as e:
                # Битая строка НАЗЫВАЕТСЯ, а не пропускается молча: архив пишется
                # дописыванием, и оборванная запись означает, что бота убили посреди
                # строки. Молчание здесь скрыло бы ровно тот момент, ради которого
                # архив и заведён.
                rows.append({"at_ms": 0, "chat": "", "kind": "БИТАЯ ЗАПИСЬ",
                             "text": f"{f.name}:{n} не разобрана: {e}"})
        out += rows[::-1]
        if len(out) >= limit:
            break
    return out[:limit]


class Pacer:
    """Темп отправки по ДОКУМЕНТИРОВАННЫМ лимитам Telegram, а не по надежде.

    core.telegram.org/bots/faq (прочитано 2026-08-17):
      «In a group, bots are not be able to send more than 20 messages per minute»;
      «In a single chat, avoid sending more than one message per second».

    Оба соблюдаются ЗДЕСЬ, в одной точке, потому что превышение стоит не отказа, а
    молчания: Telegram отвечает `retry_after`, сообщение не доходит, и без этой очереди
    оно терялось бы тем тише, чем больше в группе людей.

    Отложенные секунды и просьбы подождать СЧИТАЮТСЯ: «лимит не мешал» без числа
    неотличимо от «никто не смотрел».
    """

    PER_MINUTE = 20
    MIN_INTERVAL_S = 1.0

    def __init__(self) -> None:
        self._sent: dict[str, deque[float]] = {}
        self._locks: dict[str, asyncio.Lock] = {}
        self.delayed_s = 0.0
        self.flood_waits = 0
        self.lost = 0

    def _lock(self, key: str) -> asyncio.Lock:
        lock = self._locks.get(key)
        if lock is None:
            lock = asyncio.Lock()
            self._locks[key] = lock
        return lock

    async def send(self, chat: int | str, what: str,
                   call: Callable[[], Awaitable[object]], text: str = "") -> bool:
        key = str(chat)
        async with self._lock(key):
            await self._wait_turn(key)
            ok = await self._deliver(key, what, call)
            self._sent.setdefault(key, deque()).append(clock.monotonic_ns() / 1e9)
            if ok:
                archive_sent(chat, what, text)
            return ok

    async def _wait_turn(self, key: str) -> None:
        now = clock.monotonic_ns() / 1e9
        queue = self._sent.setdefault(key, deque())
        while queue and now - queue[0] > 60.0:
            queue.popleft()
        wait = 0.0
        if queue:
            wait = max(wait, self.MIN_INTERVAL_S - (now - queue[-1]))
        if len(queue) >= self.PER_MINUTE:
            wait = max(wait, 60.0 - (now - queue[0]))
        if wait > 0:
            self.delayed_s += wait
            await asyncio.sleep(wait)

    async def _deliver(self, key: str, what: str,
                       call: Callable[[], Awaitable[object]]) -> bool:
        for attempt in (1, 2):
            try:
                await call()
                return True
            except TelegramRetryAfter as e:
                self.flood_waits += 1
                log.degraded("Telegram просит подождать", чат=key, что=what,
                             секунд=e.retry_after, попытка=attempt)
                if e.retry_after > MAX_FLOOD_WAIT_S:
                    break
                await asyncio.sleep(float(e.retry_after))
            except TelegramAPIError as e:
                self.lost += 1
                log.degraded("сообщение не доставлено", чат=key, что=what,
                             причина=f"{type(e).__name__} {e}")
                return False
        self.lost += 1
        log.degraded("сообщение потеряно: ожидание дольше предела", чат=key, что=what,
                     предел_с=MAX_FLOOD_WAIT_S)
        return False


class Cooldown:
    """Пауза между запросами одного пользователя. Против спама, а не против людей.

    ⚠ Об отказе сообщается ОДИН раз за окно. Иначе бот усиливает спам: пятьдесят
    сообщений подряд превратились бы в пятьдесят ответов «подождите».
    """

    def __init__(self, seconds: float) -> None:
        self.seconds = seconds
        self.refused = 0
        self._last: dict[str, float] = {}
        self._notified: set[str] = set()

    def take(self, key: str) -> float:
        """0 — можно отвечать (отметка обновлена); больше нуля — сколько ещё ждать."""
        now = clock.monotonic_ns() / 1e9
        last = self._last.get(key)
        if last is not None and now - last < self.seconds:
            self.refused += 1
            return self.seconds - (now - last)
        self._last[key] = now
        self._notified.discard(key)
        return 0.0

    def should_notify(self, key: str) -> bool:
        if key in self._notified:
            return False
        self._notified.add(key)
        return True



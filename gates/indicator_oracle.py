"""ГЕЙТ: канонические величины против независимого оракула. FOUNDATION.md §10.3.

§10.3 дословно: «Гейт считает ATR/RSI/MACD проектным кодом и эталонной библиотекой на
одном срезе, сравнивает, падает при расхождении выше 1e-6.»

Проектный код здесь — `hunter.indicators`, то есть боевые обёртки (не `plta` напрямую:
так гейт проверял бы библиотеку, а не проект — находка Н-5). Оракул — pandas-ta,
вызываемый с talib=False.

⚠⚠ ЧТО ЭТОТ ГЕЙТ ПРОВЕРЯЕТ НЕЗАВИСИМО, А ЧТО НЕТ — НАЗЫВАЕТСЯ (2026-08-23). Раньше он
печатал одну таблицу на все величины, и по ней нельзя было отличить настоящую сверку
двух реализаций от сверки формулы с самой собой. Теперь у каждой строки стоит пометка:

  * `rsi14`, `bb_upper`, `bb_middle`, `bb_lower` — НАСТОЯЩАЯ независимая сверка: у
    pandas-ta своя реализация, и совпадение с нашей ничем не гарантировано заранее;
  * `ema200`, `macd` — НЕ независимы: оракул считает ту же рекурсию
    (`pandas.ewm(adjust=False)`), что и проект (`polars.ewm_mean(adjust=False)`).
    Разные библиотеки, но ОДНА формула и ОДНА затравка. Гейт сам это и печатал числом,
    только молча: «ema200 сходится сразу, 4.3e-15» — так сходятся не две реализации, а
    одна с собой. Пометка `⚠ та же рекурсия` теперь стоит в строке;
  * `atr14` — обёртки проекта нет (`indicators.atr` удалена 2026-08-06), сравниваются
    библиотека с оракулом.

⚠ Почему `ema200`/`macd` не чинятся здесь же. Независимый оракул для них — это оракул
с ДРУГОЙ ЗАТРАВКОЙ (SMA первых N, конвенция TA-Lib), а наш расчёт с 2026-08-09 сеет
первым `close` вслед за TradingView. Такой оракул был бы законно красным всегда: он
сверял бы не расчёт, а выбор конвенции. Сам выбор — открытый вопрос №4
(.claude/rules/open-method-questions.md), и решается он владельцем, а не подгонкой
прибора. До тех пор охват НАЗЫВАЕТСЯ, а не изображается.

⚠ `talib=False` ОБЯЗАТЕЛЕН. Замер 2026-08-03: с настройками по умолчанию pandas-ta
делегирует в TA-Lib, если тот установлен, и тогда гейт сверяет TA-Lib сам с собой —
зелёный при нулевом охвате. С talib=False реализации независимы и расходятся на
~1e-11 (ATR) и ~1e-8 (RSI), то есть порог 1e-6 различает «сошлось» и «разошлось».

pandas здесь — единственное место в проекте, где он допустим: §10.3 разрешает оракул
«только для гейтов, не для продакшена».

Срез — настоящие бары биржи (docs/audit/reference-slice/), а не выдуманные числа.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import polars as pl
import polars_talib as plta

TOLERANCE = 1e-6  # §10.3 дословно
SLICE = Path("docs/audit/reference-slice/BTCUSDT-1h-500.parquet")

sys.path.insert(0, "src")
from hunter import indicators  # noqa: E402

# ПРОГРЕВ: сколько баров нужно, чтобы две независимые реализации сошлись в 1e-6.
# Экспоненциальное сглаживание засевается по-разному, и разница затухает, а не
# исчезает сразу. Замер 2026-08-03 на срезе BTCUSDT 1h, 499 баров:
#   atr14  144 бара (10.3 × периода); на 20-м баре расхождение ещё 5.0e-3
#   rsi14  193 бара (13.8 × периода); на 20-м баре 6.5e-2
#   macd   111 баров (4.3 × медленного периода)
#   ema200 199 баров (1.0 × периода) — сходится сразу, 4.3e-15
# Протокол: docs/audit/indicator-warmup-2026-08-03.md
# Значение, посчитанное раньше прогрева, зависит от способа затравки, а не от рынка,
# и по §4.3 не должно выдаваться как факт.
#   bb_*   20 баров — это НЕ прогрев сглаживания, а длина окна: полосы считаются по
#          скользящему окну 20 и по SMA, экспоненциального затухания в них нет вовсе.
#          Замер 2026-08-23: сравнено 479 точек из 499, худшее расхождение 1.06e-12.
WARMUP_BARS: dict[str, int] = {
    "atr14": 144, "rsi14": 193, "macd": 111, "ema200": 199,
    "bb_upper": 20, "bb_middle": 20, "bb_lower": 20,
}


def _project(df: pl.DataFrame) -> dict[str, list[float | None]]:
    """Величины так, как их считает проект — ЧЕРЕЗ `hunter.indicators`, а не через `plta`.

    ⚠ Правка аудита 2026-08-06, находка М-06 (она же Н-5 разбора 2026-08-04). До неё
    здесь стояли прямые вызовы `plta.*`, то есть гейт сравнивал `polars_talib` с
    `pandas-ta` — ДВЕ ЧУЖИЕ БИБЛИОТЕКИ ДРУГ С ДРУГОМ — и до обёртки проекта не
    дотягивался. §10.3 обещает другое: «Гейт считает ATR/RSI/MACD **проектным кодом** и
    эталонной библиотекой».

    Пробник, которым это найдено (evidence/E-020-gate-probes): период `rsi` в
    `src/hunter/indicators.py` меняется с 14 на 20 — все три индикаторных гейта
    возвращали 0. Контроль: тем же пробником `gates/purity.py` на подсаженном нарушении
    вернул 1, то есть пробник исправен.

    `macd` шёл через проект и раньше: `plta.macd` противоречит собственным EMA библиотеки
    (macd-talib-inconsistency-2026-08-03.md), поэтому проект собирает линию сам.
    """
    out = df.select(
        # ⚠ Правка 2026-08-07 по замечанию QA (09-qa.md, раздел «б»): величины зовутся
        # ТАК ЖЕ, КАК ИХ ЗОВЁТ БОЕВОЙ КОД — без явных аргументов. card.py пишет
        # `indicators.rsi()`, `bbands_upper()`, `bbands_lower()`, то есть пользуется
        # УМОЛЧАНИЯМИ; гейт, прибивавший период явно (`rsi(14)`), подмену умолчания не
        # ловил. Первая редакция правки М-06 этого не заметила.
        indicators.rsi().alias("rsi14"),
        indicators.macd_line().alias("macd"),
        indicators.ema(200).alias("ema200"),
        # ⚠ ПОЛОСЫ БОЛЛИНДЖЕРА ДОБАВЛЕНЫ 2026-08-23. Они идут В КАРТОЧКУ (стр. 68,
        # `factors.band_narrowing` — «как скоро будет выход»), а библиотечной сверки у
        # них не было НИ ОДНОЙ строки: их проверял только рукописный
        # `gates/formula_reference.py`, то есть эталон, написанный тем же источником,
        # что и код. Здесь у них появляется вторая, чужая реализация.
        indicators.bbands_upper().alias("bb_upper"),
        indicators.bbands_middle().alias("bb_middle"),
        indicators.bbands_lower().alias("bb_lower"),
    )
    got = {c: out[c].to_list() for c in out.columns}
    # ⚠ atr14 обёртки проекта НЕ ИМЕЕТ: `indicators.atr` удалена 2026-08-06 за отсутствием
    # потребителя (см. её некролог в src/hunter/indicators.py). Поэтому строка ниже —
    # честно БИБЛИОТЕКА против оракула, а не проект против оракула, и печать это называет.
    # Убрать её молча значило бы сузить охват гейта, не сказав об этом.
    got["atr14"] = (
        df.select(plta.atr(pl.col("high"), pl.col("low"), pl.col("close"),
                           timeperiod=14).alias("a"))["a"].to_list()
    )
    return got


LIBRARY_ONLY: frozenset[str] = frozenset({"atr14"})
"""Величины, у которых обёртки проекта нет: сравнение идёт библиотека против оракула.

Печатается рядом с результатом. Первая редакция этой правки давала ключу отдельное имя, и
он молча выпал из сверки — «величин 3» вместо 4 при зелёном коде возврата. Ровно тот
дефект, который эта же правка и чинит: сужение охвата, выглядящее как успех."""

SAME_RECURSION: frozenset[str] = frozenset({"ema200", "macd"})
"""Величины, у которых оракул считает ТУ ЖЕ рекурсию, что и проект: сверка НЕ независима.

⚠⚠ ЗАВЕДЕНО 2026-08-23. `pandas.ewm(span, adjust=False)` и
`polars.ewm_mean(alpha=2/(N+1), adjust=False)` — одна формула с одной затравкой; то, что
библиотеки разные, независимости не даёт. Гейт печатал это число и молчал о его смысле:
«ema200 сходится сразу, 4.3e-15» — так сходится формула сама с собой, а не две
реализации (для сравнения: настоящие независимые пары дают 1e-8…1e-12).

Замена оракула на реализацию с ДРУГОЙ затравкой (SMA первых N, конвенция TA-Lib) сделала
бы гейт законно красным навсегда: он сверял бы выбор конвенции, а не расчёт. Сам выбор —
открытый вопрос №4, и он решается владельцем. До решения охват называется."""


def _oracle(df: pl.DataFrame) -> dict[str, list[float | None]]:
    """Те же величины независимой реализацией (§10.3)."""
    import pandas as pd  # noqa: TID251 — §10.3 разрешает оракул только в гейтах
    import pandas_ta  # noqa: F401 — регистрирует акцессор .ta

    pdf = pd.DataFrame({
        "high": df["high"].to_list(),
        "low": df["low"].to_list(),
        "close": df["close"].to_list(),
    })
    # ⚠ EMA — `pandas.ewm(span, adjust=False)`: затравка первым значением, конвенция
    # TradingView, на которую проект перешёл 2026-08-09 (см. `hunter.indicators.ema`).
    # НЕ `pdf.ta.ema(sma=False)`: проверено на срезе — тот даёт третью затравку
    # (расхождение 8.8e-5 с TV-рекурсией на баре 300), а `pandas.ewm(adjust=False)`
    # совпадает с рукописной TV-рекурсией в ноль. MACD собирается из тех же EMA, а не
    # из `pdf.ta.macd`: тот сеет SMA и сверял бы затравки, а не расчёт. Независимость
    # оракула сохранена: pandas против polars.
    ema12 = pdf["close"].ewm(span=12, adjust=False).mean()
    ema26 = pdf["close"].ewm(span=26, adjust=False).mean()
    # ⚠⚠ `ddof=0` — ЭТО КОНВЕНЦИЯ БОЛЛИНДЖЕРА, А НЕ ПОДГОНКА ПОД НАШ ОТВЕТ, и разница
    # между двумя вариантами ЗАМЕРЕНА (срез 499 баров, 2026-08-23):
    #
    #     ddof=0 (генеральное σ)  худшее расхождение 1.06e-12  — сходится
    #     ddof=1 (выборочное σ)   худшее расхождение 7.43e-04  — расходится на ВСЕХ 479
    #
    # Отношение ровно sqrt(20/19) = 1.0260, то есть весь разрыв — в делителе σ, а не в
    # расчёте. Генеральное σ берут и Боллинджер («Bollinger on Bollinger Bands»), и
    # TA-Lib (`BBANDS`), и StockCharts, и `ta.stdev` TradingView; выборочное — умолчание
    # одной библиотеки pandas-ta. Средняя линия при этом сходится к 9.2e-16 при ЛЮБОМ
    # ddof — она SMA и от σ не зависит; это и показывает, что расхождение локализовано.
    #
    # Взять `ddof=1` значило бы сверять не расчёт, а выбор делителя, — и гейт был бы
    # красным по причине, к нашему коду отношения не имеющей.
    bb = pdf.ta.bbands(length=20, std=2.0, ddof=0, talib=False)
    return {
        "atr14": pdf.ta.atr(length=14, talib=False, mamode="rma").tolist(),
        "rsi14": pdf.ta.rsi(length=14, talib=False).tolist(),
        "macd": (ema12 - ema26).tolist(),
        "ema200": pdf["close"].ewm(span=200, adjust=False).mean().tolist(),
        "bb_lower": bb.iloc[:, 0].tolist(),
        "bb_middle": bb.iloc[:, 1].tolist(),
        "bb_upper": bb.iloc[:, 2].tolist(),
    }


def compare(
    a: list[float | None], b: list[float | None], warmup: int
) -> tuple[int, float, int]:
    """Возвращает (сравнено точек, худшее относительное расхождение, сколько за порогом).

    Точки до прогрева пропускаются: там расходятся затравки, а не расчёт.
    """
    compared = 0
    worst = 0.0
    over = 0
    for i, (x, y) in enumerate(zip(a, b, strict=True)):
        if i < warmup:
            continue
        # `math.isnan`, а не идиома `x != x`. Обе верны, но вторую CodeQL помечает как
        # «сравнение выражения с самим собой» (2026-08-10), и предупреждение висело бы
        # вечно. Постоянный шум учит не смотреть — то же правило, по которому из CI
        # убран заведомо красный живой прогон.
        if x is None or y is None or math.isnan(x) or math.isnan(y):
            continue
        compared += 1
        denom = max(abs(x), abs(y), 1e-9)
        rel = abs(x - y) / denom
        worst = max(worst, rel)
        if rel > TOLERANCE:
            over += 1
    return compared, worst, over


def main() -> int:
    if not SLICE.exists():
        print(f"ПРОВАЛ: нет эталонного среза {SLICE} — проверка не состоялась")
        return 1
    df = pl.read_parquet(SLICE)
    proj = _project(df)
    orac = _oracle(df)

    names = sorted(set(proj) & set(orac))
    if not names:
        print("ПРОВАЛ: не нашлось ни одной общей величины — проверка не состоялась")
        return 1

    failed = 0
    print(f"гейт-оракул: срез {SLICE.name}, баров {df.height}, величин {len(names)}, "
          f"порог {TOLERANCE:g}")
    for n in names:
        warm = WARMUP_BARS.get(n)
        if warm is None:
            print(f"  ПРОВАЛ {n}: прогрев не замерен — сверять нечем")
            failed += 1
            continue
        compared, worst, over = compare(proj[n], orac[n], warm)
        status = "СОШЛОСЬ" if over == 0 else f"РАЗОШЛОСЬ на {over}"
        # Охват КАЖДОЙ строки называется прямо в ней: «сошлось» у независимой пары и
        # «сошлось» у формулы с самой собой — разные утверждения, и различать их обязан
        # читатель отчёта, а не тот, кто помнит устройство гейта.
        if n in LIBRARY_ONLY:
            arm = " ⚠ обёртки проекта нет: библиотека против оракула"
        elif n in SAME_RECURSION:
            arm = " ⚠ ТА ЖЕ РЕКУРСИЯ: сверка НЕ независима (см. SAME_RECURSION)"
        else:
            arm = ""
        print(f"  {n:9} прогрев {warm:4}  сравнено {compared:4}  "
              f"худшее расхождение {worst:.3e}  {status}{arm}")
        if compared == 0:
            print(f"  ПРОВАЛ {n}: сравнено 0 точек — величина не проверена")
            failed += 1
        if over:
            failed += 1
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())

"""ГЕЙТ: у числового утверждения есть команда воспроизведения. FOUNDATION.md §7.3.

§7.3 дословно: «Каждое числовое утверждение сопровождается командой воспроизведения.
Число без команды не фиксируется».

Зачем гейт, а не дисциплина: замер 2026-08-04 нашёл **16 документов из 33** с числами и
без единой команды — включая почти всё, что писалось в тот день. Владелец не программист;
число, которое он не может перепроверить, для него неотличимо от выдуманного.

Конфликт с §7.4 («зонд отвечает на один вопрос, результат в docs/audit, скрипт удаляется»)
разрешается так: скрипт удаляется, а КОМАНДА или сам зонд переносятся в протокол
фрагментом кода. Тогда нет ни осиротевших файлов, ни непроверяемых чисел.

Охват печатается числом.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOTS = (Path("docs/audit"),)

# Что считается числовым утверждением: дробь, длинное число или число с единицей.
NUM = re.compile(r"\b\d+[.,]\d+\b|\b\d{3,}\b|\b\d+\s*(?:%|МБ|ГБ|сут|баров|сделок|структур)")
# Что считается командой воспроизведения.
CMD = re.compile(r"```bash|```python|uv run|python -m hunter|gates/\w+\.py")

MIN_NUMS = 5
"""Порог, ниже которого документ считается не числовым. Пять — чтобы дата в шапке и
номер страницы курса не превращали любой текст в «числовое утверждение»."""

# Документы, которым команда не нужна по природе. Список явный: молчаливое исключение
# неотличимо от непроведённой проверки.
EXEMPT = {
    "docs/audit/corrections-2026-08-03.md",      # реестр решений, числа цитатные
    "docs/audit/sources-policy-2026-08-03.md",   # реестр решений по источникам
    # Сверка терминов: все числа — это АДРЕСА (файл:строка) и счёт самих терминов, а не
    # замеры. Проверяются они открытием названного файла и названной страницы курса, а не
    # прогоном; зондов в проекте больше нет (приказ владельца 2026-08-19).
    "docs/audit/terms-vs-implementation-2026-08-19.md",
    # Исследование внешних источников: все числа — цитаты чужих страниц и звёзды GitHub
    # с URL при каждом; проверяются переходом по ссылке, а не прогоном. Собственных
    # замеров в документе нет, и он сам это заявляет в разделе «чего проверить не удалось».
    "docs/audit/ta-terms-research-2026-09-01.md",
    # Часть 2 того же исследования: та же природа чисел — цитаты внешних страниц и
    # книг с URL, собственных замеров нет, документ сам это заявляет.
    "docs/audit/ta-terms-research-2-2026-09-01.md",
    "docs/audit/ta-terms-research-3-2026-09-01.md",  # та же серия, та же природа чисел
}


def main() -> int:
    docs = sorted(p for r in ROOTS for p in r.rglob("*.md"))
    if not docs:
        print("ПРОВАЛ: протоколов не найдено — проверка не состоялась")
        return 1
    numeric = 0
    bad: list[tuple[str, int]] = []
    for d in docs:
        text = d.read_text(encoding="utf-8")
        n = len(NUM.findall(text))
        if n < MIN_NUMS:
            continue
        numeric += 1
        if d.as_posix() in EXEMPT:
            continue
        if not CMD.search(text):
            bad.append((d.as_posix(), n))

    print(f"гейт §7.3 «число без команды не фиксируется»: протоколов {len(docs)}, "
          f"числовых {numeric}, освобождено {len(EXEMPT)}, без команды {len(bad)}")
    for p, n in bad:
        print(f"  НАРУШЕНИЕ {p}: числовых упоминаний {n}, команды воспроизведения нет")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

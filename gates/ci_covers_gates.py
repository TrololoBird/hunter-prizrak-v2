"""Гейт: каждый файл `gates/*.py` действительно ВЫЗЫВАЕТСЯ в CI.

Повод — замер, а не опасение. 2026-08-04 сверка списка файлов со списком шагов
`.github/workflows/ci.yml` показала: из четырнадцати гейтов в CI вписаны десять.
Три (`models_forbid_extra`, `doc_refs`, `repro_commands`) были написаны накануне и НИ
РАЗУ не отработали на чужой машине — они запускались только вручную, тогда, когда о них
помнили. Гейт вне CI неотличим от скрипта: он не мешает влить нарушение.

⚠⚠ ЧТО ИМЕННО ИЩЕТСЯ (ужесточено 2026-08-23). Прежде проверялось ВХОЖДЕНИЕ ИМЕНИ файла
в текст исполняемых строк — то есть достаточно было упомянуть `purity.py` в `name:`
шага, в `if:`, в переменной окружения или в пути артефакта, и гейт засчитывал его как
вызванный. Гейт, переставший исполняться, но упомянутый, проходил проверку. Теперь
ищется КОМАНДА ЗАПУСКА: `python` (в любом виде — `uv run python`, `python3`,
`python -m`) и следом путь `gates/<имя>.py`. Это и есть разница между «вписан» и
«вызывается», ради которой гейт существует.

⚠ Просматриваются ВСЕ файлы `.github/workflows/*.yml`, а не один `ci.yml` (2026-08-23).
Прежде гейт, вписанный только в `security.yml`, считался НЕ вызываемым, хотя вызывался,
— ложный минус; а гейт, вписанный туда ВМЕСТО ci.yml, был бы невидим проверке полноты.
Печатается, в каком именно потоке гейт найден: «вызывается» и «вызывается там, где надо»
— разные утверждения, и второе решает человек.

⚠ Собственную вписанность этот гейт проверяет наравне с остальными, но если ЕГО самого
удалить из CI, проверять станет некому. Дыра сжимается до одного файла и до строки в
diff'е ci.yml — совсем убрать её нельзя, и здесь она названа, а не умолчана.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

WORKFLOWS = Path(".github/workflows")
GATES = Path("gates")

CALL = re.compile(r"python[0-9.]*\s+(?:-m\s+\S+\s+)?\S*gates/(?P<name>[A-Za-z0-9_]+\.py)")
"""Команда ЗАПУСКА гейта. Не «имя встретилось», а «интерпретатор получил этот файл»."""


def calls_in(path: Path) -> set[str]:
    """Имена гейтов, ЗАПУСКАЕМЫХ этим потоком. Комментарии не считаются.

    ⚠ Строки режутся по `#` — правка 2026-08-07, находка Э-4, подтверждённая
    исполнением: прежде искалась подстрока в целом файле, поэтому ЗАКОММЕНТИРОВАННЫЙ шаг
    проходил проверку (18 из 18, код 0). Гейт, вписанный в комментарий, — это гейт,
    который не работает; ровно от этого он и должен защищать.
    """
    out: set[str] = set()
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0]
        out.update(m.group("name") for m in CALL.finditer(line))
    return out


def main() -> int:
    flows = sorted(WORKFLOWS.glob("*.yml"))
    if not flows:
        print(f"ПРОВАЛ: нет ни одного потока в {WORKFLOWS} — проверка не состоялась")
        return 1
    where: dict[str, list[str]] = {}
    for f in flows:
        for name in calls_in(f):
            where.setdefault(name, []).append(f.name)
    files = sorted(p.name for p in GATES.glob("*.py") if p.name != "__init__.py")
    missing = [n for n in files if n not in where]
    unknown = sorted(set(where) - set(files))
    print(f"гейтов в каталоге {len(files)}, ЗАПУСКАЮТСЯ в потоках "
          f"{len(files) - len(missing)} (потоков просмотрено {len(flows)}, "
          f"учтены только строки вне комментариев)")
    for n in files:
        if n in where:
            print(f"ok      gates/{n} — {', '.join(sorted(where[n]))}")
    if unknown:
        # Запуск файла, которого в каталоге нет, — тоже расхождение: шаг CI либо
        # упадёт, либо молча ничего не проверит. Называется, а не молчит.
        print(f"ПРОВАЛ: в потоках запускаются НЕСУЩЕСТВУЮЩИЕ гейты — {len(unknown)}")
        for n in unknown:
            print(f"  gates/{n}")
    if missing:
        print(f"ПРОВАЛ: не запускаются ни в одном потоке — {len(missing)}")
        for n in missing:
            print(f"  gates/{n}")
    if missing or unknown:
        return 1
    print("нарушений 0")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Гейт: цитата в «ёлочках» рядом со ссылкой «стр. N» стоит на этой странице ДОСЛОВНО.

FOUNDATION.md §0: элемент не входит в код без внешнего референта, и для метода
PrizrakTrade референт — страница мини-курса. До 2026-08-04 ни одна ссылка не
проверялась механически: их больше двухсот, сверялись они глазами при написании и
больше никогда.

ПОЧЕМУ ИМЕННО ДОСЛОВНОСТЬ, а не «страница про то же»

Первая редакция гейта сверяла ПЕРЕСЕЧЕНИЕ СЛОВАРЯ утверждения и страницы. Замер:
ложных срабатываний 3.9–7.8% (порог длины слова 4–5), а подставленную заведомо чужую
страницу такая проверка ловила лишь в 42% случаев. Инструмент, который пропускает
больше половины, — не гейт, и порог там пришлось бы подбирать на глаз.

Дословное вхождение цитаты решает обе беды сразу: ложных срабатываний нет по
построению, а подмена страницы ловится всегда. Замер на `src/hunter` при вводе:
54 цитаты, на своей странице 45, на ЧУЖОЙ 0, изменённых 9.

Те девять и есть находка. Ни одна не была ссылкой на неверную страницу — все девять
были ТИХО ОТРЕДАКТИРОВАННОЙ цитатой: выпало «ПП» из «под/над уровнем ПП», выпало
«или одной из них» (а это меняет правило: хватает одной скользящей), выпало «стоп» из
«идеально стоп прятать за них», исправлена опечатка автора «менятся», дописано моё
«ПП в Лонг — зеркально» внутрь его кавычек. Отредактированная цитата референтом не
является — проверить её нельзя, а выглядит она как проверенная.

СЛЕДСТВИЕ — КОНВЕНЦИЯ ПРОЕКТА: «ёлочки» рядом со ссылкой означают ДОСЛОВНУЮ цитату.
Для выделения своих слов «ёлочки» не годятся: гейт их не отличит, да и читатель тоже.

ЧТО ЭТОТ ГЕЙТ НЕ ПРОВЕРЯЕТ

Ссылку БЕЗ цитаты — никак. Таких примерно половина, и они остаются на честном слове;
это записано здесь, а не умолчано. Сравнение по словарю было попыткой их закрыть и
провалилось замером.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import fitz

PDF = Path("docs/course/Мини Курс по трейдингу от PrizrakTrade.pdf")
ROOTS = (Path("src/hunter"), Path("docs"), Path("CLAUDE.md"))
CITE = re.compile(r"[Сс]тр\.\s?(\d+(?:\s*[,/]\s*\d+)*)")
"""⚠ Заглавная «С» — не косметика. Первая редакция регулярки её не знала, и гейт
пропускал **53 ссылки из 271** (замер 2026-08-04): все, что стоят в начале предложения,
включая `breach.py::Breach.worked_off` и `geometry.py::TF_ORDER`. Гейт печатал
«нарушений 0», не заглянув в пятую часть популяции. Тот же урок, что с охватом CI:
проверка, не назвавшая своего охвата, утверждает больше, чем проверила."""
QUOTE = re.compile(r"«([^«»]{10,400})»")
MIN_CHARS = 15
"""Порог длины после нормализации. Короче — это термин («ПОК», «флет»), а не цитата."""

TAIL_GAP = re.compile(r"[ \t]*[(\[]?[ \t]*")
"""Что допустимо между цитатой и её ссылкой в прозаической форме `«…» (стр. 43)`."""

TAIL_CHARS = 12
"""Столько символов после закрывающей «ёлочки» ищется ссылка формы `» (стр. 43)`.

Двенадцати хватает на `» (стр. NN)` с точкой или запятой; больше — начнёт цеплять
ссылку СЛЕДУЮЩЕГО предложения и вернёт ту самую ошибку, ради которой правило написано.
"""

NEAR_CHARS = 60
"""Дальше этого от ссылки «ёлочки» цитатой не считаются — ЗАМЕР, а не круглое число.

Кавычки в проекте несут две работы: цитата и выделение своих слов. Отличить их можно
только по соседству со ссылкой. Замер 2026-08-04 по 81 дословно сошедшейся цитате:
медиана расстояния до своей ссылки 15 символов, p90 = 40, максимум 119.

Порог 60 оставляет под проверкой 78 цитат из 81 и отсекает выделения, стоящие в том же
абзаце, но в стороне. Порог 120 накрыл бы все 81 ценой семи лишних срабатываний на
выделениях — размен хуже: гейт, который ругается на верный текст, отучают читать.
Три цитаты за порогом (расстояния 86, 100, 119) проверке не подлежат — это записано,
а не умолчано.
"""

# Признаки того, что в «ёлочках» стоит код, а не текст курса.
CODE_MARKS = ("{", "::", "()", "->", "`")


def flat(s: str) -> str:
    """Только буквы и цифры: пунктуация, регистр, переносы строк и ё/е не различаются.

    Курс свёрстан в PDF, и текстовый слой рвёт строки посреди фразы. Сравнивать с
    сохранением пробелов значит ловить вёрстку, а не расхождение смысла.
    """
    return re.sub(r"[^а-яa-z0-9]", "", s.lower().replace("ё", "е"))


def _blocks(text: str) -> list[tuple[str, int]]:
    """Абзацы (разделитель — пустая строка) вместе с номером первой строки каждого."""
    out: list[tuple[str, int]] = []
    buf: list[str] = []
    start = 1
    for i, line in enumerate(text.splitlines(), 1):
        if line.strip():
            if not buf:
                start = i
            buf.append(line)
        elif buf:
            out.append(("\n".join(buf), start))
            buf = []
    if buf:
        out.append(("\n".join(buf), start))
    return out


def files() -> list[Path]:
    out: list[Path] = []
    for root in ROOTS:
        if root.is_file():
            out.append(root)
        elif root.is_dir():
            out += [p for p in sorted(root.rglob("*"))
                    if p.suffix in (".py", ".md") and "__pycache__" not in p.parts]
    return out


def main() -> int:
    if not PDF.exists():
        print(f"ПРОВАЛ: курса нет по пути {PDF} — проверка не состоялась")
        return 1
    doc = fitz.open(PDF)
    pages = {n: flat(doc[n - 1].get_text()) for n in range(1, doc.page_count + 1)}

    bad: list[str] = []
    ok = 0
    for path in files():
        # Единица разбора — АБЗАЦ, а не строка. Ссылка и её цитата разъезжаются по
        # строкам при любой переверстке докстроки: сначала я склеивал строку со
        # следующей, и тогда ссылка, стоящая СТРОКОЙ ВЫШЕ цитаты, терялась. Абзац
        # снимает вопрос целиком и заодно не даёт посчитать цитату дважды.
        for block, first_line in _blocks(path.read_text(encoding="utf-8")):
            cites = list(CITE.finditer(block))
            if not cites:
                continue
            for qm in QUOTE.finditer(block):
                q = qm.group(1)
                if "стр." in q or any(c in q for c in CODE_MARKS):
                    continue
                # ⚠ Пара выбирается по БЛИЗОСТИ, а не «первая ссылка в абзаце»: текст
                # «стр. 32 («…») и стр. 30 («…»)» встречается, и наивная пара объявила
                # верную ссылку ошибкой. Дефект найден собственным прогоном гейта.
                # В проекте живут ДВА способа записи, и правило обязано знать оба:
                #   список  —  `стр. 26  «важно захватить…»`   (ссылка ПЕРЕД цитатой)
                #   проза   —  `«важно захватить…» (стр. 26)`  (ссылка СРАЗУ ПОСЛЕ)
                # Поэтому: если сразу за закрывающей «ёлочкой» стоит ссылка — она и есть
                # своя; иначе берётся ближайшая предшествующая. Наивное «ближайшая по
                # расстоянию» ломало список (цитата с переносом липла к следующему
                # пункту), а наивное «только предшествующая» ломало прозу.
                # ⚠ «Сразу после» — это ТОЛЬКО скобка: `» (стр. 43)`. Ни перевод строки
                # (следующий пункт списка начинается через два символа), ни `; стр. 47`
                # (вторая ссылка того же предложения) своей ссылкой не являются, и обе
                # эти формы в дереве есть — каждая давала ложное срабатывание.
                after = [c for c in cites
                         if 0 <= c.start() - qm.end() <= TAIL_CHARS
                         and TAIL_GAP.fullmatch(block[qm.end():c.start()])]
                before = [c for c in cites if c.start() < qm.start()]
                near = (min(after, key=lambda c: c.start()) if after
                        else max(before, key=lambda c: c.start()) if before
                        else min(cites, key=lambda c: c.start() - qm.start()))
                if abs(near.start() - qm.start()) > NEAR_CHARS:
                    continue  # выделение своих слов, а не цитата — см. NEAR_CHARS
                pg = [int(x) for x in re.split(r"[,/]", near.group(1))]
                line_no = first_line + block[:qm.start()].count("\n")
                for frag in re.split(r"…|\.\.\.", q):
                    f = flat(frag)
                    if len(f) < MIN_CHARS:
                        continue
                    if any(f in pages[n] for n in pg if n in pages):
                        ok += 1
                        continue
                    where = [n for n in pages if f in pages[n]]
                    hint = (f"стоит на стр. {where}" if where
                            else "в курсе не найдена — цитата изменена")
                    bad.append(f"{path}:{line_no}: ссылка стр. {pg}, но цитата "
                               f"{hint}\n      «{frag.strip()[:100]}»")

    unquoted = sum(
        1
        for p in files()
        for ln in p.read_text(encoding="utf-8").splitlines()
        if CITE.search(ln) and "«" not in ln
    )
    print(f"страниц в курсе {doc.page_count}; цитат при ссылках проверено {ok + len(bad)}, "
          f"сошлись дословно {ok}")
    print(f"ссылок БЕЗ цитаты (гейт их не проверяет) — {unquoted}")
    if bad:
        print(f"ПРОВАЛ: изменённых цитат {len(bad)}")
        for b in bad:
            print(f"  {b}")
        return 1
    print("нарушений 0")
    return 0


if __name__ == "__main__":
    sys.exit(main())

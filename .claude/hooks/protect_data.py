"""ХУК: не дать удалить то, что восстанавливается дорого или не восстанавливается.

Защищаются ровно две вещи, и обе — по замеру, а не по осторожности:

  * `data/aggcache` — суточные архивы сделок. На 2026-08-06 это гигабайты, скачанные
    за часы; перекачка одного символа за 102 суток шла десятками минут. Файлы проверены
    по sha256 при укладке, то есть это ещё и сверенные данные;
  * `data/ledger.sqlite3` — боевой леджер. §8 этап 7 называет его «единственным будущим
    источником ответа на вопрос, работает ли метод». Он накапливается только временем:
    исход считается по барам, закрывшимся ПОСЛЕ записи сигнала, поэтому потерянный
    журнал не пересчитывается ничем.

⚠ Кадры прогонов (`data/frames/<id>`) НЕ защищаются намеренно: они порождаются одной
командой за минуты, и за эту сессию их удаляли шесть раз как мусор от пробников. Защита,
мешающая обычной работе, будет обойдена — и тогда перестанет защищать нужное.
"""

from __future__ import annotations

import json
import re
import sys

# Что нельзя стирать. Ключ — на что смотреть в команде, значение — чем это объяснить.
PROTECTED: dict[str, str] = {
    "data/aggcache": "суточные архивы сделок, скачанные часами и сверенные по sha256",
    "data/ledger.sqlite3": "боевой леджер — единственный источник ответа «работает ли "
                           "метод» (§8 этап 7), накапливается только временем",
}

REMOVERS = re.compile(r"\b(rm|rmdir|del|Remove-Item|shutil\.rmtree|unlink)\b")
WHOLE_DATA = re.compile(r"\brm\s+(-\w+\s+)*data/?\s*($|;|&|\|)")


def main() -> int:
    raw = sys.stdin.read()
    try:
        event = json.loads(raw) if raw.strip() else {}
    except json.JSONDecodeError:
        # Разобрать не удалось — пропускаем. Здесь это правильно: хук защищает от
        # ОПЕЧАТКИ, а не от злого умысла, и блокировать всё подряд из-за него нельзя.
        # Настоящий запрет на коммит при красных гейтах живёт в commit_gate.py.
        return 0

    command = str(event.get("tool_input", {}).get("command", ""))
    command_slashed = command.replace("\\", "/")
    if not REMOVERS.search(command_slashed):
        return 0

    hits = [(p, why) for p, why in PROTECTED.items() if p in command_slashed]
    if WHOLE_DATA.search(command_slashed):
        hits.append(("data/", "весь каталог данных целиком"))
    if not hits:
        return 0

    what = "\n".join(f"  * {p} — {why}" for p, why in hits)
    print(
        "УДАЛЕНИЕ ОСТАНОВЛЕНО. Команда трогает то, что восстанавливается дорого либо "
        f"не восстанавливается вовсе:\n{what}\n\n"
        "Если удалить действительно надо — это делает владелец руками, не агент.",
        file=sys.stderr,
    )
    return 2


if __name__ == "__main__":
    sys.exit(main())

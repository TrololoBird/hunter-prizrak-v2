"""ХУК: запретить НЕОБРАТИМОЕ — удаление данных и переписывание истории.

⚠ Эти запреты сначала были объявлены в `permissions.deny` файла `.claude/settings.json`
и НЕ РАБОТАЛИ. Проверено пробником 2026-08-06: в `deny` добавлено
`Bash(echo ПРОБА-ЗАПРЕТА *)`, команда `echo ПРОБА-ЗАПРЕТА 1` выполнилась. Двоеточная
форма `Bash(echo ПРОБА:*)` и форма без пробела дали то же самое. При этом переименование
файла команды подхватилось немедленно — значит настройки перечитываются, и дело не в кэше.

Вывод по правилам самого проекта: непроверенный запрет — это ВИДИМОСТЬ защиты, и он
опаснее отсутствия, потому что на него полагаются. Поэтому запреты живут здесь, в
механизме, доказанном пробником: `PreToolUse` с кодом возврата 2 отменяет вызов.

Защищается ровно то, что не восстанавливается или восстанавливается дорого:

  * `data/aggcache` — суточный кэш сделок. Гигабайты, собранные за часы. ⚠ С 2026-08-11
    он стал ДОРОЖЕ, а не дешевле: суточный архив `data.binance.vision` удалён из проекта,
    и восстановить кэш можно только REST-ом ccxt — около 6 минут на символ-сутки, а
    вселенная с приказа 2026-08-21 — вся доска площадки, а не горстка символов.
    Прежняя sha256-сверка ушла вместе с архивом: у REST-пути её нет. Плюс сюда же
    ложится принятое вебсокетом, а оно НЕ ВОССТАНАВЛИВАЕТСЯ ВОВСЕ
    глубже года — на такую глубину биржа сделок уже не отдаёт;
  * `data/ledger.sqlite3` — боевой леджер. §8 этап 7 называет его «единственным будущим
    источником ответа на вопрос, работает ли метод». Он накапливается ТОЛЬКО временем:
    исход считается по барам, закрывшимся после записи сигнала, поэтому потерянный
    журнал не пересчитывается ничем;
  * история git и несохранённая работа — `push --force`, `reset --hard`, `clean -fd`;
  * исполнение скачанного без чтения — `curl … | sh`.

⚠ Кадры прогонов (`data/frames/<id>`) НЕ защищаются намеренно: они порождаются одной
командой за минуты, и за одну сессию их удаляли шесть раз как мусор от пробников. Защита,
мешающая обычной работе, будет обойдена — и тогда перестанет защищать нужное.

⚠ ИЗВЕСТНАЯ ПЕРЕБЛОКИРОВКА, и она принята сознательно. Хук читает строку команды целиком
и не отличает исполняемый код от текста внутри кавычек. Поэтому блокируется и команда,
которая опасный образец лишь УПОМИНАЕТ, — например запись документации про него через
`python -c`. За первый час это случилось дважды: на пробнике и на правке CLAUDE.md.

Разбирать оболочку, чтобы отличить одно от другого, здесь не стоит: цена ошибки
несимметрична. Лишний отказ виден сразу и обходится нормальным инструментом правки
файлов; пропущенное `--force` не видно никогда. Правило простое: текст, содержащий такие
образцы, пишется файловыми инструментами, а не строкой в оболочке.
"""

from __future__ import annotations

import json
import re
import sys

PROTECTED: dict[str, str] = {
    "data/aggcache": "суточный кэш сделок: часы сбора REST-ом, "
                     "а глубже года бирже уже нечего отдать",
    "data/bars": "хранилище баров: накапливается ТОЛЬКО временем и добором хвоста, "
                 "а биржа за один запрос отдаёт максимум 1000 свечей — стёртую "
                 "глубину придётся набирать заново сутками",
    "data/ledger.sqlite3": "боевой леджер — единственный источник ответа «работает ли "
                           "метод» (§8 этап 7), накапливается только временем",
}

REMOVERS = re.compile(r"\b(rm|rmdir|del|Remove-Item|shutil\.rmtree|unlink)\b")
WHOLE_DATA = re.compile(r"\brm\s+(-\w+\s+)*data/?\s*($|;|&|\|)")

DESTRUCTIVE: tuple[tuple[str, str], ...] = (
    (r"git\s+push\b.*(--force(?!-with-lease)|\s-f\b)",
     "`git push --force` затирает уже опубликованную историю; вернуть её можно только "
     "из чужой копии. Безопасная замена — `--force-with-lease`"),
    (r"git\s+reset\s+--hard",
     "`git reset --hard` уничтожает несохранённую работу без корзины"),
    (r"git\s+clean\s+-\w*[fd]",
     "`git clean -fd` стирает неотслеживаемые файлы мимо истории"),
    (r"(curl|wget)\b[^|]*\|\s*(sudo\s+)?(ba)?sh\b",
     "исполнение скачанного без чтения"),
)


def _block(reason: str) -> int:
    print(f"КОМАНДА ОСТАНОВЛЕНА: {reason}.\n\n"
          "Если это действительно нужно — делает владелец руками, не агент.",
          file=sys.stderr)
    return 2


def main() -> int:
    raw = sys.stdin.read()
    try:
        event = json.loads(raw) if raw.strip() else {}
    except json.JSONDecodeError:
        # Разобрать не удалось — пропускаем, и это осознанно. Хук защищает от ОПЕЧАТКИ,
        # а не от злого умысла; блокировать всё подряд из-за него нельзя. Настоящий
        # обязательный запрет (гейты перед коммитом) живёт в commit_gate.py и при
        # неразобранном входе блокирует.
        return 0

    command = str(event.get("tool_input", {}).get("command", ""))
    command_slashed = command.replace("\\", "/")

    # Необратимые команды проверяются ПЕРВЫМИ: `git push --force` не содержит `rm`,
    # и ранний выход по REMOVERS пропустил бы его.
    for pattern, why in DESTRUCTIVE:
        if re.search(pattern, command_slashed):
            return _block(why)

    if not REMOVERS.search(command_slashed):
        return 0

    hits = [(p, why) for p, why in PROTECTED.items() if p in command_slashed]
    if WHOLE_DATA.search(command_slashed):
        hits.append(("data/", "весь каталог данных целиком"))
    if not hits:
        return 0

    what = "\n".join(f"  * {p} — {why}" for p, why in hits)
    return _block("команда трогает то, что восстанавливается дорого либо не "
                  f"восстанавливается вовсе:\n{what}")


if __name__ == "__main__":
    sys.exit(main())

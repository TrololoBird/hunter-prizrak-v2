#!/usr/bin/env bash
# Все проверки одной командой, с НЕНУЛЕВЫМ кодом возврата при любом провале.
#
# Написан 2026-08-04 после того, как я ДВАЖДЫ закоммитил при красном гейте. Причина оба
# раза одна: цикл `for g in gates/*.py; do ... done` возвращает код ПОСЛЕДНЕЙ итерации,
# а не худшей, и `&& git commit` после него срабатывал независимо от результата. Провал
# при этом ПЕЧАТАЛСЯ — то есть глазами он был виден, и это ровно та ситуация, против
# которой в CLAUDE.md записано «сводка обязана падать по коду возврата, а не печатать».
#
#   bash scripts/check.sh && git commit ...
#
set -u
fail=0

# Лог одного прогона. ⚠ ИМЯ ДОЛЖНО БЫТЬ СВОИМ У КАЖДОГО ПРОЦЕССА. Здесь стоял
# фиксированный путь /tmp/hunter-check.log, и 2026-08-23 это дало ложный отчёт:
# пока шёл мой прогон, параллельные агенты ревизии гоняли тот же скрипт, чужой процесс
# переписал файл между записью и чтением — и под строкой «ПРОВАЛ ruff» напечатался вывод
# СОВСЕМ ДРУГОГО гейта. Отказ этого класса не виден: обе стороны выглядят правдоподобно.
LOG="$(mktemp -t hunter-check.XXXXXX)"
trap 'rm -f "$LOG"' EXIT

# Потолок печати одного провала. Урезание НАЗЫВАЕТСЯ числом: молча урезанный вывод
# читается как «вот и всё, что было не так».
MAX_LINES=40

run() {
  local name="$1"; shift
  if ! "$@" >"$LOG" 2>&1; then
    echo "ПРОВАЛ  $name"
    # ⚠ ЗДЕСЬ БЫЛ `tail -20`, и это был тот самый дефект, против которого написан весь
    # файл. Гейты печатают ОХВАТ И СЧЁТ первой строкой («…ключей 13, нарушений 2»), а
    # хвост срезает именно её: оставались отдельные жалобы без числа проверенного.
    # Хуже того, хук коммитов читает инверсией ЭТОТ поток — то есть инвертировал уже
    # урезанное. Читаем инверсией здесь: всё, что не начинается с `ok`. Найдено
    # ревизией правил 2026-08-23.
    local total
    total=$(grep -cv '^ok' "$LOG" || true)
    grep -v '^ok' "$LOG" | head -"$MAX_LINES" || true
    if [ "${total:-0}" -gt "$MAX_LINES" ]; then
      echo "…и ещё $((total - MAX_LINES)) строк отказа не показано (потолок $MAX_LINES)"
    fi
    fail=1
  else
    echo "ok      $name"
  fi
}

run ruff uv run ruff check .
run mypy uv run mypy

n=0
for g in gates/*.py; do
  [ "$(basename "$g")" = "__init__.py" ] && continue
  run "гейт $(basename "$g" .py)" uv run --group gates python "$g"
  n=$((n + 1))
done

echo "-----------------------------------------------------------"
echo "гейтов прогнано: $n"
if [ "$fail" -ne 0 ]; then
  echo "ИТОГ: ЕСТЬ ПРОВАЛЫ — коммитить нельзя"
  exit 1
fi
echo "ИТОГ: всё зелёное"
